# -*- coding: utf-8 -*-
"""Замер готового кадра: предупреждение, а не запрет.

Пороги свои, из скила `визуал-слайдов`, замерены на живых кадрах бота. Чужие
дизайн-своды здесь бесполезны: они меряют веб-страницу, которую разглядывают,
а мы меряем кадр в ленте — уменьшенный втрое и живущий полторы секунды.

Замер НЕ блокирует выпуск. Кадр с малым числом чернил бывает верным: финальный
слайд с одной фразой именно так и устроен. Дело замера — не дать пропустить
это молча, а решает владелец.

Чего в разборе нет, то не судится: акцентного цвета у кадра может не быть
вовсе, и требовать его от каждого — значит ругаться на нарочно строгий кадр.
"""

# Пороги переставлены 12 сентября 2026, когда замер наконец подключили к
# рисовальщику. Прежние (8–15% чернил, 4–6% акцента) были сняты другой мерой,
# на чужих кадрах, и к нашим не подходили вовсе: по ним «пустыми» выходили
# одиннадцать кадров из одиннадцати, включая те, что владелец принял. Проверка,
# которая ругается всегда, не отличается от выключенной.
#
# Новые сняты со своих кадров: список 2,8%, плитки 3,9%, замена 5,2%,
# столбики 8,5%. Отсюда и границы — ловим то, что действительно сломано.
ЧЕРНИЛ = (2.2, 12.0)        # ниже — кадр почти пустой, выше — нечитаемый
# Нижней границы у акцента нет: «манифест» нарочно живёт без акцентного цвета
# вовсе, и у образца, собравшего 641 тысячу просмотров, его ровно ноль.
АКЦЕНТА = (0.0, 8.0)        # выше 8% лайм перестаёт быть акцентом и заливает кадр
КОНТРАСТ = 8.0              # в ленте кадр уменьшен втрое, тонкие штрихи съедаются
СТРОКА = 12.0               # крупная строка ниже 8% высоты не читается в превью

# Дизайны расходятся по плотности втрое, и одна норма на всех ругалась бы на
# терминале и атмосфере, которые нарочно пустые.
ПО_ДИЗАЙНУ = {
    "терминал":  {"чернил": (1.8, 9.0)},
    "манифест":  {"чернил": (2.0, 11.0), "акцента": (0.0, 4.0)},
    "атмосфера": {"чернил": (1.5, 9.0), "акцента": (0.0, 4.0)},
    "редакционный": {"чернил": (2.0, 11.0)},
}


def нормы(дизайн: str = "") -> dict:
    """Пороги для дизайна. Чей норм нет — судится общей."""
    своё = ПО_ДИЗАЙНУ.get(дизайн or "", {})
    return {"чернил": своё.get("чернил", ЧЕРНИЛ),
            "акцента": своё.get("акцента", АКЦЕНТА),
            "контраст": своё.get("контраст", КОНТРАСТ),
            "строка": своё.get("строка", СТРОКА)}


def оценить(числа: dict, дизайн: str = "") -> list[str]:
    """Замечания к кадру. Пустой список — кадр в норме.

    На самих границах кадр годен: 8% чернил и 4% акцента это норма, а не край.
    Дизайн можно не передавать: тогда судим общей нормой, как и раньше.
    """
    замечания = []
    порог = нормы(дизайн)

    чернил = числа.get("доля_чернил_%")
    if чернил is not None:
        если_мало, если_много = порог["чернил"]
        if чернил < если_мало:
            замечания.append(
                f"чернил {чернил}% при норме от {если_мало}%: кадр пустой")
        elif чернил > если_много:
            замечания.append(
                f"чернил {чернил}% при норме до {если_много}%: кадр перегружен")

    акцента = числа.get("доля_акцента_%")
    if акцента is not None:
        если_мало, если_много = порог["акцента"]
        if акцента < если_мало:
            замечания.append(
                f"акцент {акцента}% при норме от {если_мало}%: с расстояния ленты не видно")
        elif акцента > если_много:
            замечания.append(
                f"акцент {акцента}% при норме до {если_много}%: перестаёт быть акцентом")

    контраст = числа.get("контраст_текст_фон")
    if контраст is not None and контраст < порог["контраст"]:
        замечания.append(
            f"контраст текста к фону {контраст} при норме от {порог['контраст']}")

    строка = числа.get("крупная_строка_%")
    if строка is not None and строка < порог["строка"]:
        замечания.append(
            f"крупная строка {строка}% высоты при норме от {порог['строка']}%")

    return замечания


def числа_снимка(путь) -> dict:
    """Плотность готового кадра: сколько на нём чернил и сколько акцента.

    Меряем по снимку, а не по разметке: разметка знает, где стоит блок, но не
    знает, сколько он занял краски. Фон берём самым частым цветом кадра —
    кадры у нас и светлые, и тёмные, и общий порог «тёмное значит чернила»
    для них бессмыслен.

    Кадр уменьшаем втрое: доли от этого не меняются, а считается втрое быстрее.
    """
    from collections import Counter

    from PIL import Image

    import config

    кадр = Image.open(путь).convert("RGB")
    кадр = кадр.resize((max(1, кадр.width // 3), max(1, кадр.height // 3)))
    точки = list(кадр.getdata())
    если_нет = {"доля_чернил_%": None, "доля_акцента_%": None}
    if not точки:
        return если_нет
    фон = Counter(точки).most_common(1)[0][0]
    лайм = tuple(int(config.ЛАЙМ.lstrip("#")[i:i + 2], 16) for i in (0, 2, 4))
    ржавый = tuple(int(config.РЖАВЫЙ.lstrip("#")[i:i + 2], 16) for i in (0, 2, 4))

    def далеко(ц, от, порог=90):
        return sum(abs(а - б) for а, б in zip(ц, от)) > порог

    чернил = sum(1 for ц in точки if далеко(ц, фон))
    акцент = sum(1 for ц in точки
                 if not далеко(ц, лайм) or not далеко(ц, ржавый))
    всего = len(точки)
    return {"доля_чернил_%": round(чернил * 100 / всего, 1),
            "доля_акцента_%": round(акцент * 100 / всего, 1)}


def проверить_снимок(путь, дизайн: str = "") -> list[str]:
    """Замечания по готовому кадру. Молчит, если картинку прочесть не вышло."""
    try:
        return оценить(числа_снимка(путь), дизайн)
    except Exception as е:  # noqa: BLE001
        # Замер — подсказка, а не условие выпуска: упасть на ней нельзя.
        return [f"плотность кадра не замерена: {е}"]
