# -*- coding: utf-8 -*-
"""Замер готового кадра: предупреждение, а не запрет.

Пороги свои, из скила `визуал-слайдов`, замерены на живых кадрах бота. Чужие
дизайн-своды здесь бесполезны: они меряют веб-страницу, которую разглядывают,
а мы меряем кадр в ленте — уменьшенный втрое и живущий полторы секунды.

Замер НЕ блокирует выпуск. Кадр с малым числом чернил бывает верным: финальный
слайд с одной фразой именно так и устроен. Дело замера — не дать пропустить
это молча, а решает владелец.

Чего в разборе нет, то не судится: акцентного цвета у кадра может не быть
вовсе, и требовать его от каждого — значит ругаться на нарочно строгий кадр.
"""

ЧЕРНИЛ = (8.0, 15.0)        # ниже — кадр пустой, выше — нечитаемый
АКЦЕНТА = (4.0, 6.0)        # ниже 2% не видно в ленте, выше 8% уже не акцент
КОНТРАСТ = 8.0              # в ленте кадр уменьшен втрое, тонкие штрихи съедаются
СТРОКА = 12.0               # крупная строка ниже 8% высоты не читается в превью


def оценить(числа: dict) -> list[str]:
    """Замечания к кадру. Пустой список — кадр в норме.

    На самих границах кадр годен: 8% чернил и 4% акцента это норма, а не край.
    """
    замечания = []

    чернил = числа.get("доля_чернил_%")
    if чернил is not None:
        если_мало, если_много = ЧЕРНИЛ
        if чернил < если_мало:
            замечания.append(
                f"чернил {чернил}% при норме от {если_мало}%: кадр пустой")
        elif чернил > если_много:
            замечания.append(
                f"чернил {чернил}% при норме до {если_много}%: кадр перегружен")

    акцента = числа.get("доля_акцента_%")
    if акцента is not None:
        если_мало, если_много = АКЦЕНТА
        if акцента < если_мало:
            замечания.append(
                f"акцент {акцента}% при норме от {если_мало}%: с расстояния ленты не видно")
        elif акцента > если_много:
            замечания.append(
                f"акцент {акцента}% при норме до {если_много}%: перестаёт быть акцентом")

    контраст = числа.get("контраст_текст_фон")
    if контраст is not None and контраст < КОНТРАСТ:
        замечания.append(
            f"контраст текста к фону {контраст} при норме от {КОНТРАСТ}")

    строка = числа.get("крупная_строка_%")
    if строка is not None and строка < СТРОКА:
        замечания.append(
            f"крупная строка {строка}% высоты при норме от {СТРОКА}%")

    return замечания
