# -*- coding: utf-8 -*-
"""Паспорт карусели: какой она будет, решает код, а не модель.

Модели давать выбор бесполезно: из пяти каркасов она брала «шаги» в половине
случаев, а дизайн и фон не менялись вовсе. Двадцать две карусели подряд
выходили одним семейством — «чистая типографика и кот», у которого по разбору
TikTok одно из самых слабых вовлечений (2,4%).

Паспорт выбирается до сценария и не повторяет недавнего: ход мысли — двух
прошлых каруселей, вид — пяти прошлых. История лежит в настройках станка,
рядом с углом.
"""

import random

# Тип карусели и что он требует. Вес — отдача семейства по разбору TikTok:
# чем выше, тем чаще выпадает. Новый тип попадает сюда только после того, как
# владелец увидел его настоящий образец.
ТИПЫ = {
    "обычная": {"вес": 2.4, "кадров": [8, 12], "кот": True,
                "каркасы": ["боль", "шаги", "ошибки", "было и стало", "разбор"]},
    # Пост из одной картинки. Владелец просил его с самого начала: «почему не
    # делаешь варианты, где 1 картинка, но много информации». В чужих
    # каруселях такие посты собирают по 126 и 156 тысяч просмотров при одном
    # кадре — их не читают в ленте, их сохраняют.
    #
    # Вес ниже обычной: один кадр не держит внимание так долго, и делать его
    # каждым третьим постом незачем. Каркаса у типа нет вовсе — пути мысли
    # здесь нет, есть одна плотная картинка.
    "одним кадром": {"вес": 0.35, "кадров": [1, 1], "кот": False,
                     "каркасы": [], "виды": ["шпаргалка", "облако", "замена"]},
}

# Связки вида, которые владелец выбрал по листу образцов 12 сентября 2026.
# «Инверсия» пущена после того, как стала перевёрнутой палитрой: до этого на
# ней сливались галочки, «Итог» и заголовок обложки. «Карточки» нет: она
# обнуляет поля кадра, текст липнет к краю, а замер этого не видит.
# «Манифест» и «атмосфера» добавлены 12 сентября 2026 по разбору чужих
# каруселей: оба списаны с постов, собравших сотни тысяч просмотров, и оба
# держатся не на украшениях, а на устройстве кадра — узкие заглавные с
# линейкой слева и свечение с воздухом.
ДИЗАЙНЫ_ОК = ["фирменный", "швейцарский", "терминал", "манифест", "атмосфера",
              "пособие"]
ОФОРМЛЕНИЯ_ОК = ["сетка", "чистый", "инверсия", "полоса", "зерно", "линии",
                 "контур"]

ПОМНИМ_ХОД = 2
ПОМНИМ_ВИД = 5


def _ходы() -> list[tuple[str, str]]:
    return [(т, к) for т, о in ТИПЫ.items() for к in (о.get("каркасы") or [""])]


def подобрать(история: list, случай=random) -> dict:
    """Паспорт, не повторяющий недавнего. История и случай приходят снаружи."""
    недавний_ход = {(п.get("тип"), п.get("каркас")) for п in история[-ПОМНИМ_ХОД:]}
    недавний_вид = {(п.get("дизайн"), п.get("оформление"))
                    for п in история[-ПОМНИМ_ВИД:]}

    ходы = [х for х in _ходы() if х not in недавний_ход] or _ходы()
    # Вес типа делится между его каркасами: иначе тип с пятью каркасами
    # выпадал бы впятеро чаще типа с одним.
    сколько = {т: sum(1 for т_, _ in ходы if т_ == т) for т, _ in ходы}
    тип, каркас = случай.choices(
        ходы, weights=[ТИПЫ[т]["вес"] / сколько[т] for т, _ in ходы])[0]

    связки = [(д, о) for д in ДИЗАЙНЫ_ОК for о in ОФОРМЛЕНИЯ_ОК]
    дизайн, оформление = случай.choice(
        [с for с in связки if с not in недавний_вид] or связки)

    о = ТИПЫ[тип]
    паспорт = {"тип": тип, "каркас": каркас, "кадров": list(о["кадров"]),
               "дизайн": дизайн, "оформление": оформление, "кот": о["кот"]}
    # У типа может быть свой список вёрсток: пост из одного кадра собирается
    # не «мыслью», а плотной вёрсткой, иначе одна картинка выходит пустой.
    if о.get("виды"):
        паспорт["вид"] = случай.choice(о["виды"])
    return паспорт


def следующий(куда: str = "tiktok") -> dict:
    """Паспорт на очередной заказ; запоминается, чтобы следующий не повторил."""
    import конвейер
    история = list(конвейер.настройки(куда).get("форматы") or [])
    паспорт = подобрать(история)
    конвейер.сохранить(куда, форматы=(история + [паспорт])[-ПОМНИМ_ВИД:])
    return паспорт
