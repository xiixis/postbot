# -*- coding: utf-8 -*-
"""Паспорт карусели: какой она будет, решает код, а не модель.

Модели давать выбор бесполезно: из пяти каркасов она брала «шаги» в половине
случаев, а дизайн и фон не менялись вовсе. Двадцать две карусели подряд
выходили одним семейством — «чистая типографика и кот», у которого по разбору
TikTok одно из самых слабых вовлечений (2,4%).

Паспорт выбирается до сценария и не повторяет недавнего: ход мысли — двух
прошлых каруселей, вид — пяти прошлых. История лежит в настройках станка,
рядом с углом.
"""

import random

# Тип карусели и что он требует. Вес — отдача семейства по разбору TikTok:
# чем выше, тем чаще выпадает. Новый тип попадает сюда только после того, как
# владелец увидел его настоящий образец.
ТИПЫ = {
    "обычная": {"вес": 2.4, "кадров": [8, 12], "кот": True,
                "каркасы": ["боль", "шаги", "ошибки", "было и стало", "разбор"]},
    # Пост из одной картинки. Владелец просил его с самого начала: «почему не
    # делаешь варианты, где 1 картинка, но много информации». В чужих
    # каруселях такие посты собирают по 126 и 156 тысяч просмотров при одном
    # кадре — их не читают в ленте, их сохраняют.
    #
    # Вес ниже обычной: один кадр не держит внимание так долго, и делать его
    # каждым третьим постом незачем. Каркаса у типа нет вовсе — пути мысли
    # здесь нет, есть одна плотная картинка.
    "одним кадром": {"вес": 0.35, "кадров": [1, 1], "кот": False,
                     "каркасы": [], "виды": ["шпаргалка", "облако", "замена"]},
}

# Связки вида, которые владелец выбрал по листу образцов 12 сентября 2026.
# «Инверсия» пущена после того, как стала перевёрнутой палитрой: до этого на
# ней сливались галочки, «Итог» и заголовок обложки. «Карточки» нет: она
# обнуляет поля кадра, текст липнет к краю, а замер этого не видит.
# Состав пересобран 12 сентября 2026 по слову владельца: «оставить один наш
# фирменный, остальное — новое». Раньше в ротации стояли вариации одного и того
# же нашего стиля — швейцарский и терминал отличались шрифтом и линейками, но
# устройство кадра было общее, и в ленте это читалось как один дизайн.
#
# Теперь четыре из пяти списаны с чужих каруселей, разобранных по косточкам:
# манифест (@neuro.ks, 641 тыс. просмотров), пособие (@neuro.ks, 469 тыс.),
# атмосфера (ty.prompts.ai, AA Studio), каталог (@emirailab, 466 тыс.).
# Фирменный остаётся один — как якорь, чтобы канал не потерял себя.
#
# Швейцарский и терминал никуда не делись из card.ДИЗАЙНЫ: их можно вернуть,
# переработав по той же схеме — сначала разбор референса, потом кадр.
ДИЗАЙНЫ_ОК = ["фирменный", "манифест", "атмосфера", "пособие", "каталог",
              "терминал", "редакционный"]
ОФОРМЛЕНИЯ_ОК = ["сетка", "чистый", "инверсия", "полоса", "зерно", "линии",
                 "контур"]

# Дизайны, которым фон не подбирают. «Каталог» светлый, а все наши фоны
# рисуют лаймовые полупрозрачные узоры под тёмный кадр: на кремовом грунте их
# просто не видно, и семь связок вырождаются в одну и ту же картинку. Ротация
# тратила бы на них ходы, показывая владельцу ложное разнообразие.
СВОЙ_ФОН = {"каталог": "чистый",
            # У «терминала» слоем сетки нарисована текстура кода — призрачные
            # строки вывода, без которых чёрный кадр выглядит просто чёрным.
            # Любое оформление, которое прячет или перекрашивает этот слой,
            # стирает половину жанра, поэтому фон у него закреплён.
            "терминал": "сетка"}

# Связки, которые рисовальщик ломает: белый текст по крему, блок за краем.
# Каждая ссылается на запись в docs/дефекты-кадров.md. Баг починен с тестом —
# строка отсюда уходит, иначе запрет переживёт причину и молча сузит выбор.
# «тон» — тёмный или светлый кадр по card.светлый_ли, без него — любой кадр.
# Без «видов» запрещён дизайн целиком, и только по формату.
НЕЛЬЗЯ = [
    {"дефект": "Д-01", "дизайн": "каталог", "тон": "тёмный",
     "виды": {"было", "стрелка"}},
    {"дефект": "Д-02", "дизайн": "каталог", "виды": {"против"}},
    {"дефект": "Д-04", "дизайн": "пособие", "виды": {"шаг"}},
    {"дефект": "Д-05", "дизайн": "манифест", "формат": "квадрат"},
]

# Подсветка *звёздочками*, которая в дизайне пропадает на кадрах одного тона.
# Вёрстку тут менять незачем: слова видны, не видна только заливка.
БЕЗ_ПОДСВЕТКИ = {"пособие": ("светлый", "Д-03")}

# Куда переводится слайд из сломанной связки. В НЕЛЬЗЯ стоять не может: тест
# сторожит, иначе переводить станет некуда.
НАДЁЖНЫЙ_ВИД = "мысль"

# Связки, проверенные на образцах: (дизайн, вид, тон, формат). Наполняет
# прогон образцов; до него «не проверено» рисовать разрешено.
ПРОВЕРЕНО: set = set()


def тон(номер: int) -> str:
    import card
    return "светлый" if card.светлый_ли(номер) else "тёмный"


def запрет(дизайн: str, вид: str, номер: int, формат: str) -> str:
    """Номер дефекта, если связка ломается; пустая строка, если рисовать можно."""
    for п in НЕЛЬЗЯ:
        if п["дизайн"] != дизайн:
            continue
        if п.get("формат") and п["формат"] != формат:
            continue
        if п.get("тон") and п["тон"] != тон(номер):
            continue
        if "виды" not in п or вид in п["виды"]:
            return п["дефект"]
    return ""


def статус(дизайн: str, вид: str, номер: int, формат: str) -> str:
    if запрет(дизайн, вид, номер, формат):
        return "нельзя"
    if (дизайн, вид, тон(номер), формат) in ПРОВЕРЕНО:
        return "проверено"
    return "не проверено"


def дизайн_годится(дизайн: str, формат: str) -> bool:
    """Дизайн целиком не годится формату — как манифест в квадрате."""
    return not any(п["дизайн"] == дизайн and "виды" not in п
                   and not п.get("тон") and п.get("формат") == формат
                   for п in НЕЛЬЗЯ)


ПОМНИМ_ХОД = 2
ПОМНИМ_ВИД = 5


def _ходы() -> list[tuple[str, str]]:
    return [(т, к) for т, о in ТИПЫ.items() for к in (о.get("каркасы") or [""])]


def подобрать(история: list, случай=random) -> dict:
    """Паспорт, не повторяющий недавнего. История и случай приходят снаружи."""
    недавний_ход = {(п.get("тип"), п.get("каркас")) for п in история[-ПОМНИМ_ХОД:]}
    недавний_вид = {(п.get("дизайн"), п.get("оформление"))
                    for п in история[-ПОМНИМ_ВИД:]}

    ходы = [х for х in _ходы() if х not in недавний_ход] or _ходы()
    # Вес типа делится между его каркасами: иначе тип с пятью каркасами
    # выпадал бы впятеро чаще типа с одним.
    сколько = {т: sum(1 for т_, _ in ходы if т_ == т) for т, _ in ходы}
    тип, каркас = случай.choices(
        ходы, weights=[ТИПЫ[т]["вес"] / сколько[т] for т, _ in ходы])[0]

    # Сначала дизайн, потом фон — а не пара сразу. Пара сразу давала перекос:
    # у «каталога» фон один, у остальных по семь, и на общем розыгрыше он
    # выпадал раз в тридцать вместо раза в пять. Дизайн — это лицо кадра, и
    # шансы у лиц должны быть равные; фон лишь вариация внутри выбранного.
    свободно = {}
    for д in ДИЗАЙНЫ_ОК:
        фоны = [СВОЙ_ФОН[д]] if д in СВОЙ_ФОН else list(ОФОРМЛЕНИЯ_ОК)
        осталось = [о for о in фоны if (д, о) not in недавний_вид]
        if осталось:
            свободно[д] = осталось
    if not свободно:
        свободно = {д: ([СВОЙ_ФОН[д]] if д in СВОЙ_ФОН else list(ОФОРМЛЕНИЯ_ОК))
                    for д in ДИЗАЙНЫ_ОК}
    дизайн = случай.choice(sorted(свободно))
    оформление = случай.choice(свободно[дизайн])

    о = ТИПЫ[тип]
    паспорт = {"тип": тип, "каркас": каркас, "кадров": list(о["кадров"]),
               "дизайн": дизайн, "оформление": оформление, "кот": о["кот"]}
    # У типа может быть свой список вёрсток: пост из одного кадра собирается
    # не «мыслью», а плотной вёрсткой, иначе одна картинка выходит пустой.
    if о.get("виды"):
        паспорт["вид"] = случай.choice(о["виды"])
    return паспорт


def следующий(куда: str = "tiktok") -> dict:
    """Паспорт на очередной заказ; запоминается, чтобы следующий не повторил."""
    import конвейер
    история = list(конвейер.настройки(куда).get("форматы") or [])
    паспорт = подобрать(история)
    конвейер.сохранить(куда, форматы=(история + [паспорт])[-ПОМНИМ_ВИД:])
    return паспорт
