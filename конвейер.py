# -*- coding: utf-8 -*-
"""Конвейер: бот сам придумывает, рисует и ставит в план.

Разница между «умеет сделать карусель» и «конвейером» одна: во втором случае
человек не участвует в рутине. Ему не нужно выбирать тему, помнить, что давно
не выходило, и следить, чтобы в плане не образовалась дыра. Он вмешивается
только когда что-то не нравится.

Отсюда устройство. Раз в сутки конвейер смотрит, сколько публикаций стоит в
плане. Если меньше запаса, он добирает недостающие: берёт следующий угол по
кругу, сочиняет под него карусель, рисует слайды и ставит на ближайшее
свободное время. Владельцу приходит готовое с кнопкой «снять», и это
единственное, что от него требуется.
"""

import time
from datetime import timedelta

import db
import times
from content import УГЛЫ_TIKTOK

НАСТРОЙКА = "конвейер"
КОГДА = "конвейер_запуск"          # когда добирали план в прошлый раз
РАЗ_В = 20 * 3600

# Настройки у каждой площадки свои, и это главное здесь. В телеграме читают
# свои, и пять постов в день там утомляют. В TikTok зритель холодный и листает
# ленту, там пять в день это нормальный темп. Один общий конвейер на всех
# означал бы либо пустой TikTok, либо замусоренный канал.
# «режим» отвечает на вопрос, что конвейер делает с готовым постом.
#   сам   — ставит время и публикует без участия человека
#   руками — собирает и отдаёт владельцу, выкладывает он
# Второй нужен не только пока нет ключей: в TikTok многое решает момент
# публикации и звук, а это выбирает человек.
ПО_УМОЛЧАНИЮ = {
    "tiktok": {"вкл": False, "дней": 1, "угол": "", "режим": "руками",
               "часы": ["09:00", "12:30", "15:00", "18:00", "21:00"]},
    "телеграм": {"вкл": False, "дней": 3, "угол": "", "режим": "сам",
                 "часы": ["10:00"]},
}


def настройки(куда: str = "tiktok") -> dict:
    свои = (db.настройка(НАСТРОЙКА, {}) or {}).get(куда) or {}
    основа = ПО_УМОЛЧАНИЮ.get(куда, ПО_УМОЛЧАНИЮ["tiktok"])
    return {**основа, **свои}


def сохранить(куда: str = "tiktok", **поля) -> dict:
    всё = db.настройка(НАСТРОЙКА, {}) or {}
    свод = {**настройки(куда), **поля}
    всё[куда] = свод
    db.запомнить(НАСТРОЙКА, всё)
    return свод


def включённые() -> list[str]:
    return [к for к in ПО_УМОЛЧАНИЮ if настройки(к)["вкл"]]


def переключить(куда: str = "tiktok") -> bool:
    стало = not настройки(куда)["вкл"]
    сохранить(куда, вкл=стало)
    return стало


def запас(куда: str) -> int:
    """Сколько публикаций держим готовыми: часы в сутках умножить на дни."""
    с = настройки(куда)
    return max(1, len([ч for ч in с["часы"] if ч]) * int(с["дней"]))


def следующий_угол(куда: str = "tiktok") -> tuple[str, str]:
    """Углы идут по кругу: так ни один не забывается и ни один не приедается."""
    углы = list(УГЛЫ_TIKTOK)
    прошлый = настройки(куда).get("угол")
    место = углы.index(прошлый) + 1 if прошлый in углы else 0
    угол = углы[место % len(углы)]
    сохранить(куда, угол=угол)
    return угол, УГЛЫ_TIKTOK[угол]


def в_плане(площадка: str) -> list:
    """Что уже стоит в плане для этой площадки."""
    import publish
    return [п for п in db.расписание() if площадка in publish.куда_едет(п)]


def свободные_часы(куда: str, сколько: int) -> list:
    """Ближайшие свободные времена по расписанию этой площадки.

    Занятым считается час, на который уже что-то стоит: две публикации в одну
    минуту выглядят как сбой, а не как план.
    """
    с = настройки(куда)
    часы = [ч for ч in (с.get("часы") or ["12:00"]) if ч] or ["12:00"]
    занято = {times.из_базы(п["scheduled_at"]).strftime("%Y-%m-%d %H:%M")
              for п in db.расписание() if п["scheduled_at"]}
    сейчас = times.сейчас()
    итог, день = [], 0
    while len(итог) < сколько and день < 30:
        дата = сейчас + timedelta(days=день)
        for ч in часы:
            часть, минута = (ч.split(":") + ["0"])[:2]
            когда = дата.replace(hour=int(часть), minute=int(минута),
                                 second=0, microsecond=0)
            if когда <= сейчас + timedelta(minutes=20):
                continue          # слишком скоро, рисование столько не успеет
            если_занято = когда.strftime("%Y-%m-%d %H:%M") in занято
            if если_занято:
                continue
            итог.append(когда)
            занято.add(когда.strftime("%Y-%m-%d %H:%M"))
            if len(итог) >= сколько:
                break
        день += 1
    return итог


def пора() -> bool:
    if not включённые():
        return False
    return time.time() - float(db.настройка(КОГДА, 0) or 0) > РАЗ_В


def чего_не_хватает(куда: str) -> int:
    """Сколько ещё собрать.

    В ручном режиме считаем не по расписанию, а по готовым черновикам: время
    им никто не ставит, и по плану их не видно.
    """
    if настройки(куда).get("режим") == "руками":
        import publish
        готовы = [п for п in db.черновики() if куда in publish.куда_едет(п)]
        return max(0, запас(куда) - len(готовы))
    return max(0, запас(куда) - len(в_плане(куда)))


def сделать_одну(куда: str = "tiktok", ход=None) -> int:
    """Сочиняет одну карусель под следующий угол и ставит её в план."""
    import core
    угол, пояснение = следующий_угол(куда)
    указания = (f"УГОЛ ЭТОЙ КАРУСЕЛИ: «{угол}».\n{пояснение}.\n"
                "Тему под этим углом выбери сам, глядя на то, чего давно не "
                "было. Не называй угол в тексте, он для тебя, а не для зрителя.")
    ид = core.карусель(None, ход, куда, указания)
    if настройки(куда).get("режим") == "руками":
        # Время не ставим: пост остаётся черновиком, владелец выложит сам.
        return ид
    часы = свободные_часы(куда, 1)
    if часы:
        core.запланировать(ид, часы[0])
    return ид


def подтянуть(куда: str, ход=None) -> list[int]:
    """Добирает план одной площадки до запаса. Возвращает номера новых."""
    сделаны = []
    for _ in range(чего_не_хватает(куда)):
        try:
            сделаны.append(сделать_одну(куда, ход))
        except Exception:                                    # noqa: BLE001
            import traceback
            traceback.print_exc()
            break            # не получилось сейчас, попробуем в следующий раз
    return сделаны


def подтянуть_всё(ход=None) -> dict[str, list[int]]:
    итог = {к: подтянуть(к, ход) for к in включённые()}
    db.запомнить(КОГДА, time.time())
    return итог
