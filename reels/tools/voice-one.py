# Озвучка одним запросом: python tools/voice-one.py voice/<ролик>.json <голос> [резать]
# («резать» — заново нарезать уже готовую запись, без нового запроса)
#
# tools/voice.py шлёт в Fish каждую фразу отдельно, и модель каждый раз заново решает, каким
# голосом читать: высота гуляет на ±15%, настроение скачет, перечисление повисает. Отбирать дубли
# замерами долго и ненадёжно (03.10.2026 так и вышло: сто дублей, а владелец сказал «должно быть
# классно с первого раза»). Поэтому текст идёт ОДНИМ запросом и с одной манерой: голос один от
# начала до конца, а интонацию абзаца и паузы модель берёт из самой структуры текста.
#
# Текст собирается из сценария: строки абзаца через пробел, абзацы с новой строки
# (абзац кончается на строке с ролью «итог»). Манера одна на весь ролик: поле "манера" сценария.
# У строки может быть "голосу" — как писать её для Fish, если в тексте нужны значки ударения
# («о́тступы», «нахо́дит»): без них модель ставит ударение наугад.
#
# Готовая запись режется на фразы по паузам между предложениями: слова находит распознавание,
# разрез ставится в самом тихом месте паузы. Дальше всё как раньше: NN.wav и отчёт.json для
# tools/layout.py, который расставляет фразы по сценам с нужными паузами.
# Проверка одна: все ли слова на месте. Не понравилось на слух — запускают ещё раз, целиком.
# Запускать питоном 4xTube.
import difflib
import importlib.util
import json
import sys
from pathlib import Path

import numpy as np

ТУТ = Path(__file__).resolve().parent.parent
спека = importlib.util.spec_from_file_location("озвучка", ТУТ / "tools" / "voice.py")
V = importlib.util.module_from_spec(спека)
спека.loader.exec_module(V)
Ч = V.ЧАСТОТА


ЕДИНИЦЫ = "ноль один два три четыре пять шесть семь восемь девять десять одиннадцать двенадцать тринадцать четырнадцать пятнадцать шестнадцать семнадцать восемнадцать девятнадцать".split()
ДЕСЯТКИ = "двадцать тридцать сорок пятьдесят шестьдесят семьдесят восемьдесят девяносто".split()


def прописью(слово: str) -> list[str]:
    """Распознавание пишет числа цифрами («24 команды»), а в тексте они словами. Разворачиваем до 99."""
    if not слово.isdigit() or int(слово) > 99:
        return [слово]
    ч = int(слово)
    if ч < 20:
        return [ЕДИНИЦЫ[ч]]
    return [ДЕСЯТКИ[ч // 10 - 2]] + ([ЕДИНИЦЫ[ч % 10]] if ч % 10 else [])


def main():
    сценарий = json.loads(Path(sys.argv[1]).read_text(encoding="utf-8"))
    имя = sys.argv[2]
    набор = json.loads((ТУТ / "voice" / "голоса.json").read_text(encoding="utf-8"))
    папка = ТУТ / "out" / "voice" / сценарий["ролик"] / имя
    папка.mkdir(parents=True, exist_ok=True)
    строки = сценарий["строки"]

    абзацы, абзац = [], []
    for с in строки:
        абзац.append(с.get("голосу", с["текст"]))
        if с.get("роль") == "итог":
            абзацы.append(" ".join(абзац))
            абзац = []
    if абзац:
        абзацы.append(" ".join(абзац))
    манера = сценарий.get("манера", набор["манера"])
    # Абзацы идут подряд, через один перевод строки. Пустая строка между ними не годится:
    # на ней Fish вставляет лишний звук (распознавание слышит его словом), проверено 03.10.2026.
    текст = манера + " " + "\n".join(абзацы)
    (папка / "текст.txt").write_text(текст, encoding="utf-8")

    if "резать" in sys.argv[3:] and (папка / "целиком.wav").exists():
        данные = (папка / "целиком.wav").read_bytes()         # перерезать готовую запись, Fish не звать
    else:
        данные = V.озвучить(текст, набор["голоса"][имя]["id"], набор["модель"], 1.0, V.ключ())
        (папка / "целиком.wav").write_bytes(данные)
    с = V.звук(данные)
    шаг = int(Ч * 0.05)
    куски = [np.sqrt(np.mean(с[н:н + шаг] ** 2)) for н in range(0, len(с) - шаг, шаг)]
    речь = [к for к in куски if к > 0.2 * max(куски)]
    с = с * (V.ГРОМКОСТЬ / float(np.mean(речь)))         # одна громкость на всю запись, а не на каждую фразу
    с = с * min(1.0, 0.95 / np.abs(с).max())

    from faster_whisper import WhisperModel

    ухо = WhisperModel("medium", device="cpu", compute_type="int8")
    части, _ = ухо.transcribe(str(папка / "целиком.wav"), language="ru", beam_size=5, word_timestamps=True)
    слышно = []                                        # (слово, начало, конец) по одному на каждое слово записи
    for ч in части:
        for w in ч.words or []:
            for т in V.слова(w.word):
                for часть in прописью(т):
                    слышно.append((часть, w.start, w.end))
    свои, чьи = [], []                                 # слова сценария и номер строки каждого
    for н, стр in enumerate(строки):
        for т in V.слова(стр["текст"]):
            свои.append(т)
            чьи.append(н)
    пары = {}                                          # номер слова сценария → номер слова записи
    for блок in difflib.SequenceMatcher(None, свои, [x[0] for x in слышно], autojunk=False).get_matching_blocks():
        for к in range(блок.size):
            пары[блок.a + к] = блок.b + к

    def граница(н: int):
        """Где кончается строка н: (конец слова перед следующей строкой, начало следующей строки).
        Считается от первого узнанного слова следующей строки: всё, что звучит до него, принадлежит
        этой. Так чужое название в конце строки («Тэйст-скил»), которое распознавание не узнало,
        не отрезается."""
        for i, ч in enumerate(чьи):
            if ч == н + 1 and i in пары:
                б = пары[i] - sum(1 for j in range(i) if чьи[j] == н + 1)       # если узнано не первое слово, отступаем к первому
                б = max(1, б)
                return слышно[б - 1][2], слышно[б][1]
        return None, None

    резы = [0.0]
    for н in range(len(строки) - 1):
        а, б = граница(н)
        if а is None or б is None:
            raise SystemExit(f"не нашёл границу после фразы {н + 1} «{строки[н]['текст']}»: запись прочитана иначе, запустить ещё раз")
        # Тихое место ищется чуть шире стыка: распознавание ставит край слова с ошибкой до 0,1 с,
        # а соседние фразы бывают прочитаны без паузы (тогда конец одной равен началу другой).
        от, до = max(резы[-1] + 0.2, min(а, б) - 0.12), max(а, б) + 0.12
        окно = с[int(от * Ч):int(до * Ч)]
        ш = int(Ч * 0.02)
        сила = [np.mean(окно[i:i + ш] ** 2) for i in range(0, max(1, len(окно) - ш), ш)]
        резы.append(от + (int(np.argmin(сила)) * ш + ш / 2) / Ч)
    резы.append(len(с) / Ч)

    отчёт, плохо = [], False
    for н, стр in enumerate(строки, 1):
        кусок = V.обрезать(с[int(резы[н - 1] * Ч):int(резы[н] * Ч)])
        V.записать(папка / f"{н:02d}.wav", кусок)
        номера = [i for i, ч in enumerate(чьи) if ч == н - 1]
        найдено = sum(1 for i in номера if i in пары) / len(номера)
        услышано = " ".join(слышно[пары[i]][0] for i in номера if i in пары)
        порог = стр.get("сходство от", V.ПОХОЖЕ)
        плохо = плохо or найдено < порог
        отчёт.append({"строка": н, "текст": стр["текст"], "с": round(резы[н - 1], 2), "по": round(резы[н], 2), "окно до": 0,
                      "скорость": 1.0, "слышно": услышано, "сходство": round(найдено, 2)})
        print(f"{н:02d} {стр.get('ид', ''):<6} {резы[н - 1]:6.2f}–{резы[н]:6.2f}  {len(кусок) / Ч:4.2f} с  слова {найдено:.2f}"
              + ("" if найдено >= порог else "  ← НЕ ВСЕ СЛОВА") + f"  | {стр['текст']}")
    (папка / "отчёт.json").write_text(json.dumps(отчёт, ensure_ascii=False, indent=1), encoding="utf-8")
    print(f"\nзапись {len(с) / Ч:.1f} с одним запросом, манера {манера}")
    sys.exit(1 if плохо else 0)


if __name__ == "__main__":
    main()
