# Выравнивание фона снимка под цвет страницы: python flat.py <снимок> <куда.jpg> <цвет #RRGGBB> <ширина>
# Фон снимка от модели неровный: светлее в середине, темнее к углам. Кадр ролика одного цвета,
# поэтому край снимка виден прямоугольником. Здесь по пикселям фона строится гладкая поверхность
# и снимок делится на неё: фон становится ровно цветом страницы, герой меняется незаметно.
import sys

import numpy as np
from PIL import Image

откуда, куда, цвет, ширина = sys.argv[1], sys.argv[2], sys.argv[3], int(sys.argv[4])
страница = np.array([int(цвет[i:i + 2], 16) for i in (1, 3, 5)], dtype=np.float64)

к = Image.open(откуда).convert("RGB")
к = к.resize((ширина, round(к.height * ширина / к.width)), Image.LANCZOS)
а = np.asarray(к, dtype=np.float64)
В, Ш, _ = а.shape

# фон: близко к цвету рамки снимка и без резких перепадов
рамка = np.concatenate([а[:40].reshape(-1, 3), а[:, :40].reshape(-1, 3), а[:, -40:].reshape(-1, 3)])
опора = np.median(рамка, axis=0)
даль = np.abs(а - опора).max(axis=2)
серое = а.mean(axis=2)
перепад = np.abs(np.gradient(серое)[0]) + np.abs(np.gradient(серое)[1])
фон = (даль < 26) & (перепад < 2.5)

шаг = 6
ys, xs = np.mgrid[0:В:шаг, 0:Ш:шаг]
отбор = фон[::шаг, ::шаг]
y, x = ys[отбор] / В - 0.5, xs[отбор] / Ш - 0.5
основа = np.stack([np.ones_like(x), x, y, x * x, x * y, y * y], axis=1)
Y, X = np.mgrid[0:В, 0:Ш]
Y, X = Y / В - 0.5, X / Ш - 0.5
поле = np.stack([np.ones_like(X), X, Y, X * X, X * Y, Y * Y], axis=2)

итог = np.empty_like(а)
for ц in range(3):
    коэф, *_ = np.linalg.lstsq(основа, а[::шаг, ::шаг, ц][отбор], rcond=None)
    итог[..., ц] = а[..., ц] * страница[ц] / np.clip(поле @ коэф, 120, 255)
итог = np.clip(итог, 0, 255)

# остаток неровности на самом фоне убирается: пиксель фона тянется к цвету страницы тем сильнее,
# чем он к ней ближе; тень под героем и сам герой остаются как были
близость = np.clip(1 - np.abs(итог - страница).max(axis=2) / 14, 0, 1)[..., None]
итог = итог * (1 - близость) + страница * близость

Image.fromarray(итог.round().astype(np.uint8)).save(куда, quality=93, subsampling=0)
у = итог.round().astype(int)
print(куда.rsplit("/", 1)[-1], (Ш, В), "фона", f"{фон.mean():.0%}", "углы:",
      *["#%02X%02X%02X" % tuple(у[j, i]) for j, i in ((5, 5), (5, Ш - 6), (В - 6, 5), (В - 6, Ш - 6), (В // 2, 5))])
