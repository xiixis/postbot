# Длинный трек из короткого, без шва: python tools/loop.py <трек> <петля, с> <длина, с> <куда>
#
# Наши треки по 15–29 секунд, и конец у них затухает. Если ролик длиннее, простой повтор даёт
# слышный провал на стыке (владелец, 02.10.2026: «на 29 секунде странное затухание»).
# Здесь берётся отрезок «петля» — целое число тактов до затухания — и повторы стыкуются внахлёст.
# Итог — обычный файл нужной длины: в сценарии он ставится в "музыка" как любой другой трек.
# Склейку внутри tools/sound.py не делать: вместе с регулировкой громкости она обрывала музыку
# после первого повтора, и это было слышно только владельцу.
#
# После сборки печатается громкость по пятисекундным отрезкам: провал виден числом.
import subprocess
import sys

import numpy as np

НАХЛЁСТ = 0.35


def main():
    трек, петля, длина, куда = sys.argv[1], float(sys.argv[2]), float(sys.argv[3]), sys.argv[4]
    число = int(длина // петля) + 1
    граф = [f"[0:a]asplit={число}" + "".join(f"[p{к}]" for к in range(число))]
    for к in range(число):
        вход = f"afade=t=in:st=0:d={НАХЛЁСТ}," if к else ""
        мс = round(к * петля * 1000)
        граф.append(f"[p{к}]atrim=0:{петля + НАХЛЁСТ},asetpts=PTS-STARTPTS,{вход}afade=t=out:st={петля}:d={НАХЛЁСТ},adelay={мс}|{мс}[q{к}]")
    граф.append("".join(f"[q{к}]" for к in range(число)) + f"amix=inputs={число}:duration=longest:normalize=0[o]")
    subprocess.run(["ffmpeg", "-v", "error", "-y", "-i", трек, "-filter_complex", ";".join(граф), "-map", "[o]",
                    "-t", str(длина), "-c:a", "aac", "-b:a", "192k", куда], check=True)
    сырой = subprocess.run(["ffmpeg", "-v", "error", "-i", куда, "-ac", "1", "-ar", "8000", "-f", "f32le", "-"], capture_output=True).stdout
    а = np.frombuffer(сырой, dtype=np.float32)
    шаг = 8000 * 5
    дб = [20 * np.log10(max(1e-6, float(np.sqrt(np.mean(а[н:н + шаг] ** 2))))) for н in range(0, len(а) - шаг + 1, шаг)]
    print(f"{куда}: {len(а) / 8000:.1f} с, по 5 секунд, дБ: " + " ".join(f"{x:.0f}" for x in дб))
    if max(дб) - min(дб) > 6:
        raise SystemExit("громкость гуляет больше чем на 6 дБ: проверить петлю")


if __name__ == "__main__":
    main()
