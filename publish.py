# -*- coding: utf-8 -*-
"""Отправка готового поста в канал.

Вынесено отдельно от core намеренно. core тянет за собой рисование карточек и
генерацию картинок, а вместе с ними Chromium, numpy и Pillow. Публикация же
нужна и на Vercel, где ничего этого нет и быть не может: там только сеть и
база. Поэтому здесь ровно то, что умеет работать где угодно.
"""

import json
from datetime import datetime

import channels
import config
import db
import storage
import stream
import telegram as tg
import times

ТИХО = "тихо"          # общий выключатель звука, переживает перезапуск


def звук_выключен() -> bool:
    return bool(db.настройка(ТИХО, False))


def переключить_звук() -> bool:
    """Возвращает новое состояние: True это «всегда тихо»."""
    стало = not звук_выключен()
    db.запомнить(ТИХО, стало)
    return стало


def без_звука(когда: datetime | None = None) -> bool:
    """Уходит ли пост без уведомления.

    Два повода, и они складываются. Ручной выключатель, когда владелец решил
    не дёргать людей вообще. И ночь: десять тысяч уведомлений в три часа ночи
    стоят дороже любого поста, поэтому с 23:00 до 8:00 тихо всегда, даже когда
    звук включён.
    """
    час = (когда or times.сейчас()).hour
    return звук_выключен() or not (8 <= час < 23)


ПОДПИСЬ = "Подписаться"
ССЫЛКА = "subscribe_link"      # куда ведёт «Подписаться», задаётся владельцем


def ссылка_подписки() -> str:
    """Адрес для кнопки «Подписаться».

    Хранится в настройках, а не в коде: пригласительная ссылка может смениться,
    а перевыкладывать ради этого приложение незачем. Если её не задали, ведём
    на публичный адрес основного канала.
    """
    свой = (db.настройка(ССЫЛКА, "") or "").strip()
    if свой:
        return свой
    return f"https://t.me/{channels.основной().lstrip('@')}"


def футер(текст: str) -> str:
    """Дописывает призыв подписаться со ссылкой на канал.

    Делается здесь, а не моделью: подпись обязана быть в каждом посте и всегда
    одинаковой, а модель то забудет, то перефразирует. Ссылка ведёт на основной
    канал, потому что посты пересылают, и человек из пересылки должен попасть
    туда, а не в тестовый.

    Значок 🔔 выбран не случайно: он есть в наборе канала, и в посте станет
    фирменной иконкой.
    """
    if ПОДПИСЬ in текст:
        return текст                      # уже дописано, второй раз не нужно
    return f"{текст}\n\n🔔 [{ПОДПИСЬ}]({ссылка_подписки()})"


class ЧастичноВышло(RuntimeError):
    """Часть площадок приняла пост, часть отказала.

    Это не провал: где-то пост уже вышел, и повторять его туда нельзя. Тот,
    кто ловит эту ошибку, обязан считать публикацию состоявшейся и лишь
    сообщить, куда не доехало.
    """


def площадка(пост) -> str:
    """Куда едет этот пост. По умолчанию телеграм: так было всегда."""
    return (db.карточка(пост) or {}).get("площадка") or "телеграм"


def площадка_готова(куда: str) -> bool:
    """Можно ли сейчас публиковать на эту площадку."""
    if куда != "tiktok":
        return True
    try:
        import tiktok
        return tiktok.настроен()
    except Exception:                                        # noqa: BLE001
        return False


def куда_едет(пост) -> list[str]:
    """Список площадок поста. Пусто означает телеграм: так было всегда."""
    свои = (db.карточка(пост) or {}).get("куда")
    if isinstance(свои, list) and свои:
        return свои
    одна = (db.карточка(пост) or {}).get("площадка")
    return [одна] if одна else ["телеграм"]


def назначить(ид: int, куда: list[str]) -> None:
    """Запоминает, куда пост поедет. Одна площадка или несколько."""
    import площадки as пл
    ряд = db.взять(ид)
    поля = db.карточка(ряд)
    поля["куда"] = [к for к in куда if к in пл.СПИСОК] or ["телеграм"]
    db.правка(ид, card=json.dumps(поля, ensure_ascii=False))


def в_тикток(ид: int, кем: str | None = None) -> str:
    """Публикует карусель в TikTok. Возвращает номер публикации у них.

    У TikTok нет отложенных публикаций на его стороне, поэтому пост выходит
    ровно в тот момент, когда мы его отдали. Значит расписание держим сами, и
    мак в это время должен быть включён.
    """
    import tiktok
    import варианты
    пост = db.взять(ид)
    в = варианты.получить(ид, "tiktok")
    if not в["images"]:
        raise ValueError("в TikTok нечего публиковать: у поста нет слайдов")
    номер = tiktok.опубликовать(в.get("title") or пост["title"],
                                в["body"], в["images"])
    итог = tiktok.дождаться(номер)
    if итог.startswith("FAILED"):
        raise ValueError(f"TikTok отклонил публикацию: {итог}")
    return f"{номер} · {итог}"


def в_сеть(ид: int, куда: str) -> str:
    """X и Threads: там всё проще, картинки и короткий текст."""
    import варианты
    в = варианты.получить(ид, куда)
    if куда == "x":
        import x
        return x.опубликовать(в["body"], в["images"])
    import threads
    return threads.опубликовать(в["body"], в["images"])


def в_площадку(ид: int, куда: str, кем: str | None = None) -> str:
    """Одна доставка в одно место. Возвращает след: адрес или номер.

    Здесь же и только здесь решается, чем именно публиковать. Всё остальное
    в боте и приложении говорит «отправь туда-то» и не знает подробностей.
    """
    import варианты
    if куда == "телеграм":
        номер = _в_телеграм(ид, кем)
        след = str(номер)
    elif куда == "tiktok":
        след = в_тикток(ид, кем)
    else:
        след = в_сеть(ид, куда)
    варианты.отметить(ид, куда, след)
    return след


def через_аккаунт() -> bool:
    """Можно ли публиковать от вашего аккаунта.

    От аккаунта лучше по двум причинам: фирменные иконки, которых боту
    Telegram не даёт, и отложенные посты, которые он публикует сам. Но на
    Vercel файла сессии нет, и там остаётся обычный путь через бота.
    """
    try:
        import userbot
        return userbot.вошли()
    except Exception:                                        # noqa: BLE001
        return False


def отложить(ид: int, когда) -> int:
    """Отдаёт пост телеграму в отложенные. Возвращает его номер там."""
    import userbot
    пост = db.взять(ид)
    if not пост:
        raise ValueError("черновика уже нет")
    слайды = db.картинки(пост)
    if слайды:
        return userbot.альбом(channels.текущий(), слайды, футер(пост["body"]), когда)
    return userbot.отложить(channels.текущий(), футер(пост["body"]),
                            пост["image_path"], когда)


def снять_у_телеграма(пост) -> None:
    """Забирает пост из отложенных: перенос и отмена начинаются с этого.

    Молчать об ошибке здесь нельзя. Если пост остался в очереди телеграма, а
    мы его опубликовали, он выйдет второй раз в назначенный час. Поэтому не
    получилось, значит дальше идти нельзя.
    """
    номер = пост["tg_sched_id"] if "tg_sched_id" in пост.keys() else None
    if not номер:
        return
    if not через_аккаунт():
        raise ValueError("этот пост лежит в отложенных телеграма, "
                         "забрать его оттуда может только мак")
    import userbot
    userbot.отменить(пост["channel"] or channels.текущий(), [int(номер)])


def userbot_альбом(куда: str, слайды: list, тело: str) -> int:
    import userbot
    return userbot.альбом(куда, слайды, тело, None)


def _доложить(кем: str | None, куда: str, пост) -> None:
    """Владелец узнаёт о чужой публикации сразу: канал общий, отвечает он."""
    if not кем:
        return
    try:
        tg.написать(config.АДМИН,
                    f"📣 {кем} опубликовал в {куда}: {пост['title']}", разметка="")
    except Exception:                                        # noqa: BLE001
        pass


def опубликовать(ид: int, кем: str | None = None,
                 куда: list[str] | None = None) -> int:
    """Отправляет пост туда, куда он назначен. Возвращает номер в телеграме.

    Площадок может быть несколько, и падение одной не должно отменять
    остальные: TikTok может отказать по своим правилам, а телеграму до этого
    дела нет. Поэтому ошибки собираются и бросаются одной в конце, когда
    удачные доставки уже сделаны и записаны.
    """
    пост = db.взять(ид)
    if not пост:
        raise ValueError("черновика уже нет")
    if пост["status"] == "published":
        raise ValueError("этот пост уже публиковался")

    цели = куда or куда_едет(пост)
    номер, беды = 0, []
    for цель in цели:
        try:
            след = в_площадку(ид, цель, кем)
            if цель == "телеграм":
                номер = int(след or 0)
        except Exception as e:                               # noqa: BLE001
            import площадки as пл
            беды.append(f"{пл.имя(цель)}: {str(e)[:160]}")

    if len(беды) == len(цели):
        raise ValueError("; ".join(беды))       # не ушло никуда, это провал
    db.отметить_опубликованным(ид, номер, channels.текущий()
                               if "телеграм" in цели else цели[0])
    if беды:
        raise ЧастичноВышло("; ".join(беды))
    return номер


def _в_телеграм(ид: int, кем: str | None = None) -> int:
    """Доставка в канал. Возвращает message_id или бросает исключение.

    `кем` это имя человека, если публиковал не владелец. Канал общий, но
    отвечает за него владелец, поэтому о чужой публикации он узнаёт сразу.
    """
    пост = db.взять(ид)
    снять_у_телеграма(пост)          # если лежал в отложенных, забираем оттуда
    клавиатура = stream.кнопки() if пост["rubric"] == "стрим" else None
    тихо = без_звука()
    куда = channels.текущий()
    слайды = db.картинки(пост)

    # Карусель уходит группой снимков. Кнопок под группой телеграм не
    # показывает вовсе, поэтому выбора между кнопками и иконками тут нет.
    if слайды:
        тело = футер(пост["body"])
        if через_аккаунт():
            номер = userbot_альбом(куда, слайды, тело)
        else:
            ссылки = [с if с.startswith("http") else storage.во_временный(с)
                      for с in слайды]
            номер = int(tg.альбом(куда, ссылки, тело, тихо).get("message_id", 0))
        _доложить(кем, куда, пост)
        return номер

    # От аккаунта, если можем и если кнопки не нужны: только так в посте
    # остаются иконки канала. Пост с кнопками идёт другим путём, ниже.
    if через_аккаунт() and not клавиатура:
        import userbot
        номер = userbot.отложить(куда, футер(пост["body"]), пост["image_path"], None)
        _доложить(кем, куда, пост)
        return номер
    # Карточка из хранилища уходит ссылкой: так работает и там, где нет диска.
    картинка = пост["image_path"]
    if картинка and not картинка.startswith("http"):
        картинка = storage.во_временный(картинка)
    тело = футер(пост["body"])
    if картинка:
        ответ = tg.фото(куда, картинка, тело, клавиатура, тихо)
    else:
        ответ = tg.написать(куда, тело, клавиатура, тихо=тихо)

    message_id = int(ответ.get("message_id", 0))

    # Пост ушёл ботом ради кнопок, значит иконок в нём нет. Дописываем их
    # правкой от аккаунта: кнопки правка не трогает.
    if клавиатура and через_аккаунт() and message_id:
        try:
            import userbot
            userbot.дописать_иконки(куда, message_id, футер(пост["body"]))
        except Exception:                                    # noqa: BLE001
            pass          # иконки украшают, а пост уже вышел, это не повод падать

    _доложить(кем, куда, пост)
    return message_id


def сверить_с_телеграмом() -> int:
    """Приводит нашу базу в согласие с очередью телеграма.

    Пост можно снять прямо в телеграме, и тогда наша база продолжит показывать
    план, которого уже нет. Обратное тоже бывает: телеграм опубликовал пост, а
    мы об этом не узнали. Сверка возвращает число расхождений, которые
    поправили.
    """
    if not через_аккаунт():
        return 0
    import userbot
    расхождений = 0
    # Действуем только со второго промаха подряд. Очередь телеграма может
    # прийти неполной или пустой по случайной причине, и снять с плана живой
    # пост из-за одного такого ответа страшнее, чем узнать о снятии на пять
    # минут позже.
    прежние = set(db.настройка("sync_misses", []) or [])
    промахи = set()
    план = [п for п in db.расписание()
            if (п["tg_sched_id"] if "tg_sched_id" in п.keys() else None)]
    по_каналам: dict[str, list] = {}
    for п in план:
        по_каналам.setdefault(п["channel"] or channels.текущий(), []).append(п)

    for канал, посты in по_каналам.items():
        try:
            живые = {номер for номер, _ in userbot.отложенные(канал)}
        except Exception:                                    # noqa: BLE001
            continue
        for п in посты:
            if int(п["tg_sched_id"]) in живые:
                continue
            ид = int(п["id"])
            if ид not in прежние:
                промахи.add(ид)              # первый промах, запоминаем и ждём
                continue
            # Из очереди телеграма пост исчез дважды подряд. Либо вышел, либо
            # его сняли руками. Отличить можно по времени: прошло, значит вышел.
            вышло = times.из_базы(п["scheduled_at"]) <= times.сейчас()
            if вышло:
                # Настоящий номер ищется в канале: раньше здесь писался 0, все такие посты
                # слипались под ним, и охват по ним не собирался никогда (аудит 25.09.2026).
                # Не нашли — пусто, а не ноль: сбор охвата такой пост просто пропустит.
                try:
                    номер = userbot.найти_вышедший(канал, times.из_базы(п["scheduled_at"]),
                                                   футер(п["body"]))
                except Exception:                            # noqa: BLE001
                    номер = None
                db.отметить_опубликованным(ид, номер, канал)
            else:
                db.снять_с_плана(ид)
            расхождений += 1
    db.запомнить("sync_misses", sorted(промахи))
    return расхождений


ПРОСРОЧКА = 3 * 3600      # сколько ждёт пост, если бот в это время не работал


def догнать_расписание() -> list[dict]:
    """Публикует всё, чему пришло время. Зовётся на каждом круге опроса.

    Два случая, которые легко перепутать. Опоздание на минуты, бот просто был
    занят, тогда публикуем. Опоздание на часы, бота выключали, тогда НЕ
    публикуем: утренний пост, вышедший ночью, хуже невышедшего. Такой
    возвращается в черновики, и владелец решает сам.
    """
    сделано = []
    сейчас = times.сейчас()
    for пост in db.созревшие(times.в_базу(сейчас)):
        ид = int(пост["id"])
        опоздание = (сейчас - times.из_базы(пост["scheduled_at"])).total_seconds()
        if опоздание > ПРОСРОЧКА:
            db.снять_с_плана(ид)
            сделано.append({"id": ид, "итог": "просрочен",
                            "часов": round(опоздание / 3600)})
            continue
        # Боты на двух машинах смотрят в одну базу: публикует тот, кто первым взял замок.
        if not db.захватить_публикацию(ид):
            сделано.append({"id": ид, "итог": "занят"})
            continue
        try:
            опубликовать(ид)
            сделано.append({"id": ид, "итог": "вышел"})
        except Exception as e:                               # noqa: BLE001
            сделано.append({"id": ид, "итог": "ошибка", "текст": str(e)[:200]})
        finally:
            db.отпустить_публикацию(ид)
    return сделано
