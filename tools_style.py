def обзор(замеры: dict, матрица: dict) -> str:
    """README библиотеки: таблица стилей, пары-дубли, полная матрица."""
    пары = {}
    for а, соседи in матрица.items():
        for б, з in соседи.items():
            пары[tuple(sorted([а, б]))] = з
    по_убыванию = sorted(пары.items(), key=lambda п: -п[1]["общая"])
    дубли = [(п, з) for п, з in по_убыванию if з["общая"] >= 95]
    рядом = [(п, з) for п, з in по_убыванию if 90 <= з["общая"] < 95]

    с = ["# Библиотека стилей", "",
         f"Собрано `tools_style.py` {date.today().strftime('%d.%m.%Y')}. "
         f"Папка на каждый из {len(card.ДИЗАЙНЫ)} дизайнов: паспорт по одиннадцати "
         "пунктам, числа стиля в `токены.json`, живой пример и замеры.", "",
         "Все стили рисуют **один и тот же пост**, поэтому папки сравнимы между "
         "собой: разница в кадрах — это разница стилей, а не текста.", "",
         "## Что здесь лежит", "",
         "| файл | что это |", "|---|---|",
         "| `ПАСПОРТ.md` | одиннадцать пунктов дизайн-системы, замеры, схожесть, источник |",
         "| `токены.json` | числа стиля, вынутые из его CSS: палитра, кегли, радиусы, границы, тени |",
         "| `лист.jpg` | четыре кадра в ряд — быстрый взгляд |",
         "| `кадры/` | те же кадры по отдельности, шириной 1080 |", "",
         "## Стили", "",
         "| стиль | в ротации | тон | контраст | акцент | чернила | ближайший сосед |",
         "|---|---|---|---|---|---|---|"]
    for имя in card.ДИЗАЙНЫ:
        з = замеры.get(имя, {}).get("1-обложка", {})
        сосед = next(iter(матрица.get(имя, {}).items()), None)
        текст_соседа = f"{сосед[0]} {сосед[1]['общая']}%" if сосед else "—"
        с.append(f"| [{имя}]({имя}/ПАСПОРТ.md) | "
                 f"{'да' if имя in форматы.ДИЗАЙНЫ_ОК else 'нет'} | "
                 f"{з.get('фон', '—')} | {з.get('контраст', '—')}:1 | "
                 f"{з.get('акцент', '—')}% | {з.get('чернила', '—')}% | {текст_соседа} |")

    # Отдельная сводка по акценту: она видна только когда все стили рядом.
    по_кадрам = {}
    for имя, з in замеры.items():
        for кадр, знач in з.items():
            по_кадрам.setdefault(кадр, []).append((знач["акцент"], имя))
    с += ["", "## Что показали замеры", "",
          "Норма доли акцента — 4–6% площади кадра: меньше 2% не видно с "
          "расстояния ленты, больше 8% перестаёт быть акцентом. Вот как она "
          "разложилась по кадрам у всех пятнадцати стилей:", "",
          "| кадр | среднее | самый скупой | самый щедрый |", "|---|---|---|---|"]
    for кадр, значения in по_кадрам.items():
        значения.sort()
        среднее = sum(з for з, _ in значения) / len(значения)
        с.append(f"| {кадр.split('-')[1]} | {среднее:.1f}% | "
                 f"{значения[0][1]} {значения[0][0]}% | {значения[-1][1]} {значения[-1][0]}% |")
    с += ["",
          "Видно две вещи, которых по одному стилю не заметишь. Обложки почти "
          "лишены акцента — доли процента вместо четырёх: лайм там живёт тонкой "
          "линейкой и подписью «листайте». А кадр «правка» у части стилей "
          "перебирает вдвое: подсветка ключевых слов занимает площадь целой "
          "плашки. Это не поломка, кадры выпускаются и принимаются — но если "
          "обложки станут цеплять хуже, смотреть надо сюда.", ""]

    с += ["", "## Схожесть: где стили повторяют друг друга", "",
          "Считается по отрисованным кадрам, не на глаз. Структура (куда легли "
          "чернила: пятно заголовка, карточки, линейки) весит 0,6; палитра — 0,4. "
          "В ленте кадр уменьшен втрое, и первым читается именно устройство.", ""]

    if дубли:
        с += ["### Расхождение меньше 5% — это один дизайн", "",
              "| пара | схожесть | расхождение | структура | палитра |", "|---|---|---|---|---|"]
        for (а, б), з in дубли:
            с.append(f"| **{а} ↔ {б}** | {з['общая']}% | {round(100 - з['общая'], 1)}% | "
                     f"{з['структура']}% | {з['палитра']}% |")
        с += [""]
    else:
        с += ["Пар с расхождением меньше 5% нет.", ""]

    if рядом:
        с += ["### Рядом с порогом (5–10% расхождения)", "",
              "| пара | схожесть | расхождение |", "|---|---|---|"]
        for (а, б), з in рядом:
            с.append(f"| {а} ↔ {б} | {з['общая']}% | {round(100 - з['общая'], 1)}% |")
        с += [""]

    с += ["### Полная матрица, по убыванию", "",
          "<details><summary>Все 105 пар</summary>", "",
          "| пара | общая | структура | палитра |", "|---|---|---|---|"]
    for (а, б), з in по_убыванию:
        с.append(f"| {а} ↔ {б} | {з['общая']}% | {з['структура']}% | {з['палитра']}% |")
    с += ["", "</details>", "",
          "## Как пересобрать", "",
          "```sh",
          "python3 tools_style.py            # всё: отрисовка, замеры, паспорта",
          "python3 tools_style.py --мерить   # только замеры и схожесть",
          "python3 tools_style.py --собрать  # только паспорта и README",
          "```", "",
          "Отрисовка идёт через прогретый браузер и занимает около половины минуты "
          "на все пятнадцать. Источник правды — `card.ДИЗАЙНЫ` и `форматы.py`: "
          "правим там, потом пересобираем.", ""]
    return "\n".join(с)


def main():
    аргументы = sys.argv[1:]
    этапы = [а for а in аргументы if а.startswith("--")]
    имена = [а for а in аргументы if not а.startswith("--")] or list(card.ДИЗАЙНЫ)
    ПАПКА.mkdir(parents=True, exist_ok=True)

    if not этапы or "--рисовать" in этапы:
        for н, имя in enumerate(имена, 1):
            print(f"[{н}/{len(имена)}] рисую {имя}", flush=True)
            рисовать(имя)

    if not этапы or "--мерить" in этапы:
        все = list(card.ДИЗАЙНЫ)
        замеры = {и: замерить(и) for и in все}
        отпечатки = {и: отпечаток(и) for и in все}
        матрица = {}
        for и in все:
            if отпечатки[и] is None:
                continue
            пары = {д: схожесть(отпечатки[и], отпечатки[д])
                    for д in все if д != и and отпечатки[д] is not None}
            матрица[и] = dict(sorted(пары.items(), key=lambda п: -п[1]["общая"]))
        (ПАПКА / "замеры.json").write_text(
            json.dumps({"замеры": замеры, "схожесть": матрица,
                        "собрано": date.today().isoformat()},
                       ensure_ascii=False, indent=2), encoding="utf-8")
        print(f"замерено дизайнов: {len(замеры)}, пар сравнения: "
              f"{sum(len(п) for п in матрица.values()) // 2}")

    if not этапы or "--собрать" in этапы:
        данные = json.loads((ПАПКА / "замеры.json").read_text(encoding="utf-8"))
        замеры, матрица = данные["замеры"], данные["схожесть"]
        for имя in card.ДИЗАЙНЫ:
            папка = ПАПКА / имя
            папка.mkdir(exist_ok=True)
            if референс(имя):
                print(f"  {имя}: кадры источника скопированы")
            т = токены(имя, замеры.get(имя, {}))
            (папка / "токены.json").write_text(
                json.dumps(т, ensure_ascii=False, indent=2), encoding="utf-8")
            (папка / "ПАСПОРТ.md").write_text(
                паспорт(имя, т, замеры.get(имя, {}), матрица.get(имя, {})), encoding="utf-8")
        (ПАПКА / "README.md").write_text(обзор(замеры, матрица), encoding="utf-8")
        print(f"собрано папок: {len(card.ДИЗАЙНЫ)}")
    print("готово")


if __name__ == "__main__":
    main()
