def страницы(имя: str) -> list[tuple]:
    """HTML четырёх кадров без снимка: _снять подменён записью."""
    фон = форматы.СВОЙ_ФОН.get(имя, "сетка")
    снято = []
    было = card._снять
    card._снять = lambda стр, ш=1280, в=720: снято.append((стр, ш, в))
    try:
        card.слайд_обложка(*ОБЛОЖКА, None, 1, ВСЕГО, ФОРМАТ, дизайн=имя, оформление=фон)
        кадры = [снято[-1]]
        for вид, номер, поля in КАДРЫ:
            кадры.append(card.страница_вида(вид, поля, номер, ВСЕГО, ФОРМАТ,
                                            оформление=фон, дизайн=имя))
        card.слайд_финал(ВЫВОД, ВСЕГО, ВСЕГО, ФОРМАТ, ПРИЗЫВ, дизайн=имя, оформление=фон)
        кадры.append(снято[-1])
    finally:
        card._снять = было
    return кадры


def рисовать(имя: str) -> None:
    """Четыре кадра в полном размере плюс лист для быстрого взгляда."""
    import tempfile

    import браузер
    from PIL import Image

    папка = ПАПКА / имя / "кадры"
    папка.mkdir(parents=True, exist_ok=True)
    ш, в, о = 405, 540, 14
    лист = Image.new("RGB", (4 * ш + 5 * о, в + 2 * о), (28, 30, 23))
    with tempfile.TemporaryDirectory() as врем:
        for н, (стр, ширина, высота) in enumerate(страницы(имя)):
            png = Path(врем) / f"{н}.png"
            if not браузер.снять(стр, ширина, высота, png):
                raise RuntimeError(f"{имя}: кадр {н + 1} не снялся")
            with Image.open(png) as к:
                кадр = к.convert("RGB")
                # Полный кадр кладём ужатым по ширине до 1080: крупнее площадки
                # всё равно не принимают, а папка стиля не должна весить лишнего.
                доля = 1080 / кадр.width
                кадр.resize((1080, round(кадр.height * доля)), Image.LANCZOS).save(
                    папка / f"{ИМЕНА_КАДРОВ[н]}.jpg", quality=90)
                лист.paste(кадр.resize((ш, в), Image.LANCZOS), (о + н * (ш + о), о))
    лист.save(ПАПКА / имя / "лист.jpg", quality=90)


def замерить(имя: str) -> dict:
    """Кадр против наших порогов. Пороги сняты на живых кадрах, см. скил
    «визуал-слайдов»: контраст не ниже 8:1, акцент 4–6% площади, чернил 8–15%.

    Меряем все четыре кадра, а не обложку с одним разворотом. Сначала так и
    было — и доля акцента вышла 0,1–0,3% у всех пятнадцати, будто лайма в
    кадрах нет вовсе. Дело не в дизайнах: акцент живёт на кадрах «правка» и
    «финал» (подсветка, плашка призыва), а обложка держит воздух. Замер по
    двум кадрам из четырёх такую картину просто не видел.
    """
    import numpy as np
    from PIL import Image

    итог = {}
    for имя_кадра in ИМЕНА_КАДРОВ:
        путь = ПАПКА / имя / "кадры" / f"{имя_кадра}.jpg"
        if not путь.exists():
            continue
        with Image.open(путь) as к:
            п = np.asarray(к.convert("RGB"), dtype=np.float32) / 255.0

        # Относительная яркость по WCAG: сначала снимаем гамму sRGB.
        линейно = np.where(п <= 0.04045, п / 12.92, ((п + 0.055) / 1.055) ** 2.4)
        L = 0.2126 * линейно[..., 0] + 0.7152 * линейно[..., 1] + 0.0722 * линейно[..., 2]

        # Фон — самый частый тон кадра; текст — то, что от него дальше всего.
        гисто, края = np.histogram(L, bins=64, range=(0, 1))
        фон_L = float((края[гисто.argmax()] + края[гисто.argmax() + 1]) / 2)
        далёкие = np.abs(L - фон_L) > 0.25
        текст_L = float(np.median(L[далёкие])) if далёкие.any() else фон_L
        светлее, темнее = max(фон_L, текст_L), min(фон_L, текст_L)
        контраст = (светлее + 0.05) / (темнее + 0.05)

        # Доля акцента: считаем по оттенку, а не по точному совпадению цвета —
        # лайм на кадре живёт с тенями, свечением и полупрозрачностью.
        R, G, B = п[..., 0], п[..., 1], п[..., 2]
        лайм = (G > 0.45) & (G > B * 1.25) & (R > B * 1.05) & (G - B > 0.12)
        ржавый = (R > 0.45) & (R > G * 1.25) & (R > B * 1.3)
        акцент = float((лайм | ржавый).mean() * 100)

        # Чернила: доля площади, заметно отличающейся от фона. Это и текст,
        # и линейки, и карточки — всё, что «нарисовано» поверх холста.
        чернила = float((np.abs(L - фон_L) > 0.12).mean() * 100)

        итог[имя_кадра] = {"контраст": round(контраст, 1), "акцент": round(акцент, 2),
                           "чернила": round(чернила, 1),
                           "фон": "светлый" if фон_L > 0.5 else "тёмный"}
    return итог


def отпечаток(имя: str):
    """Два отпечатка кадра: структура и палитра. Их считают отдельно, потому
    что стили расходятся по-разному: «журнал» и «минимал» похожи палитрой, но
    не устройством, а «швейцарский» с «терминалом» — наоборот.
    """
    import numpy as np
    from PIL import Image

    структуры, палитры = [], []
    for имя_кадра in ИМЕНА_КАДРОВ:
        путь = ПАПКА / имя / "кадры" / f"{имя_кадра}.jpg"
        if not путь.exists():
            continue
        with Image.open(путь) as к:
            # Структура: куда легли чернила. Мелкая сетка 24x32 — это уже не
            # буквы, а пятна текста, линейки и карточки, то есть устройство кадра.
            серый = np.asarray(к.convert("L").resize((24, 32), Image.LANCZOS), dtype=np.float32)
            серый = (серый - серый.mean()) / (серый.std() + 1e-6)
            структуры.append(серый.ravel())
            # Палитра: огрублённая гистограмма цвета, нормированная по площади.
            мал = np.asarray(к.convert("RGB").resize((64, 85), Image.LANCZOS))
            кубы = (мал // 64).reshape(-1, 3)
            гисто = np.zeros(64, dtype=np.float32)
            np.add.at(гисто, кубы[:, 0] * 16 + кубы[:, 1] * 4 + кубы[:, 2], 1)
            палитры.append(гисто / гисто.sum())
    if not структуры:
        return None
    return np.concatenate(структуры), np.concatenate(палитры)


def схожесть(а, б) -> dict:
    """Насколько два дизайна читаются как один. Числа от 0 до 100."""
    import numpy as np

    стр_а, пал_а = а
    стр_б, пал_б = б
    структура = float(np.dot(стр_а, стр_б) / (np.linalg.norm(стр_а) * np.linalg.norm(стр_б)))
    структура = max(0.0, структура) * 100
    палитра = float(np.minimum(пал_а, пал_б).sum() / len(ИМЕНА_КАДРОВ)) * 100
    # Вес структуры выше: в ленте кадр уменьшен втрое, и первым читается
    # устройство — где пятно заголовка, есть ли карточки, куда идут линейки.
    общая = 0.6 * структура + 0.4 * палитра
    return {"структура": round(структура, 1), "палитра": round(палитра, 1),
            "общая": round(общая, 1)}


def референс(имя: str) -> bool:
    """Кладёт кадры чужого источника рядом со стилем.

    Копией, а не ссылкой: папка стиля должна открываться и через год, когда
    исследование переедет или его вычистят. Кадры чужие — они лежат как
    материал разбора, не для выпуска.
    """
    from PIL import Image

    сведения = ИСТОЧНИКИ.get(имя)
    if not сведения:
        return False
    автор, отдача, откуда = сведения
    if not откуда.exists():
        return False
    куда = ПАПКА / имя / "референс"
    куда.mkdir(parents=True, exist_ok=True)
    взято = []
    for н, файл in enumerate(sorted(откуда.glob("*.jpg"))[:4], 1):
        with Image.open(файл) as к:
            кадр = к.convert("RGB")
            доля = min(1.0, 900 / кадр.width)
            if доля < 1.0:
                кадр = кадр.resize((900, round(кадр.height * доля)), Image.LANCZOS)
            кадр.save(куда / f"{н:02d}.jpg", quality=88)
        взято.append(файл.name)
    (куда / "ИСТОЧНИК.md").write_text("\n".join([
        f"# Источник стиля «{имя}»", "",
        f"**Автор:** {автор}" + (f"  \n**Отдача:** {отдача}" if отдача else ""), "",
        f"**Откуда взяты кадры:** `{откуда}`", "",
        "Файлы источника: " + ", ".join(f"`{н}`" for н in взято) + ".", "",
        "## Что перенесено", "",
        "Приёмы и параметры: устройство кадра, ритм, способ выделения. "
        "Наши цвета, гарнитуры и кот остались нашими.", "",
        "## Что НЕ перенесено", "",
        "Имена, тексты, фирменный приём один в один и гарнитура-подпись автора. "
        "Совпадение по ним читается как копия, а в одной нише это видят и "
        "зрители, и площадка.", "",
        "## Разборы", "",
        "- `data/выгрузка/референсы/РАЗБОР.md` — плотность по полосам, скелет кадра, приём на вынос",
        "- `исследование-тикток-карусели/БАЗА-ЗНАНИЙ.md` — восемь семейств постов и их отдача", "",
    ]), encoding="utf-8")
    return True


def токены(имя: str, замер: dict) -> dict:
    """Числа стиля, вынутые из его CSS. Не переписанные на глаз: CSS дизайна —
    единственный источник правды, и если там поменяют радиус, пересборка это
    покажет."""
    д = card.ДИЗАЙНЫ[имя]
    css = д.get("css", "")

    def все(шаблон):
        # В CSS дизайна живут подстановки `{рамка}`, `{лайм}` — их заполняет
        # card._дизайн при отрисовке. В токенах они бесполезны и читаются как
        # мусор, поэтому берём только готовые значения.
        найдено = {м.strip() for м in re.findall(шаблон, css)}
        return sorted(з for з in найдено if "{" not in з and "}" not in з)

    # Кегли в пикселях считает card.размеры_дизайна, но она берёт готовый
    # словарь размеров вёрстки, а не формат: у каждой вёрстки он свой. Поэтому
    # в токенах держим множители — они и есть то, что задаёт дизайн.
    return {
        "имя": имя,
        "что это": д.get("о", ""),
        "холст": {"формат": ФОРМАТ, "ширина": 1620, "высота": 2160},
        "в ротации": имя in форматы.ДИЗАЙНЫ_ОК,
        "палитра": {
            "основа": "канальная: фон #12130F, текст #F1F3EA, лайм #C7E24B, ржавый #E2703A",
            "тон кадров": {к: з.get("фон") for к, з in замер.items()},
            "свои цвета в CSS": все(r"#[0-9A-Fa-f]{6}"),
        },
        "гарнитуры": [{"файл": ф, "семья": с, "вес": в} for ф, с, в in д.get("фейсы", [])],
        "множители кеглей": д.get("масштаб", {}),

        "радиусы": все(r"border-radius:\s*([^;}\n]+)"),
        "границы": все(r"border(?:-\w+)?:\s*([^;}\n]+)"),
        "тени и свечения": все(r"(?:box-shadow|text-shadow|filter):\s*([^;}\n]+)"),
        "разрядка": все(r"letter-spacing:\s*([^;}\n]+)"),
        "своя обложка": "обложка" in д,
        "пилюли-метки": "пилюля" in д,
        "форматы": ["3к4", "квадрат"],
        "фон холста": форматы.СВОЙ_ФОН.get(имя, "любой из общих"),
        "замеры": замер,
    }


