def _пост(ид, заголовок, **поля):
    основа = {
        "id": ид, "link": None, "rubric": "разбор", "shape": "карусель",
        "title": заголовок, "body": заголовок, "html": заголовок,
        "status": "published", "card": {}, "image": None, "images": [],
        "when": None, "when_iso": None, "published": None, "views": None,
        "outside": {}, "reactions": None, "at_telegram": False,
        "where": [{"код": "телеграм", "имя": "✈️ Телеграм", "готова": True,
                   "выбрана": True},
                  {"код": "tiktok", "имя": "🎵 TikTok", "готова": True,
                   "выбрана": False}],
    }
    основа.update(поля)
    return основа


