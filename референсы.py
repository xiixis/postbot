# -*- coding: utf-8 -*-
"""Референсы под рерайт: ссылки из темы «Под рерайт» группы «Полезное» в базу.

Владелец кидает ссылки на чужие посты в эту тему, а Claude по слову «возьми
референс из базы» берёт оттуда и не берёт одну и ту же дважды. Здесь только
сбор: скачивание и разбор — потом, поверх той же таблицы.

Читает аккаунт владельца, а не бот: история темы хранится без срока, поэтому
всё, что пришло, пока мак спал, добирается следующим кругом, а бота не надо
делать админом группы.
"""
import re
import time
from urllib.parse import urlsplit, urlunsplit

import db

ГРУППА = -1004462031298          # «Полезное», группа с темами
ТЕМА = 14                        # «Под рерайт»; другие темы не читаем
КУРСОР = "референсы.курсор"      # номер последнего прочитанного сообщения темы
КОГДА = "референсы.когда"
РАЗ_В = 5 * 60
_АДРЕС = re.compile(r"https?://[^\s<>\"']+")


def привести(url: str) -> str:
    """Один пост — одна строка: у Instagram и TikTok отрезаются параметры.

    Один и тот же пост, скинутый с разных кадров, отличается только
    `?img_index=…&stkn=…`. Короткие vt.tiktok.com не трогаем: раскрыть их
    значит ходить в сеть, а это уже не «только запись».
    """
    url = url.strip()
    ч = urlsplit(url)
    хост = ч.netloc.lower()
    if хост.endswith("instagram.com") or хост in ("tiktok.com", "www.tiktok.com"):
        return urlunsplit((ч.scheme, хост, ч.path, "", ""))
    return url


def площадка(url: str) -> str:
    хост = urlsplit(url).netloc.lower()
    if хост.endswith("instagram.com"):
        return "instagram"
    if хост.endswith("tiktok.com"):
        return "tiktok"
    return "другое"


def ссылки(текст: str, адреса=()) -> list[str]:
    """Адреса из сущностей сообщения и из самого текста, без повторов, по порядку."""
    итог = []
    for а in [*адреса, *_АДРЕС.findall(текст or "")]:
        а = а.rstrip(").,;")
        if а not in итог:
            итог.append(а)
    return итог


def записать(сообщения: list[dict]) -> int:
    """Кладёт ссылки сообщений в базу и двигает курсор. Возвращает число новых."""
    новых, курсор = 0, db.настройка(КУРСОР, 0)
    for м in sorted(сообщения, key=lambda м: м["id"]):
        for а in ссылки(м.get("текст", ""), м.get("адреса", [])):
            а = привести(а)
            новых += db.добавить_референс(а, площадка(а), м["id"], м["дата"])
        курсор = max(курсор, м["id"])
    db.запомнить(КУРСОР, курсор)
    return новых


def сверить(читать=None) -> int:
    """Дочитывает тему после курсора. Ошибка чтения летит наружу, курсор не трогается."""
    if читать is None:
        import userbot
        if not userbot.вошли():
            return 0
        читать = lambda после: userbot.сообщения_темы(ГРУППА, ТЕМА, после)  # noqa: E731
    # Время сверки — до чтения: без сети бот иначе стучался бы в Telegram на каждом
    # круге цикла (раз в полминуты). Курсор при ошибке всё равно стоит.
    db.запомнить(КОГДА, time.time())
    сообщения = читать(db.настройка(КУРСОР, 0))
    return записать(сообщения)


def пора() -> bool:
    return time.time() - float(db.настройка(КОГДА, 0) or 0) > РАЗ_В
