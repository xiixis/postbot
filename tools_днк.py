def main():
    имена = [а for а in sys.argv[1:] if not а.startswith("--")] or list(СТИЛИ)
    ПАПКА.mkdir(parents=True, exist_ok=True)
    for н, имя in enumerate(имена, 1):
        итог = собрать_стиль(имя, СТИЛИ[имя])
        числа = итог["числа"].get("среднее", {})
        print(f"[{н}/{len(имена)}] {имя}: чужих кадров {итог['чужих']}, "
              f"наших {итог['наших']}, контраст {числа.get('контраст', '—')}:1", flush=True)
    if len(имена) == len(СТИЛИ):
        числа = собрать_якорь()
        print(f"якорь {ЯКОРЬ}: контраст {числа.get('среднее', {}).get('контраст', '—')}:1",
              flush=True)

    # Паспорта пишем из записанного json, а не из памяти прогона: так выборочная
    # пересборка одного стиля не роняет сводку по остальным.
    все = {}
    for имя in list(СТИЛИ) + [ЯКОРЬ]:
        файл = ПАПКА / имя / "днк.json"
        if файл.exists():
            все[имя] = json.loads(файл.read_text(encoding="utf-8"))
            (ПАПКА / имя / "ДНК.md").write_text(днк_страница(имя, все[имя]), encoding="utf-8")
    (ПАПКА / "README.md").write_text(сводка(все), encoding="utf-8")
    print(f"паспортов собрано: {len(все)}")
    print("готово")


if __name__ == "__main__":
    main()
