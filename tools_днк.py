ПОРОГИ = {"контраст": (8.0, None), "акцент": (4.0, 6.0),
          "крупная строка": (12.0, 15.0), "перепад": (3.0, None)}


def сверка(среднее: dict) -> list:
    """Чужие числа против наших порогов. Без вердикта «плохо»: чужой кадр не
    обязан нам подходить — важно знать, где мы его числа возьмём, а где свои."""
    итог = []
    for ключ, (низ, верх) in ПОРОГИ.items():
        если_нет = среднее.get(ключ)
        if если_нет is None:
            continue
        в_норме = если_нет >= низ if верх is None else низ <= если_нет <= верх
        норма = f"≥{низ:g}" if верх is None else f"{низ:g}–{верх:g}"
        итог.append((ключ, если_нет, норма, в_норме))
    return итог


