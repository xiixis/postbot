def замерить(папка: Path) -> dict:
    """Гоняет шаблонный `замер.py` по кадрам и разбирает его вывод в числа."""
    if not папка or not папка.exists():
        return {}
    кадры = sorted(list(папка.glob("*.jpg")) + list(папка.glob("*.png")))
    if not кадры:
        return {}
    готово = subprocess.run([ПИТОН, str(ЗАМЕР), str(папка)],
                            capture_output=True, text=True, timeout=300)
    строки, брак = [], []
    for строка in (готово.stdout or "").splitlines():
        м = re.match(r"(\d+): контраст ([\d.]+):1 \(слабых (\d+)%\) · акцент ([\d.]+)% · "
                     r"(чернила|текст) ([\d.]+)% · крупная ([\d.]+)% · перепад ([\d.]+):1 · L ([\d.]+)",
                     строка)
        if м:
            строки.append({
                "кадр": int(м.group(1)), "контраст": float(м.group(2)),
                "слабых": int(м.group(3)), "акцент": float(м.group(4)),
                "мерка чернил": м.group(5), "чернила": float(м.group(6)),
                "крупная строка": float(м.group(7)), "перепад": float(м.group(8)),
                "светлота": float(м.group(9)),
            })
        elif строка.strip().startswith("кадр "):
            брак.append(строка.strip())
    if not строки:
        return {}
    # Среднее считаем по кадрам, где замер нашёл текст. Кадр-заставка без строк
    # даёт контраст 1,0:1 и перепад 1,0:1 — включив его, мы бы занизили ДНК
    # стиля, хотя дело не в стиле, а в том, что мерить там нечего.
    с_текстом = [с for с in строки if с["крупная строка"] > 0 and с["слабых"] < 100] or строки
    сред = lambda к: round(sum(с[к] for с in с_текстом) / len(с_текстом), 1)
    светлоты = [с["светлота"] for с in строки]
    return {
        "кадров": len(строки),
        "кадров с текстом": len(с_текстом),
        "по кадрам": строки,
        "среднее": {"контраст": сред("контраст"), "акцент": сред("акцент"),
                    "крупная строка": сред("крупная строка"), "перепад": сред("перепад")},
        "ритм ленты": {"тёмных": sum(1 for с in светлоты if с < 0.4),
                       "светлых": sum(1 for с in светлоты if с >= 0.4),
                       "разброс светлоты": round(max(светлоты) - min(светлоты), 2)},
        "замечания": брак,
    }


def выжимка(путь: Path) -> dict:
    """Достаёт из разбора то, что решает: что перенесено и что нет.

    Разборы написаны по-разному — `ДИЗАЙН.md`, `паспорт.md`, докстринг
    рисовальщика, — но раздел про перенос есть почти везде, и переписывать его
    своими словами нельзя: там сказано, почему чужой приём не берут.
    """
    if not путь or not путь.exists():
        return {}
    текст = путь.read_text(encoding="utf-8", errors="replace")
    if путь.suffix == ".py":  # разбор живёт в докстринге рисовальщика
        м = re.search(r'"""(.*?)"""', текст, re.S)
        текст = м.group(1) if м else текст[:4000]
    куски = {}
    for ключ, шаблон in (("перенесено", r"##+\s*Что перенесено\s*\n(.*?)(?=\n##|\Z)"),
                         ("не перенесено", r"##+\s*Что НЕ перенесено\s*\n(.*?)(?=\n##|\Z)")):
        м = re.search(шаблон, текст, re.S | re.I)
        if м:
            куски[ключ] = " ".join(м.group(1).split())
    return куски


