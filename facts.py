# -*- coding: utf-8 -*-
"""Что бот знает о проекте прямо сейчас.

Копилка идей хранит поводы для постов, а это другое: живые значения, которые
меняются. Каналов было четыре, стало шесть; инструмент был один, стал другой.
Пост, написанный по устаревшему числу, врёт, а канал держится на обещании
настоящих цифр.

Поэтому факты лежат отдельно, переписываются поверх старых и уходят в задание
писателя. Это же снимает главное ограничение честности: выдумывать числа
по-прежнему нельзя, но ваши настоящие теперь есть откуда взять.
"""

import time

import config
import db

СХЕМА = """CREATE TABLE IF NOT EXISTS facts (
    name       TEXT PRIMARY KEY,
    value      TEXT NOT NULL,
    updated_at DOUBLE PRECISION NOT NULL
)"""


# Рубильник. Пока False, ни один факт не попадает ни в один текст: ни в посты,
# ни в карусели, ни в ответы бота. Так решил владелец — данные неполные и
# неактуальные, и пост, написанный по ним, врёт увереннее, чем пост без чисел.
#
# Записи при этом целы и правятся через веб как раньше: запрещено пользоваться
# ими, а не хранить их. Вернуть можно одним словом — поставить True, и всё
# заработает как прежде. Снимать только по прямому слову владельца.
РАЗРЕШЕНЫ = False

_ПОДГОТОВЛЕНО = False


def подготовить() -> None:
    global _ПОДГОТОВЛЕНО
    if _ПОДГОТОВЛЕНО:
        return
    запрос = СХЕМА if db.ПОСТГРЕС else СХЕМА.replace("DOUBLE PRECISION", "REAL")
    with db.соединение() as c:
        c.execute(запрос)
    _ПОДГОТОВЛЕНО = True


def запомнить(имя: str, значение: str) -> None:
    """Записывает поверх прежнего: у факта одно текущее значение."""
    имя = (имя or "").strip().lower()[:60]
    значение = (значение or "").strip()[:200]
    if not имя or not значение:
        return
    with db.соединение() as c:
        c.execute("INSERT INTO facts (name, value, updated_at) VALUES (?,?,?)"
                  " ON CONFLICT(name) DO UPDATE SET value=excluded.value,"
                  " updated_at=excluded.updated_at", (имя, значение, time.time()))


def забыть(имя: str) -> None:
    with db.соединение() as c:
        c.execute("DELETE FROM facts WHERE name=?", ((имя or "").strip().lower(),))


def все() -> list[dict]:
    with db.соединение() as c:
        ряды = c.execute("SELECT * FROM facts ORDER BY name").fetchall()
    return [{"name": р["name"], "value": р["value"],
             "updated": р["updated_at"]} for р in ряды]


def строкой() -> str:
    """Факты для задания писателю. Пусто, если их ещё нет или если запрещены."""
    if not РАЗРЕШЕНЫ:
        return ""
    список = все()
    if not список:
        return ""
    строки = "\n".join(f"• {ф['name']}: {ф['value']}" for ф in список)
    return ("\nЧТО ИЗВЕСТНО О ПРОЕКТЕ НА СЕГОДНЯ\n"
            "Это настоящие данные владельца. Ими можно и нужно пользоваться:\n"
            f"{строки}\n"
            "Бери отсюда, если к месту, и не меняй значения. Запрет на выдуманные\n"
            "числа остаётся: всё, чего здесь нет, ты по-прежнему не знаешь.\n"
            "И это ЦИФРЫ, А НЕ СОБЫТИЯ. Сослаться на них можно, а придумать "
            "вокруг них\nисторию нельзя: «я стал делать так», «мы решили», «сначала "
            "было плохо,\nпотом наладил». Ничего этого во входных данных нет, "
            "значит этого не было.\nНужна история от первого лица, её приносит "
            "владелец сам, рубрикой «от себя».\n")


def _модели():
    """Схема ответа. Pydantic ввозится здесь, а не сверху: на Vercel этого
    модуля нет и не нужно, там показатели только читают."""
    from pydantic import BaseModel, Field

    class Факт(BaseModel):
        name: str = Field(description="короткое имя показателя по-русски, "
                                      "например «каналов на ютубе»")
        value: str = Field(description="само значение, коротко: «6», «два часа»")

    class Разбор(BaseModel):
        facts: list[Факт] = Field(description="постоянные показатели проекта")

    return Разбор


ВЫДЕЛИТЬ = """\
Владелец канала про ИИ-контент написал заметку. Найди в ней ПОСТОЯННЫЕ
показатели проекта, которые полезно помнить и обновлять со временем.

Что забирать: любое значение, которое завтра может поменяться, и тогда старое
надо будет переписать. Сколько каналов, сколько роликов в неделю, чем
пользуется, сколько приносит, сколько стоит какой-то сервис, сколько людей в
команде, на какой площадке работает.

Это ПРИМЕРЫ, а не список допустимого. Показателя такого вида раньше могло не
быть вовсе, и это не повод его пропустить: «на антидетект браузер тратим 20
долларов в месяц» это новая строка, которой просто ещё нет. Заводи её.

Чего НЕ забирать: разовые события («вчера возился с обложками»), мысли,
мнения, планы, ссылки. Это не показатели, для них есть копилка идей.
Если постоянных показателей в заметке нет, верни пустой список, это нормально
и бывает чаще всего.

Имя показателя пиши так, чтобы через месяц такая же заметка дала ТО ЖЕ имя:
«каналов на ютубе», а не «количество моих каналов сейчас».

ЗАМЕТКА:
"""


def выделить(текст: str) -> dict:
    """Достаёт из заметки постоянные показатели. Пусто, если их нет."""
    if not текст or not config.агент_на_месте():
        return {}
    try:
        import агент
        найдено = агент.по_форме(текст[:1500], _модели(), система=ВЫДЕЛИТЬ,
                                 модель=config.МОДЕЛЬ_РАЗБОРА,
                                 метка="разбор заметки").facts
    except Exception:                                        # noqa: BLE001
        return {}
    return {ф.name.strip().lower(): ф.value.strip() for ф in найдено
            if ф.name.strip() and ф.value.strip()}


def обновить_из(текст: str) -> dict:
    """Выделяет показатели из заметки и сразу их записывает."""
    подготовить()
    новые = выделить(текст)
    for имя, значение in новые.items():
        запомнить(имя, значение)
    return новые
