def сочинить(рубрика: str | None, уже_было: list[str],
             формы: list[str] | None = None, тема: str | None = None,
             материал: dict | None = None, со_ссылкой: bool = True) -> Пост:
    """Новый пост. `уже_было` это прошлые темы «заголовок — суть», чтобы не повторяться."""
    if рубрика in ТРЕБУЕТ_ФАКТА and not (тема or материал):
        raise ValueError(
            "рубрика «от себя» строится вокруг настоящего случая. "
            "Напишите одной строкой, что было: «три дня возился с озвучкой, "
            "помогла ерунда» и так далее")

    # Пришёл материал со ссылкой, значит это находка: чужая вещь, которую
    # показывают людям. Рубрику владелец может задать и сам, тогда его слово
    # главнее. В рерайте рубрика обычная: пост идёт как свой материал канала,
    # и «находкой» его называть нечего, показывать-то не на что.
    if материал and со_ссылкой and not рубрика:
        рубрика = "находка"

    форма = выбрать_форму(формы or [])
    если_рубрика = (f"Рубрика задана: {рубрика}, {РУБРИКИ[рубрика]}."
                    if рубрика in РУБРИКИ else
                    "Рубрику выбери сам, ориентируясь на то, чего давно не было.")
    если_тема = (f"Тема задана владельцем: «{тема}». Пиши именно про это, "
                 "рубрику подбери под тему.\n\n" if тема else "")
    if рубрика in ТРЕБУЕТ_ФАКТА:
        если_тема = (
            f"ЭТО СЛУЧАЙ ИЗ ЖИЗНИ ВЛАДЕЛЬЦА, вот он его словами: «{тема}».\n"
            "Пиши от первого лица и опирайся ТОЛЬКО на это. Ничего не "
            "додумывай: ни сумм, ни сроков, ни подробностей, которых он не "
            "назвал. Твоя работа не выдумать историю, а рассказать эту так, "
            "чтобы её было интересно читать: начни с того, что случилось, "
            "скажи, что оказалось неудобным, и чем всё кончилось. Если "
            "кончилось ничем, так и напиши.\n\n")
    если_материал = _блок_материала(материал, со_ссылкой)
    запрет = ("\n".join(f"• {т}" for т in уже_было) or "• пока ничего не выходило")

    задача = (
        f"{если_материал}{если_тема}{если_рубрика}\n\n"
        f"Форма этого поста: {форма}, то есть {ФОРМЫ[форма]}. "
        f"В поле shape верни ровно «{форма}».\n\n"
        + ("Уже выходило, повторять нельзя ни темой, ни мыслью. После тире "
         "стоит суть прошлого поста: сравнивайте с ней, а не с заголовком — "
         f"одну и ту же мысль легко переупаковать и не заметить:\n{запрет}\n\n")
        + ("Напиши один новый пост по скелету находки: зацепка про знакомую "
           "читателю проблему, что нашлось и как называется, 2–4 конкретные "
           "вещи из материала, вывод. Польза должна быть понятна человеку, "
           "который не программирует.\n\n" if материал and со_ссылкой else
           "Напиши один новый пост по теме материала, но своим ходом мысли: "
           "своя зацепка, 2–4 конкретные полезные вещи, свой вывод. Ни слова "
           "об источнике и ни одной ссылки. Польза должна быть понятна "
           "человеку, который не программирует.\n\n" if материал else
           "Напиши один новый пост по скелету из пяти блоков. Тема должна быть "
           "полезна человеку, который не программирует.\n\n")
        +
        "Отдельно собери карточку: короткий заголовок и 3–5 пунктов, до 45 "
        "символов каждый. Карточка дополняет пост, а не пересказывает его, "
        "и ни одна её фраза не повторяет фразу из текста.\n\n"
        "Отдельно опиши позу кота под смысл именно этого поста, она рисуется "
        "заново каждый раз, поэтому не повторяй одни и те же жесты. И выбери "
        "запасную из готовых: privet, ukazyvaet, dumaet, moneta."
    )

    пост = _спросить(задача)
    if пост.shape not in ФОРМЫ:
        пост.shape = форма

    # Ссылка ставится здесь, последним движением. Внутри поста её быть не
    # должно: адрес, который модель вписала сама, вырезается вместе со своими
    # опечатками, и остаётся ровно один, тот, что прислал владелец. Не давал
    # ссылки, значит её и не будет: правило канала про посты без материала.
    тело, _ = _снять_ссылку(пост.body)
    # В рерайте ссылку не приписываем вовсе, но снять её всё равно надо: модель
    # могла вставить адрес из материала сама, и тогда источник всплыл бы в
    # посте, которого владелец как раз не хотел.
    пост.body = (_приписать_ссылку(тело, _адрес(материал, тема))
                 if со_ссылкой else тело)
    return пост
