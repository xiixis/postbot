# -*- coding: utf-8 -*-
"""Повторяющиеся публикации.

Анонс стрима нужен каждую неделю в один и тот же час, и ставить его руками
семь раз подряд бессмысленно. Правило описывает день недели и время, а бот
держит ближайшие недели уже разложенными по отложенным телеграма.

Раскладываем вперёд, а не «в нужный час»: пост, отданный телеграму, выйдет
даже если у нас всё выключено. Правило, которое срабатывает в момент выхода,
такого не даёт и зависит от включённого мака.
"""

from datetime import timedelta

import db
import times

КЛЮЧ = "repeats"
ВПЕРЁД = 4                    # столько ближайших повторов держим разложенными

ДНИ = ["понедельник", "вторник", "среда", "четверг",
       "пятница", "суббота", "воскресенье"]


def правила() -> list[dict]:
    return db.настройка(КЛЮЧ, []) or []


def сохранить(новые: list[dict]) -> None:
    db.запомнить(КЛЮЧ, новые)


def ближайшие(правило: dict, сколько: int = ВПЕРЁД) -> list:
    """Ближайшие даты по правилу, начиная с завтрашнего дня."""
    день = int(правило.get("день", 3))               # 0 это понедельник
    час, минута = (str(правило.get("время", "19:00")).split(":") + ["0"])[:2]
    сейчас = times.сейчас()
    итог = []
    шаг = сейчас
    while len(итог) < сколько:
        шаг += timedelta(days=1)
        if шаг.weekday() != день:
            continue
        момент = шаг.replace(hour=int(час), minute=int(минута),
                             second=0, microsecond=0)
        if момент > сейчас:
            итог.append(момент)
    return итог


def _уже_стоит(момент) -> bool:
    метка = times.в_базу(момент)
    with db.соединение() as c:
        ряд = c.execute("SELECT id FROM posts WHERE scheduled_at=?"
                        " AND status='scheduled'", (метка,)).fetchone()
    return bool(ряд)


def разложить() -> list[str]:
    """Досоздаёт недостающие повторы. Зовётся рабочим раз в час."""
    import core
    сделано = []
    for правило in правила():
        if not правило.get("включено", True):
            continue
        for момент in ближайшие(правило):
            if _уже_стоит(момент):
                continue
            ид = core.анонс() if правило.get("вид") == "анонс" else core.новый(None)
            core.запланировать(ид, момент)
            сделано.append(f"{правило.get('вид', 'пост')} на {times.подпись(момент)}")
    return сделано


def описание(правило: dict) -> str:
    день = ДНИ[int(правило.get("день", 3)) % 7]
    return f"каждый {день} в {правило.get('время', '19:00')}"
