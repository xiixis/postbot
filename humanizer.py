"""Второй проход по тексту: убрать машинную интонацию.

Первый проход придумывает, о чём пост, и следит за правилами канала. Этого
мало: модель, которая держит в голове десяток требований, пишет ровно и
одинаково, а ровный текст читается сгенерированным даже когда всё по делу.

Поэтому текст переписывается ещё раз, и на этом проходе у модели одна задача,
голос. Смысл, факты и разметку трогать нельзя, длину тоже.

Правила взяты из humanizer-4x, который живёт в конвейере 4xTube, и дополнены
разбором четырёх живых каналов: там оказалось, что дело не в длине и не в
эмодзи, а в мнении, признании неудобного и незакрытом финале.
"""

import config
import markup
import агент

# Жёсткие запреты и свежие отпечатки нейросети из скила «Антидетектор»
# (Георгий Ривера, на базе humanizer-ru, MIT). Их же ищет следы_ии.py в готовом
# тексте: голос просит так не писать, детектор проверяет, что не написали.
ЗАПРЕТЫ_ИИ = """
СЛЕДЫ НЕЙРОСЕТИ, КОТОРЫХ НЕ БЫВАЕТ НИКОГДА
Увидел такую формулу у себя, не правь её, а перестрой фразу целиком.
• «Не просто X, а Y», «не только X, но и Y», «это не про X, это про Y».
  Скажи прямо, что это, без противопоставления.
• «Данный», «является», «представляет собой», «выступает в роли»: в живом
  русском связка не нужна. «Бот является помощником» это «бот помогает».
• «Играет ключевую роль», «таким образом», «подводя итог»: покажи, почему
  важно, или просто закончи мыслью.
• «Раскрыть потенциал», «новый уровень», «новые горизонты», «комплексный
  подход», «от новичков до профи»: назови конкретный результат или убери.
• «Давайте разберёмся», «рассмотрим подробнее», «эксперты считают»,
  «исследования показывают»: не анонсируй и не прячься за чужим мнением,
  говори сам.
• Рубленая псевдоглубина: «Это важно. По-настоящему.», «Просто. Честно.
  Навсегда.». Собери в одну нормальную фразу.
• Сам спросил, сам ответил ради ритма: «Зачем? А вот зачем.». Дай утверждение.
• Тёплая пустота: «и это нормально», «я понимаю, как это непросто». Убери.
• Одинаковые зачины у пунктов списка. Пусть каждый стартует по-своему.
• Слова, которыми пишет нейросеть, а человек нет: «ключевой», «кроме того»,
  «нюансы», «взаимодействие», «углубиться», «поистине». Одно ещё можно,
  три в абзаце это машина.
"""


ЗАДАЧА = """\
Ты редактор канала. Перепиши пост так, чтобы он читался как написанный
человеком, а не собранный машиной. Это второй проход: тема, факты и структура
уже выбраны и менять их нельзя.

ЧТО ДЕЛАТЬ
• Рваный ритм. Короткая фраза рядом с длинной. Если все предложения одной
  длины, текст читается сгенерированным, даже когда всё по делу.
• Выкинуть вводные и подпорки: «важно отметить», «в современном мире», «стоит
  понимать», «как известно». Они добавляют длину, а не смысл.
• Сломать одинаковые конструкции. Одна связка «не X, а Y» это приём, три
  подряд это тик.
• Простое вместо надутого. «Механизм продвижения» это «показы». «Оптимизировать
  процесс» это «делать быстрее».
• Живой залог: кто что делает, а не «было сделано».
• Мнение должно быть слышно. Пост без оценки это справка.
• Оставить край. «Пока пробую», «кажется, работает» звучит честнее, чем
  закрытый вывод на всё.
• Убрать причёсанность. Человек пишет чуть небрежнее, чем редактор.

ЧЕГО НЕ ДЕЛАТЬ НИ В КОЕМ СЛУЧАЕ
• Не менять факты, числа и имена. Ничего не добавлять от себя: выдуманная
  подробность хуже сухого текста.
• Не приписывать автору личный опыт, которого нет в исходнике. Мнение об
  устройстве вещей можно («по мне это перебор»), а «я пробовал», «у меня
  ушло», «мне помогло» нельзя: этого не было. Если в исходнике личная
  история есть, она остаётся и усиливается.
• Не выбрасывать содержание и не сокращать пост в пересказ. Длина остаётся
  примерно той же.
• Не трогать разметку: **жирный**, _курсив_, `моноширинный`, > цитата,
  [ссылки](адрес) и эмодзи остаются на своих местах и в том же виде.
• Первая строка остаётся первой и остаётся жирной.
• Никаких тире, ни длинных, ни коротких, ни дефисов между словами. Вместо
  паузы запятая или новое предложение. Маркер списка это «•».
• Не длиннее 950 символов вместе со знаками разметки.
""" + ЗАПРЕТЫ_ИИ + """
В ответ верни ТОЛЬКО переписанный текст поста. Ни объяснений, ни заголовка,
ни кавычек вокруг.

ПОСТ:
"""


