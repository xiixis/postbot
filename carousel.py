# заумные карусели. Блок стоит после РЕЗЧЕ и главнее его.
ПРОСТО = """\

ПРОСТО, ЧТОБЫ ПОНЯЛ КАЖДЫЙ
Резкость выше про уверенность, а не про сложность. Текст должен понять и
новичок, и школьник, и взрослый, который про ИИ только слышал. Простота важнее
резкости:
• слово из мира ИИ (промпт, нейросеть, модель, агент) сразу объясни простыми
  словами или примером: не «напиши промпт», а «напиши в чат, что тебе нужно»;
• одно действие в предложении, предложения короткие;
• пример из жизни лучше определения;
• если фразу надо перечитать, чтобы понять, перепиши проще.
"""


def _формат(паспорт: dict) -> str:
    """Форма карусели, решённая кодом до сценария: модель её не выбирает.

    Когда выбирала модель, «шаги» заняли половину каруселей: она тянется к
    привычному. Паспорт подбирает `форматы.следующий` без повторов.
    """
    каркас = паспорт["каркас"]
    от, до = паспорт.get("кадров") or [8, 12]
    return ("\nФОРМАТ ЭТОЙ КАРУСЕЛИ РЕШЁН ЗАРАНЕЕ, НЕ МЕНЯЙ ЕГО:\n"
            f"• каркас: {каркас} — {КАРКАСЫ.get(каркас, '')}\n"
            f"• кадров вместе с обложкой и итогом: от {от} до {до}, то есть "
            f"слайдов середины от {от - 2} до {до - 2}. Этот диапазон главнее "
            "общего правила о длине выше. Длинная карусель удерживает лучше: "
            "бери ближе к верхней границе, если мысли хватает, но не растягивай "
            "пустыми слайдами.\n")


def сочинить(тема: str | None, было: list[str], указания: str = "",
             площадка: str = "телеграм", рерайт: bool = False,
             паспорт: dict | None = None) -> Карусель:
    """Текст карусели. Голос канала общий, а правила подачи у площадок разные."""
    # Список приходит как «заголовок — суть»: по одним заголовкам повтор не
    # виден, и модель честно приносила ту же мысль в новой упаковке.
    запрет = "\n".join(f"• {т}" for т in было) or "• пока ничего не выходило"
    задача = (
        ЗАДАЧА
        + ("\n\n" + ДЛЯ_TIKTOK if площадка == "tiktok" else "")
        + (f"\n\nТема задана владельцем: «{тема}».\n" if тема else
           "\n\nТему выбери сам, ориентируясь на то, чего давно не было.\n")
        + ("\nУже выходило, повторять нельзя ни темой, ни мыслью. После тире "
           "стоит суть прошлого поста — сравнивайте с ней, а не с "
           f"заголовком:\n{запрет}\n")
        + (f"\n{указания}\n" if указания else "")
        + (_формат(паспорт) if паспорт and паспорт.get("каркас") else
           "\nКАРКАСЫ, ИЗ КОТОРЫХ ВЫБРАТЬ ОДИН:\n"
           + "\n".join(f"• {и} — {о}" for и, о in КАРКАСЫ.items()))
        + "\n\nВЁРСТКИ, ИЗ КОТОРЫХ ВЫБИРАТЬ:\n"
        + "\n".join(f"• {и} — {о}" for и, о in ВЁРСТКИ.items())
        + "\n\nПОЗЫ КОТА ДЛЯ ОБЛОЖКИ, выберите одну по смыслу:\n"
        + _позы()
    )
    # При рерайте наши данные в системное сообщение не идут вовсе. Иначе
    # модель тянет конкретику оттуда и вместо десяти инструментов исходного
    # называет те три, которыми пользуемся мы: получается не рерайт, а пересказ
    # своего хозяйства по чужому скелету. Данные подключаются обратно, только
    # когда владелец подтвердит, что они актуальны.
    наши_данные = "" if рерайт else (writer._факты() + _чужой_опыт(площадка))
    # Конвейер в системном сообщении, а не в задаче: это знание о мире, а не
    # указание, что делать. Без него модель придумывала короткий список
    # очевидного и на нём строила всю карусель.
    import humanizer
    к = агент.по_форме(
        задача, Карусель,
        # Голос хуманайзера идёт сразу за голосом канала: подпись и слайды
        # пишутся живыми с первого раза, второй проход не нужен.
        система=(writer.ГОЛОС + humanizer.ГОЛОС + writer._значки() + наши_данные
                 + _подсмотренное()
                 # Резкий регистр идёт ПОСЛЕ голоса канала: он снимает его
                 # смягчители, а значит должен стоять ниже, иначе голос
                 # перебьёт его обратно.
                 + (РЕЗЧЕ if площадка == "tiktok" else "")
                 + ПРОСТО
                 + "\n\n" + КОНВЕЙЕР),
        # Усердие задаём явно: без него CLI берёт effortLevel из общих
        # настроек Claude Code (там high), и сценарий шёл ~2,6 мин. На medium
        # та же тема вышла за 93 с и не хуже (замер 11 сентября 2026).
        модель=config.МОДЕЛЬ, метка="карусель", усердие="medium")
    if паспорт and паспорт.get("каркас"):
        к.каркас = паспорт["каркас"]

    # Второго прохода хуманайзера по подписи больше нет: его правила стоят в
    # подсказке сценария. Он стоил 10–13 с и лишний вызов модели на карусель.
    if площадка == "tiktok":
        # Ни разметки, ни фирменных иконок: TikTok покажет и то и другое как
        # мусор.
        тело, метки = _отделить_хештеги(_без_разметки(к.caption))
        к.hashtags = [м for м in (к.hashtags or []) if м.startswith("#")] or метки
        к.caption = _без_разметки(markup.без_тире(тело)) or _без_разметки(тело)
        # Название через гуманизатор не идёт: это не речь, а строка для
        # поиска, и «живее» ей только вредит. Если модель его не дала,
        # заголовок обложки лучше пустого поля.
        к.название = (_без_разметки(markup.без_тире(к.название)).strip()
                      or к.cover_title)[:90]
    else:
        к.caption = markup.причесать(icons.к_своим(к.caption))
        к.hashtags = []
        к.название = ""      # поле есть только у TikTok
    # Текст на слайдах гуманизатор не трогает: там не речь, а надписи, и
    # переписывать их «живее» значит ломать вёрстку.
    к.cover_kicker = markup.без_тире(к.cover_kicker)
    к.cover_title = markup.без_тире(к.cover_title)
    к.closing = markup.без_тире(к.closing)
    # Пустые выбрасываем, остальным подгоняем вёрстку под то, что заполнено.
    к.slides = [_подогнать_вид(с) for с in к.slides if _живой(с)]
    for с in к.slides:
        с.заголовок = markup.без_тире(с.заголовок)
        с.текст = markup.без_тире(с.текст)
        с.значение = markup.без_тире(с.значение)
        с.строки = [markup.без_тире(х) for х in (с.строки or [])]
        с.реплика = markup.без_тире(с.реплика)[:40]
    return к


def _без_разметки(текст: str) -> str:
    """Снимает звёздочки и прочую разметку.

    TikTok и Threads показывают её как есть, поэтому «**мысль**» превращается
    там в звёздочки вокруг слова. Модель про это знает, но иногда всё равно
    ставит жирную первую строку по привычке канала, и полагаться на её память
    тут нельзя.
    """
    import re
    т = re.sub(r"\*\*(.+?)\*\*", r"\1", текст or "")
    т = re.sub(r"(?<![\w*])[*_](.+?)[*_](?![\w*])", r"\1", т)
    т = re.sub(r"`(.+?)`", r"\1", т)
    т = re.sub(r"^\s*>\s?", "", т, flags=re.M)
    return т.strip()


def _отделить_хештеги(текст: str) -> tuple[str, list[str]]:
    слова = (текст or "").split()
    метки = [с for с in слова if с.startswith("#")]
    тело = " ".join(с for с in слова if not с.startswith("#"))
    return тело.strip(), метки


def подпись(к: Карусель) -> str:
    """Готовый текст под карусель: подпись и хештеги.

    Призыва подписаться здесь нет ни для одной площадки. В телеграме его
    ставит `publish.футер` со ссылкой на канал, а в TikTok он не нужен вовсе:
    там мы не собираем подписчиков этой каруселью, и просьба в конце только
    занимает место, которое лучше отдать самой мысли.
    """
    куски = [(к.caption or "").strip()]
    if к.hashtags:                      # хештеги есть только у TikTok
        куски.append(" ".join(к.hashtags))
    return "\n\n".join(ч for ч in куски if ч).strip()


# Формат под площадку. TikTok сам называет рекомендованными 16:9, 4:3 и 3:4,
# и 3к4 из них самый высокий: занимает больше экрана, оставаясь своим.
ФОРМАТ = {"телеграм": "квадрат", "tiktok": "3к4"}


# Куда ставить кота по ходу карусели. Не на каждый слайд и каждый раз иначе:
# постоянное присутствие приедается ровно так же, как одинаковая вёрстка.
# Кот на слайдах середины. Три правила, каждое из живой ошибки.
#
# Своя поза на каждом слайде. Раньше на всю карусель шла поза с обложки, и кот
# семь раз подряд махал лапой: библиотека из тридцати двух поз при этом стояла
# без дела.
#
# Не на каждом слайде. Постоянное присутствие приедается так же, как
# одинаковая вёрстка, и отнимает место у текста.
#
# Место с оглядкой на вёрстку. Широкие вёрстки занимают холст целиком, и кот
# в углу наезжает на содержимое. Полупрозрачный кот за текстом выглядел
# грязным пятном, а мелкий в углу читался как случайно попавший значок,
# поэтому обоих здесь нет.
# Позы разложены по крупности плана. Кино держит внимание сменой крупности:
# общий, средний, крупный, снова общий. Одинаковый план подряд превращает
# персонажа в наклейку, которую перестают замечать на третьем слайде.
# ── КОМПОЗИЦИЯ ─────────────────────────────────────────────────────────────
# Правила, по которым кот встаёт на слайд. Записаны здесь целиком, потому что
# ловить наложения по одному оказалось бесполезно: каждый раз вылезало новое
# место. Проще запретить всё, что может наложиться, чем каждый раз проверять.
#
# 1. Кот живёт в боковой колонке, своей и только своей. Текст на её ширину
#    ужимается, и пересечься им негде.
# 2. Центральных и «за текстом» мест нет вовсе. Именно они давали наложения:
#    у них нет своей стороны, значит нет и колонки.
# 3. За край уходит не больше четверти кота, и только у мест, которые так и
#    называются. Обрезанный наполовину персонаж читается как сбой.
# 4. Реплика живёт внутри колонки кота, над ним. Шире колонки не бывает.
# 5. Крупный план только сбоку. Он занимает половину высоты, и в центре ему
#    места нет.
# 6. Высокие вёрстки, которые тянутся вниз списком, получают кота только
#    сбоку и не крупнее среднего.

ПЛАНЫ = {
    "общий":   ["ukazyvaet", "ideya", "raduetsya", "vniz", "vverh", "noutbuk",
                "moneta", "grafik", "bezhit", "kniga"],
    "средний": ["sredniy", "sredniy_ukaz", "tri_chetverti", "profil",
                "so_spiny", "dumaet", "somnevaets", "mikrofon", "snizu",
                "sverhu", "lupa", "kamera"],
    # Крупный план это не портретный кроп, а тот же кот, снятый ближе. Готовые
    # портреты генератор рисует с обрезанными ушами и плечами, и на слайде это
    # читается как сбой, поэтому берём целые позы и показываем их крупно.
    "крупный": ["udivlen", "dumaet", "somnevaets", "vverh", "ideya",
                "krupno_lico", "krupno_glaza"],
}

# Только боковые места. Каждое из них имеет свою сторону, а значит и колонку.
МЕСТА_ПЛАНА = {
    "общий":   ["рядом", "слева", "угол"],
    "средний": ["рядом", "угол-лево", "слева"],
    "крупный": ["заглянул", "рядом", "угол"],
}

ПОРЯДОК_ПЛАНОВ = ["общий", "крупный", "средний", "общий"]

ЗАПАСНЫЕ_РЕПЛИКИ = [
    "это я придумал",
    "а меня тут видно?",
    "дальше будет лучше",
    "перечитай, тут важное",
    "я бы сказал короче",
    "листай, я подожду",
]

# Вёрстки, которые тянутся вниз списком или карточками: кот им годится, но
# не крупнее среднего.
ВЫСОКИЕ = {"список", "галочки", "пузыри", "консоль", "телефон",
           "слои", "таймлайн", "рейтинг"}

# Вёрстки, которые распирают холст по ширине: колонки, полосы, схемы. Ужать их
# нельзя, значит и колонки коту не найдётся. Проверка композиции показала это
# на «тройке»: три столбца не оставляли места ни коту, ни его реплике.
БЕЗ_КОТА = {"тройка", "полосы", "опрос", "узлы", "плитки", "лестница",
            "двацифры", "сетка4",
            # «Замена» и «столбики» занимают кадр во всю ширину: две плиты с
            # ценами и столбчатая диаграмма упираются в поля сами по себе.
            "замена", "столбики"}


def _хотя_бы_одна_реплика(слайды: list) -> list:
    """Следит, чтобы в карусели была хоть одна реплика кота.

    Приём с персонажем, который знает, что он на картинке, существует, только
    если его видно. Отдавать это целиком на усмотрение модели нельзя: она
    честно оставляет поле пустым, и карусель выходит без него вовсе.
    """
    if any((с.get("реплика") or "").strip() for с in слайды):
        return слайды
    # Ставим на первый слайд, где кот вообще будет.
    for н, с in enumerate(слайды):
        вид = с.get("вид", "мысль")
        поза, _, _ = _кот_слайда(вид, н, mascot_склад())
        if поза:
            с["реплика"] = ЗАПАСНЫЕ_РЕПЛИКИ[н % len(ЗАПАСНЫЕ_РЕПЛИКИ)]
            break
    return слайды


def mascot_склад() -> dict:
    import mascot
    return mascot.библиотека()


def _кот_слайда(вид: str, шаг: int, есть_позы: dict) -> tuple:
    """Поза, место и крупность. Кот стоит ровно на половине слайдов.

    Возвращает всегда боковое место: только у него есть колонка, а значит и
    гарантия, что текст с котом не пересекутся.
    """
    if шаг % 2 or вид in БЕЗ_КОТА:
        return None, "нет", "средний"
    н = шаг // 2
    план = ПОРЯДОК_ПЛАНОВ[н % len(ПОРЯДОК_ПЛАНОВ)]
    if вид in ВЫСОКИЕ and план == "крупный":
        план = "средний"          # списку крупный план не оставляет места
    набор = [к for к in ПЛАНЫ[план] if к in есть_позы] or ["privet"]
    места = МЕСТА_ПЛАНА[план]
    return есть_позы.get(набор[н % len(набор)]), места[н % len(места)], план


# Чего вёрстке нужно, чтобы она вообще собралась: сколько строк и нужно ли
# «значение». Отсюда же и подгонка ниже.
СКОЛЬКО_СТРОК = {"было": 2, "список": 2, "правка": 2, "полосы": 2,
                 "против": 2, "тройка": 3, "стрелка": 2,
                 "замена": 2, "столбики": 2, "поток": 2}
НУЖНО_ЗНАЧЕНИЕ = {"цифра", "шаг", "термин"}


def _живой(с) -> bool:
    """Есть ли на слайде что рисовать.

    Схема разрешает всем полям быть пустыми, и модель этим иногда пользуется:
    мысль кончилась на пятом слайде, а шестой она всё равно отдаёт пустым.
    Нарисуется он честно — пустой картинкой посреди карусели, и первым её
    увидит зритель. Дешевле выбросить здесь.
    """
    д = с.model_dump() if hasattr(с, "model_dump") else dict(с)
    словами = " ".join(str(д.get(п) or "")
                       for п in ("заголовок", "текст", "значение"))
    строки = [х for х in (д.get("строки") or []) if str(х).strip()]
    return bool(словами.strip() or строки)


def _подогнать_вид(с):
    """Правит вёрстку под то, что на слайде на самом деле заполнено.

    Вёрстку модель выбирает раньше, чем пишет содержание, и иногда выбирает
    не ту: берёт «полосы», а чисел не приносит, или «шаг» без номера.
    Рисовалка в таком случае аккуратно рисует пустые места. Пересадить слайд
    на вёрстку, которой хватает того, что есть, лучше, чем отдать дырку.
    """
    вид = (с.вид or "").strip().lower()
    строки = [х for х in (с.строки or []) if str(х).strip()]
    if вид not in ВЁРСТКИ:
        вид = "мысль"
    надо = СКОЛЬКО_СТРОК.get(вид, 0)
    if надо and len(строки) < надо:
        вид = "список" if len(строки) >= 2 else "мысль"
    if вид in ("полосы", "тройка", "столбики", "замена") and not all(
            "|" in str(х) for х in строки):
        вид = "список"          # без разделителя это не таблица, а пункты
    if вид in НУЖНО_ЗНАЧЕНИЕ and not (с.значение or "").strip():
        вид = "мысль"
    if вид == "цитата" and not (с.заголовок or "").strip():
        вид = "мысль"
    if вид == "выделение" and not (с.текст or "").strip():
        вид = "мысль"
    if вид == "мысль" and not (с.текст or "").strip() and len(строки) >= 2:
        вид = "список"          # текста нет, зато есть пункты
    с.вид, с.строки = вид, строки
    return с


def _поля(с) -> dict:
    """Пять слотов модели раскладываем в поля, которые ждёт рисовалка.

    Раскладка живёт здесь, в одном месте: рисовалка про соглашение модели
    ничего не знает, а модель ничего не знает про имена полей вёрстки.
    """
    д = с.model_dump() if hasattr(с, "model_dump") else dict(с)
    вид = д.get("вид", "мысль")
    строки = [str(х) for х in (д.get("строки") or []) if str(х).strip()]
    зн, заг, тек = д.get("значение", ""), д.get("заголовок", ""), д.get("текст", "")
    итог = {"вид": вид, "заголовок": заг, "текст": тек, "цифра": "",
            "реплика": д.get("реплика", "")}

    if вид == "цифра":
        итог["цифра"] = зн
    elif вид == "было":
        итог["было"], итог["стало"] = (строки + ["", ""])[:2]
    elif вид == "список":
        итог["пункты"] = строки[:4]
    elif вид == "цитата":
        итог["цитата"], итог["кто"] = заг, тек
    elif вид == "шаг":
        итог["номер"] = зн
    elif вид == "термин":
        итог["слово"], итог["как"], итог["текст"] = зн, заг, тек
    elif вид == "правка":
        итог["неверно"], итог["верно"] = (строки + ["", ""])[:2]
    elif вид == "полосы":
        полосы = []
        for с_ in строки[:4]:
            куски = [к.strip() for к in с_.split("|")]
            куски += [""] * (3 - len(куски))
            доля = "".join(з for з in куски[2] if з.isdigit())
            полосы.append({"имя": куски[0], "сколько": куски[1],
                           "доля": int(доля or 50)})
        итог["полосы"] = полосы
    elif вид == "против":
        итог["слева"], итог["справа"] = (строки + ["", ""])[:2]
    elif вид == "замена":
        пара = []
        for с_ in (строки + ["", ""])[:2]:
            куски = [к.strip() for к in с_.split("|")] + [""]
            пара.append((куски[0], куски[1]))
        (итог["платное"], итог["цена_платного"]) = пара[0]
        (итог["бесплатное"], итог["цена_бесплатного"]) = пара[1]
    elif вид == "столбики":
        столбики = []
        for с_ in строки[:4]:
            куски = [к.strip() for к in с_.split("|")]
            куски += [""] * (3 - len(куски))
            доля = "".join(з for з in куски[2] if з.isdigit())
            столбики.append({"имя": куски[0], "подпись": куски[1],
                             "доля": int(доля or 50)})
        итог["столбики"] = столбики
    elif вид == "поток":
        итог["шаги"] = строки[:4]
    elif вид == "тройка":
        тройка = []
        for с_ in строки[:3]:
            куски = [к.strip() for к in с_.split("|")] + [""]
            тройка.append({"что": куски[0], "имя": куски[1]})
        итог["тройка"] = тройка
    elif вид == "стрелка":
        итог["от"], итог["к"] = (строки + ["", ""])[:2]
    elif вид == "выделение":
        итог["абзац"] = тек
    return итог


def нарисовать(к: dict, формат: str = "квадрат", поза=None,
               только: int | None = None, замены: dict | None = None,
               ход=None) -> list:
    """Рисует карусель из сохранённых данных. Одна дорога для всех, кто рисует.

    Раньше отрисовка была списана в трёх местах: сборка, перерисовка и
    подготовка под другую площадку. Расходились они тихо, и пересборка для
    телеграма сплющивала все вёрстки обратно в «мысль».

    Понимает и старый вид данных, где у слайда были только title, body и
    figure: такие посты уже лежат в базе, и ломать их нельзя.

    «только» рисует один слайд по номеру, «замены» подменяет ему позу. Это
    для случая «у кота пять лап»: пересобирать из-за одной картинки всю
    карусель — минуты работы и восемь новых файлов вместо одного. Цикл при
    этом проходит целиком: выбор позы и плана считается от номера слайда, и
    пропусти мы шаги, у соседей поменялись бы коты.
    """
    import mascot
    замены = замены or {}
    if поза is None:
        поза = mascot.взять(к.get("поза") or "")
    склад = mascot.библиотека()
    # Вид карусели из паспорта. У старых постов его нет — они рисуются как
    # раньше: фирменный дизайн на сетке и кот на своих слайдах.
    паспорт = к.get("паспорт") or {}
    дизайн = паспорт.get("дизайн") or "фирменный"
    оформление = паспорт.get("оформление") or "сетка"
    с_котом = паспорт.get("кот", True)
    слайды = _хотя_бы_одна_реплика(к.get("slides") or [])
    вывод = (к.get("closing") or "").strip()
    всего = len(слайды) + (2 if вывод else 1)
    нужен = lambda н: только is None or н == только            # noqa: E731
    # Рисование занимает почти всё время генерации, и молчать эти минуты
    # незачем: номер слайда — единственное, что честно показывает, сколько
    # ещё ждать.
    шаг = (lambda н: ход(f"слайд {н} из {всего}")) if ход else (lambda н: None)
    шаг(1)
    файлы = [card.слайд_обложка(к.get("cover_kicker", ""), к.get("cover_title", ""),
                                замены.get(1) or поза, 1, всего, формат,
                                дизайн=дизайн, оформление=оформление)
             if нужен(1) else None]
    for н, с in enumerate(слайды, start=2):
        if "вид" in с:
            вид = с["вид"] if с["вид"] in ВЁРСТКИ else "мысль"
            # Слоты раскладываем на каждой отрисовке: в базе лежит то, что
            # прислала модель, и раскладка не должна там дублироваться.
            поля = _поля({**с, "вид": вид}) if "строки" in с else с
        else:                                   # старый вид данных
            вид = "цифра" if (с.get("figure") or "").strip() else "мысль"
            поля = {"заголовок": с.get("title", ""), "текст": с.get("body", ""),
                    "цифра": с.get("figure", "")}
        своя, где, план = (_кот_слайда(вид, н - 2, склад) if с_котом
                           else (None, "нет", "средний"))
        # Реплика возможна только там, где кот есть: облачко без него повисло
        # бы в пустоте.
        реплика = (с.get("реплика", "") or "").strip() if своя else ""
        if not нужен(н):
            файлы.append(None)
            continue
        шаг(н)
        файлы.append(card.слайд_вида(вид, поля, н, всего, формат,
                                     замены.get(н) or своя or поза, где,
                                     оформление=оформление, дизайн=дизайн,
                                     крупность=план, реплика=реплика))
    if вывод:
        шаг(всего)
        # Призыв стоит на последнем слайде у обеих площадок. В тексте под
        # каруселью его нет: в телеграме там футер со ссылкой, а в TikTok
        # просьба в подписи только занимает место. На слайде она к месту —
        # это последнее, что видит долиставший.
        файлы.append(card.слайд_финал(вывод, всего, всего, формат,
                                      призыв(к, "слайд"),
                                      замены.get(всего) or поза,
                                      дизайн=дизайн, оформление=оформление)
                     if нужен(всего) else None)
    return [ф for ф in файлы if ф]


def позы_слайдов(к: dict) -> dict:
    """Какая поза досталась какому слайду. Для «эта поза бракованная».

    Считается тем же кодом, что и рисует, только без самой отрисовки:
    иначе два места разошлись бы, и забраковали бы не того кота.
    """
    import mascot
    склад = mascot.библиотека()
    общая = mascot.взять(к.get("поза") or "")
    слайды = _хотя_бы_одна_реплика(к.get("slides") or [])
    вывод = (к.get("closing") or "").strip()
    всего = len(слайды) + (2 if вывод else 1)
    итог = {1: {"поза": общая, "план": "общий"}}
    for н, с in enumerate(слайды, start=2):
        вид = (с.get("вид") if с.get("вид") in ВЁРСТКИ else "мысль") \
            if "вид" in с else ("цифра" if (с.get("figure") or "").strip() else "мысль")
        своя, _, план = (_кот_слайда(вид, н - 2, склад)
                         if (к.get("паспорт") or {}).get("кот", True)
                         else (None, "нет", "средний"))
        итог[н] = {"поза": своя or общая, "план": план}
    if вывод:
        итог[всего] = {"поза": общая, "план": "общий"}
    return итог


