def призыв(к: dict, где: str = "слайд") -> str:
    """Какая из фраз достанется этой карусели.

    Выбор считается от темы, а не берётся наугад: одна и та же карусель обязана
    получать одну и ту же строку, иначе перерисовка слайдов молча меняла бы
    текст, который владелец уже одобрил.
    """
    набор = ПРИЗЫВЫ_СЛАЙД if где == "слайд" else ПРИЗЫВЫ_ПОДПИСЬ
    ключ = str(к.get("cover_title") or к.get("topic") or к.get("caption") or "")
    return набор[sum(ord(с) for с in ключ) % len(набор)]


