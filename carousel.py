def разобрать_сценарий(текст: str) -> dict:
    """Сценарий из текста превращает в данные для отрисовки.

    Вторая половина двухпроходной сборки: первый проход пишет сценарий словами,
    человек его читает и правит, а этот разбирает готовое в поля вёрсток.
    Схема тут уже не нужна: решения приняты, осталась механика.
    """
    import re
    к = {"cover_kicker": "", "cover_title": "", "slides": [], "closing": "",
         "caption": "", "hashtags": [], "название": "", "поза": "privet"}
    кусок, текущий = None, None
    строки_подписи = []

    def значение(с: str) -> tuple:
        м = re.match(r"\s*([\wа-яё_]+)\s*:\s*(.*)$", с, re.I)
        return (м.group(1).lower(), м.group(2).strip()) if м else (None, None)

    for с in текст.splitlines():
        голая = с.strip()
        if голая.upper().startswith("ОБЛОЖКА"):
            кусок, текущий = "обложка", None
            continue
        м = re.match(r"СЛАЙД\s*\d*\s*\[([^\]]+)\]", голая, re.I)
        if м:
            кусок = "слайд"
            текущий = {"вид": м.group(1).strip().lower(), "заголовок": "",
                       "текст": "", "значение": "", "строки": [], "реплика": ""}
            к["slides"].append(текущий)
            continue
        if голая.upper().startswith("ИТОГ"):
            к["closing"] = голая.split(":", 1)[-1].strip()
            кусок = None
            continue
        if голая.upper().startswith("НАЗВАНИЕ"):
            к["название"] = голая.split(":", 1)[-1].strip()[:90]
            кусок = None
            continue
        if голая.upper().startswith("ПОДПИСЬ"):
            кусок = "подпись"
            continue
        if голая.upper().startswith("ХЕШТЕГИ"):
            к["hashtags"] = [х for х in голая.split(":", 1)[-1].split() if х.startswith("#")]
            кусок = None
            continue

        if кусок == "подпись":
            строки_подписи.append(с.rstrip())
            continue
        if голая.startswith("•") and текущий is not None:
            текущий["строки"].append(голая.lstrip("•").strip())
            continue
        поле, зн = значение(с)
        if not поле:
            continue
        if кусок == "обложка":
            if поле == "надпись":
                к["cover_kicker"] = зн
            elif поле == "заголовок":
                к["cover_title"] = зн
            elif поле in ("поза", "кот"):
                к["поза"] = зн
        elif текущий is not None:
            if поле == "строки":
                тело = зн.strip().strip("[]")
                части = [ч.strip().strip('"').strip("'") for ч in тело.split(",")]
                текущий["строки"] = [ч for ч in части if ч]
            elif поле == "кот":
                текущий["реплика"] = зн
            elif поле in текущий:
                текущий[поле] = зн

    к["caption"] = "\n".join(строки_подписи).strip()
    # «полосы» и «тройка» приходят строками вида «имя|сколько|доля».
    к["slides"] = [_поля(с) | {"реплика": с.get("реплика", "")}
                   for с in к["slides"] if _живой(с)]
    return к


