# своих роликах») — у канала запрет выдумывать его, а призыв выпадает на любой
# пост, в том числе на тот, где никакого своего опыта нет. И штампов вроде
# «без воды»: их пишет каждый второй канал, и они не значат ничего.
#
# Длина тоже не вкусовщина: призыв стоит плашкой под выводом, и каждая лишняя
# строка отъедает кегль у самого вывода. Держим в пределах полусотни знаков,
