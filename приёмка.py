# -*- coding: utf-8 -*-
"""Приёмка кадров: что осталось не так, когда рисовальщик сделал всё, что мог.

Проверки кадра были и раньше, но только печатали строчку в лог и отдавали кадр
дальше. Строчку никто не читает: автопилот рисует ночью, а владелец видит уже
готовые картинки. Так кадр с обрезанным словом доезжал до папки на столе.

Здесь журнал одной отрисовки. Рисовальщик отмечает в нём брак и замечания по
кадру, а тот, кто рисовал карусель, забирает итог и решает, пускать ли её
дальше. Приём взят у html-instagram-carousel: проверка там не советует, а
выносит вердикт «годен / брак», и брак дальше сам не идёт.

Брак — то, что на картинке видно как поломку: текст за краем, слово цвета фона,
не загрузилась картинка. Замечание — то, о чём стоит знать, но что кадр не
портит: кот убран, шрифт ужат, строки легли неровно.

Журнал живёт в нити. Без начатого журнала отметки молча пропадают: так рисуют
афиша, сторис и подготовка под другую площадку, им приёмка не нужна.
"""

import threading

_своё = threading.local()

# Беды окружения, а не раскладки: файл, шрифт, браузер. Текст их не лечит, и
# сокращать ради них слайд бессмысленно.
СТРАНИЦА = "страница: "


def начать() -> None:
    _своё.журнал = {}
    _своё.номер = None


def идёт() -> bool:
    return getattr(_своё, "журнал", None) is not None


def кадр(номер: int, вид: str) -> None:
    """Дальнейшие отметки относятся к этому кадру. Повтор номера начинает его заново."""
    if not идёт():
        return
    _своё.журнал[номер] = {"номер": номер, "вид": вид, "брак": [],
                           "замечания": [], "ужато": 1.0}
    _своё.номер = номер


def _запись() -> dict | None:
    if not идёт():
        return None
    return _своё.журнал.get(getattr(_своё, "номер", None))


def брак(*беды: str) -> None:
    запись = _запись()
    if запись is None:
        return
    for беда in беды:
        if беда and беда not in запись["брак"]:
            запись["брак"].append(беда)


def замечание(текст: str) -> None:
    запись = _запись()
    if запись is not None and текст and текст not in запись["замечания"]:
        запись["замечания"].append(текст)


def ужато(доля: float) -> None:
    запись = _запись()
    if запись is not None:
        запись["ужато"] = round(min(запись["ужато"], доля), 2)


def текущий() -> dict:
    """Копия записи текущего кадра. Пусто, если журнала нет."""
    запись = _запись()
    if not запись:
        return {}
    return {**запись, "брак": list(запись["брак"]),
            "замечания": list(запись["замечания"])}


def _отчёт(кадры: list) -> dict:
    return {"годен": not any(к["брак"] for к in кадры), "кадры": кадры}


def итог() -> dict:
    """Забирает журнал и закрывает его. Пусто, если журнал не начинали."""
    журнал = getattr(_своё, "журнал", None)
    _своё.журнал, _своё.номер = None, None
    if журнал is None:
        return {}
    return _отчёт([журнал[н] for н in sorted(журнал)])


def слить(было: dict | None, свежие: dict | None) -> dict:
    """Отчёт после перерисовки части кадров: свежие записи заменяют прежние."""
    по_номеру = {к["номер"]: к for к in (было or {}).get("кадры", [])}
    по_номеру.update({к["номер"]: к for к in (свежие or {}).get("кадры", [])})
    return _отчёт([по_номеру[н] for н in sorted(по_номеру)])


def годен(отчёт: dict | None) -> bool:
    """Нет отчёта — пост рисован до приёмки, судить его нечем."""
    return (отчёт or {}).get("годен", True)


def бракованные(отчёт: dict | None) -> list[int]:
    return [к["номер"] for к in (отчёт or {}).get("кадры", []) if к["брак"]]


def строкой(отчёт: dict | None) -> str:
    """«№4: текст за краем; №7: …». Пусто, если брака нет."""
    return "; ".join(f"№{к['номер']}: {', '.join(к['брак'])}"
                     for к in (отчёт or {}).get("кадры", []) if к["брак"])


def лечится_текстом(запись: dict, порог: float = 0.78) -> bool:
    """Поможет ли сократить текст: брак от раскладки или шрифт ужат глубоко."""
    if not запись:
        return False
    раскладка = [б for б in запись.get("брак", []) if not б.startswith(СТРАНИЦА)]
    return bool(раскладка) or запись.get("ужато", 1.0) < порог
