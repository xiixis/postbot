// ── вышло ────────────────────────────────────────────────────────────
// Раздел, которого не было вовсе. История приезжала на клиент и тратилась на
// закраску сегодняшних ячеек, а увидеть, что вышло на прошлой неделе, было
// негде. Две вкладки: лента — что именно вышло, числа — как это зашло.
function экранВышло() {
  return `
    <div class="tabs" role="tablist" aria-label="Вид раздела">
      <button role="tab" data-вкладка="лента"
              aria-selected="${вкладкаВышло === "лента"}"
              class="${вкладкаВышло === "лента" ? "on" : ""}">Лента</button>
      <button role="tab" data-вкладка="числа"
              aria-selected="${вкладкаВышло === "числа"}"
              class="${вкладкаВышло === "числа" ? "on" : ""}">Числа</button>
    </div>
    <div id="нутро-вышло">${
      вкладкаВышло === "числа" ? нутроЧисла() : нутроЛенты()}</div>`;
}

const ПЛОЩАДКИ_ЛЕНТЫ = [["", "Все"], ["телеграм", "Телеграм"],
                        ["руками", "Руками"]];
const СРОКИ_ЛЕНТЫ = [[null, "Всё время"], [7, "Неделя"], [30, "Месяц"]];

function фишки(имя, пары, текущее) {
  return пары.map(([зн, подпись]) => `
    <button class="chip ${String(зн) === String(текущее) ? "on" : ""}"
            data-фильтр="${имя}" data-значение="${зн === null ? "" : экр(String(зн))}"
            aria-pressed="${String(зн) === String(текущее)}"
      >${экр(подпись)}</button>`).join("");
}

function нутроЛенты() {
  const отобрано = лента.запрос || лента.рубрика || лента.площадка || лента.дней;
  const рубрики = [["", "Все рубрики"]].concat(
    (С.rubrics || []).map(р => [р, р]));

  const шапка = `
    <div class="поиск">
      <label class="sr" for="искать">Поиск по заголовку</label>
      <input type="search" id="искать" autocomplete="off"
             placeholder="Поиск по заголовку"
             value="${экр(лента.запрос)}">
    </div>
    <div class="фишки">
      ${фишки("площадка", ПЛОЩАДКИ_ЛЕНТЫ, лента.площадка)}
      <span class="разделитель" aria-hidden="true"></span>
      ${фишки("дней", СРОКИ_ЛЕНТЫ, лента.дней === null ? "" : лента.дней)}
    </div>
    <div class="фишки">${фишки("рубрика", рубрики, лента.рубрика)}</div>`;

  if (!лента.было && лента.грузим)
    return шапка + `<div class="пусто"><b>Читаю ленту</b>Секунду.</div>`;

  if (!лента.посты.length) {
    // Пустая лента и пустой отбор — разные вещи, и говорить о них надо
    // по-разному: в одном случае работать не с чем, в другом — просто
    // слишком узкий фильтр.
    return шапка + (отобрано
      ? `<div class="пусто"><b>Ничего не нашлось</b>
           Под этот отбор не подходит ни один вышедший пост.
           <div style="margin-top:.75rem"><button class="btn ghost"
             id="сбросить-отбор">Сбросить отбор</button></div></div>`
      : `<div class="пусто"><b>Пока ничего не вышло</b>
           Как только первый пост уйдёт в канал, он появится здесь —
           с датой, ссылкой и охватом.</div>`);
  }

  // Группировка по дням. Подпись дня приходит с сервера («вчера», «8 сентября»):
  // считать день на телефоне нельзя, его часовой пояс может не совпадать с нашим.
  const дни = new Map();
  for (const п of лента.посты) {
    const день = (п.published || "").split(" в ")[0] || "без даты";
    if (!дни.has(день)) дни.set(день, []);
    дни.get(день).push(п);
  }

  return шапка + `
    <div class="сколько-нашлось">${число(лента.всего)}
      ${склонить(лента.всего, "пост", "поста", "постов")}${
        отобрано ? " под отбор" : " всего"}</div>
    ${[...дни.entries()].map(([день, посты]) => `
      <div class="lbl">${экр(сПрописной(день))}<span class="счёт">${посты.length}</span></div>
      ${посты.map(строкаВышло).join("")}`).join("")}
    ${лента.ещё ? `<button class="btn ghost wide" id="ещё-ленты"
        ${лента.грузим ? "disabled" : ""} style="margin-top:.75rem"
        >${лента.грузим ? "Читаю…" : "Показать ещё"}</button>` : ""}`;
}

// Строка вышедшего поста. От строки плана отличается тем, что говорит о
// прошлом: час выхода, куда ушло и сколько собрало.
function строкаВышло(п) {
  const рис = кар(п);
  const час = (п.published || "").split(" в ").pop();
  const куда = п.link && !п.link.includes("t.me/") ? "руками" : "телеграм";
  const охват = п.views
    ? `<span class="охват">👁 ${число(п.views)}${
        п.reactions ? " · ♥ " + число(п.reactions) : ""}</span>`
    : `<span class="охват нет">без чисел</span>`;
  return `<button class="line" data-open="${п.id}" style="margin-top:.5rem">
    ${рис ? `<img src="${рис}" alt="Превью: ${экр(п.title)}"
             width="72" height="41" loading="lazy">` : ""}
    <div><div class="t">${экр(п.title)}</div>
      <div class="w past"><span class="цифра">${экр(час)}</span>
        <span class="куда">${куда}</span>${охват}</div></div>
  </button>`;
}


// ── числа ────────────────────────────────────────────────────────────
// Всё рисуется руками на разметке и стилях: политика безопасности не пускает
// внешние скрипты, а два графика того не стоят, чтобы её ослаблять.
function нутроЧисла() {
  if (!числа.было)
    return числа.грузим
      ? `<div class="пусто"><b>Считаю</b>Секунду.</div>`
      : `<div class="пусто"><b>Числа не приехали</b>
           <div style="margin-top:.75rem"><button class="btn ghost"
             id="ещё-числа">Попробовать снова</button></div></div>`;

  const д = числа.данные || {};
  const с = д.summary || {};
  const собрано = д.collected || 0;
  const рост = с.охват_прошлые30
    ? Math.round((с.охват30 - с.охват_прошлые30) / с.охват_прошлые30 * 100) : 0;

  // Герой — одно число, которое отвечает на главный вопрос. Если охватов нет
  // вовсе, героем становится счёт публикаций: пустая рамка со словом «охват»
  // не рассказала бы ничего, а работа при этом сделана и её видно.
  const герой = собрано
    ? `<div class="герой">
         <div class="зн цифра">${число(с.охват30)}</div>
         <div class="подпись">средний охват за 30 дней${
           с.охват_прошлые30 ? `, <span class="${рост >= 0 ? "лучше" : "хуже"}"
             >${рост >= 0 ? "+" : ""}${рост}% к прошлым тридцати</span>` : ""}</div>
       </div>`
    : `<div class="герой">
         <div class="зн цифра">${число(с.всего)}</div>
         <div class="подпись">${склонить(с.всего || 0, "публикация", "публикации",
            "публикаций")} за всё время</div>
       </div>`;

  const плитки = `
    <div class="плитки">
      <div><b class="цифра">${число(с.за7)}</b><span>за неделю</span></div>
      <div><b class="цифра">${число(с.за30)}</b><span>за месяц</span></div>
      <div><b class="цифра">${число(с.всего)}</b><span>всего</span></div>
    </div>`;

  return герой + плитки + понеделям(д.weekly || [])
       + порубрикам(д.by_rubric || [])
       + зашлоНеЗашло(д.best || [], д.worst || [])
       + `<div class="оговорка">
            Просмотры и отклики собираются только по телеграму и только когда
            включён мак: у приложения нет прав на статистику TikTok — ключ
            песочный, и «список моих видео» оно запросить не может. У постов,
            выложенных руками, чисел не будет никогда, только ссылка.
          </div>`;
}

// Динамика по неделям. Один ряд — легенда не нужна, название всё говорит.
// Подписаны только края и наибольшая: число над каждым столбиком превращает
// график обратно в таблицу.
function понеделям(недели) {
  if (!недели.length) return "";
  const макс = Math.max(...недели.map(н => н.штук), 1);
  const где = недели.reduce((л, н, и) => н.штук > недели[л].штук ? и : л, 0);
  return `
    <div class="lbl свер">Выпуск по неделям</div>
    <div class="столбики" role="img"
         aria-label="Выпуск по неделям: ${недели.map(н =>
           `${н.неделя} — ${н.штук}`).join(", ")}">
      ${недели.map((н, и) => `
        <div class="столб">
          <span class="зн ${и === 0 || и === недели.length - 1 || и === где
            ? "" : "тихо"}">${н.штук}</span>
          <i style="height:${Math.max(2, Math.round(н.штук / макс * 100))}%"
             class="${н.штук ? "" : "нуль"}"></i>
          <span class="под">${экр(н.неделя.slice(8))}.${экр(н.неделя.slice(5, 7))}</span>
        </div>`).join("")}
    </div>
    <div class="hint">Неделя начинается с понедельника. Пустая неделя
      остаётся в графике: провал в выпуске — это тоже сведения.</div>`;
}

// Охват по рубрикам. Величина сравнивается длиной, а не цветом, и подписи
// стоят прямо у полос — искать их в легенде не приходится.
function порубрикам(рубрики) {
  if (!рубрики.length) return "";
  const макс = Math.max(...рубрики.map(р => р.avg), 1);
  return `
    <div class="lbl свер">Средний охват по рубрикам</div>
    ${рубрики.map(р => `
      <div class="рубрика-строка">
        <div class="имя">${экр(р.rubric)}${р.shape
          ? ` <span class="муть">${экр(р.shape)}</span>` : ""}</div>
        <div class="жёлоб"><i style="width:${Math.max(2,
          Math.round(р.avg / макс * 100))}%"></i></div>
        <div class="зн цифра">${число(р.avg)}</div>
        <div class="сколько">${р.count}&nbsp;${постов(р.count)}</div>
      </div>`).join("")}`;
}

function зашлоНеЗашло(лучшие, худшие) {
  if (!лучшие.length && !худшие.length)
    return `<div class="lbl свер">Что зашло</div>
      <div class="пусто" style="padding:1.25rem 1rem"><b>Ещё рано сравнивать</b>
        Пока замеров мало или числа слишком близки друг к другу — на такой
        разнице выводы делать нельзя.</div>`;
  const ряд = (посты, вид) => посты.map(п => `
    <div class="итог-пост ${вид}">
      <div class="т">${экр(п.заголовок)}</div>
      <div class="ч"><span class="цифра">${число(п.просмотры)}</span>
        <span class="муть">${экр(п.рубрика || "")}</span></div>
    </div>`).join("");
  return `
    <div class="lbl свер">Что зашло</div>
    ${ряд(лучшие, "верх")}
    ${худшие.length ? `<div class="lbl свер">И что нет</div>${
      ряд(худшие, "низ")}` : ""}`;
}


// ── план ─────────────────────────────────────────────────────────────
// Что выйдет дальше. День — единица, в которой человек думает о выпуске,
// поэтому запланированное разложено по дням, а не свалено одним списком.
function экранПлан() {
  const план = С.schedule || [];
  const черновики = С.drafts || [];
  const ничьи = черновики.filter(п => !(п.where || []).some(в => в.выбрана));
  const ждут = черновики.filter(п => (п.where || []).some(в => в.выбрана));

  // Подпись времени приходит с сервера строкой вида «завтра в 12:00»:
  // часовой пояс телефона может не совпадать с нашим, и день считает сервер.
  const дни = new Map();
  for (const п of план) {
    const день = (п.when || "").split(" в ")[0] || "без времени";
    if (!дни.has(день)) дни.set(день, []);
    дни.get(день).push(п);
  }

  const поДням = [...дни.entries()].map(([день, посты]) => `
    <div class="lbl свер">${экр(сПрописной(день))}
      <span class="счёт">${посты.length}</span></div>
    ${посты.map(п => строка(п, true)).join("")}`).join("");

  if (!план.length && !ничьи.length && !ждут.length)
    return `<div class="пусто"><b>План пуст</b>
      Ни одного поста впереди. Соберите — и он встанет в ближайшую ячейку.</div>
      <button class="btn primary wide" id="создать"
        ${С.mac?.alive ? "" : "disabled"}>✨ Собрать пост</button>`;

  return `
    ${ничьи.length ? `<div class="lbl">Без адреса
        <span class="счёт">${ничьи.length}</span></div>
      <div class="hint" style="margin:-.25rem 0 .5rem">Площадка не выбрана —
        такой пост никуда не поедет, пока не скажете куда.</div>
      ${ничьи.map(п => строка(п)).join("")}` : ""}

    ${поДням || ""}

    ${ждут.length ? `<div class="lbl свер">Ждут одобрения
        <span class="счёт">${ждут.length}</span></div>
      <div class="hint" style="margin:-.25rem 0 .5rem">Площадка выбрана, но
        ячейка не назначена: до одобрения пост в смену не встаёт.</div>
      ${ждут.map(п => строка(п)).join("")}` : ""}`;
}


function строка(п, толькоЧасы) {
  const рис = кар(п);
  const час = толькоЧасы && п.when ? п.when.split(" в ").pop() : п.when;
  // Пост, отданный телеграму, выйдет даже когда всё выключено. Разное
  // поведение должно и выглядеть по-разному.
  const сам = п.at_telegram ? ' <span class="сам">выйдет сам</span>' : "";
  const охват = п.views ? `<span class="охват">👁 ${п.views}</span>` : "";
  const метка = (п.images || []).length ? ` · 🎠 ${п.images.length}` : "";
  const когда = п.when ? `<div class="w">${час}${сам}${метка}</div>`
              : п.published ? `<div class="w past">вышел ${п.published} ${охват}</div>` : "";
  return `<button class="line" data-open="${п.id}" style="margin-top:.5rem">
    ${рис ? `<img src="${рис}" alt="Превью: ${экр(п.title)}"
             width="72" height="41" loading="lazy">` : ""}
    <div><div class="t">${экр(п.title)}</div>${когда}</div>
  </button>`;
}

