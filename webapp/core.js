// Русское число согласуется по последней цифре, кроме подростков.
function склонить(н, один, два, много) {
  if (н % 100 >= 11 && н % 100 <= 14) return много;
  const п = н % 10;
  return п === 1 ? один : п >= 2 && п <= 4 ? два : много;
}
