# -*- coding: utf-8 -*-
"""Экраны бота: что показать и чем это нажимается.

Экран здесь — чистая функция «кто нажал → заголовок, текст, ряды кнопок».
Она ничего не отправляет и ничего не пишет: читать базу и настройки можно
(иначе показывать нечего), а записывать и слать — нет. Отправкой занимается
`навигация.py`, изменениями — действия ниже по файлу.

Разделение нужно не ради красоты. Экран, который сам себя отправляет,
невозможно проверить, не подняв телеграм; экран как функция проверяется
обычным тестом, и статическая проверка может обойти их все разом — убедиться,
что у каждого объявлен родитель, что «назад» доходит до главного и что ни одна
кнопка не ведёт в никуда.

Родитель объявляется прямо у функции, а не запоминается по пути. Стек в памяти
терялся бы при перезапуске бота, и «назад» из одного и того же места вело бы
каждый раз в разное. По родителю из «Доступа» назад всегда в «Настройки»,
откуда бы туда ни пришли.
"""

from dataclasses import dataclass, field
from typing import Callable

import telegram as tg

# ── что такое экран ─────────────────────────────────────────────────────────

# Ряды: список рядов, ряд — список кнопок. Кнопка это пара (подпись, данные)
# либо готовый словарь (так пробрасывается tg.кнопка_приложения).
Ряды = list


@dataclass(frozen=True)
class Экран:
    заголовок: str
    текст: str = ""
    ряды: Ряды = field(default_factory=list)


@dataclass(frozen=True)
class Пар:
    """Всё, что экрану и действию нужно знать о нажавшем.

    Права приходят готовыми, а не выясняются внутри каждого экрана: иначе
    один и тот же вопрос «владелец ли» задавался бы базе по десять раз на
    отрисовку.
    """
    чат: int
    арг: str = ""            # что подставилось вместо «*» в коде экрана
    владелец: bool = False
    публикует: bool = True
    сообщение: int = 0       # сообщение, с которого нажали


class НетЭкрана(Exception):
    """Того, что показывали, больше нет: станка, поста, человека.

    Навигация покажет родителя и скажет причину. Молчать нельзя — кнопка
    могла остаться в истории чата со вчера.
    """


# ── реестр ──────────────────────────────────────────────────────────────────

@dataclass(frozen=True)
class Запись:
    код: str
    родитель: str | None
    имя: str
    только_владельцу: bool
    собрать: Callable[[Пар], Экран]


РЕЕСТР: dict[str, Запись] = {}

# Кнопки, разосланные до пересборки, остаются в истории чата живыми. Пусть
# ведут куда положено, а не отвечают «кнопка устарела».
СИНОНИМЫ = {"menu": "home", "rubrics": "r", "cv": "shop"}

# Заполнитель: экран кладёт его в ряд, где хочет видеть «назад» рядом с
# другой кнопкой. Сборщик клавиатуры подменит его на настоящую кнопку с
# кодом родителя.
НАЗАД = ("⬅️ Назад", "")


def экран(код: str, родитель: str | None, имя: str,
          только_владельцу: bool = False):
    """Объявляет экран. Родитель обязателен всем, кроме главного."""
    def обернуть(функция):
        if код != "home" and not родитель:
            raise ValueError(f"экран {код}: не объявлен родитель")
        РЕЕСТР[код] = Запись(код, родитель, имя, только_владельцу, функция)
        return функция
    return обернуть


def _подходит(шаблон: str, код: str) -> str | None:
    """Совпал ли код с шаблоном вида «set:acc:*». Возвращает аргумент."""
    ш, к = шаблон.split(":"), код.split(":")
    if len(ш) != len(к):
        return None
    арг = ""
    for части_ш, части_к in zip(ш, к):
        if части_ш == "*":
            арг = части_к
        elif части_ш != части_к:
            return None
    return арг


def найти(код: str) -> tuple[Запись | None, str]:
    """Запись экрана и подставленный аргумент.

    Сперва точное совпадение, потом шаблоны. Из нескольких подошедших
    шаблонов выигрывает тот, где меньше звёздочек: «set:acc:*» конкретнее,
    чем гипотетический «set:*:*».
    """
    код = СИНОНИМЫ.get(код, код)
    if код in РЕЕСТР:
        return РЕЕСТР[код], ""
    лучший, лучший_арг, звёзд = None, "", 99
    for шаблон, запись in РЕЕСТР.items():
        if "*" not in шаблон:
            continue
        арг = _подходит(шаблон, код)
        if арг is None:
            continue
        сколько = шаблон.count("*")
        if сколько < звёзд:
            лучший, лучший_арг, звёзд = запись, арг, сколько
    return лучший, лучший_арг


def есть(код: str) -> bool:
    return найти(код)[0] is not None


def родитель(код: str) -> str | None:
    """Куда ведёт «назад». Аргумент подставляется и в родителя тоже."""
    запись, арг = найти(код)
    if not запись or not запись.родитель:
        return None
    return запись.родитель.replace("*", арг) if арг else запись.родитель


def путь(код: str) -> list[str]:
    """Цепочка от главного до этого экрана. Пустая, если экрана нет."""
    запись, _ = найти(код)
    if not запись:
        return []
    цепочка, текущий = [], код
    # Потолок, а не «пока не None»: кольцо в родителях иначе завесило бы бота
    # намертво. Само кольцо ловит статическая проверка, здесь — страховка.
    for _ in range(12):
        цепочка.insert(0, текущий)
        текущий = родитель(текущий)
        if not текущий:
            break
    return цепочка


def крошки(код: str, заголовок: str = "") -> str:
    """Где человек находится. Пусто до третьего уровня — там и так видно.

    Последняя крошка — живой заголовок экрана, а не родовое имя из реестра.
    У параметризованных экранов это разные вещи: в реестре станок записан как
    «🏭 Станок», а показывать надо «📣 Телеграм». Крошки заменяют собой строку
    заголовка, поэтому родовое имя в конце просто съело бы имя площадки.
    """
    цепочка = путь(код)
    if len(цепочка) < 3:
        return ""
    имена = []
    for к in цепочка[1:-1]:
        запись, _ = найти(к)
        if запись:
            имена.append(запись.имя)
    последний, _ = найти(цепочка[-1])
    имена.append(заголовок or (последний.имя if последний else код))
    return " › ".join(имена)


def клавиатура(код: str, э: Экран) -> str:
    """Собирает клавиатуру экрана и дописывает «назад».

    Кнопку «назад» экран не пишет сам: её цель выводится из реестра, и
    данные у неё — просто код родителя. Поэтому она работает после
    перезапуска бота и попадает под общую проверку «каждая кнопка
    разбирается маршрутом».
    """
    ряды = [list(р) for р in э.ряды]
    куда = родитель(код)
    if not куда:
        return tg.кнопки(ряды)
    кнопка = ("⬅️ Назад", куда)
    for ряд in ряды:
        for i, к in enumerate(ряд):
            if к == НАЗАД:
                ряд[i] = кнопка
                return tg.кнопки(ряды)
    ряды.append([кнопка])
    return tg.кнопки(ряды)


# ── действия ────────────────────────────────────────────────────────────────

@dataclass(frozen=True)
class Действие:
    код: str
    сделать: Callable[[Пар], str | None]
    ответ: str
    только_владельцу: bool
    публикует: bool
    на_карточке: bool


ДЕЙСТВИЯ: dict[str, Действие] = {}


def действие(код: str, ответ: str = "", только_владельцу: bool = False,
             публикует: bool = False, на_карточке: bool = False):
    """Объявляет нажатие, которое что-то меняет.

    Обработчик возвращает код экрана, который показать после, либо None —
    «перерисовать тот, откуда нажали». Действия на карточке поста живут на
    сообщении с картинкой: правкой текста его не тронуть, телеграм не даст,
    поэтому меню после них не перерисовывается.
    """
    def обернуть(функция):
        ДЕЙСТВИЯ[код] = Действие(код, функция, ответ, только_владельцу,
                                 публикует, на_карточке)
        return функция
    return обернуть


def найти_действие(данные: str) -> tuple[Действие | None, str]:
    if данные in ДЕЙСТВИЯ:
        return ДЕЙСТВИЯ[данные], ""
    лучший, лучший_арг, звёзд = None, "", 99
    for шаблон, д in ДЕЙСТВИЯ.items():
        if "*" not in шаблон:
            continue
        арг = _подходит(шаблон, данные)
        if арг is None:
            continue
        сколько = шаблон.count("*")
        if сколько < звёзд:
            лучший, лучший_арг, звёзд = д, арг, сколько
    return лучший, лучший_арг


# ── адрес мини-приложения ───────────────────────────────────────────────────
# Ставит его bot при подъёме туннеля. Живёт здесь, а не в навигации, чтобы
# не заводить круг импортов: навигация знает про экраны, экраны про неё — нет.
АДРЕС = ""


def _чаты_доступны() -> bool:
    """Есть ли чем читать чужие чаты.

    Читает их аккаунт владельца, а не бот: боту Telegram чужую переписку не
    отдаёт вовсе. Без входа в аккаунт раздел пустой, и показывать его незачем.
    """
    try:
        import userbot
        return userbot.вошли()
    except Exception:                                        # noqa: BLE001
        return False


# ── перенос нынешних меню ───────────────────────────────────────────────────
# Пока — дословно, теми же кнопками и теми же callback_data. Шаг намеренно
# меняет устройство, не меняя поведения: только так новый каркас можно сверить
# со старым ботом кнопка в кнопку. Всё новое приходит следом.


@экран("home", родитель=None, имя="🐈‍⬛ Редактор")
def главный(п: Пар) -> Экран:
    """Главное меню. Одна строка это один вид работы, без вложенности.

    Разделы, которых у владельца сейчас нет, не показываются вовсе: пустая
    кнопка, отвечающая «не настроено», путает сильнее, чем её отсутствие.
    """
    import access
    import channels
    import core
    ряды = []
    if АДРЕС:
        # Кнопка внутри сообщения несёт адрес с собой, поэтому она всегда
        # свежая, даже если кнопка меню у человека осталась со вчера.
        ряды.append([tg.кнопка_приложения("🖥 Открыть приложение", АДРЕС)])
    ряды += [
        [("✍️ Пост в канал", "gen:auto"), ("🎠 Карусель", "carousel")],
        [("🎯 Пост по рубрике", "rubrics"), ("🔴 Анонс стрима", "stream")],
    ]
    if _чаты_доступны():
        ряды.append([("💬 Ответы в чатах", "rep")])
    ряды += [
        [("🤖 Конвейер", "cv")],
        [("🗓 Расписание", "plan"), ("📊 Сводка", "stat")],
        # У переключателей стрелка на конце. Без неё они читаются как надписи,
        # и непонятно, что их можно нажать и что от нажатия изменится.
        [(("📣 Канал: " if channels.основной_выбран() else "🧪 Канал: ")
          + channels.текущий() + " ›", "chan"),
         ("🔕 Звук: выкл ›" if core.звук_выключен() else "🔔 Звук: вкл ›",
          "sound")],
    ]
    # Открытая дверь показывается прямо в меню и всегда со сроком: так о ней
    # невозможно забыть.
    осталось = access.открыто()
    if осталось:
        ряды.append([(f"🔓 Открыто для всех, {осталось:.0f} ч", "shut")])
    return Экран("🐈‍⬛ *Редактор 4xTube*", "Что делаем?", ряды)


@экран("r", родитель="home", имя="🎯 Рубрики")
def рубрики(п: Пар) -> Экран:
    """Рубрики поста отдельным экраном, чтобы не теснить главное меню."""
    from content import РУБРИКИ
    значки = {"полезное": "💡", "как это устроено": "⚙️", "деньги": "💰",
              "опыт": "🛠", "находка": "🔎", "от себя": "🙋"}
    ряды, пара = [], []
    for р in РУБРИКИ:
        пара.append((f"{значки.get(р, '•')} {р.capitalize()}", f"gen:{р}"))
        if len(пара) == 2:
            ряды.append(пара)
            пара = []
    if пара:
        ряды.append(пара)
    return Экран("🎯 *О чём пишем?*",
                 "Без выбора бот берёт рубрику сам, глядя на то, чего давно "
                 "не было.", ряды)


@экран("shop", родитель="home", имя="🤖 Конвейер")
def цех(п: Пар) -> Экран:
    """Конвейер. Одна строка на площадку: включён ли и насколько полон план."""
    import конвейер
    import площадки as пл
    ряды, строки = [], []
    for куда in конвейер.ПО_УМОЛЧАНИЮ:
        с = конвейер.настройки(куда)
        значок = "🤖" if с["вкл"] else "💤"
        ряды.append([(f"{значок} {пл.имя(куда)} · "
                      f"{len(конвейер.в_плане(куда))} из {конвейер.запас(куда)}",
                      f"cv:{куда}")])
        строки.append(
            f"{пл.имя(куда)} · {'включён' if с['вкл'] else 'спит'} · "
            f"{'публикует сам' if с.get('режим', 'сам') == 'сам' else 'готовит, публикуете вы'}"
            f" · {пл.СПИСОК[куда]['поясн']}")
    ряды.append([("🎠 Собрать карусель сейчас", "cv:new")])
    return Экран("🤖 *Конвейер*",
                 "\n".join(строки) +
                 "\n\nВключённая площадка держит план полным сама: берёт "
                 "следующий угол по кругу, сочиняет, рисует и ставит время. "
                 "Готовое покажу, снять можно кнопкой.", ряды)


@экран("cv:*", родитель="shop", имя="🏭 Станок")
def станок(п: Пар) -> Экран:
    """Настройки одной площадки внутри конвейера."""
    import конвейер
    import площадки as пл
    куда = п.арг
    if куда not in конвейер.ПО_УМОЛЧАНИЮ:
        raise НетЭкрана("Такой площадки больше нет")
    с = конвейер.настройки(куда)
    сам = с.get("режим", "сам") == "сам"
    текст = (f"{пл.СПИСОК[куда]['поясн'].capitalize()}.\n"
             f"Выходит в {', '.join(с['часы'])}.\n"
             f"В плане {len(конвейер.в_плане(куда))} из {конвейер.запас(куда)}.")
    return Экран(пл.имя(куда), текст, [
        [(("🤖 Сам сочиняет" if с["вкл"] else "💤 Спит"), f"cv:{куда}:auto")],
        [(("🚀 Публикует сам ›" if сам else "✋ Готовит, публикую я ›"),
          f"cv:{куда}:mode")],
        [(f"🕑 Часы: {', '.join(с['часы'])} ›", f"cv:{куда}:hours")],
        [(f"📅 Держать вперёд: {с['дней']} дн. ›", f"cv:{куда}:days")],
        [("🎠 Собрать сюда сейчас", f"cv:{куда}:new")],
    ])
