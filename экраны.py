# ── очередь ─────────────────────────────────────────────────────────────────

СТРОК = 12          # столько постов показываем кнопками
ЗАГОЛОВОК = 24      # столько букв заголовка влезает в кнопку на узком экране


def _коротко(заголовок: str, предел: int = ЗАГОЛОВОК) -> str:
    """Обрезает заголовок так, чтобы кнопка не разъехалась на две строки.

    Кнопка с длинной подписью не обрезается телеграмом — она переносится, и
    список из таких кнопок перестаёт читаться столбцом. Многоточие на конце
    честнее обрыва на полуслове: видно, что это не весь заголовок.
    """
    заголовок = " ".join((заголовок or "без заголовка").split())
    return заголовок if len(заголовок) <= предел else заголовок[:предел - 1] + "…"


@экран("q", родитель="home", имя="🗓 Очередь")
def очередь(п: Пар) -> Экран:
    """План и черновики одним списком: значок отличает, тычок открывает.

    Одним, а не двумя разделами: человек держит в голове «что у меня сейчас
    в работе», а не «что из этого со временем, а что без». Время у строки и
    так видно.
    """
    import db
    import times
    # Один поход в базу вместо двух: она за океаном, и каждый запрос это
    # доли секунды на пустом месте. История здесь не нужна — она в «Сводке».
    план, черновики, _ = db.для_экрана(None, черновиков=СТРОК, истории=0)
    ряды = []
    for пост in (list(план) + list(черновики))[:СТРОК]:
        если_план = пост["status"] == "scheduled"
        когда = ""
        if если_план and пост["scheduled_at"]:
            try:
                когда = times.подпись(times.из_базы(пост["scheduled_at"]))
            except (ValueError, TypeError):
                когда = ""
        метка = f"🕑 {когда}" if если_план else "📝 черновик"
        ряды.append([(f"{метка} · {_коротко(пост['title'])}", f"p:{пост['id']}")])

    всего = len(план) + len(черновики)
    хвост = всего - len(ряды)
    if not всего:
        текст = ("Пусто. Сочините пост — он появится здесь, и время ему "
                 "ставится отсюда же.")
    else:
        текст = (f"В плане {len(план)} · черновиков {len(черновики)}."
                 + (f"\nПоказал первые {len(ряды)}, ещё {хвост} в приложении."
                    if хвост > 0 else ""))
    ряды.append([("📊 Сводка", "q:sum"), НАЗАД])
    return Экран("🗓 *Очередь*", текст, ряды)


@экран("q:sum", родитель="q", имя="📊 Сводка")
def сводка(п: Пар) -> Экран:
    """Сколько всего и что заходит.

    Средние просмотры по рубрикам стоят рядом с числами намеренно: «сделано
    сорок постов» само по себе ничего не говорит, а «разбор читают вдвое
    лучше находок» меняет то, о чём писать завтра.
    """
    import db
    с = db.сводка()
    строки = [f"🚀 Опубликовано: {с['опубликовано']}",
              f"🗓 Запланировано: {с['запланировано']}",
              f"📝 Черновиков: {с['черновики']}"]
    охват = db.охват_по_рубрикам()
    if охват:
        строки.append("\n*Средние просмотры*")
        for р in охват[:6]:
            рубрика = р["rubric"] or "без рубрики"
            форма = f" · {р['shape']}" if р["shape"] else ""
            строки.append(f"• {рубрика}{форма} · {round(р['среднее'] or 0)}"
                          f" (постов {р['штук']})")
    else:
        строки.append("\nПросмотры собираются по основному каналу и появятся "
                      "здесь после первых публикаций.")
    return Экран("📊 *Сводка*", "\n".join(строки), [])


