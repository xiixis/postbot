@экран("ideas", родитель="make", имя="💡 Копилка")
def копилка(п: Пар) -> Экран:
    """Заметки, отложенные на потом. Тычок берёт заметку в работу.

    Материал попадается днём, а писать садятся вечером — копилка и есть этот
    разрыв. Из бота она до сих пор была невидима: заметки в неё падали, а
    посмотреть, что накопилось, можно было только в приложении.
    """
    список = _идей()
    ряды = [[(_коротко(и["text"], 34), f"idea:{и['id']}")]
            for и in список[:ИДЕЙ]]
    хвост = len(список) - len(ряды)
    if список:
        текст = ("Тычок — сделать пост из заметки. Она израсходуется."
                 + (f"\nПоказал {len(ряды)}, ещё {хвост} в приложении."
                    if хвост > 0 else ""))
        ряды.append([("➕ Добавить", "idnew"), ("🗑 Убрать", "ideas:rm")])
    else:
        текст = ("Пусто. Любое сообщение боту ложится сюда — ссылка, мысль, "
                 "обрывок фразы.")
        ряды.append([("➕ Добавить", "idnew")])
    return Экран("💡 *Копилка*", текст, ряды)


