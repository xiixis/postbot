# -*- coding: utf-8 -*-
"""Что не так с постом. Замечания без модели и без сети.

Композицию карточки бот проверяет замером и сам убирает кота, если тот
наложится на текст. С текстом такого не было: что модель написала, то и
уходило владельцу, а через него в канал. Между тем половина настоящих бед
видна простым счётом: подпись длиннее того, что примет площадка; название
пустое; первая строка потрачена на разговорный разгон; хештегов три вместо
пяти.

Здесь именно такие придирки — те, у которых есть однозначный ответ. Про
«скучно» и «не цепляет» пусть судит человек, машине тут делать нечего.

Замечания не запрещают публикацию. Они показываются рядом с черновиком,
чтобы владелец знал, на что смотреть, и мог поправить одним нажатием.
"""

import json
import re

import db
import площадки

# Обороты, которыми начинают, когда не решили, с чего начать. В TikTok первая
# строка это весь пост: до нажатия «ещё» видно около сотни символов.
РАЗГОН = ("сегодня", "в этом посте", "в этой карусели", "расскажу",
          "поговорим", "давайте", "хочу рассказать", "речь пойдёт",
          "как известно", "ни для кого не секрет", "многие не знают")
ПЕРВАЯ_СТРОКА = 110          # столько видно до нажатия «ещё»
НАЗВАНИЕ = 90                # предел поля названия у фотопоста
ХЕШТЕГОВ = (6, 8)            # канон один на весь проект, см. Style/выпуск.ХЕШТЕГОВ:
                             # пять ставит половина ниши, и замер даёт им 23 тыс.
                             # показов против 159 тыс. у шести и больше
СЛАЙДОВ_МИНИМУМ = {"tiktok": 4, "телеграм": 2}

РАЗМЕТКА = re.compile(r"\*\*|__|`|\[[^\]]+\]\([^)]+\)")


def к_посту(ряд) -> list[str]:
    """Все замечания к одному черновику. Пустой список значит «придраться не к чему»."""
    if not ряд:
        return []
    поля = db.карточка(ряд) or {}
    площадка = поля.get("площадка") or "телеграм"
    карусель = поля.get("carousel")
    беды = _приёмка(поля) + _предполёт(поля) + _общее(ряд, площадка)
    if карусель:
        беды += _карусель(ряд, карусель, площадка)
        беды += _слайды_карусели(карусель)
    return беды


def _приёмка(поля: dict) -> list[str]:
    """Брак кадров первым: остальное неважно, пока картинка сломана."""
    import приёмка
    отчёт = поля.get("приёмка")
    if приёмка.годен(отчёт):
        return []
    return ["брак кадров, сам в папку и в план не уедет: " + приёмка.строкой(отчёт)]


def _предполёт(поля: dict) -> list[str]:
    """Что предполёт поменял до отрисовки и на что просит взглянуть.

    Поправленное показывается всегда: вёрстка слайда стала не той, что была в
    эскизе, и владелец должен это увидеть, а не найти на кадре.
    """
    import предполёт
    отчёт = поля.get("предполёт")
    if not отчёт:
        return []
    беды = []
    if отчёт.get("исправлено"):
        беды.append("до отрисовки поправлено: " + "; ".join(отчёт["исправлено"]))
    сказать = предполёт.строкой(отчёт)
    if сказать:
        беды.append("предполёт: " + сказать)
    return беды


def _общее(ряд, площадка: str) -> list[str]:
    беды = []
    тело = (ряд["body"] or "").strip()
    if not тело:
        беды.append("текста нет вовсе")
        return беды
    предел = площадки.предел(площадка)
    if len(тело) > предел:
        # У телеграма это не придирка, а отказ: подпись под картинкой длиннее
        # тысячи с небольшим символов не отправится вообще.
        беды.append(f"подпись {len(тело)} символов, {площадка} берёт {предел}")
    if not (ряд["title"] or "").strip():
        беды.append("заголовка нет")
    беды += _валюта(ряд)
    беды += _следы_ии(ряд)
    return беды


def _следы_ии(ряд) -> list[str]:
    """Жёсткие запреты «Антидетектора» в подписи и на слайдах.

    Голос текста просит так не писать, но просьба не гарантия. Слайды
    проверяются вместе с подписью: «данный приём» на кадре выдаёт нейросеть
    так же, как в тексте под ним.
    """
    import следы_ии
    куски = [ряд["body"] or ""]
    к = (db.карточка(ряд) or {}).get("carousel") or {}
    for с in к.get("slides") or []:
        куски += [str(с.get(п) or "") for п in ("заголовок", "текст", "значение")]
        куски += [str(х) for х in (с.get("строки") or [])]
    куски += [str(к.get(п) or "") for п in ("cover_kicker", "cover_title", "closing")]
    найдено = следы_ии.найти("\n\n".join(куски))
    if not найдено:
        return []
    return ["следы нейросети: " + "; ".join(найдено)]


# Валюта у нас одна — доллар. Софт, о котором мы пишем, продаётся в долларах, и
# пересчёт в рубли или гривны врёт уже назавтра. Правило записано в голосе
# канала, но промпт не гарантия: «Edge TTS, ноль рублей» и «0 ₽» доехали до
# готовых постов. Поэтому ловим ещё и здесь, на готовом.
ЧУЖИЕ_ДЕНЬГИ = re.compile(
    r"(₽|₴|€|\bруб\w*|\bгривн\w*|\bгривен\b|\bевро\b)", re.I)


def _валюта(ряд) -> list[str]:
    """Рубли, гривны и евро в тексте или на слайдах."""
    куски = [ряд["title"] or "", ряд["body"] or "",
             json.dumps(db.карточка(ряд) or {}, ensure_ascii=False)]
    найдено = {м.group(0).lower() for к in куски for м in ЧУЖИЕ_ДЕНЬГИ.finditer(к)}
    if not найдено:
        return []
    return [f"валюта не долларовая: {', '.join(sorted(найдено))} — "
            f"у нас только доллары"]


def _карусель(ряд, к: dict, площадка: str) -> list[str]:
    беды = []
    слайдов = len(db.картинки(ряд) or [])
    нужно = СЛАЙДОВ_МИНИМУМ.get(площадка, 2)
    if слайдов < нужно:
        беды.append(f"слайдов {слайдов}, {площадка} принимает от {нужно}")

    первая = ((ряд["body"] or "").strip().splitlines() or [""])[0].strip()
    if len(первая) > ПЕРВАЯ_СТРОКА:
        беды.append(f"первая строка {len(первая)} символов, видно около "
                    f"{ПЕРВАЯ_СТРОКА}: крючок обрежется на середине")
    низ = первая.lower()
    if any(низ.startswith(о) for о in РАЗГОН):
        беды.append("первая строка начинается с разгона, а не с крючка")

    if площадка != "tiktok":
        return беды

    название = (к.get("название") or "").strip()
    if not название:
        беды.append("название не заполнено, в поле поиска уйдёт заголовок обложки")
    elif len(название) > НАЗВАНИЕ:
        беды.append(f"название {len(название)} символов, TikTok берёт {НАЗВАНИЕ}")
    метки = [м for м in (к.get("hashtags") or []) if str(м).startswith("#")]
    если_мало, если_много = ХЕШТЕГОВ
    if not (если_мало <= len(метки) <= если_много):
        беды.append(f"хештегов {len(метки)}, нужно от {если_мало} до {если_много}")
    if РАЗМЕТКА.search(ряд["body"] or ""):
        беды.append("в подписи осталась разметка, TikTok покажет её как есть")
    return беды


def запасные_заголовки(ряд) -> list[str]:
    """Другие заголовки к тому же посту, если модель их принесла.

    Заголовок решает судьбу поста сильнее остального текста, а приходил он в
    одном экземпляре: сравнить было не с чем, и владелец либо соглашался, либо
    просил переписать весь пост целиком. Три варианта стоят того же одного
    обращения к модели.
    """
    поля = db.карточка(ряд) or {}
    свой = (ряд["title"] or "").strip()
    return [з.strip() for з in (поля.get("запасные") or [])
            if з and з.strip() and з.strip() != свой]


# Сколько текста держит внимание. Три-пять секунд чтения на слайд: на трёх
# словах зритель не задержится, на абзаце бросит. Числа с запасом, это границы
# явного перебора, а не идеал.
ТЕКСТА_НА_СЛАЙДЕ = (18, 210)
СЛАЙДОВ_СЕРЕДИНЫ = (3, 10)


def _слайды_карусели(к: dict) -> list[str]:
    """Придирки к самим слайдам: длина, однообразие, количество."""
    беды = []
    слайды = к.get("slides") or []
    мало, много = СЛАЙДОВ_СЕРЕДИНЫ
    if слайды and not (мало <= len(слайды) <= много):
        беды.append(f"слайдов середины {len(слайды)}, рабочий диапазон "
                    f"{мало}–{много}")

    коротких, длинных = [], []
    for н, с in enumerate(слайды, start=2):
        свой = " ".join(str(с.get(п) or "") for п in ("заголовок", "текст"))
        свой = " ".join(f"{свой} {' '.join(str(х) for х in (с.get('строки') or []))}".split())
        if len(свой) < ТЕКСТА_НА_СЛАЙДЕ[0]:
            коротких.append(н)
        elif len(свой) > ТЕКСТА_НА_СЛАЙДЕ[1]:
            длинных.append(н)
    if коротких:
        беды.append("слайды пролистают, не остановившись, там нечего читать: "
                    + ", ".join(f"№{н}" for н in коротких))
    if длинных:
        беды.append("слайды перегружены, их бросают: "
                    + ", ".join(f"№{н}" for н in длинных))

    # Слайды середины идут со второго: первый это обложка. Нумеруем так, как их
    # видит человек, иначе замечание указывает не на тот слайд.
    подряд = [f"№{н + 2}" for н in range(1, len(слайды))
              if (слайды[н].get("вид") or "") == (слайды[н - 1].get("вид") or "")]
    if подряд:
        беды.append("одна вёрстка подряд, однообразие видно раньше содержания: "
                    + ", ".join(подряд))
    return беды


def строкой(ряд) -> str:
    """Замечания и подсказки одним сообщением. Пусто, если сказать нечего."""
    куски = []
    беды = к_посту(ряд)
    if беды:
        куски.append("⚠️ " + "; ".join(беды))
    иначе = запасные_заголовки(ряд)
    if иначе:
        куски.append("💡 Другие заголовки:\n"
                     + "\n".join(f"  • {з}" for з in иначе))
    return "\n\n".join(куски)
