def главный_цикл() -> None:
    смещение = 0
    while ЖИВЁМ:
        try:
            догнать(config.АДМИН)
        except Exception:                                    # noqa: BLE001
            traceback.print_exc()

        # Конвейер: раз в сутки добираем план, если он просел. Работа
        # долгая, но она в том же круге, что и всё остальное: пока рисуются
        # слайды, бот всё равно никому не отвечает, и разносить это по нитям
        # значило бы ловить две генерации разом.
        try:
            import конвейер
            if конвейер.пора():
                догнать_конвейер(config.АДМИН)
        except Exception:                                    # noqa: BLE001
            traceback.print_exc()

        # Раз в сутки выносим мусор: отрисовки, которые ни к какому посту уже
        # не относятся. Молча, докладывать тут не о чем.
        try:
            import уборка
            if уборка.пора():
                итог = уборка.прибраться()
                всего = итог["диск"]["мегабайт"] + итог["хранилище"]["мегабайт"]
                if всего >= 1:
                    print(f"уборка: освободил {всего} МБ")
        except Exception:                                    # noqa: BLE001
            traceback.print_exc()

        for об in tg.обновления(смещение):
            смещение = об["update_id"] + 1
            try:
                if "callback_query" in об:
                    к = об["callback_query"]
                    чат = к["message"]["chat"]["id"]
                    # Гасилка «часиков» едет внутрь разбора, а не гасит их
                    # здесь: раньше ответ уходил до разбора, и текст в него
                    # физически не попадал — всплывашка «этого черновика уже
                    # нет» была невозможна. Подстраховка в finally: молчание
                    # телеграм показывает крутящимися часиками, и человек
                    # решает, что бот умер.
                    ответ = навигация.Ответ(к["id"])
                    if not свой(чат):
                        ответ.сказать()
                        continue
                    try:
                        разобрать_кнопку(
                            к.get("data", ""), чат,
                            к["message"]["message_id"],
                            None if access.владелец(чат) else _имя(к["from"]),
                            ответ)
                    finally:
                        ответ.сказать()

                elif "message" in об:
                    м = об["message"]
                    чат = м["chat"]["id"]
                    текст = (м.get("text") or "").strip()
                    if not свой(чат):
                        чужой(чат, текст, _имя(м.get("from", {})))
                        continue
                    if голосом(чат, м):
                        continue
                    if текст.startswith(("/start", "/menu")):
                        навигация.показать(чат, "home", владелец=access.владелец(чат),
                                           публикует=access.может_публиковать(чат))
                    elif текст.startswith("/plan"):
                        расписание(чат)
                    elif текст.startswith("/id"):
                        tg.написать(чат, f"chat_id: `{чат}`")
                    elif ответить_словами(чат, текст):
                        pass
                    elif чат in ЖДЁМ_ПРАВКУ and текст:
                        применить_правку(чат, текст)
                    elif чат in ЖДЁМ_ОКНО and текст:
                        задать_окно(чат, текст)
                    elif чат in ЖДЁМ_ЧАСЫ and текст:
                        задать_часы(чат, текст)
                    elif чат in ЖДЁМ_ФАКТ and текст:
                        ЖДЁМ_ФАКТ.discard(чат)
                        сделать_пост(чат, "от себя", текст)
                    elif текст and not текст.startswith("/"):
                        # Написанное сообщение это идея или ссылка. Кладём в
                        # копилку сразу: материал попадается днём, а писать
                        # садятся вечером. И тут же предлагаем сделать пост,
                        # если время есть прямо сейчас.
                        отложить_идею(чат, текст)
            except Exception:                                # noqa: BLE001
                traceback.print_exc()


def поднять_приложение() -> None:
    """Сервер мини-приложения и его публичный адрес."""
    global АДРЕС
    webapp.поднять(config.ПОРТ)
    print(f"веб-приложение на http://localhost:{config.ПОРТ}")

    if config.АДРЕС_ВЕБА:
        АДРЕС = config.АДРЕС_ВЕБА
        экраны.АДРЕС = АДРЕС
    elif tunnel.доступен():
        print("поднимаю туннель…")
        АДРЕС, _ = tunnel.поднять(config.ПОРТ)
        # Экраны берут адрес отсюда. Забыть эту строку — значит потерять
        # кнопку «Открыть приложение», и обнаружится это не ошибкой, а её
        # отсутствием: искать будешь долго.
        экраны.АДРЕС = АДРЕС
    else:
        print("cloudflared не найден, мини-приложение открыть будет нельзя.\n"
              "  Поставить:  brew install cloudflared\n"
              "  Или пропишите свой https-адрес в WEBAPP_URL.\n"
              "  Кнопки в чате работают и без него.")
        return

    if not АДРЕС:
        print("туннель не поднялся, остаются кнопки в чате")
        return
    print(f"мини-приложение: {АДРЕС}")
    раздать_кнопку()


def раздать_кнопку() -> None:
    """Ставит кнопку приложения всем своим, а не только владельцу.

    Адрес туннеля меняется при каждом запуске, и кнопка, поставленная вчера,
    ведёт в никуда: приложение открывается пустым экраном и бесконечным
    ожиданием. Поэтому кнопку переставляем на каждом старте и каждому, у кого
    есть доступ.
    """
    if not АДРЕС:
        return
    for кому in [config.АДМИН, *access.свои()]:
        try:
            tg.меню_приложения(АДРЕС, кому)
        except Exception as e:                               # noqa: BLE001
            print(f"кнопка меню для {кому} не встала:", e)


