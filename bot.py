def ответить_словами(чат: int, текст: str) -> bool:
    """Ответ на заданный вопрос. Ложь означает «вопроса не было».

    Возврат важен: не разобранный здесь текст уходит в копилку, и молча
    съесть его нельзя — как нельзя и класть туда ответ на вопрос.
    """
    ждём = навигация.чего_ждём(чат)
    if not ждём or not текст:
        return False
    что, _данные = ждём
    навигация.забыть(чат)
    if что == "тема":
        сделать_пост(чат, None, текст)
        return True
    if что == "идея":
        import ideas
        ideas.подготовить()
        try:
            ideas.добавить(текст)
        except ValueError:
            return True
        # Заметку клали из копилки — там ей и появиться. Спрашивать «сделать
        # пост сейчас?», как на обычное сообщение, здесь незачем: человек уже
        # сказал, что откладывает.
        навигация.перерисовать(чат, "ideas", access.владелец(чат),
                               access.может_публиковать(чат))
        return True
    return False


