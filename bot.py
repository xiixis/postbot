def превью_кнопки(ид: int) -> str:
    """Кнопки под черновиком: сначала куда, потом когда.

    Порядок не случайный. «Куда» меняет и картинки, и текст, поэтому решать
    это надо до того, как назначено время. Галочки стоят на самой карточке и
    переключаются на месте, чтобы чат не превращался в ленту одинаковых
    сообщений.
    """
    import publish
    import площадки as пл
    пост = db.взять(ид)
    выбраны = set(publish.куда_едет(пост)) if пост else {"телеграм"}
    # Показываем все площадки, а не только подключённые. Готовить пост для
    # TikTok можно и без ключей: слайды и текст под него сделаются, а
    # публикация честно скажет, чего не хватает. Скрыть площадку значило бы
    # спрятать и половину работы.
    доступны = пл.ПОРЯДОК

    ряд = [((("✅ " if к in выбраны else "") + пл.имя(к)
             + ("" if пл.готова(к) else " · нет ключей")), f"dest:{ид}:{к}")
           for к in доступны]
    ряды = [ряд[:2], ряд[2:]] if len(ряд) > 2 else [ряд]
    ряды = [р for р in ряды if р]
    готовые = [к for к in доступны if пл.готова(к)]
    if len(готовые) > 1:
        все_ли = выбраны >= set(готовые)
        ряды.append([("◻️ Снять все" if все_ли else "🌍 Во все подключённые",
                      f"dest:{ид}:all")])

    слоты = [(f"🕑 {п}", f"when:{ид}:{int(м.timestamp())}")
             for п, м in times.варианты()[:4]]
    # Порядок не случайный: сначала куда, потом когда, и только потом «сейчас».
    # Обычный путь это поставить время, а публикация сию секунду исключение.
    # Раньше она стояла выше слотов и читалась как основное действие.
    ряды += [
        слоты[:2], слоты[2:4],
        [("🚀 Опубликовать сейчас", f"pub:{ид}")],
        [("✏️ Править", f"edit:{ид}"), ("💬 Переписать", f"ask:{ид}")],
        [("🔄 Другой вариант", f"again:{ид}"), ("✖️ Отменить", f"skip:{ид}")],
    ]
    return tg.кнопки([р for р in ряды if р])


def _поле(пост, имя: str, иначе=None):
    """Значение колонки, которой у старых постов может не быть вовсе.

    База переживала не одно добавление колонок, и ряд, снятый со старой
    записи, о новых не знает. Обращение к отсутствующей колонке валит весь
    показ карточки, а не одну строку в ней.
    """
    try:
        if hasattr(пост, "keys") and имя not in пост.keys():
            return иначе
        значение = пост[имя]
    except (KeyError, IndexError, TypeError):
        return иначе
    return иначе if значение is None else значение


def ссылка_на_пост(пост) -> str:
    """Адрес вышедшего поста в канале. Пусто, если открывать нечего.

    Только публичный канал с @именем: у приватного адрес собирается из
    внутреннего номера, и кнопка вела бы в никуда у всех, кроме владельца.
    """
    канал = str(_поле(пост, "channel", ""))
    номер = _поле(пост, "tg_message_id")
    if not номер or not канал.startswith("@"):
        return ""
    return f"https://t.me/{канал[1:]}/{int(номер)}"


def кнопки_переноса(ид: int) -> str:
    """Четыре слота времени вместо кнопок поста, на той же карточке.

    Отдельным экраном это было бы хуже: карточка с картинкой остаётся перед
    глазами, и время выбирается, глядя на сам пост, а не на его номер.
    """
    слоты = [(f"🕑 {п}", f"when:{ид}:{int(м.timestamp())}")
             for п, м in times.варианты()[:4]]
    return tg.кнопки([слоты[:2], слоты[2:4], [("⬅️ К посту", f"card:{ид}")]])


def кнопки_поста(пост) -> str:
    """Под постом ровно то, что с ним можно сделать в его состоянии.

    Черновик умел всё нужное и раньше — его набор переносится как есть.
    Двух других не было вовсе: снять пост с расписания или повторить удачный
    из бота было нельзя никак, только из приложения.

    Набор зависит от состояния, а не показывается весь с отказами: «снять с
    расписания» под вышедшим постом — обещание, которого не сдержать, его
    уже прочитали десять тысяч человек.
    """
    ид = int(пост["id"])
    статус = _поле(пост, "status", "draft")
    if статус == "scheduled":
        return tg.кнопки([
            [("🕑 Перенести", f"mv:{ид}"), ("❌ Снять с плана", f"unpl:{ид}")],
            [("✏️ Править", f"edit:{ид}"), ("🚀 Опубликовать сейчас", f"pub:{ид}")],
            [("🗑 Удалить", f"del:{ид}")],
        ])
    if статус == "published":
        ряды = [[("🔁 Повторить", f"redo:{ид}"), ("📊 Просмотры", f"vw:{ид}")]]
        адрес = ссылка_на_пост(пост)
        if адрес:
            ряды.append([{"text": "🔗 Открыть в канале", "url": адрес}])
        return tg.кнопки(ряды)
    return превью_кнопки(ид)


def шапка_поста(пост) -> str:
    """Первая строка карточки: чем этот пост сейчас является."""
    ид = int(пост["id"])
    статус = _поле(пост, "status", "draft")
    if статус == "scheduled":
        когда = _поле(пост, "scheduled_at", "")
        подпись = times.подпись(times.из_базы(когда)) if когда else "без времени"
        return f"🗓 В плане · {подпись} · №{ид}\n\n"
    if статус == "published":
        вышел = _поле(пост, "published_at", "")
        подпись = times.подпись(times.из_базы(вышел)) if вышел else ""
        просмотры = _поле(пост, "views")
        хвост = f" · 👀 {просмотры}" if просмотры else ""
        return f"🚀 Вышел · {подпись}{хвост} · №{ид}\n\n"
    return (f"📝 Черновик №{ид} · {_поле(пост, 'rubric', 'без рубрики')}"
            f" · форма «{_поле(пост, 'shape', '—')}»\n\n")


