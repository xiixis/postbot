def показать(чат: int, ид: int, шапка: str = "") -> dict:
    """Шлёт карточку поста и возвращает сообщение, под которым остались кнопки.

    Возврат нужен навигации: она снимает кнопки с прошлой карточки, чтобы
    чат не превращался в ленту из карточек одного и того же поста.

    Шапка по умолчанию выводится из состояния поста: черновик, план или
    вышедший — на карточке это первое, что надо знать.
    """
    пост = db.взять(ид)
    if not пост:
        raise экраны.НетЭкрана("Этого поста уже нет")
    шапка = шапка or шапка_поста(пост)
    # Подпись «подписаться» дописывает публикация, а не модель. В превью её
    # тоже показываем: одобрять надо ровно то, что выйдет, иначе последняя
    # строка поста впервые видна уже в канале. Но только там, где она правда
    # будет: пост, который едет лишь в TikTok, уходит без неё.
    import publish
    едет = publish.куда_едет(пост)
    текст = шапка + (publish.футер(пост["body"]) if "телеграм" in едет
                     else пост["body"])
    # Замечания идут отдельным сообщением, а не в подписи: подпись под
    # картинкой ограничена, и предупреждение о её длине само бы в неё не влезло.
    import придирки
    замечания = придирки.строкой(пост)
    слайды = db.картинки(пост)
    if слайды:
        # Карусель показываем ровно так, как она уйдёт в канал: группой. Иначе
        # владелец одобряет одну картинку, а выходит пять.
        import storage
        ссылки = [с if с.startswith("http") else storage.во_временный(с)
                  for с in слайды]
        tg.альбом(чат, ссылки, текст, тихо=True)
        return tg.написать(чат, f"🎠 Слайдов: {len(слайды)}"
                           + (f"\n\n{замечания}" if замечания else ""),
                           кнопки_поста(пост), разметка="")
    if пост["image_path"]:
        from pathlib import Path
        путь = пост["image_path"]
        # Карточка может лежать и на диске, и в хранилище. Ссылку телеграм
        # заберёт сам, а вот Path из неё делает «https:/…» с одной косой, и
        # превью падает на попытке открыть такой файл.
        м = tg.фото(чат, путь if путь.startswith("http") else Path(путь),
                    текст, кнопки_поста(пост))
    else:
        м = tg.написать(чат, текст + "\n\n_(картинка не отрисовалась)_",
                        кнопки_поста(пост))
    if замечания:
        tg.написать(чат, замечания, разметка="")
    return м


# ── что можно сделать с постом ──────────────────────────────────────────────
# Действия объявляются здесь, а не в экраны.py: они шлют сообщения и меняют
# базу, а экран обязан оставаться чистой функцией. Все они «на карточке» —
# нажимаются с сообщения поста, а не с меню, поэтому перерисовывать по месту
# нажатия нечего: телеграм не даст переписать текстом сообщение с картинкой.
# Вернувшие код экрана обновляют висящее меню там, где оно висит.


@экраны.действие("p:*", свой_показ=True)
def _открыть_пост(п: экраны.Пар) -> None:
    """Тычок в строку очереди: пост приходит отдельным сообщением.

    Отдельным, а не вместо меню, и это не уступка телеграму, а смысл: пост
    это содержимое, ему место в истории чата; меню это навигация, его место
    одно и всегда внизу.
    """
    навигация.карточка(п.чат, lambda: показать(п.чат, int(п.арг)))


@экраны.действие("card:*", свой_показ=True)
def _вернуть_кнопки(п: экраны.Пар) -> None:
    """Передумал переносить: на карточку возвращается её обычный набор."""
    пост = db.взять(int(п.арг))
    if not пост:
        raise экраны.НетЭкрана("Этого поста уже нет")
    tg.правка_кнопок(п.чат, п.сообщение, кнопки_поста(пост))


@экраны.действие("mv:*", публикует=True, свой_показ=True)
def _перенести(п: экраны.Пар) -> None:
    """Слоты времени вместо кнопок поста, на той же карточке."""
    пост = db.взять(int(п.арг))
    if not пост or _поле(пост, "status") != "scheduled":
        raise экраны.НетЭкрана("Этот пост уже не в плане")
    tg.правка_кнопок(п.чат, п.сообщение, кнопки_переноса(int(п.арг)))


@экраны.действие("unpl:*", ответ="🗓 Снял с расписания, лежит в черновиках",
                 публикует=True, свой_показ=True)
def _снять(п: экраны.Пар) -> str:
    """Снятие с плана. Отданный телеграму пост забирается из отложенных.

    Иначе он вышел бы в назначенный час, хотя в боте и в приложении уже
    показывался бы черновиком: у телеграма своя копия, и о нашей базе он
    ничего не знает.
    """
    ид = int(п.арг)
    пост = db.взять(ид)
    if not пост or _поле(пост, "status") != "scheduled":
        raise экраны.НетЭкрана("Этот пост уже не в плане")
    core.снять_с_плана(ид)
    tg.правка_кнопок(п.чат, п.сообщение, кнопки_поста(db.взять(ид)))
    return "q"


@экраны.действие("del:*", ответ="🗑 Убрал. Тема запомнена, повторяться не буду",
                 публикует=True, свой_показ=True)
def _убрать(п: экраны.Пар) -> str:
    """Убрать пост из работы.

    Записи из базы не удаляются: пропущенная тема нужна, чтобы бот не принёс
    её же завтра. Поэтому «удалить» это тот же отказ, что и «отменить» у
    черновика, плюс снятие с плана — если пост успел получить время.
    """
    ид = int(п.арг)
    пост = db.взять(ид)
    if not пост:
        raise экраны.НетЭкрана("Этого поста уже нет")
    if _поле(пост, "status") == "published":
        raise экраны.НетЭкрана("Вышедший пост уже прочитали, он не удаляется")
    if _поле(пост, "status") == "scheduled":
        core.снять_с_плана(ид)
    db.отметить_пропущенным(ид)
    tg.убрать_кнопки(п.чат, п.сообщение)
    return "q"


@экраны.действие("redo:*", ответ="🔁 Сделал черновик с тем же текстом",
                 свой_показ=True)
def _повторить(п: экраны.Пар) -> str:
    """Повтор удачного поста: копия черновиком, а не публикация заново.

    Черновиком, потому что удачный пост повторяют не дословно: меняют первую
    строку, освежают пример. Копия открывается карточкой, и дальше это
    обычный черновик со всеми его кнопками.
    """
    ид = int(п.арг)
    пост = db.взять(ид)
    if not пост or _поле(пост, "status") != "published":
        raise экраны.НетЭкрана("Повторить можно только вышедший пост")
    новый = db.добавить(_поле(пост, "rubric", ""), _поле(пост, "title", ""),
                        _поле(пост, "body", ""), _поле(пост, "image_path"),
                        _поле(пост, "shape"), db.карточка(пост),
                        db.картинки(пост))
    навигация.карточка(п.чат, lambda: показать(
        п.чат, новый, f"📝 Черновик №{новый} · повтор поста №{ид}\n\n"))
    return "q"


@экраны.действие("vw:*", свой_показ=True)
def _просмотры(п: экраны.Пар) -> None:
    """Сколько людей увидело пост.

    Числа собирает воркер раз в полчаса через аккаунт владельца — боту
    телеграм охват не отдаёт вовсе. Поэтому у свежего поста их ещё нет, и
    честнее сказать это словами, чем показать ноль.
    """
    пост = db.взять(int(п.арг))
    if not пост:
        raise экраны.НетЭкрана("Этого поста уже нет")
    просмотры = _поле(пост, "views")
    отклик = _поле(пост, "reactions")
    if not просмотры:
        п.сказать("📊 Охват ещё не собран. Он появляется в первые полчаса "
                  "после выхода.")
        return
    п.сказать(f"📊 {просмотры} просмотров"
              + (f" · {отклик} откликов" if отклик else ""))


