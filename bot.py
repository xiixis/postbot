ЖДЁМ_ЧАСЫ: dict[int, str] = {}     # у кого спросили часы и для какой площадки
ЖДЁМ_ПРАВКУ: dict[int, tuple] = {}  # у кого спросили правку: (номер поста, как)
ЖДЁМ_ОКНО: set[int] = set()         # у кого спросили, с какого момента читать чаты
ЧАС = __import__("re").compile(r"([01]?\d|2[0-3])[:.\s]([0-5]\d)")


def конвейер_раздел(чат: int, что: str) -> None:
    """Раздел «Конвейер»: площадки, их темп и разовая сборка."""
    import конвейер
    import площадки as пл
    if not что:
        строки = [
            f"{пл.имя(к)} · {'включён' if конвейер.настройки(к)['вкл'] else 'спит'}"
            f" · {'публикует сам' if конвейер.настройки(к).get('режим','сам') == 'сам' else 'готовит, публикуете вы'}"
            f" · {пл.СПИСОК[к]['поясн']}"
            for к in конвейер.ПО_УМОЛЧАНИЮ]
        tg.написать(чат, "🤖 *Конвейер*\n\n" + "\n".join(строки) +
                         "\n\nВключённая площадка держит план полным сама: "
                         "берёт следующий угол по кругу, сочиняет, рисует и "
                         "ставит время. Готовое покажу, снять можно кнопкой.",
                    меню_конвейера())
        return

    if что == "new":
        сделать_карусель(чат)
        return

    куда, _, действие = что.partition(":")
    if куда not in конвейер.ПО_УМОЛЧАНИЮ:
        return

    if not действие:
        с = конвейер.настройки(куда)
        tg.написать(чат, f"{пл.имя(куда)}\n\n"
                         f"{пл.СПИСОК[куда]['поясн'].capitalize()}.\n"
                         f"Выходит в {', '.join(с['часы'])}.\n"
                         f"В плане {len(конвейер.в_плане(куда))} из "
                         f"{конвейер.запас(куда)}.",
                    меню_площадки(куда), разметка="")
        return

    if действие == "auto":
        стало = конвейер.переключить(куда)
        tg.написать(чат, (f"🤖 {пл.имя(куда)}: сочиняю сам."
                          if стало else
                          f"💤 {пл.имя(куда)}: только вручную. "
                          "Что стоит в плане, останется."),
                    меню_площадки(куда), разметка="")
        if стало:
            догнать_конвейер(чат, куда)
        return

    if действие == "mode":
        стало = "руками" if конвейер.настройки(куда).get("режим", "сам") == "сам" else "сам"
        конвейер.сохранить(куда, режим=стало)
        tg.написать(чат, ("🚀 Буду публиковать сам, по расписанию."
                          if стало == "сам" else
                          "✋ Буду только готовить: пришлю сюда готовое, "
                          "а выложите вы. Времени постам ставить не буду."),
                    меню_площадки(куда), разметка="")
        return

    if действие == "hours":
        ЖДЁМ_ЧАСЫ[чат] = куда
        tg.написать(чат, f"🕑 Во сколько публиковать в {пл.имя(куда)}? "
                         "Напишите через запятую, например «09:00, 12:30, 18:00». "
                         "Сколько времён, столько публикаций в день.",
                    разметка="")
        return

    if действие == "days":
        стало = {1: 2, 2: 3, 3: 7}.get(int(конвейер.настройки(куда)["дней"]), 1)
        конвейер.сохранить(куда, дней=стало)
        tg.написать(чат, f"📅 Держу план на {стало} дн. вперёд. "
                         f"Это {конвейер.запас(куда)} публикаций.",
                    меню_площадки(куда), разметка="")
        return

    if действие == "new":
        сделать_карусель(чат, площадка=куда)
        return


def применить_правку(чат: int, текст: str) -> None:
    """Правка поста из чата: заменой текста или указанием переписать.

    Номер поста не меняется намеренно: он может уже стоять в расписании, и
    подмена новым сбила бы время.
    """
    ид, как = ЖДЁМ_ПРАВКУ.pop(чат, (0, "edit"))
    if not ид or not db.взять(ид):
        tg.написать(чат, "Этого черновика уже нет.", меню(), разметка="")
        return
    try:
        if как == "edit":
            core.обновить(ид, текст)
            tg.написать(чат, "✏️ Заменил текст.", разметка="")
        else:
            tg.написать(чат, "💬 Переписываю…", разметка="")
            core.переписать(ид, текст)
            tg.написать(чат, "💬 Переписал.", разметка="")
    except Exception as e:                                   # noqa: BLE001
        traceback.print_exc()
        tg.написать(чат, f"⚠️ Не вышло: {str(e)[:250]}", разметка="")
        return
    показать(чат, ид, f"📝 Черновик №{ид}\n\n")


def задать_часы(чат: int, текст: str) -> None:
    """Разбирает «12:00, 19:00» и подобное. Человек пишет как удобно ему."""
    import конвейер
    import площадки as пл
    куда = ЖДЁМ_ЧАСЫ.pop(чат, "tiktok")
    часы = [f"{int(ч):02d}:{м}" for ч, м in ЧАС.findall(текст)]
    if not часы:
        tg.написать(чат, "🤔 Не разобрал время. Напишите как «12:00, 19:00».",
                    меню_площадки(куда), разметка="")
        return
    часы = sorted(dict.fromkeys(часы))[:8]
    конвейер.сохранить(куда, часы=часы)
    tg.написать(чат, f"🕑 {пл.имя(куда)}: публикуем в {', '.join(часы)}. "
                     f"Это {len(часы)} в день, держу в плане "
                     f"{конвейер.запас(куда)}.",
                меню_площадки(куда), разметка="")


def догнать_конвейер(чат: int, куда: str | None = None) -> None:
    """Добирает план и показывает владельцу то, что получилось."""
    import конвейер
    import площадки as пл
    места = [куда] if куда else конвейер.включённые()
    for место in места:
        сколько = конвейер.чего_не_хватает(место)
        if not сколько:
            continue
        tg.написать(чат, f"🤖 {пл.имя(место)}: не хватает {сколько}, собираю…",
                    разметка="")
        новые = конвейер.подтянуть(место, lambda ч: None)
        for ид in новые:
            пост = db.взять(ид)
            # «Выйдет без времени» звучало как поломка. В ручном режиме время
            # и не ставится: пост ждёт, пока владелец его одобрит.
            когда = (f"выйдет {times.подпись(times.из_базы(пост['scheduled_at']))}"
                     if пост["scheduled_at"] else "ждёт вашего одобрения")
            показать(чат, ид, f"🤖 Собрал сам · {когда}\n\n")
        if новые:
            tg.написать(чат, f"🎠 {пл.имя(место)}: собрал {len(новые)}, "
                             f"в плане {len(конвейер.в_плане(место))} из "
                             f"{конвейер.запас(место)}.", разметка="")
    db.запомнить(конвейер.КОГДА, __import__("time").time())


