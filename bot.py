def отклики_раздел(чат: int, что: str) -> None:
    """Настройки раздела: из какой папки читать и сколько показывать."""
    import отклики
    с = отклики.настройки()

    if что == "folders":
        try:
            список = отклики.папки()
        except Exception as e:                               # noqa: BLE001
            traceback.print_exc()
            tg.написать(чат, f"⚠️ Не смог спросить у Telegram папки: {str(e)[:200]}",
                        разметка="")
            return
        ПАПКИ_ЧАТОВ.clear()
        ряды = []
        for ф in список:
            ПАПКИ_ЧАТОВ[ф["ид"]] = ф["имя"]
            галка = "✅ " if ф["имя"] == с["папка"] else ""
            ряды.append([(f"{галка}{ф['имя']} · {ф['чатов']}", f"rep:f:{ф['ид']}")])
        ряды.append([("⬅️ Назад", "rep:back")])
        tg.написать(чат, "📂 Из какой папки читать чаты?\n\nСостав папки вы "
                         "меняете в самом телеграме, бот берёт её как есть.",
                    tg.кнопки(ряды), разметка="")
        return

    if что.startswith("f:"):
        имя = ПАПКИ_ЧАТОВ.get(int(что[2:]))
        if not имя:
            tg.написать(чат, "Список папок устарел, откройте его заново.",
                        разметка="")
            return
        отклики.задать_папку(имя)
        с = отклики.настройки()
    elif что.startswith("n:"):
        отклики.задать_сколько(int(что[2:]))
        с = отклики.настройки()
    elif что == "count":
        ряды = [[(str(н), f"rep:n:{н}") for н in (3, 5, 8)],
                [("⬅️ Назад", "rep:back")]]
        tg.написать(чат, "🔢 Сколько сообщений показывать за один проход?",
                    tg.кнопки(ряды), разметка="")
        return
    elif что == "when":
        ряды = [[("🕐 С этой минуты", "rep:now"), ("🌅 С утра", "rep:morning")],
                [("↩️ Вчера с утра", "rep:yesterday"),
                 (f"🔁 Последние {отклики.ДНЕЙ} дня", "rep:reset")],
                [("🧹 Забыть показанное", "rep:forget")],
                [("⬅️ Назад", "rep:back")]]
        tg.написать(чат, "📅 *С какого момента читать чаты*\n\n"
                         "Выберите кнопкой или напишите свой момент следующим "
                         "сообщением: «04.09 14:00», «вчера 18:00», "
                         "«сегодня 9:00», «12 часов», «3 дня».\n\n"
                         f"Сейчас читаю {отклики.подпись_окна(с['с'])}.",
                    tg.кнопки(ряды))
        ЖДЁМ_ОКНО.add(чат)
        return
    elif что in ("now", "morning", "yesterday", "reset"):
        from datetime import timedelta
        ЖДЁМ_ОКНО.discard(чат)
        сейчас = times.сейчас()
        момент = {
            "now": сейчас,
            "morning": сейчас.replace(hour=0, minute=0, second=0, microsecond=0),
            "yesterday": (сейчас - timedelta(days=1)).replace(
                hour=0, minute=0, second=0, microsecond=0),
            "reset": None,
        }[что]
        отклики.задать_начало(момент)
        с = отклики.настройки()
    elif что == "forget":
        отклики.забыть_показанные()
        tg.написать(чат, "🧹 Забыл, что показывал. Следующий проход может "
                         "повторить прежние находки.", разметка="")
        с = отклики.настройки()

    tg.написать(чат, "💬 *Что ответить в чатах*\n\n"
                     f"Смотрю чаты из папки «{с['папка']}» {отклики.подпись_окна(с['с'])} "
                     "и предлагаю по три варианта ответа на каждое стоящее "
                     "сообщение. Ничего никуда не отправляю: варианты "
                     "копируются касанием, отвечаете вы сами.\n\n"
                     "Показанное запоминается: следующий проход даёт другое.",
                меню_откликов(с))


