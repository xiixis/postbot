def отложить_идею(чат: int, текст: str) -> None:
    """Кладёт заметку в копилку и заодно обновляет показатели проекта."""
    import facts
    import ideas
    ideas.подготовить()
    try:
        ид = ideas.добавить(текст)
    except ValueError:
        return

    # Заметка может нести не только повод для поста, но и живое значение:
    # каналов стало шесть, роликов три в неделю. Такие переписываем поверх
    # старых, чтобы посты опирались на сегодняшние числа, а не на прошлогодние.
    обновлено = {}
    try:
        обновлено = facts.обновить_из(текст)
    except Exception:                                        # noqa: BLE001
        pass

    хвост = ""
    if обновлено:
        хвост = ("\n\n📊 Заодно обновил: "
                 + ", ".join(f"{и} {з}" for и, з in обновлено.items()))
    # Со ссылкой у поста два разных смысла, и выбирает их владелец, а не бот.
    # «Источник» это находка: чужая вещь, показанная читателям, с адресом в
    # конце. «Рерайт» это свой материал канала по той же теме, без ссылки и
    # без упоминания, откуда взялось.
    import source
    если_ссылка = source.ССЫЛКА.search(текст)
    ряды = ([[("🔗 Источник", f"idea:{ид}:src"), ("✍️ Рерайт", f"idea:{ид}:rw")]]
            if если_ссылка else [[("✨ Сделать пост", f"idea:{ид}:src")]])
    ряды.append([("📥 Пусть полежит", "later")])
    вопрос = ("💡 Записал в копилку. Как делать пост?\n\n"
              "🔗 *Источник* — находка: расскажу про эту вещь и поставлю ссылку.\n"
              "✍️ *Рерайт* — свой пост канала по теме, без ссылки и без "
              "упоминания источника."
              if если_ссылка else
              "💡 Записал в копилку. Сделать из этого пост сейчас?")
    tg.написать(чат, вопрос + хвост, tg.кнопки(ряды))


def голосом(чат: int, м: dict) -> bool:
    """Голосовая заметка: расшифровываем и дальше как обычный текст.

    Идея приходит на ходу, и надиктовать её проще, чем набрать. Возвращает
    False, если сообщение не голосовое или расшифровать не вышло.
    """
    голос = м.get("voice") or м.get("audio") or m_видео(м)
    if not голос:
        return False
    tg.написать(чат, "🎙 Слушаю…", разметка="")
    звук = tg.скачать(голос["file_id"])
    import voice
    текст = voice.расшифровать(звук or b"", голос.get("mime_type") or "audio/ogg")
    if not текст:
        tg.написать(чат, "🎙 Не разобрал. Попробуйте ещё раз или напишите текстом.",
                    разметка="")
        return True
    tg.написать(чат, f"🎙 Услышал: _{текст[:400]}_")
    if чат in ЖДЁМ_ФАКТ:
        ЖДЁМ_ФАКТ.discard(чат)
        сделать_пост(чат, "от себя", текст)
    else:
        отложить_идею(чат, текст)
    return True


