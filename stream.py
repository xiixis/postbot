# -*- coding: utf-8 -*-
"""Анонс стримов. Пост, который не сочиняется, а повторяется дословно.

Всё остальное в боте пишется заново каждый раз, и это правильно: лента живая.
Анонс стримов, наоборот, должен быть узнаваемым. Человек листает канал и
цепляется взглядом за уже знакомую афишу, а не разбирает новый текст.

Поэтому текст и афиша фиксированные, но не намертво: их можно поправить в
приложении, и правка ложится в базу. Значения из кода, это то, с чего анонс
начинается, а не то, чем он обязан остаться.
"""

from pathlib import Path

import card
import config
import db

КЛЮЧ = "stream"

ПЛОЩАДКИ = [
    # В подписях кнопок значков нет намеренно: Telegram не даёт кнопкам ни
    # своих эмодзи, ни жирного, и обычный смайлик рядом с чистым текстом
    # смотрится случайным.
    {"имя": "Twitch",  "адрес": "https://www.twitch.tv/forxmula",
     "чем": "чат живее всего"},
    {"имя": "YouTube", "адрес": "https://www.youtube.com/@ForXmula",
     "чем": "остаются записи"},
    {"имя": "TikTok",  "адрес": "https://www.tiktok.com/@4x_tube",
     "чем": "короткие включения"},
]

ТЕКСТ = """\
🟥🟧🟨🟩

**🔥 Стримлю сразу на трёх площадках**

Показываю в прямом эфире, как собираются ролики: что работает, что ломается на
ровном месте. Заходите туда, где вам удобнее, эфир везде один и тот же.

🎴 [Twitch](https://www.twitch.tv/forxmula): чат живее всего
🃏 [YouTube](https://www.youtube.com/@ForXmula): остаются записи
🀄️ [TikTok](https://www.tiktok.com/@4x_tube): короткие включения

⏲️ _Расписание эфиров кидаю сюда, в канал._

🔔 Подпишитесь на любой из трёх, чтобы не пропустить начало."""

# Первая строка это четыре иконки набора, которые складываются в слово LIVE.
# Порядок важен: он же порядок в наборе, поменяешь местами, получится ерунда.
# Дальше 🎴 🃏 🀄️ это логотипы Twitch, YouTube и TikTok из того же набора.
# В подписях кнопок оставлены обычные значки: своих эмодзи кнопки не умеют.

АФИША = {"надпись": "Прямой эфир", "заголовок": "STREAM ONLINE",
         "подзаголовок": "Собираю ролики вживую, заходите смотреть"}

КАРТОЧКА = config.АССЕТЫ / "stream_card.png"
ПОЗА = config.МАСКОТ / "stream.png"


def настройки() -> dict:
    """Правки владельца поверх значений из кода."""
    свои = db.настройка(КЛЮЧ, {}) or {}
    return {"текст": свои.get("текст") or ТЕКСТ,
            "площадки": свои.get("площадки") or ПЛОЩАДКИ,
            "афиша": {**АФИША, **(свои.get("афиша") or {})}}


def сохранить(правки: dict) -> None:
    """Запоминает анонс насовсем. Афиша перерисуется при следующем показе."""
    было = db.настройка(КЛЮЧ, {}) or {}
    стало = {**было}
    for ключ in ("текст", "площадки"):
        if правки.get(ключ):
            стало[ключ] = правки[ключ]
    if правки.get("афиша"):
        стало["афиша"] = {**было.get("афиша", {}), **правки["афиша"]}
    db.запомнить(КЛЮЧ, стало)
    if стало.get("афиша") != было.get("афиша"):
        КАРТОЧКА.unlink(missing_ok=True)          # надписи сменились, рисуем заново


def текст() -> str:
    return настройки()["текст"]


def карточка(перерисовать: bool = False) -> Path | None:
    """Одна и та же афиша на все анонсы. Рисуется при первом вызове."""
    if КАРТОЧКА.exists() and not перерисовать:
        return КАРТОЧКА
    н = настройки()
    итог = card.афиша(
        н["афиша"]["надпись"], н["афиша"]["заголовок"], н["афиша"]["подзаголовок"],
        [п["имя"].split(" ", 1)[-1] for п in н["площадки"]],
        ПОЗА if ПОЗА.exists() else None)
    if not итог:
        return None
    КАРТОЧКА.parent.mkdir(parents=True, exist_ok=True)
    КАРТОЧКА.write_bytes(Path(итог).read_bytes())
    Path(итог).unlink(missing_ok=True)
    return КАРТОЧКА


def кнопки() -> str:
    """Ссылки уходят и текстом, и кнопками: кнопку жмут чаще."""
    import json
    ряд = [{"text": п["имя"], "url": п["адрес"]} for п in настройки()["площадки"]]
    return json.dumps({"inline_keyboard": [ряд]})
