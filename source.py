# -*- coding: utf-8 -*-
"""Материал для поста: ссылка на статью или своя идея текстом.

Ссылку бот открывает сам и вытаскивает читаемый текст. Пересказ чужой статьи
своими словами для своей аудитории, это нормальная работа редактора; копировать
чужие абзацы нельзя, и об этом отдельно сказано в задании модели.

Адреса берём только внешние. Владелец бота не станет специально просить
открыть локальный адрес, но бот ходит по ссылке с той же машины, где живёт
конвейер, и служебные адреса ему видны. Проще закрыть, чем однажды объяснять.
"""

import ipaddress
import re
import socket
import tempfile
from html.parser import HTMLParser
from pathlib import Path
from urllib.parse import urlparse

import requests

ССЫЛКА = re.compile(r"https?://[^\s<>\"']+")
ПРЕДЕЛ = 2 * 1024 * 1024          # больше двух мегабайт страницы не читаем
ВЫДЕРЖКА = 6000                   # столько символов уходит в модель
СЛАЙДОВ = 12                      # больше карусель не бывает, а время бережём


class _Текст(HTMLParser):
    """Выдирает читаемый текст. Полноценный парсер тут был бы лишней зависимостью."""

    ПРОПУСК = {"script", "style", "noscript", "svg", "head", "nav", "footer"}

    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.куски: list[str] = []
        self.заголовок = ""
        self._в_заголовке = False
        self._глубина = 0

    def handle_starttag(self, тег, атрибуты):
        if тег in self.ПРОПУСК:
            self._глубина += 1
        if тег == "title":
            self._в_заголовке = True

    def handle_endtag(self, тег):
        if тег in self.ПРОПУСК and self._глубина:
            self._глубина -= 1
        if тег == "title":
            self._в_заголовке = False

    def handle_data(self, данные):
        if self._в_заголовке:
            self.заголовок += данные
        elif not self._глубина and данные.strip():
            self.куски.append(данные.strip())


def _внешний(адрес: str) -> bool:
    узел = urlparse(адрес).hostname or ""
    try:
        сведения = socket.getaddrinfo(узел, None)
    except OSError:
        return False
    for сведение in сведения:
        ип = ipaddress.ip_address(сведение[4][0])
        if ип.is_private or ип.is_loopback or ип.is_link_local or ип.is_reserved:
            return False
    return True


# ── TikTok ──────────────────────────────────────────────────────────────────
# Обычным чтением страницы TikTok не берётся: гостю он отдаёт заглушку без
# поста, а у карусели содержимое вообще не текст, а надписи на картинках.
# Поэтому здесь отдельный путь: открытый пересказчик отдаёт подпись и адреса
# слайдов, слайды скачиваются, и их читает глазами агент.

ТИКТОК = re.compile(r"^(?:www\.|vm\.|vt\.|m\.)?tiktok\.com$", re.I)
ПЕРЕСКАЗЧИК = "https://www.tikwm.com/api/"

РАЗОБРАТЬ_СЛАЙДЫ = """\
Перед тобой слайды одного поста из TikTok. Прочитай их по порядку и изложи
СОДЕРЖАНИЕ: о чём пост, какая мысль на каждом слайде, какие названия, числа и
советы там названы.

Это материал для редактора, а не готовый текст. Поэтому:
• пиши по-русски, простой прозой, без разметки и заголовков;
• не пересказывай оформление («крупная надпись», «оранжевый шрифт») — только
  смысл;
• если на слайде названы конкретные вещи, файлы, команды или числа, приведи их
  точно: редактору важно не переврать чужое;
• если чего-то не разобрать, так и скажи, не додумывай.

Отдельным абзацем в конце, под заголовком «КАРКАС», опиши, КАК пост устроен,
не пересказывая, О ЧЁМ он. Это нужно, чтобы редактор мог повторить удачное
построение своим материалом. Ответь на такие вопросы:
• чем зацепляет первый экран: обещанием, спором, признанием, вопросом;
• какой поворот в середине и на чём он держится;
• сколько содержательных блоков и одинаковые ли они по длине;
• чем заканчивается: выводом, призывом, вопросом, обещанием продолжения;
• какой ритм у фраз: рубленые короткие или развёрнутые.
Каркас это построение, а не слова. Формулировки оттуда не приводи.
"""


def _тикток(адрес: str) -> dict | None:
    """Подпись и содержимое слайдов поста TikTok."""
    try:
        о = requests.get(ПЕРЕСКАЗЧИК, params={"url": адрес}, timeout=40,
                         headers={"User-Agent": "Mozilla/5.0"})
        о.raise_for_status()
        д = (о.json() or {}).get("data") or {}
    except Exception:                                        # noqa: BLE001
        return None
    if not д:
        return None

    автор = (д.get("author") or {}).get("unique_id") or ""
    подпись = " ".join((д.get("title") or "").split())
    картинки = (д.get("images") or [])[:СЛАЙДОВ]

    куски = []
    if автор:
        куски.append(f"Автор поста: @{автор}.")
    if подпись:
        куски.append(f"Подпись: {подпись}")

    if картинки:
        try:
            куски.append(_слайды(картинки))
        except Exception:                                    # noqa: BLE001
            return None
    elif not подпись:
        return None                                   # ролик без подписи, читать нечего

    текст = " ".join(" ".join(куски).split())
    заголовок = (подпись or f"пост @{автор}" or "пост из TikTok")[:200]
    return {"адрес": адрес, "заголовок": заголовок, "текст": текст[:ВЫДЕРЖКА]}


def _слайды(ссылки: list) -> str:
    """Скачивает слайды во временную папку и отдаёт их содержание словами.

    Папка временная нарочно: слайды нужны на один разбор, а лежать чужими
    картинками в рабочих данных им незачем.
    """
    import агент
    with tempfile.TemporaryDirectory(prefix="тикток-") as папка:
        файлы = []
        for i, ссылка in enumerate(ссылки, 1):
            о = requests.get(ссылка, timeout=40, headers={"User-Agent": "Mozilla/5.0"})
            о.raise_for_status()
            путь = Path(папка) / f"слайд_{i:02d}.jpg"
            путь.write_bytes(о.content)
            файлы.append(str(путь))
        if not файлы:
            return ""
        return агент.текстом("Разбери слайды этого поста.",
                             система=РАЗОБРАТЬ_СЛАЙДЫ, метка="разбор слайдов",
                             картинки=файлы)


def забрать(адрес: str) -> dict | None:
    """Заголовок и текст страницы. None, если не открылась."""
    if not _внешний(адрес):
        return None
    if ТИКТОК.match(urlparse(адрес).hostname or ""):
        return _тикток(адрес)
    try:
        о = requests.get(адрес, timeout=20, stream=True, headers={
            "User-Agent": "Mozilla/5.0 (compatible; 4xTubeBot/1.0)"})
        о.raise_for_status()
        if "html" not in о.headers.get("Content-Type", "text/html"):
            return None
        сырое = о.raw.read(ПРЕДЕЛ, decode_content=True).decode(
            о.encoding or "utf-8", errors="replace")
    except Exception:                                        # noqa: BLE001
        return None

    разбор = _Текст()
    try:
        разбор.feed(сырое)
    except Exception:                                        # noqa: BLE001
        pass
    # Сначала берём только длинные куски: меню, списки языков и подвалы состоят
    # из коротких, и без этого фильтра первые полторы тысячи символов страницы
    # уходят в модель навигацией.
    крупные = [к for к in разбор.куски if len(к) >= 60]
    текст = re.sub(r"\s{2,}", " ", " ".join(крупные or разбор.куски))
    заголовок = " ".join(разбор.заголовок.split())[:200]
    if not заголовок and len(текст) < 200:
        return None
    return {"адрес": адрес, "заголовок": заголовок, "текст": текст[:ВЫДЕРЖКА]}


def разобрать(ввод: str) -> tuple[str | None, dict | None]:
    """Из строки владельца делает тему и, если была ссылка, содержимое страницы."""
    ввод = (ввод or "").strip()
    if not ввод:
        return None, None
    найдена = ССЫЛКА.search(ввод)
    if not найдена:
        return ввод[:300], None
    материал = забрать(найдена.group(0))
    остальное = ССЫЛКА.sub("", ввод).strip(" .,:;\n")
    тема = остальное[:300] or None
    if not материал:
        # Страница не открылась: не молчим, а пишем по адресу как по теме. Сам
        # адрес обязан остаться в теме, даже если владелец прислал ссылку со
        # словами: по нему потом ставится последняя строка поста, и без него
        # получится рассказ про вещь, до которой читателю не добраться.
        хвост = f"по ссылке {найдена.group(0)}"
        return (f"{тема}, {хвост}" if тема else хвост), None
    return тема, материал
