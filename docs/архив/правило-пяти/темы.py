"""Очередь тем и правило пяти постов.

Канал повторялся не потому, что тем мало, а потому, что запрет был мягкий:
прошлые темы уходили в модель списком, и она честно приносила ту же мысль в
новой упаковке. Список — это просьба, а не граница. Здесь граница.

МЕЖДУ ДВУМЯ ПРИМЕНЕНИЯМИ ОДНОЙ ТЕМЫ ЛЕЖАТ ПЯТЬ ЧУЖИХ ПОСТОВ.
Отсюда «разрыв больше пяти», а не «не меньше»: при разрыве ровно в пять между
постами лежит четыре чужих, и это ещё рано. Место, где легко ошибиться на
единицу, поэтому оно проверено тестом с обеих сторон.

Считается по позиции — сквозному номеру поста по порядку выхода. По дате
считать нельзя: два поста выходят в один день, а разрыв между ними есть.
Модуль нарочно не ходит ни в базу, ни в сеть: чистый счёт проверяется тестом
без подготовки окружения, а данные ему приносит вызывающий.
"""

РАЗРЫВ = 5


def доступна(theme_id: int, позиция: int, применения: dict) -> bool:
    """Прошло ли пять чужих постов с прошлого раза.

    `применения` — что и на каких позициях уже выходило: {theme_id: [позиции]}.
    Тема, которой в журнале нет, доступна всегда.
    """
    было = применения.get(theme_id) or []
    if not было:
        return True
    return позиция - max(было) > РАЗРЫВ


def свободные(позиция: int, справочник: list, применения: dict) -> list:
    """Темы, которые сегодня разрешено брать. Порядок справочника сохраняется.

    Порядок важен: справочник ведёт владелец, и первая подходящая тема в нём —
    это его выбор, а не случайность.
    """
    return [т for т in справочник
            if доступна(т["id"], позиция, применения)]
