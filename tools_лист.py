# -*- coding: utf-8 -*-
"""Лист кадров поста, чтобы посмотреть карусель одним взглядом.

    python tools_лист.py 96      → путь к картинке, брак обведён
"""
import sys

import db
import storage
import лист
import приёмка


def main(ид: int) -> None:
    ряд = db.взять(ид)
    if not ряд:
        sys.exit(f"поста {ид} нет")
    файлы = [storage.во_временный(с) for с in db.картинки(ряд)]
    отчёт = db.карточка(ряд).get("приёмка")
    print(лист.собрать(файлы, брак=приёмка.бракованные(отчёт)))
    if отчёт:
        print("годен" if приёмка.годен(отчёт) else "брак: " + приёмка.строкой(отчёт))


if __name__ == "__main__":
    main(int(sys.argv[1]))
