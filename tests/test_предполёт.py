# -*- coding: utf-8 -*-
"""Предполёт: что сломается на кадре, видно ещё по тексту карусели.

Беда — поломка, которая выйдет на кадре точно, её чинят до отрисовки.
Замечание — то, на что стоит взглянуть. Ни модели, ни Chrome.
"""
import sys
import unittest
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

import carousel  # noqa: E402
import предполёт  # noqa: E402

МЫСЛЬ = {"вид": "мысль", "заголовок": "Коротко",
         "текст": "Мысль достаточной длины, чтобы кадр не пустовал"}
БЫЛО = {"вид": "было", "заголовок": "Было и стало", "текст": "",
        "строки": ["Руками два часа", "С ИИ пять минут"]}


def карусель(дизайн="каталог", слайды=(), кадров=(8, 12), **поля):
    return {"cover_title": поля.get("cover_title", "Обложка без чисел"),
            "slides": [dict(с) for с in слайды],
            "closing": поля.get("closing", ""),
            "каркас": поля.get("каркас", "разбор"),
            "паспорт": {"дизайн": дизайн, "кадров": list(кадров)}}


def кадр(отчёт, номер):
    return next(к for к in отчёт["кадры"] if к["номер"] == номер)


class Проверить(unittest.TestCase):
    def test_было_на_тёмном_кадре_каталога_беда(self):
        отчёт = предполёт.проверить(карусель(слайды=[БЫЛО]), "3к4")
        self.assertFalse(отчёт["годен"])
        self.assertIn("Д-01", " ".join(кадр(отчёт, 2)["беды"]))

    def test_было_на_светлом_кадре_годен(self):
        отчёт = предполёт.проверить(карусель(слайды=[МЫСЛЬ, БЫЛО]), "3к4")
        self.assertTrue(отчёт["годен"])

    def test_подсветка_на_светлом_кадре_пособия_беда(self):
        светлый = {"вид": "мысль", "заголовок": "Шапка",
                   "текст": "Главное *в подсветке* и достаточно длинный текст"}
        отчёт = предполёт.проверить(карусель("пособие", [МЫСЛЬ, светлый]), "3к4")
        self.assertIn("Д-03", " ".join(кадр(отчёт, 3)["беды"]))

    def test_манифест_в_квадрате_беда_на_обложке(self):
        отчёт = предполёт.проверить(карусель("манифест", [МЫСЛЬ]), "квадрат")
        self.assertIn("Д-05", " ".join(кадр(отчёт, 1)["беды"]))
        self.assertEqual(кадр(отчёт, 2)["беды"], [])

    def test_полупустой_кадр_замечание(self):
        короткий = {"вид": "выделение", "текст": "*Коротко*"}
        отчёт = предполёт.проверить(карусель("фирменный", [короткий]), "3к4")
        self.assertTrue(отчёт["годен"])
        self.assertIn("Д-12", " ".join(кадр(отчёт, 2)["замечания"]))

    def test_длинный_заголовок_замечание(self):
        длинный = {**МЫСЛЬ, "заголовок": "Заголовок заметно длиннее предела"}
        отчёт = предполёт.проверить(карусель("фирменный", [длинный]), "3к4")
        self.assertIn("кегль ужмётся", " ".join(кадр(отчёт, 2)["замечания"]))

    def test_длинный_пункт_замечание(self):
        список = {"вид": "список", "заголовок": "Что взять",
                  "строки": ["Пункт короткий", "Пункт, который не влезет в одну строку"]}
        отчёт = предполёт.проверить(карусель("фирменный", [список]), "3к4")
        self.assertIn("ляжет в две строки", " ".join(кадр(отчёт, 2)["замечания"]))

    def test_обложка_обещает_больше_чем_слайдов(self):
        к = карусель("фирменный", [МЫСЛЬ] * 5, cover_title="6 ошибок новичка")
        отчёт = предполёт.проверить(к, "3к4")
        self.assertIn("обещает 6", " ".join(кадр(отчёт, 1)["замечания"]))

    def test_йё_в_манифесте_замечание(self):
        к = карусель("манифест", [МЫСЛЬ], cover_title="Признаки ФЕЙКА")
        отчёт = предполёт.проверить(к, "3к4")
        self.assertIn("Д-06", " ".join(кадр(отчёт, 1)["замечания"]))

    def test_призыв_про_список_без_списка(self):
        список = carousel.ПРИЗЫВЫ_СЛАЙД[4]
        заголовок = next(т for т in (f"Заголовок {н}" for н in range(100))
                         if carousel.призыв({"cover_title": т}) == список)
        к = карусель("фирменный", [МЫСЛЬ], cover_title=заголовок,
                     closing="Итог карусели", каркас="разбор")
        отчёт = предполёт.проверить(к, "3к4")
        финал = кадр(отчёт, 3)
        self.assertEqual(финал["вид"], "финал")
        self.assertIn("Д-08", " ".join(финал["замечания"]))

    def test_одним_кадром_без_обложки_и_финала(self):
        шпаргалка = {"вид": "шпаргалка", "заголовок": "Всё на одном",
                     "строки": ["Раздел: раз; два"]}
        к = карусель("фирменный", [шпаргалка], кадров=(1, 1), closing="Итог")
        отчёт = предполёт.проверить(к, "3к4")
        self.assertEqual([к_["номер"] for к_ in отчёт["кадры"]], [1])

    def test_строкой(self):
        отчёт = предполёт.проверить(карусель(слайды=[БЫЛО]), "3к4")
        self.assertTrue(предполёт.строкой(отчёт).startswith("№2: «было» ломается"))
        self.assertEqual(предполёт.строкой({"годен": True, "кадры": []}), "")


if __name__ == "__main__":
    unittest.main()
