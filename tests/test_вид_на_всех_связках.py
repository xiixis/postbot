# -*- coding: utf-8 -*-
"""Обложка, середина и финал собираются в любом дизайне на любом фоне.

Паспорт может выбрать любую одобренную связку, и падение на одной из них
роняет весь заказ. Так «карточка» падала на обложке с KeyError: цвет панели
был только у кадров середины. Chrome здесь не нужен — проверяется сборка.
"""
import sys
import unittest
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

import card  # noqa: E402


class ВсеСвязки(unittest.TestCase):
    def setUp(self):
        self.было = card._снять, card._замерить
        self.страницы = []
        card._снять = lambda страница, *а, **к: self.страницы.append(страница)
        card._замерить = lambda *а, **к: {}

    def tearDown(self):
        card._снять, card._замерить = self.было

    def test_каждый_дизайн_на_каждом_фоне(self):
        for дизайн in card.ДИЗАЙНЫ:
            for оформление in card.ОФОРМЛЕНИЯ:
                with self.subTest(дизайн=дизайн, оформление=оформление):
                    card.слайд_обложка("Над", "Заголовок обложки", None, 1, 10, "3к4",
                                       дизайн=дизайн, оформление=оформление)
                    стр, _, _ = card.страница_вида(
                        "мысль", {"заголовок": "Шапка", "текст": "Мысль"}, 4, 10, "3к4",
                        оформление=оформление, дизайн=дизайн)
                    card.слайд_финал("Вывод карусели", 10, 10, "3к4", "Подпишись",
                                     дизайн=дизайн, оформление=оформление)
                    self.assertIn("<style>", стр)
        self.assertEqual(len(self.страницы), 2 * len(card.ДИЗАЙНЫ) * len(card.ОФОРМЛЕНИЯ))
