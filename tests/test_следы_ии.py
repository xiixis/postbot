# -*- coding: utf-8 -*-
"""Следы нейросети в тексте ловятся счётом, без модели.

Правила из скила «Антидетектор»: жёсткие запреты удаляются всегда, а слова из
стоп-словаря подозрительны пачкой — три в одном абзаце.
"""
import json
import sys
import unittest
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

import следы_ии  # noqa: E402


class Запреты(unittest.TestCase):
    def test_находит_жёсткие_запреты(self):
        случаи = {
            "Это не просто нейросеть, а помощник": "«не просто X, а Y»",
            "Ускоряет не только монтаж, но и озвучку": "«не только X, но и Y»",
            "Это не про деньги. Это про время.": "«это не про X, это про Y»",
            "В современном мире все пишут посты": "«в современном мире»",
            "Стоит отметить, что бот быстрый": "«стоит отметить»",
            "Данный способ работает": "«данный»",
            "Звук играет ключевую роль в ролике": "«играет важную роль»",
            "Таким образом, выбор за тобой": "«таким образом» / «подводя итог»",
            "Раскрой потенциал канала": "маркетинговое клише",
            "Подходит всем, от новичков до профи": "ложный диапазон «от X до Y»",
            "Давайте разберёмся, как это работает": "«давайте разберёмся»",
            "Отличный вопрос! Сейчас расскажу": "артефакт чат-бота",
            "И это нормально. Все так начинали": "псевдотерапия",
            "Эксперты считают, что это будущее": "размытый авторитет",
        }
        for текст, беда in случаи.items():
            with self.subTest(текст=текст):
                self.assertIn(беда, следы_ии.найти(текст))

    def test_является_больше_одного_раза(self):
        один = "Бот является помощником. Он пишет посты."
        два = "Бот является помощником. Звук является основой."
        self.assertNotIn("«является»", " ".join(следы_ии.найти(один)))
        self.assertIn("«является» ×2", следы_ии.найти(два))

    def test_стоп_слова_пачкой(self):
        пачка = "Кроме того, ключевой момент: взаимодействие с аудиторией."
        одно = "Ключевой момент в том, что звук важнее картинки."
        self.assertTrue(any(б.startswith("слова нейросети") for б in следы_ии.найти(пачка)))
        self.assertEqual(следы_ии.найти(одно), [])

    def test_живой_текст_чист(self):
        живой = ("Озвучку сделал за вечер. Звучит почти как я, только без "
                 "запинок. Не X, а Y тут не нужно: бери и пробуй.")
        self.assertEqual(следы_ии.найти(живой), [])

    def test_нормально_с_содержанием_не_терапия(self):
        """Пост 77: мнение, а не утешение."""
        self.assertEqual(следы_ии.найти("Анимация на троечку. И это нормально, не его работа."), [])

    def test_слова_внутри_других_слов_не_ловятся(self):
        self.assertEqual(следы_ии.найти("Раздаю задания ученикам. Данные в таблице."), [])


class ВПридирках(unittest.TestCase):
    def test_следы_видны_под_черновиком(self):
        import придирки
        ряд = {"id": 1, "title": "Т", "rubric": "пост", "images": None, "image_path": None,
               "body": "Это не просто бот, а помощник. Стоит отметить, что он быстрый.",
               "card": json.dumps({"carousel": {"slides": [
                   {"вид": "мысль", "заголовок": "Шаг", "текст": "Данный приём работает"}]}},
                   ensure_ascii=False)}
        беды = " ".join(придирки.к_посту(ряд))
        self.assertIn("следы нейросети", беды)
        self.assertIn("«не просто X, а Y»", беды)
        self.assertIn("«данный»", беды)
