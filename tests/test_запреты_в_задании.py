# -*- coding: utf-8 -*-
"""Модель узнаёт, какие вёрстки в дизайне этой карусели ломаются.

Предполёт поймает сломанную связку и сам, но починка стоит похода в модель
или меняет вёрстку. Дешевле не дать её выбрать.
"""
import sys
import unittest
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

import carousel  # noqa: E402
import writer    # noqa: E402
import агент     # noqa: E402


class Запреты(unittest.TestCase):
    def test_каталог_называет_тёмные_и_светлые_кадры(self):
        т = carousel._запреты({"дизайн": "каталог"}, "3к4")
        self.assertIn("на тёмных кадрах (2, 4, 6…) не бери: было, против, стрелка", т)
        self.assertIn("на светлых кадрах (3, 5, 7…) не бери: против", т)

    def test_пособие_просит_без_подсветки_на_светлых(self):
        т = carousel._запреты({"дизайн": "пособие"}, "3к4")
        self.assertIn("не бери: шаг", т)
        self.assertIn("на кадрах 3, 5, 7… не ставь подсветку", т)

    def test_фирменный_без_блока(self):
        self.assertEqual(carousel._запреты({"дизайн": "фирменный"}, "3к4"), "")

    def test_блок_уходит_в_задание_модели(self):
        class Стоп(Exception):
            pass

        пойманное = {}

        def по_форме(задача, *а, **к):
            пойманное["задача"] = задача
            raise Стоп

        подмены = {(агент, "по_форме"): по_форме,
                   (writer, "_факты"): lambda: "",
                   (writer, "_значки"): lambda: "",
                   (carousel, "_чужой_опыт"): lambda площадка: "",
                   (carousel, "_подсмотренное"): lambda: "",
                   (carousel, "_позы"): lambda: ""}
        было = {ключ: getattr(*ключ) for ключ in подмены}
        for (модуль, имя), замена in подмены.items():
            setattr(модуль, имя, замена)
        try:
            with self.assertRaises(Стоп):
                carousel.сочинить("тема", [], площадка="tiktok", паспорт={
                    "тип": "обычная", "каркас": "шаги", "кадров": [8, 10],
                    "дизайн": "каталог", "оформление": "чистый", "кот": True})
        finally:
            for (модуль, имя), прежнее in было.items():
                setattr(модуль, имя, прежнее)
        self.assertIn("ВЁРСТКИ, КОТОРЫЕ В ЭТОМ ДИЗАЙНЕ ЛОМАЮТСЯ", пойманное["задача"])


if __name__ == "__main__":
    unittest.main()
