"""«Переписать» под каруселью правит карусель, а не превращает её в пост.

До 14 сентября 2026 правка словами шла через писателя одиночных постов, и в
карточку записывались его поля. Слайды, паспорт формата, площадка и приёмка
пропадали, и карусель оставалось только собирать заново: ещё один поход в
модель и полный прогон рисования.

Модель и рисование подменены дублёрами из теста эскиза.
"""

