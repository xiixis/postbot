from test_эскиз import _Дублёры  # noqa: E402

ПАСПОРТ = {"тип": "список", "каркас": "шаги", "кадров": [5, 7]}


def _карусель_в_базе(д):
    import db
    карточка = {"carousel": {"cover_title": "Старая обложка", "поза": "privet",
                             "slides": [{"title": "Первый шаг"}],
                             "паспорт": ПАСПОРТ},
                "площадка": "tiktok", "куда": ["tiktok", "телеграм"],
                "формат": "3к4", "суть": "субтитры бесплатно",
                "приёмка": {"годен": True}}
    db.взять = lambda ид: {"id": ид, "title": "Старая обложка",
                           "card": json.dumps(карточка, ensure_ascii=False)}
    return карточка


class ПравкаКарусели(unittest.TestCase):
    def _переписать(self, указание="убери третий слайд"):
        import carousel
        import writer
        звали = {}
        with _Дублёры() as д:
            _карусель_в_базе(д)
            сочинить = carousel.сочинить

            def запомнить(*а, **к):
                звали["сочинить"] = (а, к)
                return сочинить(*а, **к)

            carousel.сочинить = запомнить
            было_писатель = writer.переписать
            writer.переписать = lambda *а, **к: звали.setdefault("писатель", 1)
            try:
                д.core.переписать(42, указание)
            finally:
                writer.переписать = было_писатель
        return д, звали

    def test_писатель_постов_не_зовётся(self):
        _, звали = self._переписать()
        self.assertNotIn("писатель", звали)
        self.assertIn("сочинить", звали)

    def test_карусель_остаётся_каруселью(self):
        д, _ = self._переписать()
        карточка = json.loads(д.положено["card"])
        self.assertIn("carousel", карточка)
        self.assertEqual(карточка["площадка"], "tiktok")
        self.assertEqual(карточка["куда"], ["tiktok", "телеграм"])
        self.assertEqual(карточка["формат"], "3к4")
        self.assertEqual(д.нарисовано, 1)

    def test_модель_видит_нынешний_текст_и_указание(self):
        _, звали = self._переписать("убери третий слайд")
        а, к = звали["сочинить"]
        указания = к.get("указания") if "указания" in к else а[2]
        self.assertIn("Первый шаг", указания)
        self.assertIn("убери третий слайд", указания)

    def test_свой_пост_не_считается_повтором(self):
        _, звали = self._переписать()
        а, к = звали["сочинить"]
        было = к.get("было") if "было" in к else а[1]
        self.assertEqual(было, [], "правка своей же темы — не повтор")

    def test_паспорт_и_площадка_прежние(self):
        _, звали = self._переписать()
        а, к = звали["сочинить"]
        self.assertEqual(к.get("паспорт"), ПАСПОРТ)
        площадка = к.get("площадка") if "площадка" in к else а[3]
        self.assertEqual(площадка, "tiktok")


class ДругойВариант(unittest.TestCase):
    """«🔄 Другой вариант» под каруселью давал обычный пост."""

    def test_под_каруселью_новая_карусель_той_же_площадки(self):
        import bot
        import db
        звали = {}
        было = (bot.сделать_пост, bot.сделать_карусель, db.взять)
        bot.сделать_пост = lambda *а, **к: звали.setdefault("пост", а)
        bot.сделать_карусель = lambda *а, **к: звали.setdefault("карусель", (а, к))
        карточка = {"carousel": {"slides": []}, "площадка": "tiktok"}
        db.взять = lambda ид: {"id": ид, "rubric": "карусель tiktok",
                               "card": json.dumps(карточка)}
        try:
            bot.другой_вариант(7, 42)
        finally:
            bot.сделать_пост, bot.сделать_карусель, db.взять = было
        self.assertNotIn("пост", звали)
        а, к = звали["карусель"]
        self.assertEqual(к.get("площадка", а[2] if len(а) > 2 else None), "tiktok")

    def test_под_постом_по_прежнему_пост(self):
        import bot
        import db
        звали = {}
        было = (bot.сделать_пост, bot.сделать_карусель, db.взять)
        bot.сделать_пост = lambda *а, **к: звали.setdefault("пост", а)
        bot.сделать_карусель = lambda *а, **к: звали.setdefault("карусель", а)
        db.взять = lambda ид: {"id": ид, "rubric": "совет", "card": "{}"}
        try:
            bot.другой_вариант(7, 42)
        finally:
            bot.сделать_пост, bot.сделать_карусель, db.взять = было
        self.assertEqual(звали.get("пост"), (7, "совет"))
        self.assertNotIn("карусель", звали)


