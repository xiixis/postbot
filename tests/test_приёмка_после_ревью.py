class Принять(unittest.TestCase):
    def setUp(self):
        self.было = card._замерить

    def tearDown(self):
        card._замерить = self.было
        приёмка.итог()

    def _принять(self, замер):
        приёмка.начать()
        приёмка.кадр(3, "шаг")
        card._замерить = lambda *а, **к: замер
        card._принять(png(1620, 2160), "<p>", 1080, 1440)
        return приёмка.итог()["кадры"][0]

    def test_сбой_замера_это_беда_страницы(self):
        запись = self._принять({})
        self.assertEqual(запись["брак"], ["страница: не удалось замерить страницу"])
        self.assertFalse(приёмка.лечится_текстом(запись))

    def test_слово_в_боковом_поле_замечание(self):
        # Поле 3к4 — 80 px. Буквы кончаются на 1015: в поле, но у края не срезаны.
        запись = self._принять({"холст": [1080, 1440],
                                "перелив": [[".з", 900, 835, 1015]]})
        self.assertEqual(запись["брак"], [])
        self.assertIn("слово заходит в боковое поле", запись["замечания"])

    def test_слово_у_края_брак(self):
        запись = self._принять({"холст": [1080, 1440],
                                "перелив": [["h1", 1100, 920, 1180]]})
        self.assertIn("слово шире колонки", запись["брак"])

    def test_старый_замер_без_края_брак(self):
        запись = self._принять({"холст": [1080, 1440], "перелив": [["h1", 900, 800]]})
        self.assertIn("слово шире колонки", запись["брак"])


class УжатиеБезКота(unittest.TestCase):
    """Кот не поместился, кадр пересобран без него — подобранный кегль остаётся."""

    def setUp(self):
        self.было = (card._страница_вида, card._замерить, card.проверить_композицию,
                     card._снять, card._плотность)

    def tearDown(self):
        (card._страница_вида, card._замерить, card.проверить_композицию,
         card._снять, card._плотность) = self.было

    def test_пересборка_без_кота_хранит_ужатие(self):
        вызовы = []
        ответы = iter([["текст заходит в нижнее поле или вылезает за холст"], [],
                       ["кот накрывает текст"], ["кот накрывает текст"]])

        def страница(*а, **к):
            вызовы.append((а[5] if len(а) > 5 else к.get("поза"), к.get("ужатие", 1.0)))
            return "<p>", 1080, 1440

        card._страница_вида = страница
        card._замерить = lambda *а, **к: {"холст": [1080, 1440]}
        card.проверить_композицию = lambda *а, **к: next(ответы, [])
        card._снять = lambda *а, **к: Path("/tmp/кадр.png")
        card._плотность = lambda путь, вид, дизайн: путь
        card.слайд_вида("мысль", {"текст": "т"}, 3, 10, "3к4", Path("/tmp/поза.png"),
                        "угол", реплика="мяу")
        self.assertTrue([у for поза, у in вызовы if поза is None], вызовы)
        # Первая сборка до подбора кегля; все после неё — с подобранным.
        self.assertTrue(all(у == 0.88 for _, у in вызовы[1:]), вызовы)


