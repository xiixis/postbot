class ПерерисовкаСлайда(unittest.TestCase):
    def test_карточка_перечитывается_перед_записью(self):
        """Пока рисовался слайд, в карточку успели записать вариант площадки."""
        import carousel
        import core
        import db
        import mascot
        import storage
        старая = {"carousel": {"поза": "privet", "slides": [{"вид": "мысль"}]}}
        свежая = {**старая, "варианты": {"tiktok": {"images": ["x"]}}}
        чтения = iter([старая, свежая])
        записано = {}

        def взять(ид):
            return {"id": ид, "card": json.dumps(next(чтения, свежая)),
                    "images": json.dumps(["1.png", "2.png"])}

        with _Подмена(db, взять=взять, правка=lambda ид, **п: записано.update(п)), \
             _Подмена(carousel, позы_слайдов=lambda к: {2: {"поза": None, "план": "общий"}},
                      нарисовать=lambda *а, **к: [Path("/tmp/2.png")]), \
             _Подмена(mascot, библиотека=lambda: {}, взять=lambda имя: None), \
             _Подмена(storage, положить=lambda ф: "https://x/2.png"), \
             _Подмена(core, _забыть_варианты=lambda ид: None, _в_папку=lambda ид: None):
            core.перерисовать_слайд(5, 2)
        карточка = json.loads(записано["card"])
        self.assertIn("варианты", карточка)
        self.assertIn("приёмка", карточка)
