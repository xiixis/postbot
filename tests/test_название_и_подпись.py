"""Подпись не пересказывает название: выпуск ловит это сам.

Правило владельца от 19.09.2026 жило только в памяти, и за неделю семь постов
из восьми вышли с подписью, которая повторяла название другими словами.
29.09.2026 он сказал это снова, и правило стало проверкой выпуска.

Пары ниже — настоящие: «пересказ» взят из вышедших постов, «другой угол» — из
подписей, которыми их заменили.
"""
import sys
import unittest
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(КОРЕНЬ))
sys.path.insert(0, str(КОРЕНЬ / "Style"))

import выпуск  # noqa: E402

МЕТКИ = "\n\n#нейросети #ии #видео #aitools #youtube #анимация #монтаж"

ПЕРЕСКАЗ = [
    ("5 ИИ, которые собирают анимированный ролик из текста: Vyond, Kaiber, Lumen5 и другие",
     "Пять ИИ, которые собирают анимированный ролик из текста"),
    ("Зачем платить за ИИ $109 в месяц: пять платных лидеров и их бесплатные двойники",
     "Пять платных ИИ и их бесплатные двойники — итого $0 в месяц"),
    ("9 бесплатных нейросетей Google: дизайн, реклама, музыка, видео, код и картинки",
     "9 бесплатных нейросетей Google: сохрани, чтобы попробовать все"),
    ("5 новых ИИ-сайтов: приложение, сайт и 3D-иконки по описанию без кода",
     "Пять свежих ИИ-сайтов: от иконок до своего приложения. Сохрани 👇"),
]

ДРУГОЙ_УГОЛ = [
    ("5 ИИ, которые собирают анимированный ролик из текста: Vyond, Kaiber, Lumen5 и другие",
     "Ведущий, заставка или клип для ролика? Под каждую задачу свой ИИ. Сохрани"),
    ("Зачем платить за ИИ $109 в месяц: пять платных лидеров и их бесплатные двойники",
     "Проверь свои подписки на ИИ: какую из них можно отменить уже сегодня?"),
    ("ИИ-навыки 2026: промпты, агенты, автоматизация, RAG, AEO и мультимодальный ИИ",
     "Просто болтать с ChatGPT уже мало. Вот что учить дальше"),
    ("Монтаж роликов через Claude Code и Remotion: шаблон, сборка и выкладка в 9 соцсетей",
     "Я больше не открываю монтажку: ролик собирается одной командой. Сохрани схему"),
]


class НазваниеИПодпись(unittest.TestCase):
    def test_пересказ_не_выпускается(self):
        for название, подпись in ПЕРЕСКАЗ:
            with self.subTest(подпись=подпись):
                with self.assertRaises(SystemExit) as отказ:
                    выпуск.дополняют({"название": название, "подпись": подпись + МЕТКИ})
                self.assertIn("пересказывает название", str(отказ.exception))

    def test_другой_угол_проходит(self):
        for название, подпись in ДРУГОЙ_УГОЛ:
            with self.subTest(подпись=подпись):
                выпуск.дополняют({"название": название, "подпись": подпись + МЕТКИ})

    def test_слово_и_цифра_одно_и_то_же(self):
        """«Пять» в подписи и «5» в названии — повтор, а не новое слово."""
        self.assertIn("5", выпуск.основы("Пять сайтов"))

    def test_хештеги_в_счёт_не_идут(self):
        """Слова темы обязаны стоять в метках, и пересказом это не считается."""
        self.assertEqual(выпуск.основы("#нейросети #монтаж"), set())

    def test_без_названия_проверять_нечего(self):
        выпуск.дополняют({"подпись": "Пять ИИ, которые собирают ролик" + МЕТКИ})

    def test_поле_тест_пропускает_с_предупреждением(self):
        название, подпись = ПЕРЕСКАЗ[0]
        выпуск.дополняют({"название": название, "подпись": подпись + МЕТКИ, "тест": "замер"})

    def test_выпуск_зовёт_проверку(self):
        """Проверка, которую забыли позвать, ничего не ловит."""
        код = (КОРЕНЬ / "Style" / "выпуск.py").read_text(encoding="utf-8")
        self.assertIn("дополняют(пост)", код.split("def main()")[1])


if __name__ == "__main__":
    unittest.main()
