# -*- coding: utf-8 -*-
"""Правка экрана: «не изменилось» — это успех, а не беда.

Меню бота живёт одним сообщением и переписывается на месте. Телеграм отвечает
ошибкой «message is not modified», когда текст и кнопки совпали байт в байт, —
а это ровно случай «нажал ту же кнопку дважды» и «переключатель вернул прежнее
состояние». Сочти бот такой ответ провалом, и он пошлёт новое меню: получится
та самая лента мёртвых сообщений, ради избавления от которой живой экран и
заведён. Поломка при этом не видна в журнале — просто чат снова засоряется.

Второе, что здесь сторожится: правка обязана готовить текст тем же
«_разметить», что и отправка. Иначе присланный экран и он же после первого
нажатия выглядят по-разному — звёздочки и иконки канала пропадают.
"""

import sys
import unittest
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

import telegram as tg                                        # noqa: E402


class _Телеграм:
    """Дублёр сети: запоминает вызов и отвечает так, как велено.

    Мока нет намеренно — в проекте их не заводят. Дублёр заодно показывает,
    какое именно тело уходит в API, а это половина смысла теста.
    """

    def __init__(self, беда: str | None = None):
        self.беда = беда
        self.метод = ""
        self.тело: dict = {}

    def __call__(self, метод, данные=None, файлы=None, таймаут=60):
        self.метод, self.тело = метод, данные or {}
        if self.беда:
            raise tg.ОшибкаTG(self.беда)
        return {"message_id": 1}


class ПравкаТекста(unittest.TestCase):

    def setUp(self):
        self.настоящий = tg._вызвать

    def tearDown(self):
        tg._вызвать = self.настоящий

    def _прогнать(self, беда=None, **ещё):
        двойник = _Телеграм(беда)
        tg._вызвать = двойник
        итог = tg.правка_текста(1, 2, "текст", **ещё)
        return итог, двойник

    def test_не_изменилось_считается_успехом(self):
        """Иначе повторное нажатие плодит новое меню — та самая лента."""
        итог, _ = self._прогнать("editMessageText: message is not modified")
        self.assertTrue(итог)

    def test_обычная_правка_удалась(self):
        итог, двойник = self._прогнать()
        self.assertTrue(итог)
        self.assertEqual(двойник.метод, "editMessageText")

    def test_старое_сообщение_не_правится(self):
        """Сообщение удалили или оно с картинкой — надо слать новое."""
        итог, _ = self._прогнать("editMessageText: message to edit not found")
        self.assertFalse(итог)

    def test_сеть_отвалилась_не_роняет_бота(self):
        def падать(*_, **__):
            raise OSError("сеть моргнула")
        tg._вызвать = падать
        self.assertFalse(tg.правка_текста(1, 2, "текст"))

    def test_разметка_такая_же_как_при_отправке(self):
        """Звёздочки автора обязаны стать жирным и в правке тоже."""
        _, двойник = self._прогнать()
        self.assertEqual(двойник.тело["text"], tg._разметить("текст"))
        self.assertEqual(двойник.тело["parse_mode"], "HTML")

    def test_пустая_разметка_отдаёт_текст_как_есть(self):
        _, двойник = self._прогнать(разметка="")
        self.assertEqual(двойник.тело["text"], "текст")
        self.assertNotIn("parse_mode", двойник.тело)

    def test_без_клавиатуры_старые_кнопки_снимаются(self):
        """Без reply_markup телеграм оставил бы кнопки прошлого экрана."""
        _, двойник = self._прогнать()
        self.assertEqual(двойник.тело["reply_markup"], "{}")

    def test_клавиатура_доезжает(self):
        клава = tg.кнопки([[("Назад", "home")]])
        _, двойник = self._прогнать(клавиатура=клава)
        self.assertEqual(двойник.тело["reply_markup"], клава)


if __name__ == "__main__":
    unittest.main()
