"""Важное не стоит впритык к важному: между блоками кадра есть запас.

Слово владельца 15 сентября 2026: «нельзя, чтобы что-то было впритык к другому».
Замер ловил только наложение, и на финале поста 96 плашка призыва стояла в 1 px
над логотипом, а строка вывода заходила на плашку — кадр считался чистым.

Запас — 40 px на кадре 1620, около 10 точек на экране телефона. На странице
шириной 1080 это 27 px.
"""
import sys
import unittest
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

import card      # noqa: E402
import config    # noqa: E402
import форматы   # noqa: E402

ХОЛСТ = [1080, 1440]
ЗНАК = [80, 1191, 124, 1235]
ПОЛОСА = [0, 1258, 432, 1264]


def замер(**роли) -> dict:
    return {"холст": ХОЛСТ, "знак": [ЗНАК], "полоса": [ПОЛОСА], **роли}


def впритык(беды: list[str]) -> list[str]:
    return [б for б in беды if "впритык" in б]


class Зазоры(unittest.TestCase):
    def test_запас_от_ширины_холста(self):
        self.assertEqual(card.запас({"холст": [1080, 1440]}), 27)
        self.assertEqual(card.запас({"холст": [1620, 2160]}), 40)

    def test_призыв_на_логотипе_это_беда(self):
        """Финал поста 96: плашка кончается на 1190, логотип начинается на 1191."""
        беды = card.проверить_композицию(замер(призыв=[[80, 1041, 1000, 1190]]), "3к4")
        self.assertIn("призыв впритык к логотипу", беды)

    def test_строка_у_призыва_это_беда(self):
        беды = card.проверить_композицию(
            замер(строки=[[80, 900, 800, 1020]], текст=[[80, 900, 800, 1020]],
                  призыв=[[80, 1030, 1000, 1150]]), "3к4")
        self.assertIn("текст впритык к призыву", беды)

    def test_строка_у_кота_это_беда(self):
        беды = card.проверить_композицию(
            замер(строки=[[80, 700, 700, 760]], текст=[[80, 700, 700, 760]],
                  кот=[[712, 700, 1000, 1100]]), "3к4")
        self.assertIn("текст впритык к коту", беды)

    def test_строка_у_реплики_это_беда(self):
        беды = card.проверить_композицию(
            замер(строки=[[80, 700, 600, 760]], текст=[[80, 700, 600, 760]],
                  реплика=[[400, 770, 1000, 830]], кот=[[787, 900, 1000, 1150]]), "3к4")
        self.assertIn("текст впритык к реплике кота", беды)

    def test_строка_у_логотипа_это_беда(self):
        беды = card.проверить_композицию(
            замер(строки=[[80, 1100, 600, 1170]], текст=[[80, 1100, 600, 1170]]), "3к4")
        self.assertIn("текст впритык к логотипу или полосе", беды)

    def test_кот_у_логотипа_это_беда(self):
        беды = card.проверить_композицию(замер(кот=[[130, 900, 400, 1180]]), "3к4")
        self.assertIn("кот впритык к логотипу или полосе", беды)

    def test_зазор_в_запас_тихо(self):
        беды = card.проверить_композицию(
            замер(строки=[[80, 700, 700, 760]], текст=[[80, 700, 700, 760]],
                  кот=[[727, 787, 1000, 1100]],
                  призыв=[[80, 1000, 1000, 1164]]), "3к4")
        self.assertEqual(впритык(беды), [])

    def test_реплика_у_своего_кота_тихо(self):
        """Облачко прижато к коту нарочно: у него хвостик, это одна фигура (пост 96, кадр 4)."""
        беды = card.проверить_композицию(
            замер(реплика=[[673, 752, 1000, 815]], кот=[[787, 831, 1000, 1150]]), "3к4")
        self.assertEqual(впритык(беды), [])

    def test_пустой_край_шрифта_не_в_счёт(self):
        """Финал поста 96: рамка строки в 25 px от плашки, хвосты букв — в ~29."""
        беды = card.проверить_композицию(
            замер(строки=[[80, 792, 721, 947]], текст=[[80, 255, 1000, 947]],
                  призыв=[[80, 972, 1000, 1120]]), "3к4")
        self.assertEqual(впритык(беды), [])

    def test_по_строкам_а_не_по_коробке(self):
        """Коробка вывода растянута margin-bottom:auto до плашки, буквы кончаются выше."""
        беды = card.проверить_композицию(
            замер(текст=[[80, 700, 1000, 1030]], строки=[[80, 700, 900, 900]],
                  призыв=[[80, 1040, 1000, 1150]]), "3к4")
        self.assertEqual(впритык(беды), [])


class ПосадкаКота(unittest.TestCase):
    """Кота сажают сразу с запасом: иначе проверка его потом выкидывает («рисую без кота»)."""

    def test_ноги_кота_выше_логотипа_на_запас(self):
        for формат in ("3к4", "квадрат"):
            with self.subTest(формат=формат):
                д = card.ФОРМАТЫ[формат]
                верх_логотипа = д["низ_знака"] + card.ВЫСОТА_ЗНАКА
                self.assertGreaterEqual(card._низ_кота(д) - верх_логотипа,
                                        card._запас_px(д["ширина"]))

    def test_кот_в_колонке_не_жмётся_к_тексту(self):
        """Кадр 2 поста 101: строка кончалась в 15 px от кота, стоявшего сбоку."""
        тексты = [[570, 781, 876, 848]]
        ш, в, низ, доля, поле = 1080, 1440, 276, 0.6, 80
        рост = card._рост_в_колонке(тексты, ш, в, низ, доля, поле, 520, False)
        self.assertGreaterEqual(рост, card.МИН_КОТ)
        кот = [ш - поле - рост * доля, в - низ - рост, ш - поле, в - низ]
        self.assertGreaterEqual(card._зазор(тексты[0], кот), card._запас_px(ш))


def страницы_финала(формат: str, поза) -> dict:
    """Финал каждого дизайна белого списка: вёрстка, которую рисовальщик отдал бы в снимок."""
    было = card._снять
    итог = {}
    try:
        for дизайн in форматы.ДИЗАЙНЫ_ОК:
            if not форматы.дизайн_годится(дизайн, формат):
                continue
            снято = []
            card._снять = lambda страница, *а, **к: снято.append((страница, *а))
            card.слайд_финал("Проверь формулу на трёх строках", 10, 10, формат,
                             "Забери в закладки. Подпишись: один приём за пост",
                             поза=поза, дизайн=дизайн, оформление="чистый")
            итог[дизайн] = снято[-1]
    finally:
        card._снять = было
    return итог


@unittest.skipUnless(config.хром(), "нужен Chrome")
class ВБраузере(unittest.TestCase):
    def test_финал_со_строкой_призыва_с_запасом(self):
        for формат in ("3к4", "квадрат"):
            for дизайн, (страница, ш, в) in страницы_финала(формат, None).items():
                with self.subTest(формат=формат, дизайн=дизайн):
                    беды = card.проверить_композицию(card._замерить(страница, ш, в), формат)
                    self.assertEqual(впритык(беды), [])

    def test_финал_с_котом_и_облачком_с_запасом(self):
        поза = config.АССЕТЫ / "mascot" / "позы" / "ukazyvaet.png"
        for формат in ("3к4", "квадрат"):
            for дизайн, (страница, ш, в) in страницы_финала(формат, поза).items():
                with self.subTest(формат=формат, дизайн=дизайн):
                    беды = card.проверить_композицию(card._замерить(страница, ш, в), формат)
                    self.assertEqual(впритык(беды), [])

    def test_стрелка_не_логотип(self):
        """В «стрелке» стрелка — `div.знак`; логотипом её считать нельзя (пост 96, кадр 3)."""
        страница = ('<meta charset="utf-8"><body style="margin:0">'
                    '<div class="знак" style="position:absolute;left:400px;top:300px;'
                    'width:200px;height:200px">→</div>'
                    '<img class="знак" style="position:absolute;left:80px;top:1191px;'
                    'width:44px;height:44px" src="data:image/gif;base64,'
                    'R0lGODlhAQABAAAAACH5BAEKAAEALAAAAAABAAEAAAICTAEAOw=="></body>')
        з = card._замерить(страница, 1080, 1440)
        self.assertEqual(з["знак"], [[80, 1191, 124, 1235]])


if __name__ == "__main__":
    unittest.main()
