# -*- coding: utf-8 -*-
"""Матрица связок: какие вёрстки в каком дизайне ломаются, и реестр под ними.

Сломанная связка видна ещё по тексту: «было» в каталоге на тёмном кадре
выходит белым по крему всегда. Матрица говорит об этом до отрисовки, а реестр
хранит, откуда запрет взялся, чтобы его сняли вместе с починкой, а не забыли.
"""
import random
import re
import sys
import unittest
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

import форматы  # noqa: E402

РЕЕСТР = Path(__file__).resolve().parent.parent / "docs" / "дефекты-кадров.md"
СТАТУСЫ = ("открыт", "обход в матрице", "обход в предполёте", "обход в рисовальщике",
           "починен с тестом", "автопроверка")


class Матрица(unittest.TestCase):
    def test_каталог_на_тёмном_кадре_не_берёт_было(self):
        self.assertEqual(форматы.запрет("каталог", "было", 2, "3к4"), "Д-01")
        self.assertEqual(форматы.запрет("каталог", "стрелка", 4, "квадрат"), "Д-01")

    def test_каталог_на_светлом_кадре_было_можно(self):
        self.assertEqual(форматы.запрет("каталог", "было", 3, "3к4"), "")

    def test_против_в_каталоге_нельзя_нигде(self):
        for номер in (2, 3):
            with self.subTest(номер=номер):
                self.assertEqual(форматы.запрет("каталог", "против", номер, "3к4"), "Д-02")

    def test_шаг_в_пособии_нельзя(self):
        self.assertEqual(форматы.запрет("пособие", "шаг", 5, "3к4"), "Д-04")

    def test_манифест_в_квадрате_нельзя_целиком(self):
        self.assertEqual(форматы.запрет("манифест", "мысль", 3, "квадрат"), "Д-05")
        self.assertFalse(форматы.дизайн_годится("манифест", "квадрат"))
        self.assertTrue(форматы.дизайн_годится("манифест", "3к4"))
        self.assertTrue(форматы.дизайн_годится("каталог", "квадрат"))

    def test_фирменный_без_запретов(self):
        self.assertEqual(форматы.запрет("фирменный", "против", 2, "квадрат"), "")

    def test_надёжный_вид_не_запрещён_ни_в_одной_связке(self):
        for п in форматы.НЕЛЬЗЯ:
            with self.subTest(дефект=п["дефект"]):
                if "виды" in п:
                    self.assertNotIn(форматы.НАДЁЖНЫЙ_ВИД, п["виды"])
                else:
                    self.assertTrue(п.get("формат") and not п.get("тон"),
                                    "дизайн целиком запрещается только по формату")

    def test_статус_проверено_берётся_из_образцов(self):
        было = set(форматы.ПРОВЕРЕНО)
        try:
            форматы.ПРОВЕРЕНО.add(("терминал", "список", "тёмный", "3к4"))
            self.assertEqual(форматы.статус("терминал", "список", 2, "3к4"), "проверено")
            self.assertEqual(форматы.статус("терминал", "список", 3, "3к4"), "не проверено")
            self.assertEqual(форматы.статус("каталог", "против", 3, "3к4"), "нельзя")
        finally:
            форматы.ПРОВЕРЕНО.clear()
            форматы.ПРОВЕРЕНО.update(было)


class Реестр(unittest.TestCase):
    def setUp(self):
        self.текст = РЕЕСТР.read_text(encoding="utf-8")
        self.записи = set(re.findall(r"^## (Д-\d\d)\.", self.текст, re.M))

    def test_каждый_запрет_записан_в_реестре(self):
        дефекты = {п["дефект"] for п in форматы.НЕЛЬЗЯ}
        дефекты |= {дефект for _, дефект in форматы.БЕЗ_ПОДСВЕТКИ.values()}
        self.assertEqual(дефекты - self.записи, set())

    def test_у_каждой_записи_есть_статус(self):
        for кусок in re.split(r"^## ", self.текст, flags=re.M)[1:]:
            with self.subTest(запись=кусок.splitlines()[0]):
                статус = re.search(r"^- Статус: (.+)$", кусок, re.M)
                self.assertIsNotNone(статус)
                self.assertIn(статус.group(1).strip(), СТАТУСЫ)


class Паспорт(unittest.TestCase):
    def test_квадрат_не_получает_манифест(self):
        for зерно in range(300):
            п = форматы.подобрать([], random.Random(зерно), формат="квадрат")
            self.assertNotEqual(п["дизайн"], "манифест")

    def test_вертикаль_получает_манифест(self):
        дизайны = {форматы.подобрать([], random.Random(з), формат="3к4")["дизайн"]
                   for з in range(300)}
        self.assertIn("манифест", дизайны)

    def test_следующий_берёт_формат_площадки(self):
        import конвейер
        было = (конвейер.настройки, конвейер.сохранить, форматы.подобрать)
        звали = []

        def подобрать(история, случай=None, формат=None):
            звали.append(формат)
            return {"дизайн": "каталог"}

        конвейер.настройки = lambda куда: {"форматы": []}
        конвейер.сохранить = lambda куда, **поля: None
        форматы.подобрать = подобрать
        try:
            форматы.следующий("телеграм")
            форматы.следующий("tiktok")
        finally:
            конвейер.настройки, конвейер.сохранить, форматы.подобрать = было
        self.assertEqual(звали, ["квадрат", "3к4"])


if __name__ == "__main__":
    unittest.main()
