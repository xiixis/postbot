# -*- coding: utf-8 -*-
"""Висячее слово в заголовке: «Тему для / ролика / подберёт / ИИ».

Беда видна на каждой второй обложке, а рисовальщик её не замечал: кегль
подбирался прикидкой `_строк_выйдет`, где ширина знака взята одним числом
(0.52 em) на все гарнитуры. Замер 12 сентября 2026 показал настоящие доли:
Onest 0,57, Oswald в заглавных 0,58, Unbounded 0,81. Прикидка занижала ширину,
кегль выходил крупнее нужного, и заголовок, обещанный в три строки, ложился в
четыре — с одиноким коротким словом в последней.
"""
import sys
import unittest
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

import card    # noqa: E402
import config  # noqa: E402


class Огрызок(unittest.TestCase):
    """Что считать висячей строкой. Числа — настоящие замеры обложек 100 и 101."""

    def test_одинокое_ии_в_последней_строке_это_огрызок(self):
        self.assertTrue(card._висит([661, 520, 687, 224]))

    def test_одинокая_цифра_это_огрызок(self):
        self.assertTrue(card._висит([920, 783, 95, 827]))

    def test_ровные_строки_не_огрызок(self):
        self.assertFalse(card._висит([795, 676, 836]))

    def test_одна_строка_не_огрызок(self):
        self.assertFalse(card._висит([880]))

    def test_пусто_не_огрызок(self):
        self.assertFalse(card._висит([]))

    def test_короткая_последняя_но_не_огрызок(self):
        """Половина меры читается как строка, а не как обрывок."""
        self.assertFalse(card._висит([900, 870, 460]))


@unittest.skipUnless(config.хром(), "нужен Chrome")
class ВБраузере(unittest.TestCase):
    """Замер обязан отдавать строки крупных блоков по отдельности."""

    СТРАНИЦА = ('<meta charset="utf-8"><body style="margin:0;background:#12130F">'
                '<h1 style="width:920px;font:800 176px sans-serif;line-height:1.04;'
                'color:#F1F3EA">Программа без кода: 6 промахов</h1></body>')

    def test_замер_видит_строки_заголовка_по_отдельности(self):
        з = card._замерить(self.СТРАНИЦА, 1080, 1440)
        крупные = [б for б in з.get("набор", []) if б["кл"] == "h1"]
        self.assertEqual(len(крупные), 1, з.get("набор"))
        self.assertGreaterEqual(len(крупные[0]["строки"]), 3)

    def test_обложка_не_оставляет_висячего_слова(self):
        """Живая обложка поста 100: прежде выходило «Тему для/ролика/подберёт/ИИ»."""
        кегль = card._кегль_обложки("Без выдумывания", "Тему для ролика подберёт ИИ",
                                    1, 12, "3к4", "пособие", "зерно")
        строки = card._строки_заголовка(
            *card._обложка_страница("Без выдумывания", "Тему для ролика подберёт ИИ",
                                    None, 1, 12, "3к4", "пособие", "зерно", кегль))
        self.assertLessEqual(len(строки), 3, строки)
        self.assertFalse(card._висит(строки), строки)


if __name__ == "__main__":
    unittest.main()
