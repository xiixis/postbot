# -*- coding: utf-8 -*-
"""Кот не должен уходить под карточки новых вёрсток.

Найдено на живом посте 100: карточки «потока» тянутся во всю ширину, кот встал
ПОД ними и торчал кусками между карточками. Проверка композиции молчала —
блоков этих вёрсток не было в её списке.
"""
import unittest

import card
import carousel


class ВёрсткиБезКота(unittest.TestCase):
    def test_поток_рисуется_без_кота(self):
        self.assertIn("поток", carousel.БЕЗ_КОТА)

    def test_широкие_вёрстки_все_без_кота(self):
        """Всё, что тянется во всю ширину, коту места не оставляет."""
        for вид in ("замена", "столбики", "шпаргалка", "облако", "поток"):
            self.assertIn(вид, carousel.БЕЗ_КОТА, вид)


class ЗамерВидитКарточки(unittest.TestCase):
    """Замер должен знать блоки новых вёрсток, иначе он слеп к наложениям."""

    def test_карточки_новых_вёрсток_в_списке(self):
        for селектор in (".шаг-к", ".ст", ".раздел li", ".облако span",
                         ".места li", ".сетка4 div"):
            self.assertIn(f"'{селектор}'", card.ЗАМЕР, селектор)

    def test_селекторы_не_задвоены(self):
        """Задвоенный селектор мерил бы один блок дважды."""
        начало = card.ЗАМЕР.index("var что = {текст:")
        конец = card.ЗАМЕР.index("кот:", начало)
        кусок = card.ЗАМЕР[начало:конец]
        имена = [ч.strip().strip("',") for ч in кусок.split("'") if ч.startswith(".")]
        self.assertEqual(len(имена), len(set(имена)),
                         sorted(и for и in имена if имена.count(и) > 1))


if __name__ == "__main__":
    unittest.main()
