"""Паспорт доходит до сценария и до всех кадров; без паспорта всё как раньше."""
import sys
import unittest
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

import card       # noqa: E402
import carousel   # noqa: E402
import writer     # noqa: E402
import агент      # noqa: E402

КАРУСЕЛЬ = {"cover_kicker": "н", "cover_title": "Заголовок", "closing": "Итог",
            "slides": [{"вид": "мысль", "заголовок": f"Слайд {н}", "текст": "мысль",
                        "строки": []} for н in range(4)]}


class Подмены(unittest.TestCase):
    def setUp(self):
        self.было = []

    def подменить(self, модуль, имя, значение):
        self.было.append((модуль, имя, getattr(модуль, имя)))
        setattr(модуль, имя, значение)

    def tearDown(self):
        for модуль, имя, значение in reversed(self.было):
            setattr(модуль, имя, значение)


class Рисование(Подмены):
    def нарисовать(self, к):
        пойманное = []

        def ловить(имя):
            def ловушка(*а, **кл):
                пойманное.append({"кадр": имя, "дизайн": кл.get("дизайн"),
                                  "оформление": кл.get("оформление"),
                                  "кот": а[6] if имя == "середина" else None})
                return None
            return ловушка

        self.подменить(card, "слайд_обложка", ловить("обложка"))
        self.подменить(card, "слайд_вида", ловить("середина"))
        self.подменить(card, "слайд_финал", ловить("финал"))
        carousel.нарисовать(к, "3к4")
        return пойманное

    def test_дизайн_и_фон_доходят_до_всех_кадров(self):
        к = {**КАРУСЕЛЬ, "паспорт": {"дизайн": "швейцарский", "оформление": "свет",
                                     "кот": True}}
        п = self.нарисовать(к)
        self.assertEqual({(х["дизайн"], х["оформление"]) for х in п},
                         {("швейцарский", "свет")})
        self.assertEqual({х["кадр"] for х in п}, {"обложка", "середина", "финал"})

    def test_без_паспорта_как_раньше(self):
        п = self.нарисовать(dict(КАРУСЕЛЬ))
        self.assertEqual({(х["дизайн"], х["оформление"]) for х in п},
                         {("фирменный", "сетка")})

    def test_без_кота_в_середине(self):
        к = {**КАРУСЕЛЬ, "паспорт": {"кот": False}}
        середина = [х for х in self.нарисовать(к) if х["кадр"] == "середина"]
        self.assertTrue(середина)
        self.assertEqual({х["кот"] for х in середина}, {"нет"})


class Сценарий(Подмены):
    def сочинить(self, паспорт):
        пойманное = {}

        def по_форме(задача, форма, система="", **к):
            пойманное.update(задача=задача, система=система)
            return carousel.Карусель.model_construct(
                topic="т", каркас="шаги", cover_kicker="н", cover_title="з", slides=[],
                closing="в", caption="Подпись. #ии", запасные_заголовки=[],
                название="н", hashtags=["#ии"], поза="privet")

        self.подменить(агент, "по_форме", по_форме)
        for имя in ("_факты", "_значки"):
            self.подменить(writer, имя, lambda *а, **к: "")
        for имя in ("_чужой_опыт", "_подсмотренное", "_позы"):
            self.подменить(carousel, имя, lambda *а, **к: "")
        к = carousel.сочинить("тема", [], "", "tiktok", False, паспорт=паспорт)
        return к, пойманное

    def test_каркас_решён_заранее(self):
        к, п = self.сочинить({"каркас": "ошибки", "кадров": [8, 12]})
        self.assertIn("ФОРМАТ ЭТОЙ КАРУСЕЛИ", п["задача"])
        self.assertIn("каркас: ошибки", п["задача"])
        self.assertIn("слайдов середины от 6 до 10", п["задача"])
        self.assertNotIn("КАРКАСЫ, ИЗ КОТОРЫХ ВЫБРАТЬ", п["задача"])
        self.assertEqual(к.каркас, "ошибки")

    def test_без_паспорта_выбор_как_раньше(self):
        _, п = self.сочинить(None)
        self.assertIn("КАРКАСЫ, ИЗ КОТОРЫХ ВЫБРАТЬ", п["задача"])

    def test_простой_язык_после_резкого_регистра(self):
        _, п = self.сочинить(None)
        с = п["система"]
        self.assertIn("ПРОСТО, ЧТОБЫ ПОНЯЛ КАЖДЫЙ", с)
        self.assertLess(с.index("РЕГИСТР ЭТОЙ КАРУСЕЛИ"), с.index("ПРОСТО, ЧТОБЫ ПОНЯЛ"))
