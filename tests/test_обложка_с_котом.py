"""Обложка не теряет кота на длинном заголовке (Д-17).

Сверка 15.09.2026 на живых каруселях (91–102): 7 обложек из 10 рисовались
без кота. `_обложка_страница` сажала его по CSS одного роста
(`кот_высота`), а `_кегль_обложки` подбирает кегль под три строки, не зная о
коте — длинный заголовок дотягивался до него, и `слайд_обложка` убирал кота
целиком. У кадров середины рост кота давно считается от настоящего низа
текста (`страница_вида`, `_рост_в_колонке`), у обложки его не было.
"""
import sys
import unittest
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

import card    # noqa: E402
import config  # noqa: E402


class РостКотаОбложки(unittest.TestCase):
    """`_рост_кота_обложки`: тот же приём, что `_рост_в_колонке` у середины,
    но для прямоугольника кота на обложке (по центру или справа)."""

    def setUp(self):
        self.ш, self.в = 1080, 1440
        self.поле = 80
        self.доля = 0.7
        self.предел = 500
        # CSS-низ кота на обложке (низ_кота) переведён в абсолютную
        # координату дна, как считает `слайд_обложка`: низ = в - низ_кота.
        self.низ = self.в - 34
        self.запас = card._запас_px(self.ш)

    def test_текст_высоко_рост_равен_пределу(self):
        тексты = [[80, 100, 700, 300]]
        рост = card._рост_кота_обложки(тексты, self.ш, self.в, self.низ,
                                       self.доля, self.предел, False, self.поле)
        self.assertEqual(рост, self.предел)

    def test_текст_до_середины_рост_меньше_предела_с_запасом(self):
        тексты = [[80, 850, 700, 900]]
        рост = card._рост_кота_обложки(тексты, self.ш, self.в, self.низ,
                                       self.доля, self.предел, False, self.поле)
        self.assertLess(рост, self.предел)
        self.assertGreaterEqual(рост, card.МИН_КОТ)
        ширина = рост * self.доля
        лево = self.ш - self.поле - ширина
        верх = self.низ - рост
        кот = [лево, верх, лево + ширина, self.низ]
        self.assertGreaterEqual(card._зазор(кот, тексты[0]), self.запас)

    def test_текст_до_низа_это_ноль(self):
        # У правого края (где встаёт кот) и вплотную к низу — не разойтись
        # ни на каком росте, включая МИН_КОТ.
        тексты = [[900, 1390, 1000, 1406]]
        рост = card._рост_кота_обложки(тексты, self.ш, self.в, self.низ,
                                       self.доля, self.предел, False, self.поле)
        self.assertEqual(рост, 0)

    def test_по_центру_прямоугольник_вокруг_середины(self):
        """3:4: кот стоит по центру под заголовком (`кот_лево` = 50%)."""
        тексты = [[80, 100, 700, 300]]
        рост = card._рост_кота_обложки(тексты, self.ш, self.в, self.низ,
                                       self.доля, self.предел, True, self.поле)
        self.assertEqual(рост, self.предел)
        ширина = рост * self.доля
        лево_ожид, право_ожид = self.ш / 2 - ширина / 2, self.ш / 2 + ширина / 2
        # Формула не завязана на реализацию: проверяем прямо по определению
        # места, которое кот по центру должен занять.
        self.assertAlmostEqual(лево_ожид + право_ожид, self.ш)


def обложка(формат: str, заголовок: str, поза):
    """Записывает страницу обложки, как её отдал бы рисовальщик в снимок."""
    было = card._снять
    снято = []
    card._снять = lambda страница, ш, в: снято.append((страница, ш, в))
    try:
        card.слайд_обложка("Разбор", заголовок, поза, 1, 10, формат)
    finally:
        card._снять = было
    return снято[-1]


ДЛИННЫЙ_ЗАГОЛОВОК = ("Почему нейросети путают простые факты и что с этим "
                     "делать прямо сегодня, если сроки уже горят")


@unittest.skipUnless(config.хром(), "нужен Chrome")
class ОбложкаВБраузере(unittest.TestCase):
    def test_длинный_заголовок_не_теряет_кота(self):
        поза = config.АССЕТЫ / "mascot" / "позы" / "ukazyvaet.png"
        страница, ш, в = обложка("3к4", ДЛИННЫЙ_ЗАГОЛОВОК, поза)
        self.assertIn('class="кот"', страница)
        беды = card.проверить_композицию(card._замерить(страница, ш, в), "3к4")
        плохие = [б for б in беды if "кот" in б or "впритык" in б]
        self.assertEqual(плохие, [], f"беды: {беды}")


if __name__ == "__main__":
    unittest.main()
