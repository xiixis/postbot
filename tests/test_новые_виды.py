# -*- coding: utf-8 -*-
"""Замена, столбики и поток: раскладка полей и разметка."""
import unittest

import card
import carousel


class Слайд:
    """Что приходит от модели: пять слотов и вид."""

    def __init__(self, вид, значение="", заголовок="", текст="", строки=None):
        self.вид, self.значение = вид, значение
        self.заголовок, self.текст = заголовок, текст
        self.строки = строки or []

    def model_dump(self):
        return {"вид": self.вид, "значение": self.значение,
                "заголовок": self.заголовок, "текст": self.текст,
                "строки": self.строки}


class РаскладкаПолей(unittest.TestCase):
    def test_замена_разбирает_пару(self):
        поля = carousel._поля(Слайд("замена", заголовок="Чем заменить",
                                    строки=["Notion|от 10 $ в месяц",
                                            "Obsidian|0 $, файлы у вас"]))
        self.assertEqual(поля["платное"], "Notion")
        self.assertEqual(поля["цена_платного"], "от 10 $ в месяц")
        self.assertEqual(поля["бесплатное"], "Obsidian")
        self.assertEqual(поля["цена_бесплатного"], "0 $, файлы у вас")

    def test_столбики_берут_долю_числом(self):
        поля = carousel._поля(Слайд("столбики", заголовок="Кто пишет",
                                    строки=["ChatGPT|новичку|62",
                                            "Claude|нам|100"]))
        self.assertEqual([с["доля"] for с in поля["столбики"]], [62, 100])
        self.assertEqual([с["имя"] for с in поля["столбики"]], ["ChatGPT", "Claude"])

    def test_поток_берёт_шаги_по_порядку(self):
        поля = carousel._поля(Слайд("поток", заголовок="Как выходит",
                                    строки=["первый", "второй", "третий"]))
        self.assertEqual(поля["шаги"], ["первый", "второй", "третий"])


class ПодгонкаВида(unittest.TestCase):
    def test_замена_без_разделителя_становится_списком(self):
        """Без «|» это не пара, а два пункта — рисовать нечем."""
        с = carousel._подогнать_вид(Слайд("замена", строки=["Notion", "Obsidian"]))
        self.assertEqual(с.вид, "список")

    def test_столбики_без_строк_становятся_мыслью(self):
        с = carousel._подогнать_вид(Слайд("столбики", текст="что-то"))
        self.assertEqual(с.вид, "мысль")

    def test_новые_виды_есть_и_в_списке_для_модели(self):
        for вид in ("замена", "столбики", "поток"):
            self.assertIn(вид, carousel.ВЁРСТКИ, "модель не узнает про вид")
            self.assertIn(вид, card.ВИДЫ, "рисовалка не знает вид")


class Разметка(unittest.TestCase):
    def собрать(self, вид, з):
        д = card._виды_размеры(card._общее(3, 10, формат="тикток"))
        return card._нутро(вид, д, з)

    def test_замена_ставит_знаки_инструментов(self):
        html = self.собрать("замена", {"заголовок": "Чем заменить",
                                       "платное": "Notion", "цена_платного": "10 $",
                                       "бесплатное": "Obsidian",
                                       "цена_бесплатного": "0 $"})
        self.assertEqual(html.count("плашка-зн"), 2)
        self.assertIn("Платно", html)
        self.assertIn("Бесплатно", html)

    def test_замена_без_знака_оставляет_название(self):
        """Логотипа Midjourney у нас нет — название всё равно должно остаться."""
        html = self.собрать("замена", {"заголовок": "Чем заменить",
                                       "платное": "Midjourney", "цена_платного": "10 $",
                                       "бесплатное": "Flux", "цена_бесплатного": "0 $"})
        self.assertIn("Midjourney", html)

    def test_у_самого_высокого_столбика_свой_класс(self):
        html = self.собрать("столбики", {"заголовок": "Кто",
                                         "столбики": [{"имя": "ChatGPT", "доля": 60},
                                                      {"имя": "Claude", "доля": 100}]})
        self.assertEqual(html.count("ст главный"), 1)

    def test_поток_нумерует_шаги(self):
        html = self.собрать("поток", {"заголовок": "Как", "шаги": ["раз", "два"]})
        self.assertIn("<b>01</b>", html)
        self.assertIn("<b>02</b>", html)
        self.assertEqual(html.count("вниз"), 1, "стрелка ставится между шагами")


if __name__ == "__main__":
    unittest.main()
