# -*- coding: utf-8 -*-
"""Паспорт карусели: не повторяет недавнего и честно делит вес между типами."""
import random
import sys
import unittest
from collections import Counter
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

import форматы  # noqa: E402


class Ротация(unittest.TestCase):
    def setUp(self):
        self.было = {к: dict(в) for к, в in форматы.ТИПЫ.items()}

    def tearDown(self):
        форматы.ТИПЫ.clear()
        форматы.ТИПЫ.update(self.было)

    def test_каркас_не_повторяет_двух_прошлых(self):
        история = [{"тип": "обычная", "каркас": "шаги"},
                   {"тип": "обычная", "каркас": "ошибки"}]
        for зерно in range(200):
            п = форматы.подобрать(история, random.Random(зерно))
            self.assertNotIn(п["каркас"], ("шаги", "ошибки"))

    def test_вид_не_повторяет_пяти_прошлых(self):
        # Не повторяется связка дизайн + фон: тот же фон в другом дизайне уже
        # выглядит иначе.
        занято = [("фирменный", о) for о in форматы.ОФОРМЛЕНИЯ_ОК[:5]]
        история = [{"дизайн": д, "оформление": о} for д, о in занято]
        for зерно in range(200):
            п = форматы.подобрать(история, random.Random(зерно))
            self.assertNotIn((п["дизайн"], п["оформление"]), занято)

    def test_когда_всё_занято_берётся_любое(self):
        # Остальные типы на время убраны: проверяем, что делает ротация, когда
        # выбирать уже не из чего, а не как типы делят между собой вес.
        форматы.ТИПЫ.clear()
        форматы.ТИПЫ["обычная"] = {"вес": 2.4, "кадров": [8, 12], "кот": True,
                                   "каркасы": ["шаги"]}
        п = форматы.подобрать([{"тип": "обычная", "каркас": "шаги"}], random.Random(1))
        self.assertEqual(п["каркас"], "шаги")

    def test_паспорт_полный(self):
        обязательные = {"тип", "каркас", "кадров", "дизайн", "оформление", "кот"}
        # «Вид» есть только у типов со своим списком вёрсток — у поста из
        # одного кадра. Проверяем все паспорта, а не первый попавшийся: с
        # одним зерном тип со своим видом мог и не выпасть.
        for зерно in range(60):
            п = форматы.подобрать([], random.Random(зерно))
            self.assertTrue(обязательные <= set(п))
            self.assertTrue(set(п) <= обязательные | {"вид"})
        self.assertIn(п["дизайн"], форматы.ДИЗАЙНЫ_ОК)
        self.assertIn(п["оформление"], форматы.ОФОРМЛЕНИЯ_ОК)

    def test_вес_типа_делится_между_каркасами(self):
        """Тип с пятью каркасами не должен выпадать впятеро чаще одноходового."""
        форматы.ТИПЫ.clear()
        форматы.ТИПЫ["обычная"] = {"вес": 2.4, "кадров": [8, 12], "кот": True,
                                   "каркасы": ["боль", "шаги", "ошибки",
                                               "было и стало", "разбор"]}
        форматы.ТИПЫ["чат"] = {"вес": 2.4, "кадров": [6, 9], "кот": False,
                               "каркасы": [""]}
        типы = Counter(форматы.подобрать([], random.Random(з))["тип"] for з in range(2000))
        self.assertAlmostEqual(типы["чат"] / 2000, 0.5, delta=0.05)

    def test_следующий_запоминает_историю(self):
        import конвейер
        хранилище = {}
        было = конвейер.настройки, конвейер.сохранить
        конвейер.настройки = lambda куда="tiktok": dict(хранилище)
        конвейер.сохранить = lambda куда="tiktok", **поля: хранилище.update(поля) or хранилище
        try:
            подряд = [форматы.следующий("tiktok") for _ in range(7)]
        finally:
            конвейер.настройки, конвейер.сохранить = было
        self.assertEqual(len(хранилище["форматы"]), форматы.ПОМНИМ_ВИД)
        for а, б in zip(подряд, подряд[1:]):
            self.assertNotEqual(а["каркас"], б["каркас"])
