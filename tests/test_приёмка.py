# -*- coding: utf-8 -*-
"""Журнал приёмки: вердикт по кадрам вместо строчки в логе."""
import sys
import threading
import unittest
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

import приёмка  # noqa: E402


class Журнал(unittest.TestCase):
    def tearDown(self):
        приёмка.итог()

    def test_без_журнала_отметки_пропадают(self):
        приёмка.кадр(1, "обложка")
        приёмка.брак("текст за краем")
        self.assertFalse(приёмка.идёт())
        self.assertEqual(приёмка.итог(), {})

    def test_брак_делает_карусель_негодной(self):
        приёмка.начать()
        приёмка.кадр(1, "обложка")
        приёмка.кадр(2, "мысль")
        приёмка.брак("текст заходит в нижнее поле или вылезает за холст")
        отчёт = приёмка.итог()
        self.assertFalse(отчёт["годен"])
        self.assertEqual([к["номер"] for к in отчёт["кадры"]], [1, 2])
        self.assertEqual(отчёт["кадры"][1]["брак"],
                         ["текст заходит в нижнее поле или вылезает за холст"])
        self.assertFalse(приёмка.идёт(), "итог закрывает журнал")

    def test_замечания_не_брак(self):
        приёмка.начать()
        приёмка.кадр(3, "список")
        приёмка.замечание("кот убран")
        приёмка.ужато(0.78)
        приёмка.ужато(0.88)
        отчёт = приёмка.итог()
        self.assertTrue(отчёт["годен"])
        self.assertEqual(отчёт["кадры"][0]["ужато"], 0.78)
        self.assertEqual(отчёт["кадры"][0]["замечания"], ["кот убран"])

    def test_повтор_номера_начинает_кадр_заново(self):
        приёмка.начать()
        приёмка.кадр(4, "мысль")
        приёмка.брак("слово шире колонки")
        приёмка.кадр(4, "мысль")
        self.assertTrue(приёмка.итог()["годен"])

    def test_одинаковая_беда_один_раз(self):
        приёмка.начать()
        приёмка.кадр(2, "мысль")
        приёмка.брак("слово шире колонки", "слово шире колонки")
        self.assertEqual(приёмка.текущий()["брак"], ["слово шире колонки"])

    def test_слить_заменяет_перерисованный_кадр(self):
        было = {"годен": False, "кадры": [
            {"номер": 1, "вид": "обложка", "брак": [], "замечания": [], "ужато": 1.0},
            {"номер": 2, "вид": "мысль", "брак": ["слово шире колонки"],
             "замечания": [], "ужато": 1.0}]}
        свежие = {"годен": True, "кадры": [
            {"номер": 2, "вид": "мысль", "брак": [], "замечания": [], "ужато": 1.0}]}
        итог = приёмка.слить(было, свежие)
        self.assertTrue(итог["годен"])
        self.assertEqual([к["номер"] for к in итог["кадры"]], [1, 2])

    def test_строкой_и_номера(self):
        отчёт = {"годен": False, "кадры": [
            {"номер": 4, "вид": "мысль", "брак": ["а", "б"], "замечания": [], "ужато": 1},
            {"номер": 5, "вид": "мысль", "брак": [], "замечания": [], "ужато": 1}]}
        self.assertEqual(приёмка.строкой(отчёт), "№4: а, б")
        self.assertEqual(приёмка.бракованные(отчёт), [4])
        self.assertTrue(приёмка.годен(None), "старый пост без отчёта не судим")

    def test_лечится_текстом(self):
        self.assertTrue(приёмка.лечится_текстом(
            {"брак": ["слово шире колонки"], "ужато": 1.0}))
        self.assertTrue(приёмка.лечится_текстом({"брак": [], "ужато": 0.70}))
        self.assertFalse(приёмка.лечится_текстом({"брак": [], "ужато": 0.88}))
        self.assertFalse(приёмка.лечится_текстом(
            {"брак": [приёмка.СТРАНИЦА + "шрифт не загрузился: Onest"], "ужато": 1.0}))
        self.assertFalse(приёмка.лечится_текстом({}))

    def test_у_каждой_нити_свой_журнал(self):
        приёмка.начать()
        приёмка.кадр(1, "обложка")
        чужое = []

        def в_другой_нити():
            чужое.append(приёмка.идёт())

        н = threading.Thread(target=в_другой_нити)
        н.start()
        н.join()
        self.assertEqual(чужое, [False])


