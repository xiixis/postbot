# -*- coding: utf-8 -*-
"""Финальный кадр: заголовок не налезает на подпись «Итог».

«Итог» лежит absolute и места под себя не занимает. У вывода в шаблоне
`margin-top:auto; margin-bottom:auto`: пока вывод невысок, он встаёт
посередине и до «Итога» не дотягивается. Высокий вывод съедает оба отступа,
встаёт в самый верх и ложится прямо на «Итог».

В ветке финала с котом под «Итог» зарезервировано место, а в запасной — без
кота — не было. 11 сентября на ней вышли посты 91 и 92: у 92 «ИТОГ» лёг
поверх «Учит», у 91 — вплотную к «Проиграй». Цикл подбора кегля этого не
ловил: он смотрит наезд на плашку призыва и выход за кромку, а не на «Итог».
Чем короче вывод, тем крупнее кегль и тем сильнее он лез вверх — поэтому
лечить укорачиванием текста было нельзя.
"""

import sys
import unittest
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

import card                                                  # noqa: E402


class _Подмена:
    """Подменяет имена в модуле на время проверки."""

    def __init__(self, модуль, **что):
        self.модуль, self.что, self.было = модуль, что, {}

    def __enter__(self):
        for имя, зн in self.что.items():
            self.было[имя] = getattr(self.модуль, имя)
            setattr(self.модуль, имя, зн)
        return self

    def __exit__(self, *_):
        for имя, зн in self.было.items():
            setattr(self.модуль, имя, зн)


class ЗапаснаяВетка(unittest.TestCase):
    """Финал без кота. Браузер не нужен: проверяется сама страница."""

    def _страница(self, вывод: str, призыв: str = "Сохрани. Подпишись") -> str:
        снято = []

        def снять(страница, *_, **__):
            снято.append(страница)
            return Path("/tmp/кадр-финала.png")

        with _Подмена(card, _замерить=lambda *а, **к: {},
                      проверить_композицию=lambda *а, **к: [],
                      _снять=снять):
            card.слайд_финал(вывод, 10, 10, "3к4", призыв, поза=None)
        self.assertTrue(снято, "финал ничего не снял")
        return снято[-1]

    def _отступ(self) -> int:
        return round(card._общее(10, 10, "3к4")["точка"] * 3.4)

    def test_под_итогом_оставлено_место(self):
        """Тот же отступ, что уже стоит в ветке с котом: «Итог» один и тот
        же, и две ветки одного кадра не должны расходиться."""
        страница = self._страница("Учит не ответ ИИ, а твой ответ ему")
        self.assertIn(f".вывод{{margin-top:{self._отступ()}px", страница)

    def test_без_призыва_тоже(self):
        страница = self._страница("Коротко и крупно", призыв="")
        self.assertIn(f".вывод{{margin-top:{self._отступ()}px", страница)

    def test_поправка_идёт_после_шаблона(self):
        """В шаблоне у вывода свой margin-top:auto. Поправка с той же
        силой селектора побеждает, только если стоит ниже."""
        страница = self._страница("Учит не ответ ИИ, а твой ответ ему")
        шаблон = страница.index("margin-top:auto;margin-bottom:auto")
        поправка = страница.index(f".вывод{{margin-top:{self._отступ()}px")
        self.assertGreater(поправка, шаблон)


if __name__ == "__main__":
    unittest.main()
