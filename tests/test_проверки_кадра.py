# -*- coding: utf-8 -*-
"""Проверки кадра, которых не было: слово цвета фона и слово, порванное посреди."""
import sys
import unittest
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

import card      # noqa: E402
import carousel  # noqa: E402
import config    # noqa: E402

ХОЛСТ = {"холст": [1080, 1440]}
ПРАВКА = {"неверно": "Продажи упали из-за рекламы", "верно": "Продажи *упали из-за цены*"}
СЛИВ = ('<meta charset="utf-8"><body style="margin:0;background:#12130F">'
        '<div class="мысль" style="font-size:60px;color:#F1F3EA">'
        '<span style="background:#C7E24B;color:#C7E24B">пропало</span> видно</div></body>')
СТРЕЛКА = {"от": "Сплошной текст", "к": "Переформатирование", "текст": "Одна мысль на слайд"}


class Беды(unittest.TestCase):
    def test_слово_цвета_фона_это_беда(self):
        беды = card.проверить_композицию({**ХОЛСТ, "невидимо": ["из-за"]}, "3к4")
        self.assertIn("текст сливается с фоном: из-за", беды)

    def test_порванное_слово_это_беда(self):
        беды = card.проверить_композицию({**ХОЛСТ, "порвано": ["Формула"]}, "3к4")
        self.assertIn("слово порвано посреди: Формула", беды)

    def test_без_находок_тихо(self):
        self.assertEqual(card.проверить_композицию(
            {**ХОЛСТ, "невидимо": [], "порвано": []}, "3к4"), [])


@unittest.skipUnless(config.хром(), "нужен Chrome")
class ВБраузере(unittest.TestCase):
    def test_замер_видит_слово_цвета_фона(self):
        з = card._замерить(СЛИВ, 1080, 1440)
        self.assertIn("пропало", з["невидимо"])
        self.assertNotIn("видно", з["невидимо"])

    def test_на_правке_слово_с_дефисом_не_пропадает(self):
        стр, ш, в = card.страница_вида("правка", ПРАВКА, 7, 10, "3к4")
        self.assertEqual(card._замерить(стр, ш, в)["невидимо"], [])

    def test_замер_видит_порванное_слово_в_стрелке(self):
        стр, ш, в = card.страница_вида("стрелка", СТРЕЛКА, 3, 10, "3к4")
        self.assertIn("Переформатирование", card._замерить(стр, ш, в)["порвано"])

    def test_на_всех_вёрстках_тихо(self):
        образец = {"заголовок": "Короткий заголовок", "текст": "Одна мысль на слайд",
                   # Пробелы вокруг «|» нарочно: полосы и тройка их срезают, а
                   # слитное «Альфа|10|60» в узкой «стрелке» и правда рвётся.
                   "значение": "42",
                   "строки": ["Альфа | 10 | 60", "Бета | 20 | 40", "Гамма | 30 | 20"]}
        for вид in carousel.ВЁРСТКИ:
            for номер in (2, 3):
                with self.subTest(вид=вид, номер=номер):
                    поля = carousel._поля({**образец, "вид": вид})
                    стр, ш, в = card.страница_вида(вид, поля, номер, 10, "3к4")
                    з = card._замерить(стр, ш, в)
                    self.assertEqual(з.get("невидимо"), [], вид)
                    self.assertEqual(з.get("порвано"), [], вид)
