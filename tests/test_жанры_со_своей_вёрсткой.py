"""Жанр — это своя вёрстка кадра, а не другой шрифт поверх общей.

12 сентября 2026 владелец потратил два часа на то, чтобы объяснить это: в
ротации стояли «дизайны», которые меняли гарнитуру и цвет линейки, но кадр
собирали одинаково. Эти тесты держат границу: если жанр объявлен новым, у него
должна быть своя разметка, а не только CSS.
"""
import unittest

import card
import форматы


class СвояВёрстка(unittest.TestCase):
    #  Жанры, перенесённые с листа, который владелец одобрил. Фирменного тут
    #  нет намеренно: он и есть наша общая вёрстка, якорь канала.
    С_ВЁРСТКОЙ = ("терминал", "редакционный", "каталог", "манифест",
                  "пособие", "атмосфера")

    def test_у_перенесённых_жанров_своя_обложка(self):
        for имя in self.С_ВЁРСТКОЙ:
            with self.subTest(дизайн=имя):
                self.assertIn("обложка", card.ДИЗАЙНЫ[имя],
                              "жанр без своей обложки — это тема, а не жанр")

    def test_обложки_различаются_разметкой(self):
        """Не просто «есть», а действительно разные: свои блоки у каждого."""
        # Пилюля — часть разметки обложки: у каталога и редакционного каркас
        # обложки общий, а различает их сама пилюля (у редакционного с точкой).
        разметки = {и: card.ДИЗАЙНЫ[и]["обложка"] + card.ДИЗАЙНЫ[и].get("пилюля", "")
                    for и in self.С_ВЁРСТКОЙ}
        self.assertEqual(len(set(разметки.values())), len(разметки))
        self.assertIn("команда", разметки["терминал"])
        self.assertIn("надбровие", разметки["редакционный"])
        self.assertIn("пилюли", разметки["каталог"])
        self.assertIn("манифест-под", разметки["манифест"])
        self.assertIn("ярлык-шага", разметки["пособие"])
        self.assertIn("воздух", разметки["атмосфера"])

    def test_обложка_собирается_с_нужными_полями(self):
        """В разметку подставляются надпись, заголовок и номера кадров."""
        for имя in self.С_ВЁРСТКОЙ:
            with self.subTest(дизайн=имя):
                готово = card.ДИЗАЙНЫ[имя]["обложка"].format(
                    над="НАД", заголовок="ЗАГОЛОВОК", номер=1, всего=8,
                    пилюли="")
                self.assertIn("НАД", готово)
                self.assertIn("ЗАГОЛОВОК", готово)
                self.assertNotIn("{", готово, "осталось неподставленное поле")

    def test_все_жанры_в_ротации(self):
        for имя in self.С_ВЁРСТКОЙ:
            self.assertIn(имя, форматы.ДИЗАЙНЫ_ОК)


class ПриёмыЖанров(unittest.TestCase):
    def размеры(self):
        return card._виды_размеры(card._общее(2, 8, формат="тикток"))

    def test_терминал_рисует_окно_запроса(self):
        css = card._дизайн("терминал", self.размеры())
        self.assertIn('content:"запрос"', css)
        self.assertIn('content:"копировать"', css)

    def test_терминал_подсвечивает_подстановки_скобками(self):
        css = card._дизайн("терминал", self.размеры())
        self.assertIn('.свет:before{content:"["', css.replace(" ", ""))

    def test_манифест_ставит_кавычки_вокруг_цитаты(self):
        css = card._дизайн("манифест", self.размеры())
        self.assertIn('content:"«"', css)
        self.assertIn('content:"»"', css)

    def test_редакционный_кладёт_мысль_в_карточку(self):
        css = card._дизайн("редакционный", self.размеры())
        self.assertIn("border-radius:24px", css)

    def test_дизайн_собирается_и_без_размеров_вида(self):
        """Обложка и финал зовут дизайн без размеров вида — он не должен падать.

        Это ловилось трижды подряд и каждый раз одинаково: дизайн просил ключ
        («поверхность», «мягкий», «ржавый»), который кладут только размеры
        вида, и падал на обложке с KeyError. Тест держит весь набор разом.
        """
        голое = card._общее(1, 8, формат="тикток")
        for имя in card.ДИЗАЙНЫ:
            with self.subTest(дизайн=имя):
                card._дизайн(имя, голое)

    def test_дизайн_собирается_на_любом_кадре_и_фоне(self):
        """Не только обложка: светлые кадры и инверсия тоже зовут дизайн."""
        for номер in (1, 2, 3):
            for оформление in ("сетка", "чистый", "инверсия"):
                д = card._общее(номер, 8, формат="тикток", оформление=оформление)
                for имя in card.ДИЗАЙНЫ:
                    with self.subTest(дизайн=имя, кадр=номер, фон=оформление):
                        card._дизайн(имя, д)


class МеткиШпаргалки(unittest.TestCase):
    def нутро(self, пункты):
        д = card._виды_размеры(card._общее(3, 10, формат="тикток"))
        return card._нутро("шпаргалка", д,
                           {"заголовок": "Что брать",
                            "разделы": [{"имя": "Тексты", "пункты": пункты}]})

    def test_метка_после_черты_становится_пилюлей(self):
        html = self.нутро(["Claude длинный текст|чаще", "Canva обложки|новичку"])
        self.assertIn("чаще всего", html)
        self.assertIn("новичку", html)

    def test_без_меток_легенды_нет(self):
        """Легенда объясняет метки: без них она была бы подписью к пустоте."""
        self.assertNotIn("легенда", self.нутро(["Claude длинный текст"]))

    def test_с_метками_легенда_появляется(self):
        self.assertIn("легенда", self.нутро(["Claude длинный текст|чаще"]))

    def test_черта_не_попадает_в_видимый_текст(self):
        html = self.нутро(["Claude длинный текст|чаще"])
        self.assertNotIn("текст|", html)


if __name__ == "__main__":
    unittest.main()
