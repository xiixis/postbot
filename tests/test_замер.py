# -*- coding: utf-8 -*-
"""Пороги замера кадра.

Числа здесь не выдуманы: они сняты с наших же кадров 12 сентября 2026, когда
замер подключили к рисовальщику. До этого модуль был написан, покрыт тестами
и не вызывался ниоткуда — а пороги в нём были сняты другой мерой и на чужих
кадрах.
"""
import sys
import unittest
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

import замер                                                 # noqa: E402


ГОДНЫЙ = {"доля_чернил_%": 6.0, "доля_акцента_%": 2.0,
          "контраст_текст_фон": 12.0, "крупная_строка_%": 13.0}


class Пороги(unittest.TestCase):
    def test_годный_кадр_молчит(self):
        self.assertEqual(замер.оценить(ГОДНЫЙ), [])

    def test_пустой_кадр_замечен(self):
        замечания = замер.оценить({**ГОДНЫЙ, "доля_чернил_%": 1.1})
        self.assertTrue(any("чернил" in з for з in замечания), замечания)

    def test_перегруженный_кадр_замечен(self):
        замечания = замер.оценить({**ГОДНЫЙ, "доля_чернил_%": 24.3})
        self.assertTrue(any("чернил" in з for з in замечания), замечания)

    def test_кадр_залитый_лаймом_замечен(self):
        замечания = замер.оценить({**ГОДНЫЙ, "доля_акцента_%": 19.0})
        self.assertTrue(any("акцент" in з for з in замечания), замечания)

    def test_кадр_без_акцента_не_судится(self):
        """«Манифест» нарочно без акцента, и у образца его ровно ноль."""
        self.assertEqual(замер.оценить({**ГОДНЫЙ, "доля_акцента_%": 0.0}), [])

    def test_низкий_контраст_замечен(self):
        замечания = замер.оценить({**ГОДНЫЙ, "контраст_текст_фон": 1.77})
        self.assertTrue(any("контраст" in з for з in замечания), замечания)

    def test_мелкий_заголовок_замечен(self):
        замечания = замер.оценить({**ГОДНЫЙ, "крупная_строка_%": 6.9})
        self.assertTrue(any("строка" in з for з in замечания), замечания)

    def test_границы_включительно(self):
        край = {**ГОДНЫЙ, "доля_чернил_%": 2.2, "доля_акцента_%": 8.0,
                "контраст_текст_фон": 8.0, "крупная_строка_%": 12.0}
        self.assertEqual(замер.оценить(край), [])

    def test_чего_не_замерили_то_не_судим(self):
        """Разбор не всегда находит акцент: у кадра его может не быть вовсе."""
        self.assertEqual(замер.оценить({"доля_чернил_%": 6.0}), [])


class НормаНаДизайн(unittest.TestCase):
    def test_терминалу_пустота_прощается(self):
        пустой = {"доля_чернил_%": 2.0}
        self.assertTrue(замер.оценить(пустой), "общей нормой это кадр пустой")
        self.assertEqual(замер.оценить(пустой, "терминал"), [])

    def test_незнакомый_дизайн_судится_общей_нормой(self):
        self.assertEqual(замер.нормы("такого-нет")["чернил"], замер.ЧЕРНИЛ)

    def test_перегруз_ловится_и_в_своей_норме(self):
        замечания = замер.оценить({"доля_чернил_%": 22.0}, "терминал")
        self.assertTrue(замечания)


class НашиКадрыПроходят(unittest.TestCase):
    """Главное требование: проверка не должна ругаться на принятые кадры.

    Числа — замеры настоящих кадров бота 12 сентября 2026.
    """

    СНЯТО = [("список", "фирменный", 2.8), ("плитки", "фирменный", 3.9),
             ("чипы", "фирменный", 3.4), ("рейтинг", "фирменный", 4.0),
             ("замена", "фирменный", 5.2), ("поток", "фирменный", 5.6),
             ("столбики", "фирменный", 8.5),
             ("обложка", "манифест", 4.0), ("разворот", "манифест", 3.4),
             ("обложка", "атмосфера", 5.0), ("разворот", "атмосфера", 2.1)]

    def test_ни_один_принятый_кадр_не_ругается(self):
        шумит = [(вид, диз) for вид, диз, чернил in self.СНЯТО
                 if замер.оценить({"доля_чернил_%": чернил}, диз)]
        self.assertEqual(шумит, [])


if __name__ == "__main__":
    unittest.main()
