# -*- coding: utf-8 -*-
"""Замер готового кадра по своим порогам.

Пороги не выдуманы и не взяты из чужих дизайн-скилов: те меряют веб-страницу,
а не кадр в ленте, где картинка уменьшена втрое и висит полторы секунды. Они
из скила `визуал-слайдов`, замерены на живых кадрах бота.

Замер предупреждает, а не запрещает. Кадр, где чернил мало, всё равно бывает
верным — например, финальный слайд с одной фразой. Решение остаётся за
владельцем, дело замера — не дать пропустить это молча.

Проверка идёт по уже посчитанным числам, а не по картинке: разбор пикселей
живёт отдельно и требует Pillow, а правило порогов должно проверяться без него.
"""

import sys
import unittest
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

import замер                                                 # noqa: E402


ГОДНЫЙ = {"доля_чернил_%": 12.0, "доля_акцента_%": 5.0,
          "контраст_текст_фон": 12.0, "крупная_строка_%": 13.0}


class Пороги(unittest.TestCase):
    def test_годный_кадр_молчит(self):
        self.assertEqual(замер.оценить(ГОДНЫЙ), [])

    def test_пустой_кадр_замечен(self):
        замечания = замер.оценить({**ГОДНЫЙ, "доля_чернил_%": 5.3})
        self.assertTrue(any("чернил" in з for з in замечания), замечания)

    def test_перегруженный_кадр_замечен(self):
        замечания = замер.оценить({**ГОДНЫЙ, "доля_чернил_%": 24.3})
        self.assertTrue(any("чернил" in з for з in замечания), замечания)

    def test_акцента_мало(self):
        замечания = замер.оценить({**ГОДНЫЙ, "доля_акцента_%": 0.4})
        self.assertTrue(any("акцент" in з for з in замечания), замечания)

    def test_акцента_много(self):
        замечания = замер.оценить({**ГОДНЫЙ, "доля_акцента_%": 9.7})
        self.assertTrue(any("акцент" in з for з in замечания), замечания)

    def test_низкий_контраст_замечен(self):
        замечания = замер.оценить({**ГОДНЫЙ, "контраст_текст_фон": 1.77})
        self.assertTrue(any("контраст" in з for з in замечания), замечания)

    def test_мелкий_заголовок_замечен(self):
        замечания = замер.оценить({**ГОДНЫЙ, "крупная_строка_%": 6.9})
        self.assertTrue(any("строка" in з for з in замечания), замечания)

    def test_границы_включительно(self):
        """На самих границах кадр годен: 8% чернил и 4% акцента это норма."""
        край = {**ГОДНЫЙ, "доля_чернил_%": 8.0, "доля_акцента_%": 4.0,
                "контраст_текст_фон": 8.0, "крупная_строка_%": 12.0}
        self.assertEqual(замер.оценить(край), [])

    def test_несколько_бед_перечисляются_все(self):
        плохой = {"доля_чернил_%": 5.3, "доля_акцента_%": 0.4,
                  "контраст_текст_фон": 1.77, "крупная_строка_%": 6.9}
        self.assertEqual(len(замер.оценить(плохой)), 4)

    def test_чего_не_замерили_то_не_судим(self):
        """Разбор не всегда находит акцент: у кадра его может не быть вовсе."""
        self.assertEqual(замер.оценить({"доля_чернил_%": 12.0}), [])


if __name__ == "__main__":
    unittest.main()
