# -*- coding: utf-8 -*-
"""Пилюли на обложке называют то, что будет в карусели, а не одно и то же.

13 сентября 2026 на контент-плане все каталоги выходили с пилюлями «тексты,
картинки, озвучка, сборка», а редакционные — «приёмы, запросы, по шагам»:
слова были прошиты в шаблоне и стояли на любой теме. У образца (@emirailab)
обложка работает оглавлением — пилюли называют разделы, которые встретятся
дальше. Чужое оглавление хуже никакого.
"""
import unittest

import card
import carousel

С_ПИЛЮЛЯМИ = ("каталог", "редакционный")


def обложка(дизайн, метки=None):
    страница, _, _ = card._обложка_страница(
        "Надпись", "Заголовок обложки", None, 1, 10, "3к4", дизайн, "чистый",
        метки=метки)
    return страница


class ПилюлиИзДанных(unittest.TestCase):
    def test_в_шаблонах_нет_прошитых_слов(self):
        for имя in С_ПИЛЮЛЯМИ:
            with self.subTest(дизайн=имя):
                шаблон = card.ДИЗАЙНЫ[имя]["обложка"]
                for слово in ("озвучка", "сборка", "запросы", "по шагам"):
                    self.assertNotIn(слово, шаблон)

    def test_метки_попадают_на_обложку(self):
        for имя in С_ПИЛЮЛЯМИ:
            with self.subTest(дизайн=имя):
                html = обложка(имя, ["Перевод", "Галерея", "Диктовка"])
                self.assertIn('class="пилюли"', html)
                for метка in ("Перевод", "Галерея", "Диктовка"):
                    self.assertIn(метка, html)

    def test_без_меток_ряда_нет(self):
        for имя in С_ПИЛЮЛЯМИ:
            with self.subTest(дизайн=имя):
                self.assertNotIn('class="пилюли"', обложка(имя))
                self.assertNotIn('class="пилюли"', обложка(имя, []))

    def test_метка_экранируется(self):
        html = обложка("каталог", ["<b>жирно</b>", "два"])
        self.assertNotIn("<b>жирно</b>", html)
        self.assertIn("&lt;b&gt;", html)

    def test_у_редакционного_точка_в_пилюле(self):
        """Точка-маркер — часть почерка жанра, её терять нельзя."""
        html = обложка("редакционный", ["один", "два"])
        self.assertIn("<span><i></i>один</span>", html)


class МеткиКарусели(unittest.TestCase):
    def test_свои_метки_главнее(self):
        к = {"метки": ["Камера", "Фото"], "slides": [{"заголовок": "Другое"}]}
        self.assertEqual(carousel.метки_обложки(к), ["Камера", "Фото"])

    def test_без_меток_берутся_короткие_заголовки_слайдов(self):
        к = {"slides": [{"заголовок": "Место и свет"},
                        {"заголовок": "Вышло не то, что хотел?"},
                        {"заголовок": "Очень длинный заголовок слайда"},
                        {"заголовок": "*Формат* кадра"},
                        {"заголовок": "Место и свет"},
                        {"заголовок": ""}]}
        self.assertEqual(carousel.метки_обложки(к), ["Место и свет", "Формат кадра"])

    def test_одной_метки_мало(self):
        к = {"slides": [{"заголовок": "Место и свет"}, {"текст": "без заголовка"}]}
        self.assertEqual(carousel.метки_обложки(к), [])

    def test_не_больше_четырёх(self):
        к = {"slides": [{"заголовок": f"Раздел {н}"} for н in range(7)]}
        self.assertEqual(len(carousel.метки_обложки(к)), 4)


if __name__ == "__main__":
    unittest.main()
