# -*- coding: utf-8 -*-
"""Один проход модели по слайдам со сломанной вёрсткой.

Модель выбирала вёрстку, не зная дизайна. Здесь ей называют, что на этом месте
можно, и просят переложить ту же мысль. Не вышло — остаётся как было, и дальше
чинит предполёт без модели.
"""
import sys
import unittest
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

import carousel   # noqa: E402
import агент      # noqa: E402
import предполёт  # noqa: E402

БЫЛО = {"вид": "было", "заголовок": "Было и стало", "текст": "", "значение": "",
        "реплика": "мяу", "строки": ["Руками два часа", "С ИИ пять минут"]}
МЫСЛЬ = {"вид": "мысль", "заголовок": "Коротко", "значение": "", "реплика": "",
         "текст": "Мысль достаточной длины, чтобы кадр не пустовал", "строки": []}


def карусель():
    return {"cover_title": "Обложка", "closing": "", "каркас": "разбор",
            "slides": [dict(БЫЛО), dict(МЫСЛЬ)],
            "паспорт": {"дизайн": "каталог", "кадров": [8, 12]}}


class Переверстать(unittest.TestCase):
    def setUp(self):
        self.было = агент.по_форме
        self.задачи = []
        self.ответ = None

        def по_форме(задача, форма, **к):
            self.задачи.append(задача)
            if isinstance(self.ответ, Exception):
                raise self.ответ
            return self.ответ

        агент.по_форме = по_форме

    def tearDown(self):
        агент.по_форме = self.было

    def _переверстать(self, к):
        return carousel.переверстать(к, предполёт.проверить(к, "3к4"), "3к4")

    def test_заменяет_только_сломанный_слайд(self):
        self.ответ = carousel.Переверстка(slides=[carousel.Слайд(
            вид="мысль", заголовок="Было и стало",
            текст="Руками два часа, с ИИ *пять минут* на всё")])
        к = карусель()
        новая = self._переверстать(к)
        self.assertEqual(новая["slides"][0]["вид"], "мысль")
        self.assertEqual(новая["slides"][0]["реплика"], "мяу")
        self.assertEqual(новая["slides"][1], МЫСЛЬ)
        self.assertEqual(к["slides"][0]["вид"], "было")

    def test_задание_называет_разрешённые_вёрстки(self):
        self.ответ = RuntimeError("нет сети")
        self._переверстать(карусель())
        self.assertIn("Можно вёрстки: мысль, цифра, список, цитата", self.задачи[0])

    def test_снова_сломанная_вёрстка_не_принимается(self):
        self.ответ = carousel.Переверстка(slides=[carousel.Слайд(
            вид="стрелка", текст="Откуда и куда",
            строки=["Руками", "С ИИ"])])
        к = карусель()
        self.assertIs(self._переверстать(к), к)

    def test_сбой_модели_оставляет_как_было(self):
        self.ответ = RuntimeError("нет сети")
        к = карусель()
        self.assertIs(self._переверстать(к), к)

    def test_другое_число_слайдов_не_принимается(self):
        слайд = carousel.Слайд(вид="мысль", текст="Мысль достаточной длины для кадра")
        self.ответ = carousel.Переверстка(slides=[слайд, слайд])
        к = карусель()
        self.assertIs(self._переверстать(к), к)

    def test_без_бед_модель_не_зовётся(self):
        к = {**карусель(), "slides": [dict(МЫСЛЬ)]}
        self.assertIs(self._переверстать(к), к)
        self.assertEqual(self.задачи, [])


if __name__ == "__main__":
    unittest.main()
