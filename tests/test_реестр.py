# -*- coding: utf-8 -*-
"""Реестр экранов: родители, пути и рубрики.

Этот файл пришёл на смену временному тесту переноса. Тот сверял новые экраны
со старыми меню в bot.py кнопка в кнопку, и был прав ровно до тех пор, пока
старые меню существовали: цех и станок переехали последними, и сверять стало
не с чем.

Осталось то, что проверяет не переезд, а само устройство: «назад» выводится
из объявленного родителя, а не из стека в памяти, и потому обязано доходить
до главного из любого экрана.
"""

import sys
import unittest
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

import экраны                                                # noqa: E402


class Родители(unittest.TestCase):

    def test_родитель_объявлен_у_всех_кроме_главного(self):
        for код, запись in экраны.РЕЕСТР.items():
            with self.subTest(экран=код):
                if код == "home":
                    self.assertIsNone(запись.родитель)
                else:
                    self.assertTrue(запись.родитель, код)

    def test_родитель_существует(self):
        for код, запись in экраны.РЕЕСТР.items():
            if not запись.родитель:
                continue
            with self.subTest(экран=код):
                # У экрана с параметром и родитель с параметром: подставляем
                # какой-нибудь аргумент, иначе «cv:*» не с чем сверять.
                self.assertTrue(экраны.есть(запись.родитель.replace("*", "1")),
                                f"{код} → {запись.родитель}")

    def test_назад_доходит_до_главного(self):
        """Кольцо в родителях завесило бы бота: «назад» ходило бы по кругу."""
        for код in экраны.РЕЕСТР:
            with self.subTest(экран=код):
                путь = экраны.путь(код.replace("*", "1"))
                self.assertTrue(путь, код)
                self.assertEqual(путь[0], "home", код)

    def test_коды_экранов_латиницей(self):
        """Кириллица занимает по два байта, а в кнопку влезает 64."""
        for код in экраны.РЕЕСТР:
            with self.subTest(экран=код):
                self.assertTrue(код.isascii(), код)


class Рубрики(unittest.TestCase):

    def test_ни_одна_рубрика_не_потерялась(self):
        """Список рубрик — это content.РУБРИКИ, а не зажившая своей жизнью копия."""
        from content import РУБРИКИ
        запись, _ = экраны.найти("r")
        э = запись.собрать(экраны.Пар(чат=1, владелец=True))
        коды = [к[1] for ряд in э.ряды for к in ряд]
        for р in РУБРИКИ:
            with self.subTest(рубрика=р):
                self.assertIn(f"gen:{р}", коды)


if __name__ == "__main__":
    unittest.main()
