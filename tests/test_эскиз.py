# -*- coding: utf-8 -*-
"""Эскиз до рисования: текст показывается раньше, чем поднимается Chrome.

Раньше `core.карусель` сочиняла и сразу рисовала. Любая правка текста — хоть
одного слова на обложке — означала новый прогон целиком: семь кадров, минуты
работы безголового Chrome и восемь новых файлов в хранилище. Стадия эскиза
разрывает это надвое: сперва текст, и только когда он одобрен — кадры.

Стадия помечается внутри карточки, а не статусом поста. Новый статус пришлось
бы учесть везде, где статусы перечисляются: черновики, очередь, расписание,
экраны бота. Пометка в карточке не видна ничему, что про неё не спрашивает.

Модель здесь не зовётся: тест сторожит устройство конвейера, а не то, что
сочиняет Claude. Дублёры подменяют и сочинение, и рисование, и базу.
"""

import sys
import unittest
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))


class _Карусель:
    """Столько от настоящей Карусели, сколько читает core."""

    cover_title = "Хватит платить за устаревший ИИ"
    поза = "privet"
    topic = "выбор нейросети под задачу"
    запасные_заголовки = ["Пять рейтингов"]
    название = "Какую нейросеть выбрать"
    slides = []

    def model_dump(self):
        return {"cover_title": self.cover_title, "slides": [],
                "closing": "", "поза": self.поза}


class _Дублёры:
    """Подменяет сочинение, рисование и запись в базу."""

    def __enter__(self):
        import carousel
        import core
        import db
        import mascot
        import storage
        self.нарисовано = 0
        self.положено = {}
        self._было = {
            "сочинить": carousel.сочинить,
            "нарисовать": carousel.нарисовать,
            "подпись": carousel.подпись,
            "добавить": db.добавить,
            "взять": db.взять,
            "правка": db.правка,
            # Без этой подмены тест уходит за списком прошлых тем в боевую
            # базу: DATABASE_URL задан, и db молча открывает постгрес.
            "о_чём_писали": db.о_чём_писали,
            # Иначе дорисовка честно полезет грузить кадры в Supabase.
            "положить": storage.положить,
            "взять_позу": mascot.взять,
            "сохранить_позу": core._сохранить_позу,
        }

        def нарисовать(*д, **к):
            self.нарисовано += 1
            return ["/tmp/слайд1.png", "/tmp/слайд2.png"]

        def добавить(рубрика, заголовок, текст, картинка, форма=None,
                     карточка=None, картинки=None):
            self.положено = {"рубрика": рубрика, "заголовок": заголовок,
                             "карточка": карточка, "картинки": картинки}
            return 42

        carousel.сочинить = lambda *д, **к: _Карусель()
        carousel.нарисовать = нарисовать
        carousel.подпись = lambda к: "подпись"
        db.добавить = добавить
        db.взять = lambda ид: {"id": ид, "card": None}
        db.о_чём_писали = lambda *д, **к: []
        db.правка = lambda ид, **поля: self.положено.update(поля)
        storage.положить = lambda ф: None
        mascot.взять = lambda имя: None
        core._сохранить_позу = lambda поза: None
        self.core = core
        return self

    def __exit__(self, *беда):
        import carousel
        import db
        carousel.сочинить = self._было["сочинить"]
        carousel.нарисовать = self._было["нарисовать"]
        carousel.подпись = self._было["подпись"]
        db.добавить = self._было["добавить"]
        db.взять = self._было["взять"]
        db.правка = self._было["правка"]
        db.о_чём_писали = self._было["о_чём_писали"]
        import mascot
        import storage
        storage.положить = self._было["положить"]
        mascot.взять = self._было["взять_позу"]
        import core
        core._сохранить_позу = self._было["сохранить_позу"]
        return False


class Эскиз(unittest.TestCase):
    def test_эскиз_не_рисует(self):
        with _Дублёры() as д:
            д.core.эскиз(тема="проверка", площадка="tiktok")
        self.assertEqual(д.нарисовано, 0, "эскиз поднял Chrome, а не должен")

    def test_эскиз_кладёт_пост_без_картинок(self):
        with _Дублёры() as д:
            д.core.эскиз(тема="проверка", площадка="tiktok")
        self.assertFalse(д.положено["картинки"])

    def test_эскиз_помечает_стадию(self):
        with _Дублёры() as д:
            д.core.эскиз(тема="проверка", площадка="tiktok")
        self.assertEqual(д.положено["карточка"].get("стадия"), "эскиз")


class Дорисовка(unittest.TestCase):
    """Вторая половина: кадры по готовому тексту, без похода в модель."""

    def _подготовить(self, д):
        import json
        import db
        карточка = {"carousel": {"поза": "privet", "slides": []},
                    "формат": "3к4", "стадия": "эскиз"}
        db.взять = lambda ид: {"id": ид,
                               "card": json.dumps(карточка, ensure_ascii=False)}
        return д

    def test_дорисовка_рисует_один_раз(self):
        with _Дублёры() as д:
            self._подготовить(д)
            д.core.дорисовать(42)
        self.assertEqual(д.нарисовано, 1)

    def test_дорисовка_снимает_стадию(self):
        import json
        with _Дублёры() as д:
            self._подготовить(д)
            д.core.дорисовать(42)
        карточка = json.loads(д.положено["card"])
        self.assertNotIn("стадия", карточка)

    def test_дорисовка_забывает_вариант_площадки(self):
        """Иначе на стол уедут кадры, нарисованные до правки.

        Пост 98 так и вышел 12 сентября 2026: карусель перерисована в новом
        жанре, а папка на столе собралась из вчерашних картинок — вариант
        TikTok лежал в карточке готовым и никто его не сбрасывал.
        """
        with _Дублёры() as д:
            self._подготовить(д)
            забыто = []
            import варианты
            было = варианты.забыть
            варианты.забыть = lambda ид, куда=None: забыто.append(ид)
            try:
                д.core.дорисовать(42)
            finally:
                варианты.забыть = было
        self.assertEqual(забыто, [42])

    def test_отчёт_приёмки_ложится_в_карточку(self):
        import json
        import carousel
        import приёмка
        with _Дублёры() as д:
            self._подготовить(д)

            def с_браком(*а, **к):
                приёмка.кадр(2, "мысль")
                приёмка.брак("слово шире колонки")
                return ["/tmp/слайд1.png"]

            carousel.нарисовать = с_браком
            д.core.дорисовать(42)
        карточка = json.loads(д.положено["card"])
        self.assertFalse(карточка["приёмка"]["годен"])
        self.assertFalse(приёмка.идёт(), "журнал закрыт после дорисовки")

    def test_дорисовка_не_сочиняет(self):
        with _Дублёры() as д:
            self._подготовить(д)
            звали = []
            import carousel
            carousel.сочинить = lambda *а, **к: звали.append(1)
            д.core.дорисовать(42)
        self.assertEqual(звали, [], "дорисовка сходила в модель, а не должна")


if __name__ == "__main__":
    unittest.main()
