# -*- coding: utf-8 -*-
"""Главный экран: четыре кнопки и строка состояния.

Прежнее главное меню было списком всего, что бот умеет: девять кнопок вровень
друг с другом, от «сделать пост» до переключателя звука. Выбирать из него надо
было чтением, а не взглядом.

Новый главный отвечает на два вопроса сразу: что сейчас происходит и что можно
сделать. Происходящее — текстом, потому что оно сообщает, а не предлагает
нажать; дела — кнопками, и их четыре.

Сторожится тут то, что молча врёт. Строка состояния собирается из четырёх
разных модулей, и любой из них может промолчать: сбойный станок не показать —
значит человек узнает о нём через день, когда не выйдет пост. А «⏳ Сейчас»,
показанное при пустом станке, наоборот заставляет ждать несуществующую работу.
"""

import sys
import unittest
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

import экраны                                                # noqa: E402


class _Состояние:
    """Подменяет всё, из чего собирается главный экран, разом.

    По отдельности их не подменить: экран ходит в базу, в очередь заданий и в
    настройки канала, и любой непокрытый поход в тесте лезет в живую базу за
    океаном.
    """

    def __init__(self, **как):
        self.как = {"план": 7, "черновики": 2, "неделя": 5, "работа": [],
                    "беды": [], "открыто": 0, "чаты": False, "тихо": False,
                    "канал": "@4xtube", "основной": True}
        self.как.update(как)
        self.было = {}

    def __enter__(self):
        import access
        import channels
        import core
        import db
        import jobs
        к = self.как
        self.было = {
            (db, "сводка"): db.сводка, (jobs, "в_работе"): jobs.в_работе,
            (jobs, "последние_беды"): jobs.последние_беды,
            (access, "открыто"): access.открыто,
            (core, "звук_выключен"): core.звук_выключен,
            (channels, "текущий"): channels.текущий,
            (channels, "основной_выбран"): channels.основной_выбран,
            (экраны, "_чаты_доступны"): экраны._чаты_доступны,
        }
        db.сводка = lambda *_, **__: {
            "всего": 40, "опубликовано": 30, "черновики": к["черновики"],
            "запланировано": к["план"], "за_неделю": к["неделя"]}
        jobs.в_работе = lambda *_, **__: к["работа"]
        jobs.последние_беды = lambda *_, **__: к["беды"]
        access.открыто = lambda: к["открыто"]
        core.звук_выключен = lambda: к["тихо"]
        channels.текущий = lambda: к["канал"]
        channels.основной_выбран = lambda: к["основной"]
        экраны._чаты_доступны = lambda: к["чаты"]
        return self

    def __exit__(self, *_):
        for (модуль, имя), было in self.было.items():
            setattr(модуль, имя, было)


def _собрать(код: str, владелец: bool = True) -> экраны.Экран:
    запись, _ = экраны.найти(код)
    return запись.собрать(экраны.Пар(чат=1, владелец=владелец))


def _кнопки(э: экраны.Экран) -> list[tuple[str, str]]:
    return [к for ряд in э.ряды for к in ряд if not isinstance(к, dict)]


def _коды(э: экраны.Экран) -> list[str]:
    return [к[1] for к in _кнопки(э)]


class Главный(unittest.TestCase):

    def test_четыре_дела_и_ничего_лишнего(self):
        with _Состояние():
            коды = _коды(_собрать("home"))
        self.assertEqual(коды, ["make", "q", "shop", "set"])

    def test_очередь_с_числом(self):
        """План и черновики — одно дело: «разобрать, что накопилось»."""
        with _Состояние(план=7, черновики=2):
            подписи = dict((к[1], к[0]) for к in _кнопки(_собрать("home")))
        self.assertIn("9", подписи["q"])

    def test_состояние_строкой_а_не_кнопками(self):
        with _Состояние(план=7, черновики=2, неделя=5, канал="@4xtube"):
            э = _собрать("home")
        self.assertIn("@4xtube", э.текст)
        self.assertIn("7", э.текст)
        self.assertIn("5", э.текст)

    def test_работа_видна_пока_идёт(self):
        with _Состояние(работа=[{"вид": "карусель", "этап": "рисую",
                                 "куда": "tiktok", "сколько": 5, "давно": 20}]):
            э = _собрать("home")
        self.assertIn("Сейчас", э.текст)
        self.assertIn("рисую", э.текст)

    def test_на_холостом_станке_ожидания_нет(self):
        """«⏳ Сейчас» при пустой очереди заставляет ждать несуществующее."""
        with _Состояние(работа=[]):
            self.assertNotIn("Сейчас", _собрать("home").текст)

    def test_сбой_виден_сразу_а_не_в_приложении(self):
        with _Состояние(беды=[{"вид": "карусель", "беда": "TikTok не принял",
                               "куда": "tiktok", "давно": 300}]):
            э = _собрать("home")
        self.assertIn("TikTok не принял", э.текст)

    def test_открытая_дверь_показывается_со_сроком(self):
        with _Состояние(открыто=0):
            self.assertNotIn("shut", _коды(_собрать("home")))
        with _Состояние(открыто=71.6):
            подписи = dict((к[1], к[0]) for к in _кнопки(_собрать("home")))
        self.assertIn("72", подписи["shut"])

    def test_отклики_только_когда_есть_чем_читать(self):
        """Чужие чаты читает аккаунт владельца: без входа раздел пуст."""
        with _Состояние(чаты=False):
            self.assertNotIn("rep", _коды(_собрать("home")))
        with _Состояние(чаты=True):
            self.assertIn("rep", _коды(_собрать("home")))

    def test_клавиатура_не_переполняется(self):
        with _Состояние(чаты=True, открыто=72):
            self.assertLessEqual(len(_кнопки(_собрать("home"))), 10)


class Настройки(unittest.TestCase):
    """Пока в них ровно то, что бот уже умел: канал и звук."""

    def test_канал_и_звук_на_месте(self):
        with _Состояние():
            коды = _коды(_собрать("set"))
        self.assertIn("set:ch", коды)
        self.assertIn("sound", коды)

    def test_звук_переключается_не_заходя_внутрь(self):
        """У переключателя нет своего экрана: заходить в него незачем."""
        with _Состояние(тихо=True):
            подписи = dict((к[1], к[0]) for к in _кнопки(_собрать("set")))
        self.assertIn("выкл", подписи["sound"])

    def test_канал_настраивает_только_владелец(self):
        """Право публиковать и право решать куда — разные вещи."""
        запись, _ = экраны.найти("set:ch")
        self.assertTrue(запись.только_владельцу)
        self.assertEqual(экраны.родитель("set:ch"), "set")
        self.assertEqual(экраны.родитель("set"), "home")

    def test_старые_кнопки_из_истории_чата_ведут_куда_положено(self):
        """Кнопка «Расписание» со вчерашнего меню всё ещё нажимается."""
        for старый, нынешний in (("plan", "q"), ("stat", "q:sum"),
                                 ("chan", "set:ch"), ("menu", "home")):
            with self.subTest(старый=старый):
                запись, _ = экраны.найти(старый)
                self.assertIsNotNone(запись, старый)
                self.assertEqual(запись.код, нынешний)


if __name__ == "__main__":
    unittest.main()
