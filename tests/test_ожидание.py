# -*- coding: utf-8 -*-
"""Ожидание текста: один словарь вместо четырёх, и у каждого вопроса — отмена.

Раньше ожиданий было четыре: часы, правка, окно чтения чатов и «что было» для
рубрики «от себя». Ни у одного не было отмены — начал вводить часы, передумал,
написал что-то другое, и это уходило в часы. Дальше становилось только хуже:
с паритетом мини-приложения таких словарей стало бы около десяти.

Теперь словарь один, и правило одно: любое нажатие любой кнопки его чистит.
Ушёл в другой раздел — бот больше не ждёт от тебя часов.
"""

import sys
import unittest
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

import навигация                                             # noqa: E402


class _Молчун:
    """Телеграм, который ничего не отправляет и всем доволен."""

    def __enter__(self):
        import telegram as tg
        self.tg = tg
        self.было = (tg.написать, tg.правка_текста, tg.убрать_кнопки,
                     tg.ответить_на_кнопку)
        tg.написать = lambda *а, **к: {"message_id": 1}
        tg.правка_текста = lambda *а, **к: True
        tg.убрать_кнопки = lambda *а, **к: None
        tg.ответить_на_кнопку = lambda *а, **к: None
        return self

    def __exit__(self, *_):
        (self.tg.написать, self.tg.правка_текста, self.tg.убрать_кнопки,
         self.tg.ответить_на_кнопку) = self.было


class ЧистыйСтол(unittest.TestCase):

    def setUp(self):
        self.было = (dict(навигация.ЖДЁМ), dict(навигация.ЭКРАН))
        навигация.ЖДЁМ.clear()
        навигация.ЭКРАН.clear()

    def tearDown(self):
        навигация.ЖДЁМ.clear()
        навигация.ЭКРАН.clear()
        навигация.ЖДЁМ.update(self.было[0])
        навигация.ЭКРАН.update(self.было[1])


class ОдинСловарь(ЧистыйСтол):

    def test_отдельных_словарей_в_боте_не_осталось(self):
        """Проверка устройства, а не поведения: четыре словаря сведены в один."""
        исходник = Path(__file__).resolve().parent.parent / "bot.py"
        текст = исходник.read_text(encoding="utf-8")
        self.assertNotIn("ЖДЁМ_", текст)

    def test_вопрос_помнит_чего_ждёт_и_с_чем(self):
        with _Молчун():
            навигация.спросить(1, "правка", "текст?", "q", {"ид": 5,
                                                            "как": "edit"})
        что, данные = навигация.чего_ждём(1)
        self.assertEqual(что, "правка")
        self.assertEqual(данные["ид"], 5)

    def test_у_вопроса_есть_отмена_на_свой_экран(self):
        клавиатуры = []
        with _Молчун() as м:
            м.tg.написать = lambda чат, текст, клава=None, **к: (
                клавиатуры.append(клава) or {"message_id": 1})
            навигация.спросить(1, "тема", "о чём?", "make")
        import json
        кнопка = json.loads(клавиатуры[0])["inline_keyboard"][0][0]
        self.assertEqual(кнопка["callback_data"], "make")
        self.assertIn("Отменить", кнопка["text"])

    def test_любое_нажатие_чистит_ожидание(self):
        """Правило живёт в одном месте — в показе экрана, а не в каждом вопросе."""
        import bot                                           # noqa: F401
        import db
        настоящая = db.сводка
        db.сводка = lambda *_, **__: {"всего": 0, "опубликовано": 0,
                                      "за_неделю": 0, "черновики": 0,
                                      "запланировано": 0}
        навигация.ЖДЁМ[1] = ("часы", {"куда": "tiktok"})
        try:
            with _Молчун():
                навигация.показать(1, "home", владелец=True)
        finally:
            db.сводка = настоящая
        self.assertIsNone(навигация.чего_ждём(1))


class ЧетыреВопроса(ЧистыйСтол):
    """Каждый из прежних словарей отвечает через общий разбор."""

    def test_правка_заменяет_текст_поста(self):
        import bot
        import core
        import db
        заменили, показали = [], []
        настоящие = (core.обновить, db.взять, bot.показать)
        core.обновить = lambda ид, текст: заменили.append((ид, текст))
        db.взять = lambda ид: {"id": ид, "status": "draft", "title": "т",
                               "body": "было", "image_path": None,
                               "images": None, "card": None}
        bot.показать = lambda *а, **к: показали.append(а)
        навигация.ЖДЁМ[1] = ("правка", {"ид": 5, "как": "edit"})
        try:
            with _Молчун():
                bot.ответить_словами(1, "стало")
        finally:
            core.обновить, db.взять, bot.показать = настоящие
        self.assertEqual(заменили, [(5, "стало")])
        self.assertTrue(показали)

    def test_переписать_идёт_указанием_а_не_заменой(self):
        import bot
        import core
        import db
        переписали = []
        настоящие = (core.переписать, db.взять, bot.показать)
        core.переписать = lambda ид, указание: переписали.append((ид, указание))
        db.взять = lambda ид: {"id": ид, "status": "draft", "title": "т",
                               "body": "было", "image_path": None,
                               "images": None, "card": None}
        bot.показать = lambda *а, **к: None
        навигация.ЖДЁМ[1] = ("правка", {"ид": 5, "как": "ask"})
        try:
            with _Молчун():
                bot.ответить_словами(1, "покороче")
        finally:
            core.переписать, db.взять, bot.показать = настоящие
        self.assertEqual(переписали, [(5, "покороче")])

    def test_рассказ_о_себе_становится_постом(self):
        import bot
        сочинили = []
        настоящая = bot.сделать_пост
        bot.сделать_пост = lambda чат, рубрика, тема=None, *а, **к: (
            сочинили.append((рубрика, тема)))
        навигация.ЖДЁМ[1] = ("факт", {})
        try:
            with _Молчун():
                bot.ответить_словами(1, "три дня бился с озвучкой")
        finally:
            bot.сделать_пост = настоящая
        self.assertEqual(сочинили, [("от себя", "три дня бился с озвучкой")])

    def test_окно_чтения_чатов_разбирается_словами(self):
        import bot
        import отклики
        задали = []
        настоящие = (отклики.задать_начало, отклики.разобрать_момент,
                     отклики.настройки, отклики.подпись_окна)
        отклики.разобрать_момент = lambda текст: "момент" if текст else None
        отклики.задать_начало = lambda момент: задали.append(момент)
        отклики.настройки = lambda: {"с": 0, "папка": "", "чаты": [],
                                     "стиль": "", "сколько": 0}
        отклики.подпись_окна = lambda _: "со вчера"
        навигация.ЖДЁМ[1] = ("окно", {})
        try:
            with _Молчун():
                bot.ответить_словами(1, "вчера 18:00")
        finally:
            (отклики.задать_начало, отклики.разобрать_момент,
             отклики.настройки, отклики.подпись_окна) = настоящие
        self.assertEqual(задали, ["момент"])

    def test_непонятое_окно_переспрашивает(self):
        import bot
        import отклики
        задали = []
        настоящие = (отклики.задать_начало, отклики.разобрать_момент)
        отклики.разобрать_момент = lambda текст: None
        отклики.задать_начало = lambda момент: задали.append(момент)
        навигация.ЖДЁМ[1] = ("окно", {})
        try:
            with _Молчун():
                bot.ответить_словами(1, "как-нибудь")
        finally:
            отклики.задать_начало, отклики.разобрать_момент = настоящие
        self.assertEqual(задали, [])
        self.assertEqual(навигация.чего_ждём(1)[0], "окно")


if __name__ == "__main__":
    unittest.main()
