# -*- coding: utf-8 -*-
"""Переполненный слайд сперва сокращается, и только потом мельчит шрифт.

Правило из html-instagram-carousel: не влезает — убрать повтор, сократить
текст, и лишь в конце уменьшать кегль. Мелкий текст там считается браком.
"""
import sys
import unittest
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

import card      # noqa: E402
import carousel  # noqa: E402
import mascot    # noqa: E402
import агент     # noqa: E402
import приёмка   # noqa: E402

ДЛИННЫЙ = "Одна мысль, которая растянулась слишком далеко и не лезет в кадр"
ДЛИННЫЙ_ВЫВОД = "Итог, который вышел длиннее, чем помещается в последний кадр"


def карусель(вывод: str = "") -> dict:
    return {"cover_kicker": "Над", "cover_title": "Обложка",
            "slides": [{"вид": "мысль", "заголовок": "Раз", "текст": ДЛИННЫЙ}],
            "closing": вывод, "паспорт": {"кот": False}}


class Сократить(unittest.TestCase):
    def setUp(self):
        self.было = (card.слайд_обложка, card.слайд_вида, card.слайд_финал,
                     mascot.библиотека, агент.по_форме)
        self.тексты, self.выводы = [], []
        self.ответ = carousel.Короче(заголовок="Раз", текст="Мысль *короче*")

        def вида(вид, поля, *а, **к):
            self.тексты.append(поля.get("текст"))
            if поля.get("текст") == ДЛИННЫЙ:
                приёмка.ужато(0.64)
            return Path("/tmp/кадр.png")

        def финал(вывод, *а, **к):
            self.выводы.append(вывод)
            if вывод == ДЛИННЫЙ_ВЫВОД:
                приёмка.брак("текст налезает на призыв")
            return Path("/tmp/финал.png")

        card.слайд_обложка = lambda *а, **к: Path("/tmp/обложка.png")
        card.слайд_вида = вида
        card.слайд_финал = финал
        mascot.библиотека = lambda: {}
        агент.по_форме = lambda *а, **к: self.ответ

    def tearDown(self):
        (card.слайд_обложка, card.слайд_вида, card.слайд_финал,
         mascot.библиотека, агент.по_форме) = self.было
        приёмка.итог()

    def _нарисовать(self, к, сокращать):
        приёмка.начать()
        carousel.нарисовать(к, "3к4", Path("/tmp/поза.png"), сокращать=сокращать)
        return приёмка.итог()

    def test_ужатый_слайд_сокращается_и_рисуется_заново(self):
        к = карусель()
        отчёт = self._нарисовать(к, True)
        self.assertEqual(self.тексты, [ДЛИННЫЙ, "Мысль *короче*"])
        self.assertEqual(к["slides"][0]["текст"], "Мысль *короче*",
                         "сокращённый текст остаётся в карусели и уйдёт в базу")
        кадр = отчёт["кадры"][1]
        self.assertEqual(кадр["ужато"], 1.0)
        self.assertTrue(any("сокращён" in з for з in кадр["замечания"]), кадр)

    def test_без_разрешения_текст_не_трогается(self):
        к = карусель()
        self._нарисовать(к, False)
        self.assertEqual(self.тексты, [ДЛИННЫЙ])
        self.assertEqual(к["slides"][0]["текст"], ДЛИННЫЙ)

    def test_модель_не_сократила_второго_прохода_нет(self):
        self.ответ = carousel.Короче(заголовок="Раз", текст=ДЛИННЫЙ + " и ещё")
        к = карусель()
        self._нарисовать(к, True)
        self.assertEqual(self.тексты, [ДЛИННЫЙ])

    def test_вывод_с_браком_сокращается(self):
        self.ответ = carousel.Короче(текст="Итог короче")
        к = карусель(ДЛИННЫЙ_ВЫВОД)
        к["slides"][0]["текст"] = "Мысль влезла"
        отчёт = self._нарисовать(к, True)
        self.assertEqual(self.выводы, [ДЛИННЫЙ_ВЫВОД, "Итог короче"])
        self.assertEqual(к["closing"], "Итог короче")
        self.assertTrue(отчёт["годен"])

    def test_сбой_модели_не_роняет(self):
        def падает(*а, **к):
            raise RuntimeError("модель недоступна")
        агент.по_форме = падает
        поля = {"вид": "мысль", "заголовок": "Раз", "текст": ДЛИННЫЙ}
        self.assertIs(carousel.сократить(поля, "мысль", "не влезло"), поля)

    def test_число_пунктов_не_меняется(self):
        поля = {"вид": "список", "заголовок": "Три", "текст": "",
                "строки": ["первый длинный пункт", "второй длинный пункт",
                           "третий длинный пункт"]}
        self.ответ = carousel.Короче(заголовок="Три", строки=["первый", "второй"])
        self.assertIs(carousel.сократить(поля, "список", "не влезло"), поля)
