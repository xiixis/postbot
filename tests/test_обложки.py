# -*- coding: utf-8 -*-
"""Каталог запасных обложек: каждый макет проходит приёмку досок в теме каждого стиля.

«Проверенный макет» — не слово, а свойство: тест собирает все макеты каталога в теме «пар»
(светлая) и «сервисов» (тёмная) на образцовых полях постов 24.09 и прогоняет приёмку. Сцена —
синтетическая (кремовый фон, тёмный овал-«кот» по известной рамке), чтобы тест не зависел от
`.claude/маскот`.
"""
import json
import shutil
import sys
import tempfile
import unittest
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(КОРЕНЬ))
sys.path.insert(0, str(КОРЕНЬ / "Style"))

import config            # noqa: E402
import обложки           # noqa: E402

ОБРАЗЦЫ = Path(__file__).resolve().parent / "эталоны" / "обложки"
ЗНАЧКИ = Path(__file__).resolve().parent / "эталоны" / "доски"
О = json.loads((ОБРАЗЦЫ / "образцы.json").read_text(encoding="utf-8"))


def данные(**лишнее) -> dict:
    return {"значки": О["значки"], "пары": О["пары"], "сцены": ОБРАЗЦЫ, **лишнее}


def стиль_модуль(имя: str):
    import importlib.util
    путь = КОРЕНЬ / "Style" / имя
    спек = importlib.util.spec_from_file_location("стиль_" + путь.stem, путь)
    м = importlib.util.module_from_spec(спек)
    спек.loader.exec_module(м)
    return м


def холст(модуль, обложки_: dict, д: dict) -> Path:
    """Временный холст из досок каталога в теме модуля стиля."""
    import дизайн_холст as дх
    корень = Path(tempfile.mkdtemp()) / "холст"
    врем = корень / "_файлы"
    файлы = list(модуль.ШРИФТЫ) + [дх.логотип(врем)] + обложки.файлы(обложки_, врем, д["сцены"])
    файлы += [ЗНАЧКИ / з["значок"] for з in д["значки"]]
    файлы += [ЗНАЧКИ / п[с]["значок"] for п in д["пары"] for с in ("платно", "бесплатно")]
    доски = [(f"Oblozhka{н}.dc.html", имя, дх.доска(имя, обложки.нарисовать(имя, о, модуль.ТЕМА, д),
                                                   обложки.грунт(имя, модуль.ТЕМА), модуль.CSS))
             for н, (имя, о) in enumerate(обложки_.items(), 2)]
    return дх.собрать(корень, "проба", доски, sorted(set(файлы)), источник="https://example.com")


class Проверка(unittest.TestCase):
    def test_все_макеты_на_месте(self):
        self.assertEqual(set(обложки.МАКЕТЫ), {"замена", "списание", "превращение", "плёнка", "число", "сцена"})
        for имя, м in обложки.МАКЕТЫ.items():
            self.assertTrue(м.крючок, имя)

    def test_образцы_полны(self):
        for имя, о in О["обложки"].items():
            with self.subTest(имя):
                self.assertEqual(обложки.проверить(имя, о, данные()), [])

    def test_нехватка_поля_и_данных(self):
        беды = обложки.проверить("списание", {"строки": ["а", "б"]}, {})
        self.assertIn("«списание»: нет поля «сумма»", беды)
        self.assertIn("«списание»: пост не дал «значки»", беды)

    def test_неизвестный_макет(self):
        self.assertEqual(обложки.проверить("веер", {}, {}), ["нет макета «веер» в каталоге: " + ", ".join(обложки.МАКЕТЫ)])

    def test_сцена_без_карточки(self):
        беды = обложки.проверить("сцена", {**О["обложки"]["сцена"], "сцена": "nety"}, данные())
        self.assertTrue(any("карточк" in б for б in беды), беды)


@unittest.skipUnless(config.хром(), "нужен Chrome")
class ВТемах(unittest.TestCase):
    """Все макеты × обе темы → приёмка досок: годен."""

    def прогнать(self, файл: str):
        import приёмка
        import приёмка_досок
        отчёт = приёмка_досок.проверить(холст(стиль_модуль(файл), О["обложки"], данные()))
        self.assertTrue(приёмка.годен(отчёт), приёмка.строкой(отчёт))

    def test_тема_пар(self):
        self.прогнать("пары/категории.py")

    def test_тема_сервисов(self):
        self.прогнать("сервисы/карточка.py")

    def test_текст_на_коте_сцены(self):
        """Карточка, где «пусто» задевает кота, — текст садится на кота, и приёмка это видит."""
        import приёмка_досок
        сцены = Path(tempfile.mkdtemp())
        shutil.copy(ОБРАЗЦЫ / "scena-proba.jpg", сцены)
        (сцены / "scena-proba.json").write_text(json.dumps(
            {"тёмная": False, "пусто": [80, 560, 1000, 1080], "кот": [620, 640, 880, 1280]}))
        папка = холст(стиль_модуль("пары/категории.py"), {"сцена": О["обложки"]["сцена"]}, данные(сцены=сцены))
        беды = приёмка_досок.по_разметке(папка, "Oblozhka2.dc.html")
        self.assertTrue([б for б in беды if "кот-сцены" in б], беды)


if __name__ == "__main__":
    unittest.main()
