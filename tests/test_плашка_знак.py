# -*- coding: utf-8 -*-
"""Раскладка «выделение»: знак после плашки не уходит на отдельную строку.

Эта раскладка режет абзац по звёздочкам на отдельные БЛОЧНЫЕ абзацы: до
плашки, сама плашка, после неё. Всё, что стоит сразу за закрывающей
звёздочкой, поэтому обязано начаться с новой строки. Так на посте 90 вышло
«, без сторон и сумм» — строка с запятой в начале, а на посте 91 одинокая
точка встала отдельной строкой под плашкой.

Знак сразу за выделением — хвост выделенных слов, а не начало следующего
абзаца. Его место внутри плашки.

В остальных раскладках плашка — строчный span, и браузер сам не отрывает
от него знак: на тридцати кадрах 11 сентября так ни разу и не случилось.
"""

import sys
import unittest
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

import card                                                  # noqa: E402


def _нутро(абзац: str) -> str:
    д = card._общее(4, 10, "3к4")
    return card._нутро("выделение", д, {"абзац": абзац})


class ЗнакПослеПлашки(unittest.TestCase):
    def test_запятая_уходит_в_плашку(self):
        """Пост 90: «, без сторон и сумм» начиналось с запятой."""
        итог = _нутро("Из договора бери *один пункт*, без сторон и сумм")
        self.assertIn('<p class="свет">один пункт,</p>', итог)
        self.assertIn("<p>без сторон и сумм</p>", итог)

    def test_одинокая_точка_не_становится_абзацем(self):
        """Пост 91: точка стояла одна строкой под плашкой."""
        итог = _нутро("Сохрани роль в GPT или Gem: *свой тренажёр готов*.")
        self.assertIn('<p class="свет">свой тренажёр готов.</p>', итог)
        self.assertNotIn("<p>.</p>", итог)
        self.assertEqual(итог.count("<p"), 2, итог)

    # Пробелы по краям абзаца срезает сам _текст, поэтому ниже их нет.

    def test_точка_перед_плашкой_остаётся_на_месте(self):
        итог = _нутро("Сбивайся и повторяйся. *Каша из слов годится*")
        self.assertIn("<p>Сбивайся и повторяйся.</p>", итог)
        self.assertIn('<p class="свет">Каша из слов годится</p>', итог)

    def test_плашка_без_знака_не_меняется(self):
        итог = _нутро("Бери *один пункт* без сторон и сумм")
        self.assertIn('<p class="свет">один пункт</p>', итог)
        self.assertIn("<p>без сторон и сумм</p>", итог)

    def test_две_плашки_в_одном_абзаце(self):
        итог = _нутро("Сначала *карта*, потом *детали*.")
        self.assertIn('<p class="свет">карта,</p>', итог)
        self.assertIn('<p class="свет">детали.</p>', итог)
        self.assertNotIn("<p>.</p>", итог)

    def test_несколько_знаков_подряд(self):
        итог = _нутро("Правда *понял*?! Проверь")
        self.assertIn('<p class="свет">понял?!</p>', итог)
        self.assertIn("<p>Проверь</p>", итог)


if __name__ == "__main__":
    unittest.main()
