# -*- coding: utf-8 -*-
"""Перенос меню в экраны: кнопка в кнопку.

Временный тест. Меню переезжают из bot.py в экраны.py, и на шаге переезда
поведение обязано остаться прежним — меняется устройство, а не то, что видит
человек. Проверить это глазами нельзя: кнопок два десятка, и пропажу одной
строки замечаешь через неделю, когда она понадобилась.

Переехавшее и уже переросшее оригинал отсюда уходит: главный экран и рубрики
сверять не с чем, старых функций в bot.py не осталось. Здесь держатся те, чей
черёд ещё не настал, — цех и станок.

Сверяются коды (callback_data), а не подписи: в подписях живые числа и время,
они меняются между двумя вызовами сами по себе.

Удалить вместе со старыми меню-функциями, когда лестница разбора опустеет.
"""

import json
import sys
import unittest
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

import экраны                                                # noqa: E402


def _коды(строка: str) -> list[list[str]]:
    """tg.кнопки отдаёт JSON-строку, а не структуру — разбираем обратно.

    Коды приводятся через синонимы: старое меню писало в «назад» псевдоним
    («menu», «cv»), новые экраны пишут канонический код («home», «shop»).
    Ведут они в одно и то же место, и замораживать здесь псевдоним значило бы
    мешать переносу вместо того, чтобы сторожить потерянную кнопку.
    """
    сетка = json.loads(строка)["inline_keyboard"]
    return [[экраны.СИНОНИМЫ.get(к.get("callback_data", "web_app"),
                                 к.get("callback_data", "web_app"))
             for к in ряд] for ряд in сетка]


def _экран(код: str, арг: str = "") -> list[list[str]]:
    запись, _ = экраны.найти(код)
    э = запись.собрать(экраны.Пар(чат=1, арг=арг, владелец=True))
    return _коды(экраны.клавиатура(код, э))


class Перенос(unittest.TestCase):
    """Сверка со старыми меню bot.py.

    bot ввозится внутрь тестов, а не сверху: на импорте он поднимает
    настройки и трогает окружение, а нам нужны только четыре функции.
    """

    def _bot(self):
        import bot
        return bot

    def test_ни_одна_рубрика_не_потерялась(self):
        """Сверять больше не с чем: старых меню в bot.py не осталось.

        Главный экран и рубрики переросли свои оригиналы и уехали в реестр
        целиком. Сторожить осталось живое требование: рубрики на экране —
        это ровно рубрики из content, а не список, зажитый своей жизнью.
        """
        from content import РУБРИКИ
        коды = [к for ряд in _экран("r") for к in ряд]
        for р in РУБРИКИ:
            with self.subTest(рубрика=р):
                self.assertIn(f"gen:{р}", коды)

    def test_конвейер_кнопка_в_кнопку(self):
        b = self._bot()
        self.assertEqual(_экран("shop"), _коды(b.меню_конвейера()))

    def test_каждый_станок_кнопка_в_кнопку(self):
        b = self._bot()
        import конвейер
        for куда in конвейер.ПО_УМОЛЧАНИЮ:
            with self.subTest(куда=куда):
                self.assertEqual(_экран(f"cv:{куда}", куда),
                                 _коды(b.меню_площадки(куда)))


class НазадИзРеестра(unittest.TestCase):
    """«Назад» выводится из объявленного родителя, а не пишется экраном."""

    def test_рубрики_ведут_в_сочинить(self):
        self.assertEqual(экраны.родитель("r"), "make")
        self.assertEqual(экраны.родитель("make"), "home")

    def test_станок_ведёт_в_цех(self):
        self.assertEqual(экраны.родитель("cv:телеграм"), "shop")

    def test_у_главного_родителя_нет(self):
        self.assertIsNone(экраны.родитель("home"))

    def test_путь_любого_экрана_доходит_до_главного(self):
        for код in ("r", "make", "ideas", "q", "shop", "cv:телеграм"):
            with self.subTest(код=код):
                self.assertEqual(экраны.путь(код)[0], "home")


if __name__ == "__main__":
    unittest.main()
