# -*- coding: utf-8 -*-
"""«Каталог» — единственный светлый дизайн, и ротация под него подстроена."""
import collections
import random
import unittest

import card
import замер
import форматы


class ДизайнВНаборе(unittest.TestCase):
    def test_есть_и_в_ротации(self):
        self.assertIn("каталог", card.ДИЗАЙНЫ)
        self.assertIn("каталог", форматы.ДИЗАЙНЫ_ОК)

    def test_светлый_всегда_даже_на_тёмном_кадре(self):
        """В том и приём: в ленте тёмных постов он читается как чужой."""
        чётный = card._виды_размеры(card._общее(2, 8, формат="тикток"))
        self.assertFalse(card.светлый_ли(2))
        css = card._дизайн("каталог", чётный)
        self.assertIn(f"background:{card.config.ТЕКСТ}", css)

    def test_текст_в_карточках_красится_сам(self):
        """Иначе на чётном кадре светлые буквы пропадали на белой карточке."""
        css = card._дизайн("каталог", card._виды_размеры(card._общее(2, 8)))
        self.assertIn("ul.пункты .имя-и", css)
        self.assertIn("ul.пункты li,ol.места li", css)

    def test_пятна_не_на_псевдоэлементах_холста(self):
        """body:before занят оформлением: «полоса» и «линии» затирали пятна."""
        css = card._дизайн("каталог", card._виды_размеры(card._общее(2, 8)))
        куски = css.split(".grid{")
        self.assertGreater(len(куски), 1, "пятна должны жить на слое сетки")
        # Ищем правило, а не упоминание: в комментарии рядом эти имена есть
        # нарочно — там записано, почему пятна отсюда переехали.
        self.assertNotIn("body:before{", css)
        self.assertNotIn("body:after{", css)

    def test_знак_и_полоса_остаются_по_углам(self):
        """От position:relative логотип вставал в поток и растягивался."""
        css = card._дизайн("каталог", card._виды_размеры(card._общее(2, 8)))
        слой = css[css.index(".знак,.полоса{"):]
        self.assertNotIn("position", слой.split("}")[0])


class РотацияПодСветлыйДизайн(unittest.TestCase):
    def test_у_каталога_свой_фон(self):
        self.assertEqual(форматы.СВОЙ_ФОН.get("каталог"), "чистый")
        случай = random.Random(3)
        for _ in range(200):
            п = форматы.подобрать([], случай)
            if п["дизайн"] == "каталог":
                self.assertEqual(п["оформление"], "чистый")

    def test_дизайны_выпадают_сопоставимо(self):
        """Пара «дизайн+фон» сразу давала каталогу один шанс из тридцати."""
        случай = random.Random(7)
        история, счёт = [], collections.Counter()
        for _ in range(2000):
            п = форматы.подобрать(история, случай)
            история = (история + [п])[-5:]
            счёт[п["дизайн"]] += 1
        доля = счёт["каталог"] / 2000
        self.assertGreater(доля, 0.06, "светлый кадр почти не выходит")
        self.assertLess(доля, 0.3)

    def test_один_наш_дизайн_и_остальные_новые(self):
        """Слово владельца: «оставить один наш фирменный, остальное новое».

        «Терминал» и «редакционный» считаются новыми с 12 сентября 2026: они
        переписаны по пробам со своей вёрсткой кадра, а не остались темами
        поверх общей.
        """
        новые = {"манифест", "атмосфера", "пособие", "каталог",
                 "терминал", "редакционный"}
        свои = set(форматы.ДИЗАЙНЫ_ОК) - новые
        self.assertEqual(свои, {"фирменный"})


class НормаЗамера(unittest.TestCase):
    def test_воздушный_кадр_не_считается_пустым(self):
        """Замеры каталога на семи фонах: 2,0–2,7% чернил."""
        for чернил in (2.0, 2.7):
            self.assertEqual(замер.оценить({"доля_чернил_%": чернил}, "каталог"), [])

    def test_совсем_пустой_кадр_всё_равно_замечен(self):
        self.assertTrue(замер.оценить({"доля_чернил_%": 0.6}, "каталог"))


if __name__ == "__main__":
    unittest.main()
