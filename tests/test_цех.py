# -*- coding: utf-8 -*-
"""Цех и станок: переключатели площадки и файлы для ручной выкладки.

Станок переехал в реестр ещё на шаге переноса, но его кнопки до сих пор
разбирала лестница `elif` в bot.py — экран новый, руки старые. Здесь они
становятся объявленными действиями, и заодно появляется то, чего в боте не
было: забрать файлы поста в чат.

Файлы нужны ровно для ручного режима. У TikTok нет отложенных публикаций, и
карусель выкладывают руками с телефона — значит слайды и текст должны приехать
в чат как файлы, а не как пережатые телеграмом снимки.
"""

import sys
import unittest
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

import навигация                                             # noqa: E402
import экраны                                                # noqa: E402


class _Цех:
    """Дублёры настроек площадки и её постов."""

    def __init__(self, режим: str = "сам", посты=None):
        self.как = {"режим": режим, "посты": посты or []}
        self.было = {}

    def __enter__(self):
        import db
        import конвейер
        к = self.как
        self.было = {(конвейер, "настройки"): конвейер.настройки,
                     (конвейер, "в_плане"): конвейер.в_плане,
                     (db, "черновики"): db.черновики,
                     (db, "расписание"): db.расписание}
        конвейер.настройки = lambda куда="tiktok": {
            "вкл": True, "режим": к["режим"], "часы": ["12:00"], "дней": 2}
        конвейер.в_плане = lambda куда: []
        db.черновики = lambda *_, **__: к["посты"]
        db.расписание = lambda *_, **__: []
        return self

    def __exit__(self, *_):
        for (модуль, имя), было in self.было.items():
            setattr(модуль, имя, было)


def _собрать(код: str, арг: str = "tiktok") -> экраны.Экран:
    запись, _ = экраны.найти(код)
    return запись.собрать(экраны.Пар(чат=1, арг=арг, владелец=True))


def _коды(э: экраны.Экран) -> list[str]:
    return [к[1] for ряд in э.ряды for к in ряд if not isinstance(к, dict)]


def _пост(ид: int, заголовок: str) -> dict:
    return {"id": ид, "title": заголовок, "status": "draft", "card": None,
            "images": '["https://a/1.jpg","https://a/2.jpg"]'}


class Станок(unittest.TestCase):

    def test_переключатели_разбираются_объявленными_действиями(self):
        """Раньше их ловила лестница elif — экран новый, руки старые.

        bot ввозится ради побочного действия: объявления живут в нём, и без
        импорта реестр действий пуст.
        """
        import bot                                           # noqa: F401
        with _Цех():
            коды = _коды(_собрать("cv:tiktok"))
        for код in коды:
            with self.subTest(код=код):
                действие, _ = экраны.найти_действие(код)
                экран = экраны.есть(код)
                self.assertTrue(действие or экран, код)

    def test_файлы_забирают_только_в_ручном_режиме(self):
        """Когда площадка публикует сама, забирать файлы незачем."""
        with _Цех(режим="сам"):
            self.assertNotIn("cv:tiktok:take", _коды(_собрать("cv:tiktok")))
        with _Цех(режим="руками"):
            self.assertIn("cv:tiktok:take", _коды(_собрать("cv:tiktok")))

    def test_забрать_ведёт_назад_на_свой_станок(self):
        """У экрана с параметром и родитель с параметром."""
        self.assertEqual(экраны.родитель("cv:tiktok:take"), "cv:tiktok")
        self.assertEqual(экраны.путь("cv:tiktok:take")[0], "home")


class ЗабратьФайлами(unittest.TestCase):

    def test_посты_кнопками_с_площадкой_в_коде(self):
        with _Цех(режим="руками", посты=[_пост(4, "Пять ошибок")]):
            коды = _коды(_собрать("cv:tiktok:take"))
        self.assertIn("take:4:tiktok", коды)

    def test_без_готовых_постов_экран_отказывает(self):
        """Пустой экран «заберите файлы» обещает то, чего нет."""
        with _Цех(режим="руками", посты=[]):
            with self.assertRaises(экраны.НетЭкрана):
                _собрать("cv:tiktok:take")

    def test_код_влезает_в_кнопку(self):
        with _Цех(режим="руками", посты=[_пост(999999, "Заголовок")]):
            for к in _коды(_собрать("cv:tiktok:take")):
                with self.subTest(код=к):
                    self.assertLessEqual(len(к.encode("utf-8")), 64)


class ЧасыСловами(unittest.TestCase):
    """Часы публикации спрашиваются словами и помнят, чья это площадка."""

    def setUp(self):
        import telegram as tg
        self.было = (dict(навигация.ЖДЁМ), dict(навигация.ЭКРАН))
        навигация.ЖДЁМ.clear()
        навигация.ЭКРАН.clear()
        self.написать, self.tg = tg.написать, tg
        tg.написать = lambda *а, **к: {"message_id": 1}

    def tearDown(self):
        навигация.ЖДЁМ.clear()
        навигация.ЭКРАН.clear()
        навигация.ЖДЁМ.update(self.было[0])
        навигация.ЭКРАН.update(self.было[1])
        self.tg.написать = self.написать

    def test_время_ложится_в_свою_площадку(self):
        import bot
        import конвейер
        сохранили = []
        настоящая = конвейер.сохранить
        конвейер.сохранить = lambda куда="tiktok", **поля: сохранили.append(
            (куда, поля))
        навигация.ЖДЁМ[1] = ("часы", {"куда": "tiktok"})
        try:
            bot.ответить_словами(1, "09:00, 12.30 и ещё 18 00")
        finally:
            конвейер.сохранить = настоящая
        self.assertEqual(len(сохранили), 1, сохранили)
        куда, поля = сохранили[0]
        self.assertEqual(куда, "tiktok")
        self.assertEqual(поля["часы"], ["09:00", "12:30", "18:00"])

    def test_без_времени_переспрашивает(self):
        import bot
        import конвейер
        сохранили = []
        настоящая = конвейер.сохранить
        конвейер.сохранить = lambda *а, **к: сохранили.append(а)
        навигация.ЖДЁМ[1] = ("часы", {"куда": "tiktok"})
        try:
            bot.ответить_словами(1, "когда получится")
        finally:
            конвейер.сохранить = настоящая
        self.assertEqual(сохранили, [])
        self.assertEqual(навигация.чего_ждём(1)[0], "часы",
                         "переспросили — значит снова ждём время")


if __name__ == "__main__":
    unittest.main()
