# -*- coding: utf-8 -*-
"""Следы нейросети в тексте: что видно простым счётом, без модели.

Правила из скила «Антидетектор» (Георгий Ривера, на базе humanizer-ru, MIT).
Голос текста просит модель так не писать, но просьба не гарантия: «ноль
рублей» тоже был запрещён и всё равно доезжал до постов. Поэтому готовый текст
проверяется ещё раз, и находки показываются под черновиком.

Ловим только однозначное: жёсткие запреты скила и стоп-слова пачкой. Ритм,
«душу» и лишнюю гладкость счётом не поймать, это остаётся голосу и глазам.
"""

import re

# Жёсткие запреты: встретилось хоть раз — это маркер, а не стиль.
ЗАПРЕТЫ = [
    (r"\bне просто\b[^.!?\n]{1,80}?,\s*а\b", "«не просто X, а Y»"),
    (r"\bне только\b[^.!?\n]{1,80}?\bно и\b", "«не только X, но и Y»"),
    (r"\bэто не про\b[^\n]{1,80}?\bэто про\b", "«это не про X, это про Y»"),
    (r"\bв современном мире\b|\bв наше время\b", "«в современном мире»"),
    (r"\b(стоит|важно|следует) (отметить|понимать|подчеркнуть)\b", "«стоит отметить»"),
    # «Данные» и «данных» не трогаем: это ещё и существительное.
    (r"\bданн(ый|ая|ое|ого|ой|ую|ым|ом)\b", "«данный»"),
    (r"\bигра(ет|ют|л|ла|ли) (важную|ключевую|огромную|значительную|решающую) роль\b",
     "«играет важную роль»"),
    (r"\bтаким образом\b|\bподводя итог\w*\b|\bв заключение\b",
     "«таким образом» / «подводя итог»"),
    (r"\bраскр\w* (свой |твой |ваш |его )?потенциал\w*\b|\bна новый уровень\b|"
     r"\bновые горизонты\b|\bправила игры\b|\bинновационн\w+ решени\w+\b|"
     r"\bкомплексн\w+ (подход|решени)\w*\b|\bидеально подход\w+\b",
     "маркетинговое клише"),
    (r"\bот (новичк\w+|начинающ\w+|стартап\w+|малого бизнеса|школьник\w+|студент\w+) до\b",
     "ложный диапазон «от X до Y»"),
    (r"\bдавайте (разбер[её]мся|рассмотрим|погрузимся)\b|\bрассмотрим подробнее\b|"
     r"\bразбер[её]м по полочкам\b|\bкопн[её]м глубже\b", "«давайте разберёмся»"),
    (r"\bотличный вопрос\b|\bрад помочь\b|\bнадеюсь, (это )?было полезно\b|"
     r"\bдайте знать, если\b", "артефакт чат-бота"),
    # Только отдельной фразой: «И это нормально, не его работа» уже мнение
    # с содержанием (пост 77), а пустое утешение кончается точкой.
    (r"\bи это нормально\s*[.!…]|\bя понимаю, как это непросто\b|"
     r"\bзнакомая ситуация, правда\b", "псевдотерапия"),
    (r"\bэксперты (считают|полагают|отмечают)\b|\bпо мнению экспертов\b|"
     r"\bисследования показывают\b|\bмногие специалисты\b", "размытый авторитет"),
]

# Стоп-словарь: одно слово не приговор, три в одном абзаце — почти наверняка ИИ.
СТОП_СЛОВА = (r"\bкроме того\b|\bв контексте\b|\bключев\w+\b|\bуглуб\w+\b|"
              r"\bподч[её]ркивая\b|\bнепреходящ\w+\b|\bспособствуя\b|"
              r"\bвзаимодействи\w+\b|\bнюанс\w*\b|\bландшафт\w*\b|\bзнаков\w+\b|"
              r"\bпродемонстрир\w+\b|\bсвидетельств\w+\b|\bакцентир\w+\b|"
              r"\bпоистине\b|\bпо-настоящему\b|\bв самом сердце\b|\bзахватывающ\w+\b")
СТОП_ПАЧКА = 3

_ЗАПРЕТЫ = [(re.compile(шаблон, re.I), имя) for шаблон, имя in ЗАПРЕТЫ]
_СТОП = re.compile(СТОП_СЛОВА, re.I)
_ЯВЛЯЕТСЯ = re.compile(r"\bявля(ется|ются)\b", re.I)


def найти(текст: str) -> list[str]:
    """Названия найденных следов, без повторов, в порядке каталога."""
    текст = текст or ""
    беды = [имя for шаблон, имя in _ЗАПРЕТЫ if шаблон.search(текст)]
    беды = list(dict.fromkeys(беды))
    # «Является» не запрет само по себе: скил ругается на него, когда оно
    # тиком, а в коротком посте второе уже тик.
    сколько = len(_ЯВЛЯЕТСЯ.findall(текст))
    if сколько > 1:
        беды.append(f"«является» ×{сколько}")
    for абзац in re.split(r"\n\s*\n", текст):
        слова = [м.group(0).lower() for м in _СТОП.finditer(абзац)]
        if len(слова) >= СТОП_ПАЧКА:
            беды.append("слова нейросети пачкой: " + ", ".join(dict.fromkeys(слова)))
            break
    return беды
