# -*- coding: utf-8 -*-
"""Разметка постов: из привычных звёздочек в HTML телеграма.

Почему не отдавать телеграму Markdown как есть: в его старом режиме `Markdown`
жирный пишется одной звёздочкой, двойная пропадает вместе с текстом, а цитаты
`>` не поддерживаются вовсе. Проверено запросом к API: `**жирный**` вернулся
вообще без разметки. Режим MarkdownV2 чинит это ценой экранирования полутора
десятков символов, и любая точка в тексте роняет отправку с ошибкой.

Поэтому автор пишет как удобно (звёздочки, подчёркивания, `>`), а перед
отправкой текст переводится в HTML: экранируются только три символа, и
сломаться нечему.
"""

import html as _html
import re

ТИРЕ = "—–−"          # длинное, среднее, минус


def без_тире(текст: str) -> str:
    """Убирает тире как знак препинания, оставляя дефис внутри слов.

    «Кто-то» и «во-первых» трогать нельзя, а вот пауза тире посреди фразы
    выдаёт машинный текст сильнее любого другого признака.
    """
    if not текст:
        return текст
    строки = []
    for строка in текст.split("\n"):
        # тире в начале строки почти всегда маркер списка
        строка = re.sub(rf"^(\s*)[{ТИРЕ}-]\s+", r"\1• ", строка)
        # тире между словами заменяем запятой: в русском оно обычно её и заменяет
        строка = re.sub(rf"\s+[{ТИРЕ}]\s+|\s+-{{1,2}}\s+", ", ", строка)
        строка = re.sub(r",\s*,", ",", строка)
        строка = re.sub(r"([,:;])\s*,", r"\1", строка)
        строки.append(строка)
    return "\n".join(строки)


def жирная_первая(текст: str) -> str:
    """Первая непустая строка всегда жирная целиком.

    Если модель слепила заголовок с крючком в один абзац, жирным станет
    вся простыня, и пост начнётся стеной. Поэтому длинную первую строку
    режем по концу первого предложения: заголовком становится оно, остаток
    уезжает в следующий абзац.
    """
    строки = текст.split("\n")
    for i, строка in enumerate(строки):
        if not строка.strip():
            continue
        чисто = строка.strip().replace("**", "").replace("__", "")
        м = re.match(r"^(.{20,90}?)[.!?]\s+(\S.*)$", чисто) if len(чисто) > 90 else None
        if м:
            строки[i:i + 1] = [f"**{м.group(1)}**", "", м.group(2)]
        else:
            строки[i] = f"**{чисто.rstrip('.')}**"
        break
    return "\n".join(строки)


def _цитаты(текст: str) -> str:
    """Подряд идущие строки с «>» сливаются в одну цитату."""
    итог, буфер = [], []

    def слить():
        if буфер:
            итог.append("<blockquote>" + "\n".join(буфер) + "</blockquote>")
            буфер.clear()

    for строка in текст.split("\n"):
        м = re.match(r"^\s*&gt;\s?(.*)$", строка)
        if м:
            буфер.append(м.group(1))
        else:
            слить()
            итог.append(строка)
    слить()
    return "\n".join(итог)


def _в_адрес(адрес: str) -> str:
    """Гасит кавычки в адресе, который поедет внутрь href.

    Общий escape тут не годится: к этому месту текст уже прошёл его один раз,
    и второй превратил бы «&» в «&amp;amp;», разломав ссылки с параметрами.
    А вот кавычки первый проход пропускает нарочно (quote=False), и в теле
    поста это безобидно — но не в атрибуте: кавычка закрывает href, и дальше
    пишется что угодно, вплоть до обработчика события. Текст поста сочиняет
    модель и правит человек, так что доверять ему нельзя.
    """
    return адрес.replace('"', "&quot;").replace("'", "&#x27;")


def в_html(текст: str) -> str:
    """Текст автора → HTML для parse_mode=HTML."""
    if not текст:
        return ""

    склад: list[str] = []

    def спрятать(содержимое: str, тег: str) -> str:
        склад.append((тег, содержимое))
        return f"\x00{len(склад) - 1}\x00"

    текст = re.sub(r"```[a-zA-Z]*\n?(.*?)```",
                   lambda м: спрятать(м.group(1), "pre"), текст, flags=re.S)
    текст = re.sub(r"`([^`\n]+)`",
                   lambda м: спрятать(м.group(1), "code"), текст)

    текст = _html.escape(текст, quote=False)
    текст = _цитаты(текст)

    # Адреса убираем с глаз до разбора звёздочек и подчёркиваний. В ссылке
    # вида .../_docs_ подчёркивания это часть пути, а правило курсива видит в
    # них разметку и съедает их вместе с адресом: пост уезжает в никуда.
    текст = re.sub(r"\[([^\]\n]+)\]\((https?://[^)\s]+)\)",
                   lambda м: спрятать(f'<a href="{_в_адрес(м.group(2))}">'
                                      f'{м.group(1)}</a>', "готовое"), текст)
    текст = re.sub(r"https?://[^\s<>\"']+",
                   lambda м: спрятать(м.group(0), "готовое"), текст)
    текст = re.sub(r"\*\*(.+?)\*\*", r"<b>\1</b>", текст, flags=re.S)
    текст = re.sub(r"(?<![\w*])\*([^*\n]+)\*(?![\w*])", r"<b>\1</b>", текст)
    текст = re.sub(r"(?<![\w_])__([^_\n]+)__(?![\w_])", r"<i>\1</i>", текст)
    текст = re.sub(r"(?<![\w_])_([^_\n]+)_(?![\w_])", r"<i>\1</i>", текст)
    текст = re.sub(r"~~(.+?)~~", r"<s>\1</s>", текст, flags=re.S)

    for i, (тег, содержимое) in enumerate(склад):
        if тег == "готовое":          # ссылка, уже экранирована и собрана
            готово = содержимое
        else:
            готово = _html.escape(содержимое, quote=False)
            готово = (f"<pre><code>{готово}</code></pre>" if тег == "pre"
                      else f"<code>{готово}</code>")
        текст = текст.replace(f"\x00{i}\x00", готово)
    return текст


def длина(текст: str) -> int:
    """Сколько символов увидит телеграм: разметка в лимит не входит."""
    голый = re.sub(r"<[^>]+>", "", в_html(текст))
    return len(_html.unescape(голый))


def причесать(текст: str) -> str:
    """Полная подготовка текста поста перед отправкой."""
    return жирная_первая(без_тире(текст)).strip()


def без_разметки(текст: str) -> str:
    """Голый текст: снимает markdown, который площадки показывают как есть.

    Жила в трёх копиях — `carousel`, `crosspost`, `варианты`, — и копии успели
    разойтись: только версия из `варианты` снимала ссылки `[текст](адрес)`,
    остальные оставляли их в подписи целиком. Сведено 21.09.2026, взята полная.
    """
    т = re.sub(r"\*\*(.+?)\*\*", r"\1", текст or "")
    т = re.sub(r"(?<![\w*])[*_](.+?)[*_](?![\w*])", r"\1", т)
    т = re.sub(r"`(.+?)`", r"\1", т)
    т = re.sub(r"\[(.+?)\]\((.+?)\)", r"\1", т)
    return re.sub(r"^\s*>\s?", "", т, flags=re.M).strip()


def отделить_хештеги(текст: str) -> tuple[str, list[str]]:
    """Текст без хештегов и сами хештеги списком."""
    слова = (текст or "").split()
    метки = [с for с in слова if с.startswith("#")]
    тело = " ".join(с for с in слова if not с.startswith("#"))
    return тело.strip(), метки
