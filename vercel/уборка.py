# -*- coding: utf-8 -*-
"""Уборка за собой: и на диске, и в хранилище.

Каждый черновик оставляет след. Карточка отрисовалась, кот отрисовался, потом
пост переписали и отрисовали заново, а старые файлы остались лежать. За месяц
это десятки мегабайт мусора, за год сотни.

Правило простое и осторожное: удаляется только то, на что не ссылается ни один
пост, и только если оно уже полежало. Пауза важна: TikTok забирает картинки
сам и не сразу, а Telegram отдаёт отложенный пост через сутки или через
неделю. Удалить файл, за которым ещё придут, хуже, чем хранить лишнее.
"""

import json
import time
from pathlib import Path

import config
import db
import storage

ПАУЗА = 3 * 86400          # столько файл живёт даже никому не нужный
ПАУЗА_ДИСКА = 86400        # на маке копия нужна меньше: канонический адрес в хранилище


def _имя(ссылка: str) -> str:
    return (ссылка or "").rsplit("/", 1)[-1].split("?")[0]


def _ссылки(значение) -> set[str]:
    """Все имена файлов внутри любой вложенности.

    Раньше карточка разбиралась на один уровень, и картинки, подготовленные
    под площадку, туда не попадали: они лежат глубже, в «варианты». Уборка
    считала их ничьими и через трое суток снесла бы слайды у живого поста.
    Теперь обходим всё дерево целиком.
    """
    найдено: set[str] = set()
    if isinstance(значение, str):
        if "/" in значение or значение.endswith((".png", ".jpg", ".jpeg")):
            найдено.add(_имя(значение))
    elif isinstance(значение, list):
        for э in значение:
            найдено |= _ссылки(э)
    elif isinstance(значение, dict):
        for э in значение.values():
            найдено |= _ссылки(э)
    найдено.discard("")
    return найдено


def занятые() -> set[str]:
    """Имена файлов, на которые ссылается хоть один пост.

    Смотрим во все места сразу: одиночную картинку, слайды карусели и позу
    кота из карточки. Поза нужна, чтобы пост можно было перерисовать, и
    выкидывать её вместе с мусором нельзя.
    """
    нужны: set[str] = set()
    with db.соединение() as c:
        ряды = c.execute("SELECT image_path, images, card FROM posts").fetchall()
    for р in ряды:
        нужны.add(_имя(р["image_path"] or ""))
        for поле in ("images", "card"):
            сырое = р[поле] if поле in р.keys() else None
            if not сырое:
                continue
            try:
                значение = json.loads(сырое)
            except (TypeError, ValueError):
                continue
            нужны |= _ссылки(значение)
    нужны.discard("")
    return нужны


def почистить_хранилище(пауза: int = ПАУЗА, правда: bool = True) -> dict:
    """Выносит из хранилища всё, на что никто не ссылается."""
    if not storage.включено():
        return {"пропущено": "хранилище не настроено"}
    import requests
    нужны = занятые()
    рубеж = time.time() - пауза
    лишние, освободили = [], 0
    смещение = 0
    while True:
        о = requests.post(
            f"{storage.АДРЕС}/storage/v1/object/list/{storage.ВЕДРО}",
            headers=storage._заголовки("application/json"),
            json={"prefix": "", "limit": 1000, "offset": смещение}, timeout=60)
        if not о.ok:
            break
        куски = о.json() or []
        if not куски:
            break
        for э in куски:
            имя = э.get("name") or ""
            if not имя or имя in нужны:
                continue
            когда = э.get("created_at") or ""
            if когда and _в_секунды(когда) > рубеж:
                continue          # слишком свежий, за ним ещё могут прийти
            лишние.append(имя)
            освободили += (э.get("metadata") or {}).get("size", 0)
        if len(куски) < 1000:
            break
        смещение += len(куски)

    if лишние and правда:
        # Supabase принимает список за раз, но не бесконечный.
        for н in range(0, len(лишние), 100):
            requests.delete(f"{storage.АДРЕС}/storage/v1/object/{storage.ВЕДРО}",
                            headers=storage._заголовки("application/json"),
                            json={"prefixes": лишние[н:н + 100]}, timeout=120)
    return {"убрано": len(лишние), "мегабайт": round(освободили / 1048576, 1)}


def _в_секунды(метка: str) -> float:
    from datetime import datetime
    try:
        return datetime.fromisoformat(метка.replace("Z", "+00:00")).timestamp()
    except ValueError:
        return 0.0


def почистить_диск(пауза: int = ПАУЗА_ДИСКА, правда: bool = True) -> dict:
    """Убирает с мака то, что уже лежит в хранилище или никому не нужно.

    На маке файл это черновой оттиск: настоящий адрес карточки в хранилище.
    Поэтому здесь пауза короче, чем там.
    """
    папка = config.ВЫВОД
    if not папка.exists():
        return {"убрано": 0, "мегабайт": 0}
    нужны = занятые()
    в_хранилище = storage.включено()
    рубеж = time.time() - пауза
    убрали, освободили = 0, 0
    for ф in папка.iterdir():
        if not ф.is_file():
            continue
        if ф.stat().st_mtime > рубеж:
            continue
        # Файл, на который ссылается пост, удаляем только если хранилище
        # включено: там лежит настоящая копия. Без хранилища диск это всё,
        # что у нас есть.
        if ф.name in нужны and not в_хранилище:
            continue
        вес = ф.stat().st_size
        if правда:
            try:
                ф.unlink()
            except OSError:
                continue
        убрали += 1
        освободили += вес
    return {"убрано": убрали, "мегабайт": round(освободили / 1048576, 1)}


КОГДА = "cleanup_at"          # когда убирались в прошлый раз
РАЗ_В = 20 * 3600


def пора() -> bool:
    return time.time() - float(db.настройка(КОГДА, 0) or 0) > РАЗ_В


def прибраться(правда: bool = True) -> dict:
    """Полная уборка. Зовётся раз в сутки сама и кнопкой по требованию."""
    итог = {"диск": почистить_диск(правда=правда),
            "хранилище": почистить_хранилище(правда=правда)}
    if правда:
        db.запомнить(КОГДА, time.time())
    return итог
