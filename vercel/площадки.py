# -*- coding: utf-8 -*-
"""Реестр площадок: единственное место, где перечислено, куда мы публикуем.

Раньше площадка была свойством поста: карусель собиралась «для телеграма» или
«для TikTok» и в другое место уже не годилась. Это неудобно и неверно. Пост
это содержимое, а площадка это адрес доставки, и одно содержимое можно
доставить в несколько мест, если под каждое его правильно подготовить.

Подготовка у каждой своя. Телеграм читает квадрат и понимает разметку с
фирменными иконками. TikTok хочет 3:4, не понимает разметку и ждёт хештеги. X
берёт 280 символов и четыре картинки. Всё это здесь и описано, чтобы
остальной код не гадал.
"""

СПИСОК = {
    "телеграм": {
        "имя": "Телеграм", "значок": "📣", "формат": "квадрат",
        "картинок": 10, "подпись": 1024,
        "поясн": "свои, читают вдумчиво, много каждый день не нужно",
    },
    "tiktok": {
        "имя": "TikTok", "значок": "🎵", "формат": "3к4",
        "картинок": 35, "подпись": 2200,
        # PNG он не принимает вовсе, только JPEG или WebP, и не крупнее 1080p.
        # Мы рисуем в полуторном масштабе ради резкости, поэтому под TikTok
        # картинку надо и пережать, и ужать.
        "файл": "jpeg", "ширина": 1080,
        "поясн": "холодные, листают ленту, чем больше публикаций, тем лучше",
    },
    "x": {
        "имя": "X", "значок": "𝕏", "формат": "квадрат",
        "картинок": 4, "подпись": 280,
        "поясн": "одна мысль и точка",
    },
    "threads": {
        "имя": "Threads", "значок": "@", "формат": "квадрат",
        "картинок": 20, "подпись": 500,
        "поясн": "спокойный тон, два-три абзаца",
    },
}

ПОРЯДОК = ["телеграм", "tiktok", "x", "threads"]


def имя(куда: str) -> str:
    с = СПИСОК.get(куда, {})
    return f"{с.get('значок', '•')} {с.get('имя', куда)}"


def формат(куда: str) -> str:
    return СПИСОК.get(куда, {}).get("формат", "квадрат")


def файл(куда: str) -> str:
    """В каком виде площадка принимает картинки: png или jpeg."""
    return СПИСОК.get(куда, {}).get("файл", "png")


def ширина(куда: str) -> int:
    """До какой ширины ужимать. Ноль означает «оставить как нарисовано»."""
    return int(СПИСОК.get(куда, {}).get("ширина", 0))


def предел(куда: str) -> int:
    return СПИСОК.get(куда, {}).get("подпись", 1024)


def картинок(куда: str) -> int:
    return СПИСОК.get(куда, {}).get("картинок", 10)


def готова(куда: str) -> bool:
    """Можно ли туда публиковать прямо сейчас.

    Телеграм готов всегда: бот в канале и есть по определению. Остальным нужны
    ключи, и без них показывать кнопку незачем.
    """
    if куда == "телеграм":
        return True
    try:
        if куда == "tiktok":
            import tiktok
            # Именно «подключён», а не «настроен»: второе требует секрета
            # приложения, а он лежит только на маке. В облаке пост всё равно
            # не публикуется, там его только показывают, и там площадка
            # выглядела неподключённой, хотя вход давно пройден.
            return tiktok.подключён()
        if куда == "x":
            import x
            return x.настроен()
        if куда == "threads":
            import threads
            return threads.настроен()
    except Exception:                                        # noqa: BLE001
        return False
    return False


def готовые() -> list[str]:
    return [к for к in ПОРЯДОК if готова(к)]
