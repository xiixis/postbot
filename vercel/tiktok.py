# -*- coding: utf-8 -*-
"""Публикация в TikTok.

TikTok устроен строже остальных площадок, и об этом лучше знать заранее.

Первое. Фотопост забирает картинки ТОЛЬКО по ссылке, файлы он не принимает. И
ссылка должна лежать на домене, который вы подтвердили в кабинете TikTok.
Хранилище Supabase не наше, подтвердить его нельзя, поэтому слайды отдаются
через наш же адрес на Vercel, а он подтверждается обычным файлом.

Второе. Пока приложение не прошло проверку TikTok, всё опубликованное видно
только вам самим. Это ограничение их площадки, а не нашего кода.

Третье. Токен доступа живёт сутки, а обновляющий год, и при каждом обновлении
меняется. Поэтому он хранится в настройках, а не в .env: файл на маке и файл
на Vercel разъехались бы в первый же день.
"""

import html as _html
import os
import time

import requests

import db

БАЗА = "https://open.tiktokapis.com/v2"
ТОКЕНЫ = "https://open.tiktokapis.com/v2/oauth/token/"
ВХОД = "https://www.tiktok.com/v2/auth/authorize/"

КЛЮЧ = os.getenv("TIKTOK_CLIENT_KEY", "").strip()
СЕКРЕТ = os.getenv("TIKTOK_CLIENT_SECRET", "").strip()
ВОЗВРАТ = os.getenv("TIKTOK_REDIRECT_URI", "").strip()

ОБНОВЛЯЮЩИЙ = "tiktok_refresh"     # живёт в настройках: он меняется сам
ДОСТУП = "tiktok_access"
ДО = "tiktok_access_until"

ПОДПИСЬ = 2200        # столько символов берёт описание поста
СНИМКОВ = 35          # столько картинок берёт фотопост
ПРАВА = "user.info.basic,video.publish"


class ОшибкаTikTok(RuntimeError):
    pass


def настроен() -> bool:
    """Можно ли отсюда публиковать. Нужны ключи и разовый вход."""
    return bool(КЛЮЧ and СЕКРЕТ and db.настройка(ОБНОВЛЯЮЩИЙ, ""))


def подключён() -> bool:
    """Вошли ли мы в аккаунт вообще.

    Отличается от `настроен` тем, что не требует секрета приложения. Секрет
    лежит только на маке, а знать о подключении нужно и облаку: оно рисует
    экран, но не публикует.
    """
    return bool(db.настройка(ОБНОВЛЯЮЩИЙ, ""))


def профиль() -> dict:
    """Запомненные имя и права. Без обращения к TikTok, только из базы."""
    return db.настройка(ПРОФИЛЬ, {}) or {}


# ── вход и токены ───────────────────────────────────────────────────────────

def ссылка_входа(состояние: str = "postbot") -> str:
    """Адрес, по которому владелец один раз разрешает боту постить."""
    from urllib.parse import urlencode
    return ВХОД + "?" + urlencode({
        "client_key": КЛЮЧ, "scope": ПРАВА, "response_type": "code",
        "redirect_uri": ВОЗВРАТ, "state": состояние})


def _обменять(поля: dict) -> dict:
    о = requests.post(ТОКЕНЫ, data={"client_key": КЛЮЧ,
                                    "client_secret": СЕКРЕТ, **поля},
                      headers={"Content-Type": "application/x-www-form-urlencoded"},
                      timeout=60)
    тело = о.json() if о.content else {}
    если_беда = тело.get("error") or тело.get("error_description")
    if о.status_code >= 300 or если_беда:
        raise ОшибкаTikTok(f"{о.status_code}: {тело.get('error_description') or если_беда}")
    return тело


def _запомнить_токены(тело: dict) -> None:
    db.запомнить(ДОСТУП, тело.get("access_token", ""))
    db.запомнить(ДО, time.time() + int(тело.get("expires_in", 86400)) - 300)
    if тело.get("refresh_token"):
        db.запомнить(ОБНОВЛЯЮЩИЙ, тело["refresh_token"])


def войти(код: str) -> dict:
    """Меняет код из браузера на токены. Делается один раз."""
    тело = _обменять({"code": код, "grant_type": "authorization_code",
                      "redirect_uri": ВОЗВРАТ})
    _запомнить_токены(тело)
    return тело


def токен() -> str:
    """Свежий токен доступа. Обновляется сам, когда протух."""
    если = db.настройка(ДОСТУП, "")
    if если and time.time() < float(db.настройка(ДО, 0) or 0):
        return если
    обновляющий = db.настройка(ОБНОВЛЯЮЩИЙ, "")
    if not обновляющий:
        raise ОшибкаTikTok("бот ещё не входил в TikTok: нужен разовый вход")
    тело = _обменять({"grant_type": "refresh_token", "refresh_token": обновляющий})
    _запомнить_токены(тело)
    return тело.get("access_token", "")


def _голова() -> dict:
    return {"Authorization": f"Bearer {токен()}",
            "Content-Type": "application/json; charset=UTF-8"}


def _ответ(о) -> dict:
    тело = о.json() if о.content else {}
    беда = (тело.get("error") or {})
    код = беда.get("code", "ok")
    if о.status_code >= 300 or код not in ("ok", "", None):
        raise ОшибкаTikTok(f"{код}: {беда.get('message') or о.text[:200]}")
    return тело.get("data") or тело


# ── сведения об авторе ──────────────────────────────────────────────────────

def сведения() -> dict:
    """Кто мы в TikTok и какая видимость нам разрешена.

    TikTok требует спрашивать это перед каждой публикацией: настройки
    приватности автор может поменять в любой момент, и постить, не спросив,
    их правила запрещают.
    """
    return _ответ(requests.post(f"{БАЗА}/post/publish/creator_info/query/",
                                headers=_голова(), timeout=60))


ПРОФИЛЬ = "tiktok_profile"       # кто подключён, чтобы не спрашивать на каждый экран
ПРОФИЛЬ_СРОК = 600


def кто_мы(заново: bool = False) -> dict:
    """Кто подключён и что нам разрешено. Ответ живёт десять минут.

    Спрашивать TikTok на каждое открытие экрана незачем: это лишняя задержка
    и лишний расход лимита, а имя профиля меняется редко.
    """
    свод = db.настройка(ПРОФИЛЬ, {}) or {}
    свежо = time.time() - float(свод.get("когда", 0)) < ПРОФИЛЬ_СРОК
    if свод.get("имя") and свежо and not заново:
        return свод
    кто = сведения()
    свод = {
        "имя": кто.get("creator_nickname") or кто.get("creator_username") or "",
        "ник": кто.get("creator_username") or "",
        "видимость": кто.get("privacy_level_options") or [],
        "когда": time.time(),
    }
    db.запомнить(ПРОФИЛЬ, свод)
    return свод


def песочница() -> bool:
    """Работаем ли мы ключом песочницы. У них узнаваемый префикс."""
    return КЛЮЧ.startswith("sb")


def _видимость(разрешено: list[str]) -> str:
    """Самая открытая из разрешённых.

    Кроме песочницы: непроверенное приложение TikTok пускает только с
    видимостью «только я», и любая другая отбивается отказом. Узнали это на
    живом отказе, в документации формулировка мягче и звучит как ограничение
    на аккаунт, а не на пост.
    """
    if песочница():
        return "SELF_ONLY"
    for з in ("PUBLIC_TO_EVERYONE", "FOLLOWER_OF_CREATOR",
              "MUTUAL_FOLLOW_FRIENDS", "SELF_ONLY"):
        if з in (разрешено or []):
            return з
    return "SELF_ONLY"


# ── свой адрес для картинок ─────────────────────────────────────────────────

def наш_адрес(ссылка: str) -> str:
    """Переписывает ссылку на слайд с Supabase на наш собственный адрес.

    TikTok забирает картинки сам и берёт их только с домена, который вы
    подтвердили в его кабинете. Хранилище Supabase чужое, подтвердить его
    нельзя, зато наш адрес на Vercel подтверждается обычным файлом. Поэтому
    слайд отдаётся через нас, а мы просто пересылаем его из хранилища.
    """
    import config
    основа = (config.АДРЕС_ВЕБА or "").rstrip("/")
    if not основа or not ссылка.startswith("http"):
        return ссылка
    имя = ссылка.rsplit("/", 1)[-1].split("?")[0]
    if not имя:
        return ссылка
    return f"{основа}/api/slide?f={имя}"


# ── публикация ──────────────────────────────────────────────────────────────

def опубликовать(заголовок: str, подпись: str, картинки: list,
                 видимость: str | None = None) -> str:
    """Фотопост из наших слайдов. Возвращает номер публикации.

    Номер не адрес: TikTok собирает пост у себя не мгновенно, и узнать, что
    получилось, можно только отдельным вопросом о состоянии.
    """
    if not настроен():
        raise ОшибкаTikTok("TikTok не подключён: нужны ключи и разовый вход")
    ссылки = [наш_адрес(с) for с in (картинки or [])
              if isinstance(с, str) and с.startswith("http")][:СНИМКОВ]
    if not ссылки:
        raise ОшибкаTikTok("в TikTok нечего публиковать: пост без картинок")

    кто = сведения()
    тело = {
        "post_mode": "DIRECT_POST",
        "media_type": "PHOTO",
        "post_info": {
            "title": (заголовок or "")[:90],
            "description": (подпись or "")[:ПОДПИСЬ],
            # Видимость можно задать явно: первую пробу разумно сделать
            # «только я», чтобы проверить вёрстку и подпись, никого не дёргая.
            "privacy_level": видимость or _видимость(кто.get("privacy_level_options")),
            "disable_comment": bool(кто.get("comment_disabled")),
            "auto_add_music": True,
        },
        "source_info": {"source": "PULL_FROM_URL", "photo_images": ссылки,
                        "photo_cover_index": 0},
    }
    о = _ответ(requests.post(f"{БАЗА}/post/publish/content/init/",
                             headers=_голова(), json=тело, timeout=180))
    номер = о.get("publish_id")
    if not номер:
        raise ОшибкаTikTok("TikTok не вернул номер публикации")
    return str(номер)


def состояние(номер: str) -> dict:
    """Что стало с публикацией: собирается, вышла или отклонена."""
    return _ответ(requests.post(f"{БАЗА}/post/publish/status/fetch/",
                                headers=_голова(),
                                json={"publish_id": номер}, timeout=60))


def дождаться(номер: str, секунд: int = 60) -> str:
    """Ждёт итога публикации, но недолго: висеть в задании незачем."""
    до = time.time() + секунд
    последнее = "PROCESSING"
    while time.time() < до:
        try:
            о = состояние(номер)
        except ОшибкаTikTok:
            break
        последнее = о.get("status", последнее)
        if последнее in ("PUBLISH_COMPLETE", "FAILED"):
            причина = о.get("fail_reason") or ""
            return последнее if not причина else f"{последнее}: {причина}"
        time.sleep(4)
    return последнее


# ── возврат из TikTok ───────────────────────────────────────────────────────
# Страницу после разрешения доступа рисуем сами: TikTok приводит сюда браузер
# и передаёт либо код, либо причину отказа. Причина приходит параметром
# запроса, то есть её пишет не TikTok, а тот, кто прислал ссылку. Домен у этой
# страницы общий с мини-приложением, а в его localStorage лежит ключ доступа,
# и чужой скрипт, выполнившийся здесь, забирает бота целиком. Поэтому всё
# чужое проходит через escape, а сборка живёт здесь, а не на краю: край
# принимает запрос, а что показать человеку — решает общий модуль.

_РУБАШКА = (
    "<meta charset='utf-8'><meta name='viewport' "
    "content='width=device-width,initial-scale=1'><style>"
    "body{{font:16px/1.6 system-ui;max-width:34rem;margin:3rem auto;"
    "padding:0 1rem;background:#12130F;color:#F1F3EA}}"
    "h2{{color:#C7E24B}}pre{{background:#1B1E17;padding:1rem;"
    "border-radius:.5rem;overflow-x:auto}}</style>{нутро}"
)


def нутро_возврата(код: str, беда: str, поставить) -> str:
    """Что показать человеку, вернувшемуся из TikTok.

    Код на токены меняет мак: там лежит секрет приложения, и в облаке ему
    делать нечего. Здесь код только уходит заданием — этим и занимается
    «поставить», отдельным доводом, чтобы страницу можно было проверить, не
    поднимая ни сервера, ни очереди.
    """
    код = (код or "").strip()
    беда = (беда or "").strip()
    if код:
        try:
            поставить(код)
        except Exception as e:                               # noqa: BLE001
            return ("<h2>Код получен, но не сохранился</h2>"
                    f"<pre>{_html.escape(str(e))}</pre>")
        return ("<h2>Готово</h2><p>Аккаунт подключается. Вернитесь в "
                "приложение, через несколько секунд там появится имя "
                "профиля.</p>")
    if беда:
        return f"<h2>TikTok отказал</h2><p>{_html.escape(беда)}</p>"
    return "<h2>Ни кода, ни ошибки</h2>"


def страница_возврата(код: str, беда: str, поставить) -> bytes:
    """Та же страница целиком, готовая к отправке."""
    return _РУБАШКА.format(нутро=нутро_возврата(код, беда, поставить)).encode()
