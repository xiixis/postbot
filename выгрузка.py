# -*- coding: utf-8 -*-
"""Забрать пост файлами: чтобы выложить его руками.

TikTok у нас в ручном режиме, и это не временная мера: приложение постит
надёжнее, чем их API, а карусель там вообще принимается только по ссылкам,
которые нужно откуда-то отдать. Значит, самый частый путь публикации —
человек берёт картинки и подпись и выкладывает их сам с телефона.

Отдаём двумя дорогами сразу, потому что человек бывает то за маком, то нет:
папка открывается на маке, а те же файлы приходят в чат документами, откуда
их достаёт телефон. Документами, а не снимками: телеграм жмёт снимки, а мы
рисовали ровно 1080 и ровно в JPEG, как просит TikTok.
"""

import os
import platform
import re
import shutil
import subprocess
from pathlib import Path

import config
import db
import storage
import telegram as tg
import варианты
import площадки as пл

def _куда_складывать() -> Path:
    """Папка «Посты» на рабочем столе, а если его нет — внутри проекта.

    Забирают файлы, чтобы тут же выложить их руками, и искать их в недрах
    `postbot/data` неудобно: это папка программы, а не человека. Рабочий стол
    ближе всего к рукам, но складывать прямо на него нельзя — после десятка
    выгрузок стол будет состоять из них одних. Поэтому одна папка «Посты», а
    внутри по папке на пост.

    Путь можно задать своим через ВЫГРУЗКА_ПАПКА в .env: у сервера рабочего
    стола нет вовсе.
    """
    return config.папка_постов()


ПАПКА = _куда_складывать()


def _имя_папки(ид: int, заголовок: str, куда: str) -> str:
    """Имя, по которому папку узнают в Finder через неделю."""
    чисто = re.sub(r"[^\w\s-]", "", заголовок or "", flags=re.U).strip()
    чисто = re.sub(r"\s+", "-", чисто)[:40].strip("-")
    return f"{ид}-{куда}-{чисто}" if чисто else f"{ид}-{куда}"


def _убрать_прежние(ид: int, куда: str) -> None:
    """Убирает папки этого же поста на этой же площадке.

    Имя папки содержит заголовок. Сменили заголовок правкой — сменилось и имя,
    и прежняя папка осталась бы рядом со старыми слайдами: две папки одного
    поста, и какую выкладывать, уже не понять. Чужие посты не трогаем: имя
    поста 8 начинается с «8-tiktok-», а не с «88-tiktok-».
    """
    if not ПАПКА.is_dir():
        return
    своё = f"{ид}-{куда}"
    for п in ПАПКА.iterdir():
        if п.is_dir() and (п.name == своё or п.name.startswith(своё + "-")):
            shutil.rmtree(п, ignore_errors=True)


def сразу(ид: int) -> list[Path]:
    """Складывает готовый пост в папку — для площадок, где выкладывает человек.

    Раньше папку собирала кнопка «Забрать»: пост готов, а файлов на столе нет,
    пока их не попросишь. Шаг «нажми, чтобы получить уже готовое» ничего не
    добавлял и забывался — так пост 88 ушёл в TikTok без папки, и её пришлось
    восстанавливать задним числом.

    Только ручные площадки: телеграм публикует бот сам, папка для него —
    мусор на столе. Молча: Finder не открывается и в чат ничего не уходит,
    потому что автопилот рисует и ночью. Никогда не падает: папка — удобство,
    а не часть поста.
    """
    ряд = db.взять(ид)
    if not ряд:
        return []
    # Папка на столе означает «готово к выкладке». Карусель с браком кадров
    # готовой не бывает: её сперва перерисовывают. Кнопка «Забрать» при этом
    # работает — если владелец решит, что брак терпим, решение за ним.
    import приёмка
    отчёт = db.карточка(ряд).get("приёмка")
    import publish
    import конвейер
    if not приёмка.годен(отчёт):
        print(f"пост {ид}: папку не собираю, брак кадров — {приёмка.строкой(отчёт)}")
        # Прежняя папка того же поста лежит на столе как «готово» со вчерашними
        # кадрами или текстом. Такая хуже никакой: её легко выложить по ошибке.
        for куда in publish.куда_едет(ряд):
            try:
                if конвейер.настройки(куда).get("режим") == "руками":
                    _убрать_прежние(ид, куда)
            except Exception:                                # noqa: BLE001
                import traceback
                traceback.print_exc()
        return []
    готовые = []
    for куда in publish.куда_едет(ряд):
        try:
            if конвейер.настройки(куда).get("режим") != "руками":
                continue
            готовые.append(собрать(ид, куда)["папка"])
        except Exception:                                    # noqa: BLE001
            import traceback
            traceback.print_exc()
    return готовые


def собрать(ид: int, куда: str = "tiktok") -> dict:
    """Складывает слайды и подпись в папку. Возвращает путь и список файлов."""
    ряд = db.взять(ид)
    if not ряд:
        raise ValueError(f"поста {ид} нет")
    в = варианты.получить(ид, куда)
    ссылки = в.get("images") or []
    if not ссылки:
        raise ValueError("у поста нет картинок")

    папка = ПАПКА / _имя_папки(ид, ряд["title"], куда)
    # Вместе с прежней папкой уходят и те, что остались от старого заголовка.
    _убрать_прежние(ид, куда)
    папка.mkdir(parents=True, exist_ok=True)

    файлы = []
    for н, с in enumerate(ссылки, 1):
        источник = storage.во_временный(с)
        if not источник:
            continue
        # Нумеруем с ведущим нулём: иначе десятый слайд встаёт вторым и в
        # Finder, и в загрузчике TikTok, а порядок в карусели — это смысл.
        цель = папка / f"{н:02d}{Path(источник).suffix or '.jpg'}"
        shutil.copyfile(источник, цель)
        файлы.append(цель)

    подпись = (в.get("body") or "").strip()
    # У TikTok название отдельно от подписи: его вставляют в своё поле.
    название = (в.get("title") or "").strip()
    if название:
        подпись = f"{название}\n\n{подпись}".strip()
    if подпись:
        (папка / "подпись.txt").write_text(подпись + "\n", encoding="utf-8")
    return {"папка": папка, "файлы": файлы, "подпись": подпись,
            "название": название}


def путь_папки(ид: int, куда: str = "tiktok") -> Path | None:
    """Где лежала бы папка этого поста. Существует она или нет — не проверяем.

    Имя складывается из номера, площадки и заголовка, то есть считается
    одинаково в любой момент. Именно поэтому мак может найти папку, собранную
    неделю назад, ничего о ней не запоминая.
    """
    ряд = db.взять(ид)
    if not ряд:
        return None
    return ПАПКА / _имя_папки(ид, ряд["title"], куда)


def открыть(ид: int, куда: str = "tiktok", чат: int | None = None) -> dict:
    """Открыть рабочую папку поста, а если её удалили — собрать заново.

    Пересобрать можно почти всегда: слайды лежат в хранилище, а не только на
    этом маке. Поэтому «папки нет» — это не тупик, а лишние несколько секунд,
    и заканчивать на сообщении об ошибке было бы издевательством: человек
    нажал кнопку, чтобы получить файлы, а не чтобы узнать, что их нет.

    Пустая папка считается отсутствующей: открывать в ней нечего.
    """
    папка = путь_папки(ид, куда)
    if папка is None:
        raise ValueError(f"поста {ид} нет")
    была = папка.is_dir() and any(папка.iterdir())
    if not была:
        итог = собрать(ид, куда)
        папка = итог["папка"]
    открыть_папку(папка)
    if чат:
        tg.написать(чат, (f"📂 Папка на маке: `{папка}`" if была else
                          "📂 Папки не было — её удалили. Собрал заново:\n"
                          f"`{папка}`"))
    return {"была": была, "папка": папка}


def открыть_папку(папка: Path) -> bool:
    """Показывает папку в проводнике системы.

    Раньше умела только мак и на всём остальном молча отвечала «нет». Команды
    `open` нет ни на Windows, ни на линуксе, поэтому каждая система зовётся
    своим способом: os.startfile на Windows, xdg-open на линуксе.
    """
    система = platform.system()
    try:
        if система == "Darwin":
            subprocess.run(["open", str(папка)], check=False, timeout=10)
        elif система == "Windows":
            os.startfile(str(папка))                         # noqa: S606
        else:
            subprocess.run(["xdg-open", str(папка)], check=False, timeout=10)
        return True
    except Exception:                                        # noqa: BLE001
        return False


def в_чат(чат: int, итог: dict, заголовок: str, куда: str) -> None:
    """Присылает файлы и подпись отдельными сообщениями.

    Подпись идёт своим сообщением и без разметки: её копируют целиком и
    вставляют в чужое поле, а звёздочки разметки туда попадать не должны.
    """
    файлы = итог["файлы"]
    if файлы:
        tg.документы(чат, файлы,
                     f"📥 {пл.имя(куда)}: {len(файлы)} слайдов, по порядку")
    if итог["подпись"]:
        tg.написать(чат, итог["подпись"], разметка="")
    tg.написать(чат, f"📂 Папка на маке: `{итог['папка']}`")


def забрать(ид: int, куда: str = "tiktok", чат: int | None = None,
            файлами: bool = False) -> int:
    """Собрать папку, открыть её и — если попросили — прислать файлы в чат.

    Отправка отделена от сборки нарочно. Папка собирается за доли секунды:
    карточки лежат на этом же маке, и это просто копирование. А двенадцать
    документов уходят в телеграм по одному, и именно они делали ту самую
    минуту ожидания — при том, что человеку за маком они не нужны вовсе.
    Кто выкладывает с телефона, тот жмёт «прислать в чат» отдельно.
    """
    итог = собрать(ид, куда)
    открыть_папку(итог["папка"])
    ряд = db.взять(ид)
    if чат and файлами:
        в_чат(чат, итог, ряд["title"] if ряд else "", куда)
    elif чат:
        # Без файлов, но с подписью: её всё равно копируют руками, а ждать
        # ради неё загрузку картинок незачем.
        if итог["подпись"]:
            tg.написать(чат, итог["подпись"], разметка="")
        tg.написать(чат, f"📂 {len(итог['файлы'])} слайдов по порядку в папке:\n"
                         f"`{итог['папка']}`")
    return ид
