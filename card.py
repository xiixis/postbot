def _строк_выйдет(текст: str, кегль: int, ширина_набора: int) -> int:
    """Сколько строк займёт текст при этом кегле. Считаем как браузер.

    Раньше здесь было деление общей длины на ширину строки — будто текст
    сплошной поток. Слова так не переносятся, и на этом всё и ломалось:
    «Одна строка,» это 948 px при мере 920, значит «Одна» остаётся в строке
    одна, а заголовок из тридцати четырёх знаков разъезжается на пять строк
    вместо расчётных трёх и садится коту на голову.

    Считаем жадной укладкой: слово влезает в текущую строку — кладём туда,
    не влезает — начинаем новую. Ровно так делает браузер, и никакого
    браузера для этого звать не нужно.
    """
    слова = (текст or "").split()
    if not слова:
        return 0
    строк, набрано = 1, 0.0
    for слово in слова:
        ширина_слова = len(слово) * кегль * ШИРИНА_ЗНАКА
        пробел = кегль * ШИРИНА_ЗНАКА if набрано else 0.0
        if набрано + пробел + ширина_слова <= ширина_набора:
            набрано += пробел + ширина_слова
        else:
            строк += 1
            набрано = ширина_слова
    return строк


def _кегль_по_длине(длина, кегли: tuple, ширина_набора: int,
                    строк: int = 2) -> int:
    """Самый крупный кегль, при котором заголовок укладывается в `строк` строк.

    Первым доводом принимается сам текст: только по нему видно, где встанут
    переносы. Число оставлено ради старых вызовов — тогда работает прежняя
    прикидка по длине, но она годится лишь там, где слова короткие.
    """
    текст = длина if isinstance(длина, str) else None
    for к in кегли:
        if текст is not None:
            if _строк_выйдет(текст, к, ширина_набора) <= строк:
                return к
        elif длина <= (ширина_набора / (к * ШИРИНА_ЗНАКА)) * строк:
            return к
    return кегли[-1]


def слайд_обложка(надпись: str, заголовок: str, поза, номер: int, всего: int,
                  формат: str = "квадрат"):
    """Первый слайд: цепляет и заставляет листнуть."""
    д = _общее(номер, всего, формат)
    длина = " ".join((заголовок or "").split())
    # Обложке позволительны три строки: под ней нет ни черты, ни мысли.
    кегль = _кегль_по_длине(длина, д["обложка_кегли"],
                            д["ширина"] - 2 * д["поле_бок"], строк=3)
    # Путь обязан быть полным: file:// от относительного браузер молча не
    # откроет, и вместо кота останется пустое место.
    есть_кот = bool(поза and Path(поза).exists())
    # Кот стоит по центру там, где формат так велит, и тогда его надо поднять
    # над нижним полем и сдвинуть на половину собственной ширины. Определяем
    # это по самому формату, а не по его имени: имён со временем станет больше.
    по_центру = д["кот_лево"] == "50%"
    # Над зоной площадки кот поднимается в любом случае, а не только когда
    # стоит по центру. На вертикали TikTok закрывает подписью нижние 320 px, и
    # кот, поставленный «в самый низ», уходил прямо под интерфейс: замер это
    # видел и убирал его совсем — вместо кота получалось пустое место.
    д = {**д, "низ_кота": max(д["поле_низ"] - 40, 0),
         "сдвиг_кота": "translateX(-50%)" if по_центру else "none"}

    def собрать(с_котом: bool) -> str:
        кот = (f'<div class="кот"><img src="file://{Path(поза).resolve()}"></div>'
               if с_котом else "")
        нутро = (f'<div class="над">{html.escape(_обрезать(надпись, 40))}</div>'
                 f'<h1>{_текст(заголовок, 60)}</h1>'
                 f'<div class="листай">Листайте →</div>{кот}')
        return СЛАЙД.format(**д, ещё=ОБЛОЖКА_ЕЩЁ.format(**д, кегль=кегль),
                            нутро=нутро)

    страница = собрать(есть_кот)
    # Проверки тут не было вовсе: считалось, что на обложке короткий заголовок
    # и коту всегда хватит места. С крупным кеглем это перестало быть правдой —
    # заголовок в четыре строки дотягивается до кота, и тот садится прямо на
    # букву. Молча: рисовальщик слайдов такое ловит, а обложка шла мимо.
    if есть_кот:
        беды = проверить_композицию(_замерить(страница, д["ширина"], д["высота"]),
                                    формат)
        if беды:
            print(f"обложка: {'; '.join(беды)} — рисую без кота")
            страница = собрать(False)
    return _снять(страница, д["ширина"], д["высота"])


def слайд(заголовок: str, мысль: str, цифра: str, номер: int, всего: int,
          формат: str = "квадрат"):
    """Середина: одна мысль, при желании с крупным значением."""
    д = _общее(номер, всего, формат)
    длина = len(" ".join((заголовок or "").split()))
    кегль = _кегль_по_длине(длина, д["шапка_кегли"],
                            д["ширина"] - 2 * д["поле_бок"], строк=2)
    метка = (f'<div class="цифра">{html.escape(_обрезать(цифра, 12))}</div>'
             if (цифра or "").strip() else '<div class="черта"></div>')
    куски = [f'<div class="стек"><div class="шапка">{_текст(заголовок, 52)}</div>'
             f'{метка}<div class="мысль">'
             f'{_подсветить(_текст(мысль, 150), блоком=True)}</div></div>']
    страница = СЛАЙД.format(**д, ещё=СЛАЙД_ЕЩЁ.format(**д, кегль=кегль),
                            нутро="".join(куски))
    # Кота здесь нет, а вот текст уехать за нижний край может: на крупном
    # кегле длинная мысль перестаёт помещаться. Двигать тут нечего, поэтому
    # только предупреждаем — но не молчим, как раньше.
    беды = проверить_композицию(_замерить(страница, д["ширина"], д["высота"]),
                                формат)
    if беды:
        print(f"слайд: {'; '.join(беды)} — сократите текст")
    return _снять(страница, д["ширина"], д["высота"])


def слайд_финал(вывод: str, номер: int, всего: int,
                формат: str = "квадрат", призыв: str = "", поза=None):
    """Последний: одна фраза, к которой всё вело, и что делать дальше.

    Призыв стоит именно здесь, а не на каждом слайде: до последнего долистали
    те, кому понравилось, и просить их о чём-то не грубость, а следующий шаг.
    На обложке та же просьба выглядела бы как плата за вход.

    Говорит его кот. Строкой внизу слайда просьба читалась как строчка мелкого
    шрифта в договоре: её видно, но она ничья и её пропускают. В облачке у
    кота это уже чья-то реплика, а на неё смотрят — тем более что весь пост
    зритель листал вместе с ним. Если позы нет, остаётся прежняя строка:
    просьба важнее, чем то, кто её произносит.
    """
    д = _общее(номер, всего, формат)
    # Кегль призыва снижен с 0.98 до 0.86 от «мысли»: на плашке он стал
    # заметнее сам по себе, и в прежнем размере лайм занимал 9% кадра
    # вместо положенных 4–6.
    д["призыв"] = round(д["мысль"] * 0.86)
    д["призыв_низ"] = д["низ_знака"] + 78
    # Тот же отступ от низа, но для плашки в потоке: снизу у body уже есть
    # своё поле, и его надо вычесть, иначе призыв уедет выше логотипа.
    д["призыв_отступ_низ"] = max(0, д["призыв_низ"] - д["поле_низ"])
    д["призыв_отступ"] = round(д["поле_бок"] * 0.35)
    # Поля плашки с призывом. По кругу в треть бокового поля акцент
    # занимал 11% кадра при норме 4–6%, а выше 8% он перестаёт быть
    # акцентом и превращается во второй фон.
    д["призыв_поле"] = round(д["поле_бок"] * 0.10)
    д["призыв_бок"] = round(д["поле_бок"] * 0.16)
    зов = (призыв or "").strip()
    точка_и_вывод = (f'<div class="точка">Итог</div>'
                     f'<div class="вывод">{_текст(вывод, 110)}</div>')

    if зов and поза and Path(поза).exists():
        # Рост кота подбираем, а не назначаем: вывод бывает и в две строки, и
        # в пять, и облачко над котом упирается в него снизу. Начинаем с
        # крупного и уменьшаем, пока замер не скажет, что все разошлись.
        for доля in (0.30, 0.26, 0.22):
            слой, стили_кота = _кот("рядом", поза, д, "средний", зов,
                                    round(д["высота"] * доля),
                                    д["низ_знака"] + 62, в_колонке=True)
            # Вывод встаёт не «в самый верх», а под надпись «Итог»: она лежит
            # absolute, в потоке места не занимает, и вывод наезжал на неё.
            шире = (f'.вывод{{margin-top:{round(д["точка"] * 3.4)}px;'
                    f'margin-bottom:auto;max-width:11ch}}'
                    # Облачко на финале шире обычного: там не короткая шутка на
                    # полях, а целая просьба, и в узкий пузырь она ложится
                    # лесенкой по два слова.
                    f'.реплика-кота{{max-width:{round(д["ширина"] * 0.62)}px;'
                    f'font-size:{round(д["мысль"] * 0.86)}px}}')
            страница = СЛАЙД.format(**д, ещё=ФИНАЛ_ЕЩЁ.format(**д) + стили_кота + шире,
                                    нутро=слой + точка_и_вывод)
            if not проверить_композицию(_замерить(страница, д["ширина"], д["высота"]),
                                        формат):
                return _снять(страница, д["ширина"], д["высота"])
        print("композиция «финал»: кот с призывом не поместился, оставляю строку")

    нутро = точка_и_вывод + (f'<div class="призыв">{_текст(зов, 90)}</div>'
                             if зов else "")
    # Запасной путь раньше снимал кадр вслепую: проверки здесь не было вовсе,
    # и обрезанное слово уходило в карусель молча — именно так вышли три
    # карусели 9 сентября. Теперь замеряем, и если не сходится, уменьшаем
    # кегль вывода ступенями. Приём не новый: тем же способом выше
    # подбирается рост кота — пробуем, меряем, убавляем.
    #
    # Ниже 0.64 не опускаемся. От 190 px это 122 px, и крупная строка ещё
    # держит иерархию к призыву; дальше кадр перестаёт читаться с расстояния
    # ленты, а это хуже, чем перенос.
    полный = д["вывод"]
    страница = беды = None
    for доля in (1.0, 0.86, 0.74, 0.64):
        д["вывод"] = round(полный * доля)
        страница = СЛАЙД.format(**д, ещё=ФИНАЛ_ЕЩЁ.format(**д), нутро=нутро)
        беды = проверить_композицию(
            _замерить(страница, д["ширина"], д["высота"]), формат)
        if not беды:
            if доля < 1.0:
                print(f"композиция «финал»: вывод уменьшен до {round(доля * 100)}%")
            return _снять(страница, д["ширина"], д["высота"])
    print(f"композиция «финал»: {'; '.join(беды)} — не сошлось и на 64%")
    return _снять(страница, д["ширина"], д["высота"])


