def подобрать(ход=lambda что: None, момент: datetime | None = None) -> dict:
    """Читает чаты за окно, выбирает сообщения и придумывает по три ответа."""
    с = настройки()
    граница = порог(момент or с["с"])
    видели = set(_показанные())
    ход("читаю")
    чаты = asyncio.run(_обход(с["папка"], с["чаты"], граница, видели))
    итог = {"чатов": len(чаты),
            "сообщений": sum(ч["прочитано"] for ч in чаты),
            "годных": sum(len(ч["годные"]) for ч in чаты),
            "окно": подпись_окна(момент or с["с"]),
            "урезали": False,
            "упёрлись": any(ч["упёрлись"] for ч in чаты),
            "находки": []}
    лента, карта, итог["урезали"] = _лента(чаты)
    итог["символов"] = len(лента)
    if not карта:
        return итог

    ход("выбираю")
    # Отбор идёт по готовому перечню признаков, размышлять тут не над чем, а
    # ждать владельцу. Поэтому усердие низкое: разница в выборе на глаз не
    # видна, разница во времени в разы.
    отбор = _спросить(config.МОДЕЛЬ_РАЗБОРА,
                      ОТБОР.format(окно=итог["окно"], сколько=с["сколько"],
                                   лента=лента),
                      Отбор, усердие="low")
    выбраны = [(п, карта[п.n]) for п in отбор.picks[:с["сколько"]] if п.n in карта]
    if not выбраны:
        return итог

    ход("пишу")
    куски = [f"#{п.n} (почему выбрано: {п.why})\n{_окружение(чат, з)}"
             for п, (чат, з) in выбраны]
    ответы = _спросить(config.МОДЕЛЬ,
                       ВАРИАНТЫ.format(выбранное="\n\n".join(куски)),
                       Ответы, добавка=_факты())
    по_номеру = {т.n: т.variants for т in ответы.answers}

    for п, (чат, з) in выбраны:
        варианты = [" ".join(в.split()) for в in по_номеру.get(п.n, []) if в.strip()]
        if not варианты:
            continue
        итог["находки"].append({
            "чат": чат["имя"], "чат_номер": чат["номер"], "ид": з["ид"],
            "кто": з["кто"], "когда": _время(з["когда"]),
            "текст": з["текст"], "ссылка": _ссылка(чат, з["ид"]),
            "почему": п.why, "варианты": варианты[:3],
        })
    # Показанное запоминаем сразу: следующее нажатие должно дать другое.
    запомнить_показанные(итог["находки"])
    return итог


def оформить(находка: dict) -> str:
    """Одна находка сообщением в чат.

    Варианты идут в обратных кавычках: телеграм рисует их моноширинным блоком,
    который копируется одним касанием. Разметку из чужого текста вычищаем,
    иначе одна звёздочка в чужом сообщении съест половину нашего.
    """
    def чисто(строка: str) -> str:
        return строка.replace("`", "'").replace("*", "").replace("_", "")

    цитата = "\n".join(f"> {с}" for с in чисто(находка["текст"]).split("\n"))
    варианты = "\n\n".join(f"{i}. `{чисто(в)}`"
                           for i, в in enumerate(находка["варианты"], 1))
    return (f"💬 *{чисто(находка['чат'])}* · {чисто(находка['кто'])} · "
            f"{находка['когда']}\n"
            f"{цитата}\n\n"
            f"__{чисто(находка['почему'])}__\n"
            f"[Открыть в чате]({находка['ссылка']})\n\n"
            f"{варианты}")
