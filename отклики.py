def запомнить_показанные(находки: list[dict]) -> None:
    """Больше не предлагать то, что владелец уже видел.

    Без этого повторное нажатие в том же окне возвращает те же три сообщения:
    переписка не изменилась, значит и выбор модели не изменится. С памятью
    второе нажатие даёт следующие по силе, и кнопку можно жать, пока не
    кончится стоящее.
    """
    было = _показанные()
    новые = [f"{н['чат_номер']}:{н['ид']}" for н in находки]
    db.запомнить("отклики.показанные", (было + новые)[-ПАМЯТЬ:])


