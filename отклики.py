def _время(когда: datetime) -> str:
    return когда.astimezone(times.ЗОНА).strftime("%d.%m %H:%M")


def _лента(чаты: list[dict]) -> tuple[str, dict, bool]:
    """Переписка простынёй + карта «номер в списке → сообщение».

    В ленту идёт НЕ всё подряд и не куски чата вокруг кандидата, а сам
    кандидат и его ветка: то, на что он отвечает, и прямые ответы на него.
    Ветка это ровно тот контекст, ради которого сюда вообще что-то добавляют:
    по ней видно, ответили человеку или нет, а лезть вторым в закрытый вопрос
    хуже, чем промолчать. Соседи по времени этого не показывают, зато тянут за
    собой почти весь чат: на живых данных они занимали треть окна и не
    добавляли к решению ничего.

    Одно сообщение следом всё же берём: в чатах отвечают и без кнопки
    «ответить», просто следующей строкой, и связь такого ответа видна только
    по порядку. Разрывы помечаем многоточием, чтобы модель не считала
    соседние по строке реплики соседними по времени.

    Номер получают только кандидаты: выбрать модель может лишь то, что мы
    готовы показать владельцу.
    """
    пары = [(ч, з) for ч in чаты for з in ч["годные"]]
    урезали = len(пары) > ПОТОЛОК
    # Очередь по весу, а при равном весе по свежести: если окно широкое и всё
    # не влезает, отваливается слабое и старое, а не случайное.
    отобранные = sorted(пары, key=lambda п: (п[1]["вес"], п[1]["когда"]),
                        reverse=True)[:ПОТОЛОК]
    доступно = {(ч["номер"], з["ид"]) for ч, з in отобранные}

    карта, куски, н = {}, [], 0
    for чат in чаты:
        лента = чат["лента"]
        место = {з["ид"]: i for i, з in enumerate(лента)}
        дети = {}
        for з in лента:
            if з["на"]:
                дети.setdefault(з["на"], []).append(з)

        нужные = set()
        for i, з in enumerate(лента):
            if (чат["номер"], з["ид"]) not in доступно:
                continue
            нужные.add(i)
            if з["на"] in место:                 # реплика, на которую отвечают
                нужные.add(место[з["на"]])
            for ответ in дети.get(з["ид"], [])[:ОТВЕТОВ]:
                нужные.add(место[ответ["ид"]])
            if i + 1 < len(лента):               # ответ без кнопки «ответить»
                нужные.add(i + 1)
        if not нужные:
            continue

        строки, прошлый = [], None
        for i in sorted(нужные):
            if прошлый is not None and i > прошлый + 1:
                строки.append("   …")
            прошлый = i
            з = лента[i]
            метка = ""
            if (чат["номер"], з["ид"]) in доступно:
                н += 1
                карта[н] = (чат, з)
                метка = f"#{н} "
            строки.append(f"{метка}{_время(з['когда'])} {з['кто']}: {з['текст']}")
        куски.append(f"── чат «{чат['имя']}» ──\n" + "\n".join(строки))
    return "\n\n".join(куски), карта, урезали


def _окружение(чат: dict, запись: dict) -> str:
    """Сообщение с соседями: без них не видно, о чём вообще речь."""
    лента = чат["лента"]
    место = next((i for i, з in enumerate(лента) if з["ид"] == запись["ид"]), 0)
    рядом = лента[max(0, место - ОКРУЖЕНИЕ):место + ОКРУЖЕНИЕ // 2 + 1]
    строки = [("→ " if з["ид"] == запись["ид"] else "  ")
              + f"{_время(з['когда'])} {з['кто']}: {з['текст']}" for з in рядом]
    родитель = next((з for з in лента if з["ид"] == запись["на"]), None)
    если_ответ = (f"  (это ответ на: {родитель['кто']}: {родитель['текст'][:200]})\n"
                  if родитель else "")
    return (f"── чат «{чат['имя']}» ──\n" + если_ответ + "\n".join(строки))


