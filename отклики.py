# ── чтение чатов ────────────────────────────────────────────────────────────

async def _папки(клиент) -> list[dict]:
    from telethon.tl.functions.messages import GetDialogFiltersRequest
    ответ = await клиент(GetDialogFiltersRequest())
    итог = []
    for ф in getattr(ответ, "filters", ответ) or []:
        имя = getattr(ф, "title", None)
        # В новых слоях протокола заголовок папки это объект с текстом внутри,
        # в старых просто строка. Поддерживаем оба, иначе папка «пропадёт».
        имя = getattr(имя, "text", имя)
        куда = getattr(ф, "include_peers", None)
        if имя and куда is not None:
            итог.append({"ид": getattr(ф, "id", 0), "имя": имя,
                         "чатов": len(куда), "куда": list(куда)})
    return итог


def папки() -> list[dict]:
    """Папки чатов, как их видит сам Telegram."""
    async def сделать():
        async with userbot._клиент() as k:
            return [{к: з for к, з in ф.items() if к != "куда"}
                    for ф in await _папки(k)]
    return asyncio.run(сделать())


def _кто(сообщение) -> str:
    автор = getattr(сообщение, "sender", None)
    if автор is None:
        return "кто-то"
    имя = " ".join(filter(None, [getattr(автор, "first_name", None),
                                 getattr(автор, "last_name", None)])).strip()
    return (имя or getattr(автор, "username", None)
            or getattr(автор, "title", None) or "кто-то")


def _ссылка(чат: dict, номер: int) -> str:
    if чат["псевдоним"]:
        return f"https://t.me/{чат['псевдоним']}/{номер}"
    return f"https://t.me/c/{чат['номер']}/{номер}"


def _ключ(текст: str) -> str:
    """Огрублённый текст для поиска повторов: регистр и знаки не в счёт."""
    return re.sub(r"[^\w\s]", "", текст.lower()).strip()


def _мусор(текст: str) -> bool:
    """Отвечать не на что. Проверки идут до модели и стоят ноль.

    Живой чат на три четверти состоит из «ага», «+», «спасибо», смайликов и
    репостов ссылками. В ленту они попадали наравне с вопросами и съедали
    больше половины окна, которое мы отдаём модели. Разобрать их может и
    регулярка, а токенов они стоили как настоящие сообщения.
    """
    if len(текст) < КОРОТКОЕ:
        return True
    if not БУКВА.search(текст):            # одни смайлики, знаки или цифры
        return True
    if ПУСТАЯ.match(текст):                # голая ссылка, упоминание, хештег
        return True
    return len(текст.split()) < СЛОВ


def _вес(запись: dict, отвечали: set) -> int:
    """Насколько похоже, что тут есть на что ответить. Считается без модели.

    Кандидатов в живом чате всё равно остаются сотни, и половина из них это
    утверждения, которые никто не подхватил. Отвечать на такое некуда: разговор
    не начат, вопроса нет, темы нет. Поэтому перед моделью выстраиваем очередь
    по пяти дешёвым признакам и берём голову.

    Ноль признаков означает «отвечать не на что», и такие в ленту не попадают
    вовсе: на живых чатах это треть всего объёма и ни одного стоящего повода.
    """
    текст = запись["текст"]
    вес = 0
    if "?" in текст:
        вес += 3
    if ВОПРОСОМ.match(текст):
        вес += 2
    if запись["ид"] in отвечали:        # разговор вокруг сообщения уже завязался
        вес += 2
    if len(текст) > 120:                # развёрнутая мысль, а не реплика
        вес += 1
    if ПО_ТЕМЕ.search(текст):
        вес += 1
    return вес


def _бот(сообщение) -> bool:
    автор = getattr(сообщение, "sender", None)
    return bool(getattr(автор, "bot", False))


async def _прочитать(клиент, сущность, порог: datetime, я: int,
                     видели: set) -> dict:
    """Один чат за окно.

    Возвращаем и все сообщения, и отобранных кандидатов. Все нужны для
    связности: без соседних реплик не понять, ответили человеку или нет, а
    отвечать вторым на уже закрытый вопрос это худшее, что можно написать
    в чате.
    """
    чат = {
        "имя": (getattr(сущность, "title", None)
                or getattr(сущность, "username", None) or str(сущность.id)),
        "псевдоним": getattr(сущность, "username", None),
        "номер": сущность.id,
        "лента": [], "годные": [], "прочитано": 0, "упёрлись": False,
    }
    свежие, мои_ответы, повторы = [], set(), set()
    прочитано = 0
    async for м in клиент.iter_messages(сущность, limit=ПОТОЛОК_ЧАТА):
        if м.date < порог:
            break
        прочитано += 1
        текст = " ".join((м.message or "").split())
        if not текст:
            continue
        свой = м.sender_id == я
        родитель = getattr(getattr(м, "reply_to", None), "reply_to_msg_id", None)
        if свой and родитель:
            мои_ответы.add(родитель)
        # Отсев считаем здесь же, а не потом: чтобы решить «годен ли», нужен
        # сам объект сообщения (бот ли автор), а дальше его уже не будет.
        негоден = свой or _бот(м) or _мусор(текст)
        ключ = _ключ(текст)
        if not негоден and ключ in повторы:      # то же самое уже писали выше
            негоден = True
        повторы.add(ключ)
        свежие.append({"ид": м.id, "кто": "я" if свой else _кто(м), "свой": свой,
                       "текст": текст[:ДЛИНА], "когда": м.date, "на": родитель,
                       "негоден": негоден})

    # Упёрлись в потолок, не дойдя до начала окна: значит показали не всё.
    чат["упёрлись"] = прочитано >= ПОТОЛОК_ЧАТА
    чат["прочитано"] = прочитано
    чат["лента"] = list(reversed(свежие))          # от старых к новым
    отвечали = {з["на"] for з in чат["лента"] if з["на"]}
    годные = []
    for з in чат["лента"]:
        if (з["негоден"] or з["ид"] in мои_ответы
                or f"{чат['номер']}:{з['ид']}" in видели):
            continue
        з["вес"] = _вес(з, отвечали)
        if з["вес"]:
            годные.append(з)
    чат["годные"] = годные
    return чат


async def _обход(папка: str, чаты: list, граница: datetime,
                 видели: set) -> list[dict]:
    async with userbot._клиент() as k:
        я = (await k.get_me()).id
        адресаты = []
        if папка:
            найдена = next((ф for ф in await _папки(k)
                            if ф["имя"].strip().lower() == папка.strip().lower()),
                           None)
            if not найдена:
                raise ValueError(f"папки «{папка}» в Telegram нет")
            адресаты += найдена["куда"]
        адресаты += list(чаты)

        собрано, уже = [], set()
        for куда in адресаты:
            сущность = await k.get_entity(куда)
            if сущность.id in уже:
                continue
            уже.add(сущность.id)
            собрано.append(await _прочитать(k, сущность, граница, я, видели))
        return собрано


