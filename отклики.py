# -*- coding: utf-8 -*-
"""«Что ответить»: читает чужие чаты за три дня и предлагает варианты ответа.

Зачем это нужно. В тематических чатах владельца знают по тому, что он там
пишет, а не по каналу. Но прочитать три чата по тысяче сообщений за три дня
руками невозможно: хороший вопрос уезжает вверх за час и больше не всплывает.
Поэтому чаты читает бот, а владелец получает короткий список «вот на это
стоит ответить» и по три готовых варианта на каждое.

Ничего никуда не отправляется. Бот только показывает. Ответ в чужом чате это
разговор, и вести его должен человек: отправленное ботом неудачное слово
чинится не кнопкой «отменить», а репутацией. Варианты приходят в блоках,
которые в телеграме копируются одним касанием.

Голос здесь не тот, что в постах, и writer.ГОЛОС сюда не берётся намеренно.
В канале владелец рассказывает, в чате разговаривает: короче, без структуры,
без заголовков и без единого упоминания своего канала.

Два прохода, а не один. Первый читает всю переписку и решает, на что вообще
стоит отвечать: работа механическая, ей хватает модели попроще. Второй видит
только отобранное с его окружением и занимается тем, как это звучит. Гонять
полторы тысячи чужих сообщений через дорогую модель незачем, а писать ответы
дешёвой значит получить вежливую пустоту.
"""

import asyncio
import re
from datetime import datetime, timedelta, timezone

from pydantic import BaseModel, Field

import config
import db
import times
import userbot
import агент

ПАПКА = "ChatsYouTube"     # папка Telegram по умолчанию
ДНЕЙ = 3                   # запасное окно, если начало не задано
СКОЛЬКО = 5                # сколько сообщений показываем за раз
КОРОТКОЕ = 25              # символов: короче этого отвечать не на что
СЛОВ = 3                   # слов: «ага», «+1» и «спасибо» отсекаются здесь
ДЛИНА = 300                # до скольких символов режем чужое сообщение
ПОТОЛОК_ЧАТА = 3000        # предохранитель на случай чата-муравейника
ПОТОЛОК = 400              # сколько сообщений максимум уходит в отбор
ОКРУЖЕНИЕ = 4              # соседей вокруг выбранного во втором проходе
ОТВЕТОВ = 3                # прямых ответов на кандидата даём отбору
ПАМЯТЬ = 900               # сколько показанных сообщений помним, чтобы не повторяться

# Есть ли в строке хоть одна буква. Сообщение из одних смайликов, знаков и
# цифр отвечать не на что, а места в ленте занимает столько же.
БУКВА = re.compile(r"[^\W\d_]", re.UNICODE)
# Строка целиком из адресов, упоминаний и хештегов: репост или ссылка без слов.
ПУСТАЯ = re.compile(r"^(?:https?://\S+|t\.me/\S+|@[\w_]+|#[^\s#]+|[\s,;.!?—-])+$")
# Сообщение начинается как вопрос, даже если знак вопроса забыли поставить.
ВОПРОСОМ = re.compile(
    r"^(как|где|что|чем|чё|чо|почему|зачем|кто|сколько|какой|какая|какие|каким|"
    r"можно ли|стоит ли|кто-нибудь|кто нибудь|подскажите|подскажет|посоветуйте|"
    r"а есть|есть ли|не подскажете|реально ли)\b", re.I)
# Тема канала. Не приговор, а один голос из пяти: без темы сообщение ещё может
# пройти по вопросу или по тому, что вокруг него завязался разговор.
ПО_ТЕМЕ = re.compile(
    r"(ютуб|youtube|канал|ролик|видео|монтаж|озвуч|нейросет|нейронк|\bии\b|\bai\b|"
    r"gpt|claude|gemini|midjourney|sora|veo|runway|подпис|просмотр|монетиз|обложк|"
    r"превью|шортс|shorts|промпт|рендер|сценар|доход|заработ|бюджет|реклам|"
    r"алгоритм|ctr|rpm|удержан|трафик|ниш|контент|аватар|липсинк|субтитр|сток)", re.I)


