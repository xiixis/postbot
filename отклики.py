def настройки() -> dict:
    """Папка Telegram и добавленные вручную чаты.

    Папку владелец ведёт в самом телеграме, и это правильное место: состав
    чатов он меняет там же, где их читает. Ручной список нужен для чата,
    которому в папке не место, но заглядывать в него хочется.
    """
    return {
        "папка": db.настройка("отклики.папка", ПАПКА),
        "чаты": list(db.настройка("отклики.чаты", [])),
        "сколько": int(db.настройка("отклики.сколько", СКОЛЬКО)),
        "с": начало(),
    }


# ── окно: откуда читать ─────────────────────────────────────────────────────

def начало() -> datetime | None:
    """С какого момента читать. None — окно не задано, берём запасные сутки.

    Момент хранится строкой, а не «сколько дней назад»: владелец назначает
    точку («с утра понедельника») и ждёт, что она останется на месте. Число
    дней сдвигалось бы каждую ночь само, и одно и то же нажатие давало бы
    разный охват.
    """
    строка = db.настройка("отклики.с", "")
    if not строка:
        return None
    try:
        м = datetime.fromisoformat(строка)
    except ValueError:
        return None
    return м if м.tzinfo else м.replace(tzinfo=times.ЗОНА)


def задать_начало(момент: datetime | None) -> None:
    db.запомнить("отклики.с", момент.isoformat(timespec="minutes") if момент else "")


def порог(момент: datetime | None = None) -> datetime:
    """Момент, раньше которого не читаем, в UTC."""
    м = момент or начало()
    if м is None:
        м = datetime.now(timezone.utc) - timedelta(days=ДНЕЙ)
    return м.astimezone(timezone.utc)


ОТНОСИТЕЛЬНО = re.compile(r"^(\d+)\s*(ч|час|часа|часов|д|дн|день|дня|дней)\b")
ДАТА = re.compile(r"^(\d{1,2})[.\-/](\d{1,2})(?:[.\-/](\d{2,4}))?")
ЧАСЫ = re.compile(r"(\d{1,2})[:.](\d{2})")


def разобрать_момент(текст: str) -> datetime | None:
    """Человеческая запись начала окна → момент времени.

    Понимает «04.09 14:00», «04.09», «14:00», «вчера», «вчера 18:00»,
    «сегодня 9:00», «12 часов», «3 дня». Записывать момент придётся руками и
    нечасто, поэтому разбираем щедро: отказ на «вчера» злил бы каждый раз.
    """
    строка = (текст or "").strip().lower().replace(",", " ")
    if not строка:
        return None
    сейчас = datetime.now(times.ЗОНА)

    м = ОТНОСИТЕЛЬНО.match(строка)
    if м:
        сколько, единица = int(м.group(1)), м.group(2)
        шаг = timedelta(hours=сколько) if единица.startswith("ч") else timedelta(days=сколько)
        return сейчас - шаг

    день = None
    if строка.startswith("вчера"):
        день, строка = (сейчас - timedelta(days=1)).date(), строка[5:].strip()
    elif строка.startswith("сегодня"):
        день, строка = сейчас.date(), строка[7:].strip()
    else:
        м = ДАТА.match(строка)
        if м:
            число, месяц = int(м.group(1)), int(м.group(2))
            год = int(м.group(3) or сейчас.year)
            год += 2000 if год < 100 else 0
            try:
                день = datetime(год, месяц, число).date()
            except ValueError:
                return None
            строка = строка[м.end():].strip()

    часы = ЧАСЫ.search(строка)
    ч, мин = (int(часы.group(1)), int(часы.group(2))) if часы else (0, 0)
    if день is None:
        if not часы:
            return None
        # Одно время без даты это сегодня, а если оно ещё не наступило, вчера:
        # окно всегда смотрит назад.
        день = сейчас.date()
        предположение = datetime(день.year, день.month, день.day, ч, мин,
                                 tzinfo=times.ЗОНА)
        return предположение if предположение <= сейчас else предположение - timedelta(days=1)
    if ч > 23 or мин > 59:
        return None
    return datetime(день.year, день.month, день.day, ч, мин, tzinfo=times.ЗОНА)


def подпись_окна(момент: datetime | None = None) -> str:
    """Как окно называется владельцу."""
    м = момент or начало()
    if м is None:
        return f"последние {ДНЕЙ} дня"
    return "с " + м.astimezone(times.ЗОНА).strftime("%d.%m %H:%M")


