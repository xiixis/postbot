def новый(рубрика: str | None, ход: Ход = None, тема: str | None = None,
          со_ссылкой: bool = True) -> int:
    """Сочиняет пост с карточкой и кладёт черновиком. Возвращает его номер.

    В `тема` может прийти что угодно от владельца: своя мысль, ссылка на
    статью или то и другое сразу. Ссылку бот открывает и читает сам, иначе
    пришлось бы копировать текст руками, а это и есть работа, от которой
    он избавляет.
    """
    # Тему не задали, значит смотрим в копилку: своя заготовка почти всегда
    # лучше выдуманной с нуля.
    из_копилки = None
    if not тема:
        import ideas
        ideas.подготовить()
        из_копилки = ideas.самая_старая()
        тема = (из_копилки or {}).get("text")

    материал = None
    if тема:
        if ход:
            ход("читаю")
        тема, материал = source.разобрать(тема)
    if ход:
        ход("пишу")
    пост = writer.сочинить(рубрика, db.о_чём_писали(), db.последние_формы(),
                           тема, материал, со_ссылкой)

    if ход:
        ход("рисую")
    поля = _поля(пост)
    поза = mascot.поза(пост.mascot_pose) or mascot.запасная(пост.mascot_fallback)
    поля["pose_file"] = _сохранить_позу(поза)
    картинка = _картинка(поля, поза)

    ид = db.добавить(пост.rubric, пост.title, пост.body,
                     картинка, пост.shape, поля)
    if из_копилки:
        import ideas
        ideas.израсходовать(из_копилки["id"])
    return ид


ПО_ЧУЖОМУ = """\
ЭТО ЧУЖОЙ МАТЕРИАЛ, А КАРУСЕЛЬ ВЫХОДИТ КАК СВОЯ

ГЛАВНОЕ: ПОСЫЛ ОСТАЁТСЯ ТОТ ЖЕ И ТОЙ ЖЕ СИЛЫ.
Материал сработал не темой самой по себе, а тем, КАК в нём подана мысль:
резкой заявкой, названной в лоб проблемой, конкретным обещанием и закрытым
финалом. Если из этого уйти в рассуждение и оговорки, карусель развалится,
даже когда все факты на месте. Слабее исходного она быть не должна.

ХОДЫ СЦЕНАРИЯ ПОВТОРИ ВСЕ, ПО ПОРЯДКУ.
В конце материала описано, как устроен исходный. Каждый его ход обязан быть
закрыт, ни один не пропускай и не сливай с соседним:
• если там начинается с доверия или ожидания — начни с того же;
• если дальше идёт разворот, где ожидание не оправдалось, — сделай разворот;
• если проблема названа в лоб одним резким словом — назови её так же в лоб,
  своим словом, но не мягче;
• если дано обещание с числом — дай обещание с числом;
• если приёмы перечислены по одному, в своём порядке — перечисли так же и в
  том же порядке, не переставляя и не объединяя;
• если финал это развязка, а не вопрос — закрой развязкой.
Число слайдов при этом то же, что в исходном, включая обложку.

ОБЛОЖКА НЕ ВЫДАЁТ ОТВЕТ.
Она ставит заявку или обещание, а разворот и решение раскрываются внутри.
Ответ, вынесенный на обложку, убивает причину листать дальше.

ЧТО ОСТАЁТСЯ НАШИМ
• Формулировки: пиши нашим голосом, а не переписывай строки подряд.

ЧТО БЕРЁТСЯ ИЗ МАТЕРИАЛА ЦЕЛИКОМ
• Вся конкретика: названия, пункты, числа, суммы. Сколько пунктов в исходном,
  столько и у нас — десять инструментов значит десять, а не те, которыми
  пользуемся мы сами. Своими данными чужую конкретику не подменяй: сумма из
  исходного остаётся его суммой, а не превращается в нашу.
• Про источник не упоминай ВООБЩЕ: ни «наткнулся», ни «автор», ни «в одном
  посте», ни в подписи, ни на слайдах. Ссылки не будет, и такое упоминание
  это разговор про вещь, до которой зрителю не добраться.
• Спорить с источником и поправлять его тоже нельзя: для зрителя его нет.
"""


def карусель(тема: str | None = None, ход: Ход = None,
             площадка: str = "телеграм", указания: str = "") -> int:
    """Пост-листалка: несколько слайдов в одном стиле под общей подписью.

    Хранится обычным черновиком: то же расписание, тот же звук, тот же футер.
    Отличие одно, в поле images лежат все слайды, и публикация видит по нему,
    что отправлять надо группой.
    """
    import carousel
    материал = None
    # «По мотивам» это рерайт: чужой удачный пост разбирается в конструктор, и
    # по нему собирается наш — тот же предмет, то же устройство, тот же порядок
    # ходов, наш голос. Предмет исходного становится нашей темой: пока тему
    # выбирал сам генератор, от исходного поста оставалось одно настроение.
    по_мотивам = ""
    if тема and тема.strip().lower().startswith(("по мотивам", "разбери")):
        if ход:
            ход("читаю")
        хвост = тема.split(":", 1)[-1].strip() if ":" in тема else ""
        _, чужое = source.разобрать(хвост)
        import вдохновение
        по_мотивам, предмет = вдохновение.указания(чужое or хвост)
        # Предмет уходит темой, но без повторного source.разобрать: это уже
        # разобранный текст, а не ссылка, и второй заход по сети только
        # вернул бы ту же страницу.
        тема = None
        если_есть_предмет = предмет.strip()
        if если_есть_предмет:
            по_мотивам = f"ТЕМА НАШЕЙ КАРУСЕЛИ: {если_есть_предмет}\n\n{по_мотивам}"
    if тема:
        if ход:
            ход("читаю")
        тема, материал = source.разобрать(тема)
        if материал:
            # Материал приходит словарём, а в тему уходит его текст. Резать
            # словарь ломтями нельзя, и раньше карусель по ссылке падала здесь
            # всегда, ещё до модели.
            выдержка = (материал.get("текст") or "")[:4000]
            заголовок = материал.get("заголовок") or ""
            тема = (f"{тема or заголовок}\n\nМатериал по теме:\n{выдержка}")
            # Ссылок в карусели нет по устройству, а значит и упоминать
            # источник нельзя: «наткнулся на пост» без адреса это разговор про
            # вещь, до которой читателю не добраться. Плюс чужие формулировки
            # на слайде выглядят цитатой, хотя автора мы не называем.
            указания = (указания + "\n\n" + ПО_ЧУЖОМУ).strip()
    if по_мотивам:
        указания = f"{указания}\n\n{по_мотивам}".strip()

    # Рерайт — это и «по мотивам», и присланный ссылкой материал: в обоих
    # случаях содержание идёт из исходного, а не из нашей базы.
    это_рерайт = bool(по_мотивам or материал)
    к, слайды = carousel.собрать(тема, db.о_чём_писали(), ход, площадка,
                                 указания, это_рерайт)
    поля = {"carousel": к.model_dump(), "card_title": к.cover_title,
            "pose": к.поза, "fallback": "privet",
            "суть": к.topic, "запасные": list(к.запасные_заголовки or []),
            # Название поста для TikTok. Лежит рядом, а не только внутри
            # карусели: его спрашивает подготовка варианта под площадку.
            "tiktok_title": к.название,
            # Куда пост поедет. Список, а не одно значение: владелец может
            # добавить площадок кнопками под черновиком, и генерация задаёт
            # лишь первое приближение.
            "куда": [площадка], "площадка": площадка,
            # В каком формате слайды уже нарисованы. Без этой отметки пересборка
            # под другую площадку решила бы, что перерисовывать нечего, и в
            # телеграм уехала бы вертикаль.
            "формат": carousel.ФОРМАТ.get(площадка, "квадрат")}
    рубрика = "карусель tiktok" if площадка == "tiktok" else "карусель"
    return db.добавить(рубрика, к.cover_title, carousel.подпись(к), None,
                       "карусель", поля, картинки=слайды)


def переписать(ид: int, указание: str, ход: Ход = None) -> int:
    """Правит существующий пост по указанию владельца. Номер остаётся тем же.

    Номер важен: пост может уже стоять в расписании, и подмена его новым
    выбила бы время. Поэтому правим на месте.
    """
    ряд = db.взять(ид)
    if not ряд:
        raise ValueError("черновика уже нет")
    if ход:
        ход("пишу")
    прежний = {"body": ряд["body"], "rubric": ряд["rubric"], "shape": ряд["shape"],
               "card": db.карточка(ряд)}
    пост = writer.переписать(прежний, указание)

    if ход:
        ход("рисую")
    поля = _поля(пост)
    поза = mascot.поза(пост.mascot_pose) or mascot.запасная(пост.mascot_fallback)
    поля["pose_file"] = _сохранить_позу(поза)
    картинка = _картинка(поля, поза)

    db.правка(ид, title=пост.title, body=пост.body,
              card=json.dumps(поля, ensure_ascii=False),
              image_path=картинка)
    _забыть_варианты(ид)
    return ид


def обновить(ид: int, текст: str | None = None, поля: dict | None = None) -> None:
    """Ручная правка: текст поста и надписи на карточке.

    Карточка перерисовывается только если её поля тронули: рисование занимает
    секунды, а правка одной запятой в тексте картинки не касается.
    """
    ряд = db.взять(ид)
    if not ряд:
        raise ValueError("черновика уже нет")
    новое = {}
    if текст is not None:
        новое["body"] = markup.причесать(текст)
    if поля:
        было = db.карточка(ряд)
        стало = {**было, **{к: з for к, з in поля.items() if з is not None}}
        if стало != было:
            новое["card"] = json.dumps(стало, ensure_ascii=False)
            картинка = _картинка(стало, _поза_поста(стало))
            if картинка:
                новое["image_path"] = картинка
    db.правка(ид, **новое)
    if новое:
        _забыть_варианты(ид)


def _забыть_варианты(ид: int) -> None:
    """После правки посчитанные варианты площадок становятся ложью.

    Вариант считается один раз и живёт в карточке. Пока пост не трогали, это
    экономия; как только тронули — это старый текст, который уедет на
    площадку вместо нового.
    """
    try:
        import варианты
        варианты.забыть(ид)
    except Exception:                                        # noqa: BLE001
        pass          # сброс кэша не стоит того, чтобы из-за него падала правка


def _поза_поста(поля: dict):
    """Кот для перерисовки. Берём того же, что уже стоит на карточке.

    Рисовать нового кота при правке запятой незачем: это и деньги, и лишняя
    разница между черновиком, который видели, и тем, что уйдёт в канал.
    """
    прежняя = поля.get("pose_file")
    если_есть = storage.во_временный(прежняя) if прежняя else None
    return если_есть or mascot.запасная(поля.get("fallback", "privet"))


def перерисовать(ид: int) -> int:
    """Новая поза кота под тот же текст. Модель каждый раз рисует иначе."""
    ряд = db.взять(ид)
    if not ряд:
        raise ValueError("черновика уже нет")
    поля = db.карточка(ряд)
    if поля.get("carousel"):
        return _перерисовать_карусель(ид, поля)
    поза = mascot.поза(поля.get("pose") or "standing and waving a paw") \
        or mascot.запасная(поля.get("fallback", "privet"))
    поля["pose_file"] = _сохранить_позу(поза)
    картинка = _картинка(поля, поза)
    db.правка(ид, card=json.dumps(поля, ensure_ascii=False), image_path=картинка)
    _забыть_варианты(ид)
    return ид


def _перерисовать_карусель(ид: int, поля: dict) -> int:
    """Пересобирает слайды по сохранённому тексту, ничего не сочиняя заново.

    Нужно после правки вёрстки: текст уже одобрен, менять его незачем, а
    картинки должны стать такими же, как у новых каруселей.
    """
    import carousel
    к = поля["carousel"]
    поза = mascot.взять(к.get("поза") or "")
    поля["pose_file"] = _сохранить_позу(поза)
    формат = поля.get("формат") or "квадрат"
    файлы = carousel.нарисовать(к, формат, поза)
    ссылки = [storage.положить(ф) or str(ф) for ф in файлы if ф]
    db.правка(ид, card=json.dumps(поля, ensure_ascii=False),
              images=json.dumps(ссылки, ensure_ascii=False),
              image_path=ссылки[0] if ссылки else None)
    return ид


def перерисовать_слайд(ид: int, номер: int, брак: bool = False,
                       новая: bool = False) -> int:
    """Одну картинку заново, другой позой кота.

    У кота бывает пять лап или лишний хвост: с точки зрения пикселей поза
    безупречна, автоматика её не ловит, а видно сразу. Пересобирать из-за
    неё всю карусель — минуты работы и восемь новых файлов вместо одного.

    «брак» помечает виноватую позу навсегда: без этого она вернётся через
    слайд, и разговор повторится.
    """
    import carousel
    ряд = db.взять(ид)
    if not ряд:
        raise ValueError("черновика уже нет")
    поля = db.карточка(ряд)
    к = поля.get("carousel")
    if not к:
        return перерисовать(ид)          # у одиночного поста слайд всего один
    ссылки = db.картинки(ряд)
    if not 1 <= номер <= len(ссылки):
        raise ValueError(f"слайда {номер} в этой карусели нет")

    было = carousel.позы_слайдов(к).get(номер) or {}
    ключ = Path(было["поза"]).stem if было.get("поза") else ""
    if брак and ключ:
        mascot.забраковать(ключ)

    # Две дороги. Из библиотеки — мгновенно и бесплатно, и обычно этого
    # хватает. Нарисовать заново — минута и деньги, зато поза, которой ещё
    # не было; она тут же ложится в библиотеку и работает на все следующие
    # карусели, а не на один слайд.
    план = было.get("план") or "общий"
    поза_файл = None
    if новая:
        поза_файл = mascot.пополнить(
            carousel.ОПИСАНИЕ_ПЛАНА.get(план, carousel.ОПИСАНИЕ_ПЛАНА["общий"]),
            план)
    if not поза_файл:
        склад = mascot.библиотека()
        свободные = [п for кл, п in склад.items() if кл != ключ] \
            or list(склад.values())
        поза_файл = random.choice(свободные) if свободные else None

    формат = поля.get("формат") or "квадрат"
    файлы = carousel.нарисовать(к, формат, mascot.взять(к.get("поза") or ""),
                                только=номер, замены={номер: поза_файл})
    if not файлы:
        raise ValueError("слайд не нарисовался")
    свежая = storage.положить(файлы[0]) or str(файлы[0])
    ссылки[номер - 1] = свежая
    db.правка(ид, images=json.dumps(ссылки, ensure_ascii=False),
              image_path=ссылки[0])
    _забыть_варианты(ид)
    return ид


def заказ(сколько: int = 1, куда: str = "tiktok", часы=None,
          тема: str | None = None, ход: Ход = None) -> list[int]:
    """Партия каруселей на один станок, сразу разложенная по ячейкам.

    Заказ это не «создай пост», а «закрой мне столько ячеек». Разница видна
    на пятой публикации за день: собирать по одной и каждую руками ставить
    на время — десять действий вместо одного.

    Углы берутся по кругу даже внутри одной партии: три карусели подряд под
    одним углом отличались бы только словами, а не мыслью.
    """
    import конвейер
    import publish
    сколько = max(1, min(10, int(сколько or 1)))
    времена = list(часы or [])
    if not времена:
        времена = конвейер.свободные_часы(куда, сколько)
    сделаны = []
    for н in range(сколько):
        # Внутренние шаги перебивали общий: «собираю 2 из 3» жило полсекунды
        # и сменялось на «пишу», а сколько всего и на какой мы — терялось.
        # Поэтому номер партии подмешивается в каждый шаг, а не сообщается
        # отдельным.
        шаг = (lambda что, н=н: ход(f"{н + 1} из {сколько} · {что}")) if ход else None
        угол, пояснение = конвейер.следующий_угол(куда)
        указания = (f"УГОЛ ЭТОЙ КАРУСЕЛИ: «{угол}».\n{пояснение}.\n"
                    "Тему под этим углом выбери сам, глядя на то, чего давно "
                    "не было. Не называй угол в тексте, он для тебя.")
        ид = карусель(тема or None, шаг, куда, указания)
        publish.назначить(ид, [куда])
        # Время ставим только если станок публикует сам. В ручном режиме
        # оно ничего не значит: выкладывает человек, и раньше он всё равно
        # не выложит, а «просрочено» в плане будет мозолить глаза.
        if н < len(времена) and конвейер.настройки(куда).get("режим") == "сам":
            try:
                запланировать(ид, времена[н])
            except Exception:                                # noqa: BLE001
                traceback.print_exc()
        сделаны.append(ид)
    return сделаны


def анонс() -> int:
    """Черновик анонса стримов. Текст и карточка всегда одни и те же."""
    картинка = stream.карточка()
    return db.добавить("стрим", "Анонс стримов", stream.текст(),
                       str(картинка) if картинка else None, "анонс")


# Публикация живёт в publish: она нужна и там, где нет ни браузера, ни
# моделей. Здесь только то, что уходит туда целиком; звук и догон
# расписания ниже переопределены своими — им нужна проверка площадки.
опубликовать = publish.опубликовать


def запланировать(ид: int, когда) -> None:
    """Ставит время. Если можем, отдаём пост телеграму насовсем.

    Отданный пост Telegram публикует сам, и с этого момента ни мак, ни сервер
    ему не нужны. Иначе время хранится у нас, и публикует бот.
    """
    прежний = db.взять(ид)
    if прежний:
        publish.снять_у_телеграма(прежний)
    у_телеграма = None
    # Телеграму отдаём не всё. Анонс стрима нельзя: у него кнопки со ссылками,
    # а в отложенные они не переезжают. Карусель для TikTok тем более: она в
    # телеграм вообще не едет, её в назначенный час публикует мак, и у самого
    # TikTok отложенных публикаций нет.
    своим_ходом = ((прежний or {})["rubric"] == "стрим"
                   or publish.площадка(прежний) == "tiktok")
    if publish.через_аккаунт() and not своим_ходом:
        try:
            у_телеграма = publish.отложить(ид, когда)
        except Exception:                                    # noqa: BLE001
            traceback.print_exc()
    db.запланировать(ид, times.в_базу(когда), у_телеграма)


def снять_с_плана(ид: int) -> None:
    """Снимает время. Если пост лежал у телеграма, забираем его оттуда.

    Без этого он остался бы в отложенных и вышел бы, хотя в приложении уже
    показывался бы черновиком.
    """
    пост = db.взять(ид)
    if пост:
        publish.снять_у_телеграма(пост)
    db.снять_с_плана(ид)




ТИХО = "тихо"          # общий выключатель звука, переживает перезапуск


def звук_выключен() -> bool:
    return bool(db.настройка(ТИХО, False))


def переключить_звук() -> bool:
    """Возвращает новое состояние: True это «всегда тихо»."""
    стало = not звук_выключен()
    db.запомнить(ТИХО, стало)
    return стало


def без_звука() -> bool:
    """Уходит ли пост без уведомления.

    Два повода, и они складываются. Ручной выключатель, когда владелец решил
    не дёргать людей вообще. И ночь: десять тысяч уведомлений в три часа ночи
    стоят дороже любого поста, поэтому с 23:00 до 8:00 тихо всегда, даже когда
    звук включён.
    """
    return звук_выключен() or not (8 <= times.сейчас().hour < 23)


ПРОСРОЧКА = 3 * 3600      # сколько ждёт пост, если бот в это время не работал


def догнать_расписание() -> list[dict]:
    """Публикует всё, чему пришло время. Зовётся на каждом круге опроса.

    Два случая, которые легко перепутать. Опоздание на минуты, бот просто был
    занят, тогда публикуем. Опоздание на часы, бота выключали, тогда НЕ
    публикуем: утренний пост, вышедший ночью, хуже невышедшего. Такой
    возвращается в черновики, и владелец решает сам.

    Ошибку не глотаем и не роняем цикл: пост остаётся в расписании, вызвавший
    решает, писать ли о ней владельцу. Иначе упавшая сеть тихо съедала бы посты.
    """
    сделано = []
    сейчас = times.сейчас()
    for пост in db.созревшие(times.в_базу(сейчас)):
        ид = int(пост["id"])
        # Площадка не подключена: публиковать нечем. Повторять попытку каждые
        # полминуты бессмысленно и шумно, поэтому возвращаем в черновики и
        # говорим об этом один раз.
        куда = publish.площадка(пост)
        if not publish.площадка_готова(куда):
            db.снять_с_плана(ид)
            сделано.append({"id": ид, "итог": "нет площадки", "куда": куда})
            continue
        опоздание = (сейчас - times.из_базы(пост["scheduled_at"])).total_seconds()
        if опоздание > ПРОСРОЧКА:
            db.снять_с_плана(ид)
            сделано.append({"id": ид, "итог": "просрочен",
                            "часов": round(опоздание / 3600)})
            continue
        try:
            опубликовать(ид)
            db.запомнить(f"сбои_{ид}", 0)
            сделано.append({"id": ид, "итог": "вышел"})
        except publish.ЧастичноВышло as e:
            # Куда-то пост уже ушёл. Повторять нельзя, считаем состоявшимся и
            # только рассказываем, где не приняли.
            db.запомнить(f"сбои_{ид}", 0)
            сделано.append({"id": ид, "итог": "вышел частично",
                            "текст": str(e)[:200]})
        except Exception as e:                               # noqa: BLE001
            # Повторять можно, но не бесконечно. Опрос идёт раз в полминуты, и
            # пост, который площадка отвергает по своим правилам, завалил бы
            # владельца одинаковыми сообщениями за считанные минуты.
            сбоев = int(db.настройка(f"сбои_{ид}", 0) or 0) + 1
            db.запомнить(f"сбои_{ид}", сбоев)
            if сбоев >= 3:
                db.снять_с_плана(ид)
                db.запомнить(f"сбои_{ид}", 0)
                сделано.append({"id": ид, "итог": "сдался",
                                "текст": str(e)[:200]})
            else:
                сделано.append({"id": ид, "итог": "ошибка",
                                "текст": str(e)[:200]})
    return сделано
