def _поля(пост) -> dict:
    """Всё, что нужно, чтобы потом перерисовать карточку без новой генерации."""
    return {"card_eyebrow": пост.card_eyebrow, "card_title": пост.card_title,
            "card_lines": пост.card_lines, "card_footer": пост.card_footer,
            "pose": пост.mascot_pose, "fallback": пост.mascot_fallback,
            # Суть нужна не картинке, а следующему посту: по ней видно, что
            # тему уже брали, даже если заголовок вышел совсем другой.
            "суть": getattr(пост, "суть", ""),
            "запасные": list(getattr(пост, "запасные_заголовки", []) or [])}


