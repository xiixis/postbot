# -*- coding: utf-8 -*-
"""Куда публиковать: тестовый канал или основной.

Разница между ними не в настройке, а в цене ошибки. В тестовом сидит один
человек, в основном десять тысяч, и отменить публикацию там нельзя. Поэтому
выбранный канал виден всё время в шапке, основной подсвечен, а переключать
может только владелец: у своих людей есть право публиковать, но не право
решать, куда.

Адрес основного канала задаётся из приложения и проверяется на месте: бот
спрашивает у Telegram, admin ли он там и может ли писать. Узнать это при
первой публикации, когда пост уже сочинён, было бы поздно.
"""

import config
import db
import telegram as tg

КЛЮЧ = "channels"
ТЕСТ, ОСНОВНОЙ = "тест", "основной"


def настройки() -> dict:
    """Адреса обоих каналов и выбранный. Тестовый по умолчанию из .env."""
    свои = db.настройка(КЛЮЧ, {}) or {}
    return {ТЕСТ: свои.get(ТЕСТ) or config.КАНАЛ,
            ОСНОВНОЙ: свои.get(ОСНОВНОЙ, ""),
            "выбран": свои.get("выбран", ТЕСТ)}


def текущий() -> str:
    """Адрес канала, в который уходят посты прямо сейчас."""
    н = настройки()
    return н.get(н["выбран"]) or н[ТЕСТ]


def основной() -> str:
    """Адрес основного канала.

    По нему считается всё, что показывают человеку: история, охват, сводка.
    Тестовый канал существует, чтобы пробовать, и его числа в общей картине
    только мешают. Если основной ещё не задан, берём тот, в который пишем.
    """
    н = настройки()
    return н.get(ОСНОВНОЙ) or н.get(ТЕСТ) or config.КАНАЛ


def основной_выбран() -> bool:
    return настройки()["выбран"] == ОСНОВНОЙ


def выбрать(вид: str) -> dict:
    """Переключает канал. На пустой адрес не переключаемся."""
    н = настройки()
    if вид not in (ТЕСТ, ОСНОВНОЙ):
        raise ValueError("такого канала нет")
    if not н.get(вид):
        raise ValueError("адрес этого канала ещё не задан")
    свои = db.настройка(КЛЮЧ, {}) or {}
    свои["выбран"] = вид
    db.запомнить(КЛЮЧ, свои)
    return настройки()


def задать(вид: str, адрес: str) -> dict:
    if вид not in (ТЕСТ, ОСНОВНОЙ):
        raise ValueError("такого канала нет")
    свои = db.настройка(КЛЮЧ, {}) or {}
    свои[вид] = (адрес or "").strip()
    if not свои[вид] and свои.get("выбран") == вид:
        свои["выбран"] = ТЕСТ                     # адрес стёрли, уходим в тест
    db.запомнить(КЛЮЧ, свои)
    return настройки()


def проверить(адрес: str) -> dict:
    """Существует ли канал и может ли бот там публиковать.

    Возвращает {'ок': bool, 'что': текст для человека, 'имя': название канала}.
    """
    адрес = (адрес or "").strip()
    if not адрес:
        return {"ок": False, "что": "адрес пустой"}
    if not (адрес.startswith("@") or адрес.lstrip("-").isdigit()):
        return {"ок": False, "что": "нужен @имя_канала или числовой id вида -100…"}
    try:
        канал = tg._вызвать("getChat", {"chat_id": адрес})
    except Exception as e:                                   # noqa: BLE001
        return {"ок": False, "что": f"канал не найден: {str(e)[:120]}"}

    имя = канал.get("title") or адрес
    try:
        я = tg.кто_я()
        член = tg._вызвать("getChatMember", {"chat_id": адрес, "user_id": я["id"]})
    except Exception:                                        # noqa: BLE001
        # Telegram отвечает «member list is inaccessible», и это почти всегда
        # означает одно: бота в канал не добавили.
        return {"ок": False, "имя": имя,
                "что": f"бот не добавлен в «{имя}». Добавьте его "
                       "администратором с правом публикации сообщений."}
    if член.get("status") != "administrator":
        return {"ок": False, "имя": имя,
                "что": f"бот не админ в «{имя}». Добавьте его администратором "
                       "с правом публикации сообщений."}
    if член.get("can_post_messages") is False:
        return {"ок": False, "имя": имя,
                "что": f"в «{имя}» у бота нет права публиковать сообщения."}
    return {"ок": True, "имя": имя, "что": f"«{имя}», бот админ и может публиковать"}
