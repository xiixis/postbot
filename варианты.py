# -*- coding: utf-8 -*-
"""Один пост, разные площадки: подготовка содержимого под каждую.

Слайды карусели пишутся один раз: мысль на них от площадки не зависит. А вот
всё вокруг зависит сильно. Телеграму нужен квадрат, разметка и фирменные
иконки. TikTok хочет 3:4, не понимает разметку и ждёт хештеги. X даёт 280
символов.

Поэтому вариант под площадку готовится по требованию и запоминается в
карточке поста: рисовать одни и те же слайды заново на каждое нажатие незачем,
а вот тратить модель и браузер на площадку, куда пост так и не поедет, тем
более.
"""

import json

import db
import площадки

ГДЕ = "варианты"          # ключ в карточке поста


def сохранённые(ряд) -> dict:
    return (db.карточка(ряд) or {}).get(ГДЕ) or {}


def _запомнить(ид: int, куда: str, вариант: dict) -> None:
    ряд = db.взять(ид)
    поля = db.карточка(ряд)
    поля.setdefault(ГДЕ, {})[куда] = вариант
    db.правка(ид, card=json.dumps(поля, ensure_ascii=False))


def _подпись(ряд, куда: str) -> str:
    """Текст под площадку.

    Пост, сочинённый прямо под эту площадку, переписывать не надо: он уже
    написан по её правилам, и второй проход только испортит. Раньше карусель
    для TikTok прогонялась через переклад ещё раз и возвращалась с жирной
    первой строкой, которую TikTok показывает звёздочками.
    """
    if куда == "телеграм":
        import publish
        return publish.футер(ряд["body"])

    if (db.карточка(ряд) or {}).get("площадка") == куда:
        текст = ряд["body"]
    else:
        import crosspost
        версии = crosspost.тексты(int(ряд["id"]))
        текст = версии.get(куда) or ряд["body"]
    # Последний рубеж. Разметку сюда может занести что угодно: старый пост,
    # сочинённый до правил, ручная правка владельца, сбой модели. За пределами
    # телеграма она всегда мусор, поэтому снимается здесь, а не там, где её
    # надеялись не создать.
    return _без_разметки(текст)


def _без_разметки(текст: str) -> str:
    import re
    т = re.sub(r"\*\*(.+?)\*\*", r"\1", текст or "")
    т = re.sub(r"(?<![\w*])[*_](.+?)[*_](?![\w*])", r"\1", т)
    т = re.sub(r"`(.+?)`", r"\1", т)
    т = re.sub(r"\[(.+?)\]\((.+?)\)", r"\1", т)
    return re.sub(r"^\s*>\s?", "", т, flags=re.M).strip()


def _слайды(ряд, куда: str) -> list[str]:
    """Слайды в формате площадки. Если формат совпадает, ничего не рисуем."""
    исходные = db.картинки(ряд)
    if not исходные:
        return []
    поля = db.карточка(ряд)
    к = поля.get("carousel")
    нужен = площадки.формат(куда)
    # Старые посты отметки о формате не имеют: выводим её из площадки, для
    # которой пост собирался.
    сейчас = поля.get("формат") or площадки.формат(поля.get("площадка", "телеграм"))
    # Пропорции совпали, но файл может не подойти: TikTok не берёт PNG и не
    # берёт крупнее 1080p, а рисуем мы в полуторном масштабе.
    подойдёт = all(с.lower().endswith(".jpg") for с in исходные) \
        if площадки.файл(куда) == "jpeg" else True
    if not к or (нужен == сейчас and подойдёт):
        return исходные[:площадки.картинок(куда)]

    try:
        import card
        import carousel
        import mascot
        import storage
        from pathlib import Path
    except ImportError:
        return исходные[:площадки.картинок(куда)]

    поза = поля.get("pose_file")
    поза = Path(storage.во_временный(поза)) if поза else None
    if not поза or not Path(поза).exists():
        поза = mascot.взять(к.get("поза") or "")
    файлы = carousel.нарисовать(к, нужен, поза)

    вид, ширина = площадки.файл(куда), площадки.ширина(куда)
    if вид == "jpeg" or ширина:
        файлы = [card.пережать(ф, вид, ширина) for ф in файлы if ф]
    ссылки = [storage.положить(ф) or str(ф) for ф in файлы if ф]
    return ссылки[:площадки.картинок(куда)]


def получить(ид: int, куда: str, заново: bool = False) -> dict:
    """Готовое содержимое для площадки: картинки и текст.

    Считается один раз и живёт в карточке поста. Второе нажатие на ту же
    площадку ничего не пересчитывает.
    """
    ряд = db.взять(ид)
    if not ряд:
        raise ValueError("поста уже нет")
    было = сохранённые(ряд)
    if куда in было and not заново:
        return было[куда]

    вариант = {"images": _слайды(ряд, куда), "body": _подпись(ряд, куда)}
    if куда == "tiktok":
        # Карусель, сочинённая под TikTok, приносит название с собой: оно уже
        # написано по правилам площадки. Звать за ним модель второй раз значит
        # тратить лимит на готовое и рисковать получить хуже. Модель нужна
        # только посту, который писался для телеграма.
        своё = ((db.карточка(ряд) or {}).get("tiktok_title") or "").strip()
        if not своё:
            import crosspost
            своё = crosspost.тексты(ид).get("tiktok_title") or ряд["title"]
        вариант["title"] = своё[:90]
    _запомнить(ид, куда, вариант)
    return вариант


def выложено(ряд) -> dict:
    """Куда этот пост уже ушёл. Ключ площадка, значение адрес или отметка."""
    return (db.карточка(ряд) or {}).get("выложено") or {}


def отметить(ид: int, куда: str, след: str) -> None:
    ряд = db.взять(ид)
    поля = db.карточка(ряд)
    поля.setdefault("выложено", {})[куда] = след
    db.правка(ид, card=json.dumps(поля, ensure_ascii=False))
