# -*- coding: utf-8 -*-
"""Кого пускать к боту.

Бота можно найти по имени, поэтому проверка нужна: без неё публиковать в
канал на десять тысяч человек сможет любой прохожий. Но и владелец в боте не
один, есть напарник, и упираться в один зашитый id неправильно.

Отсюда список своих. Пополняется не вписыванием чисел руками, а кодом:
владелец создаёт код, отправляет его человеку, тот присылает код боту и
оказывается внутри. Так никому не нужно ходить к стороннему боту за своим id
и диктовать его в переписке.

Права у всех своих одинаковые, кроме одного: управлять доступом может только
владелец. И о каждой чужой публикации он узнаёт: канал общий, но отвечает за
него он.
"""

import hmac
import secrets
import time

import config
import db

СВОИ = "trusted"
КОДЫ = "invites"
ЖИЗНЬ_КОДА = 24 * 3600
АЛФАВИТ = "ABCDEFGHJKLMNPQRSTUVWXYZ23456789"      # без похожих 0/O и 1/I


def свои() -> dict:
    """{id: {'имя': …, 'когда': …}}. Владельца в списке нет, он есть всегда."""
    return {int(к): з for к, з in (db.настройка(СВОИ, {}) or {}).items()}


# Временно открытая дверь. Нужна, чтобы показать работу приложения с обычного
# браузера, где подписи телеграма нет: например при проверке приложения в
# TikTok, где на видео должен быть виден адрес сайта.
#
# Срок обязателен и хранится вместе с признаком. Дверь, открытая «на пару
# дней», без срока остаётся открытой навсегда: закрыть её никто не вспомнит,
# потому что ничего не сломается.
ОТКРЫТО = "open_until"


def открыть(часов: int = 72) -> float:
    до = time.time() + часов * 3600
    db.запомнить(ОТКРЫТО, до)
    return до


def закрыть() -> None:
    db.запомнить(ОТКРЫТО, 0)


def открыто() -> float:
    """Сколько часов осталось. Ноль означает «закрыто»."""
    до = float(db.настройка(ОТКРЫТО, 0) or 0)
    осталось = до - time.time()
    return round(осталось / 3600, 1) if осталось > 0 else 0


def можно(ид: int) -> bool:
    if открыто():
        return True
    return bool(ид) and (ид == config.АДМИН or ид in свои())


def владелец(ид: int) -> bool:
    return ид == config.АДМИН


ПОЛНЫЙ, ГОТОВИТ = "полный", "готовит"


def добавить(ид: int, имя: str, роль: str = ПОЛНЫЙ) -> None:
    список = db.настройка(СВОИ, {}) or {}
    прежнее = список.get(str(ид), {})
    список[str(ид)] = {"имя": имя[:60] or прежнее.get("имя") or "без имени",
                       "роль": роль if роль in (ПОЛНЫЙ, ГОТОВИТ) else ПОЛНЫЙ,
                       "когда": прежнее.get("когда") or int(time.time())}
    db.запомнить(СВОИ, список)


def роль(ид: int) -> str:
    """Что человеку позволено. У владельца всегда полный доступ."""
    if владелец(ид):
        return ПОЛНЫЙ
    return (свои().get(ид) or {}).get("роль", ПОЛНЫЙ)


def может_публиковать(ид: int) -> bool:
    """Право трогать канал. У роли «готовит» его нет.

    Сочинять и править может любой свой человек: испортить этим нечего,
    черновик всегда виден. А публикация в канал на десять тысяч необратима,
    и раздавать её всем подряд незачем.
    """
    return роль(ид) == ПОЛНЫЙ


def убрать(ид: int) -> None:
    список = db.настройка(СВОИ, {}) or {}
    список.pop(str(ид), None)
    db.запомнить(СВОИ, список)


def _живые_коды() -> dict:
    коды = db.настройка(КОДЫ, {}) or {}
    сейчас = time.time()
    живые = {к: з for к, з in коды.items() if сейчас - з.get("когда", 0) < ЖИЗНЬ_КОДА}
    if живые != коды:
        db.запомнить(КОДЫ, живые)
    return живые


def создать_код() -> str:
    """Одноразовый код на сутки. Дольше он и не нужен, а лежать вечно опасно."""
    код = "".join(secrets.choice(АЛФАВИТ) for _ in range(6))
    коды = _живые_коды()
    коды[код] = {"когда": int(time.time())}
    db.запомнить(КОДЫ, коды)
    return код


def похоже_на_код(текст: str) -> bool:
    т = текст.strip().upper().replace("-", "")
    return len(т) == 6 and all(с in АЛФАВИТ for с in т)


def принять(текст: str, ид: int, имя: str) -> bool:
    """Гасит код и впускает человека. Код одноразовый: второй раз не сработает."""
    код = текст.strip().upper().replace("-", "")
    коды = _живые_коды()
    if код not in коды:
        return False
    # Гасим все коды разом, а не только сработавший. Приглашение выдаётся
    # одному человеку; если их выписали несколько, лишние это просто ключи
    # от канала, лежащие в переписке до конца суток.
    db.запомнить(КОДЫ, {})
    добавить(ид, имя)
    return True


def живых_кодов() -> int:
    return len(_живые_коды())


def погасить_коды() -> None:
    db.запомнить(КОДЫ, {})


# Вход по личной ссылке. Приложение живёт внутри телеграма и узнаёт человека по
# его подписи, но иногда нужен обычный браузер: показать работу с ноутбука,
# записать экран так, чтобы был виден адрес сайта. Для этого есть длинный
# случайный ключ, который владелец носит в ссылке.
ВЕБ_КЛЮЧ = "web_key"


def ключ_доступа(новый: bool = False) -> str:
    """Ключ личной ссылки. Заводится сам при первом обращении."""
    ключ = db.настройка(ВЕБ_КЛЮЧ, "") or ""
    if новый or not ключ:
        ключ = secrets.token_urlsafe(24)
        db.запомнить(ВЕБ_КЛЮЧ, ключ)
    return ключ


def по_ключу(ключ: str) -> int:
    """Кто пришёл по личной ссылке. Ноль, если ключ не тот.

    Сравнение постоянное по времени: ключ короткий и подбирается перебором
    тем легче, чем больше подсказок даёт скорость ответа.
    """
    свой = db.настройка(ВЕБ_КЛЮЧ, "") or ""
    if not свой or not ключ:
        return 0
    # Сравниваем байтами: compare_digest не работает со строками, где есть
    # символы вне ASCII, а в чужой ключ прийти может что угодно.
    совпал = hmac.compare_digest(свой.encode("utf-8", "ignore"),
                                 str(ключ).encode("utf-8", "ignore"))
    return config.АДМИН if совпал else 0
