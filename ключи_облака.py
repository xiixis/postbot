# -*- coding: utf-8 -*-
"""Ключи команды из общего облака — в память процесса, а не на диск.

Порядок завёл партнёр в 4xTube 14 сентября 2026 (`yt-searcher/app/keys.py`): ключи живут
в Supabase, приложение забирает их при запуске и держит только в переменных окружения
своего процесса. Смысл в том, что ключ, лежащий копией в `.env`, продолжает работать в
любом чужом скрипте даже после того, как человеку сняли доступ; ключ, живущий в памяти,
исчезает вместе с процессом.

Постбот подключается к тому же хранилищу и тем же входом — код связи не дублируется, а
берётся из 4xTube. Так при любой правке у партнёра мы не разойдёмся с ним в поведении.

Если связи нет или вход просрочен, молча остаётся то, что уже есть в окружении: бот на
сервере поднимается со своего `.env` и без облака.
"""
from __future__ import annotations

import os
import sys
from pathlib import Path

# Поисковик лежит соседней папкой рядом с postbot, а не по жёсткому адресу:
# иначе код работает только на одной машине.
ПОИСКОВИК = Path(__file__).resolve().parent.parent / "yt-searcher"

# Какой сервис в облаке какой переменной окружения соответствует. Имена взяты из
# `app/keys.py`, чтобы у нас и у 4xTube ключ назывался одинаково.
ПЕРЕМЕННЫЕ = {
    "gemini": "GEMINI_API_KEY",
    "anthropic": "ANTHROPIC_API_KEY",
    "voice": "VOICE_API_KEY",
    "heygen": "HEYGEN_API_KEY",
    "pexels": "PEXELS_API_KEY",
    "pixabay": "PIXABAY_API_KEY",
    "youtube": "YOUTUBE_API_KEY",
    "notion": "NOTION_API_KEY",
}


def подтянуть(тихо: bool = True) -> dict[str, str]:
    """Кладёт ключи команды в окружение процесса. Возвращает {переменная: сервис}.

    Ничего не пишет на диск и не возвращает сами значения: их место — в `os.environ`
    этого процесса и нигде больше.
    """
    если_было = sys.path[:]
    try:
        sys.path.insert(0, str(ПОИСКОВИК))
        from app import cloud                                  # noqa: PLC0415
    except Exception as е:                                     # noqa: BLE001
        if not тихо:
            print(f"облако недоступно: {type(е).__name__}: {е}"[:160])
        return {}
    finally:
        sys.path[:] = если_было

    try:
        if not cloud.configured() or not cloud.token():
            if not тихо:
                print("облако не настроено или нет входа — остаёмся на своём .env")
            return {}
        строки = cloud.team_keys()
    except Exception as е:                                     # noqa: BLE001
        if not тихо:
            print(f"облако не отдало ключи: {type(е).__name__}: {е}"[:160])
        return {}

    положено = {}
    for строка in строки:
        сервис = (строка.get("service") or "").strip().lower()
        значение = (строка.get("value") or "").strip()
        переменная = ПЕРЕМЕННЫЕ.get(сервис)
        if not переменная or not значение:
            continue
        # Облако главнее файла: ключ в `.env` может быть старым, как случилось с Gemini,
        # упёршимся в лимит. Локальную правку при этом можно оставить жёстко через
        # переменную окружения, заданную до запуска, — она не перезаписывается.
        if os.environ.get(f"{переменная}_LOCKED"):
            continue
        os.environ[переменная] = значение
        положено[переменная] = сервис
    if not тихо:
        print("из облака получено:", ", ".join(sorted(положено)) or "ничего")
    return положено


if __name__ == "__main__":
    подтянуть(тихо=False)
