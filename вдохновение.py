# -*- coding: utf-8 -*-
"""Свайп-файл: чужой удачный пост — в наш рерайтом.

Правило владельца: **рерайт разрешён и это основной способ работы с чужим**.
Берём идею, замысел, конструктор, скелет, логику — всё, что можно перенести, —
и делаем это в нашем стиле, максимально близко к оригиналу.

Рерайт это и есть переписывание: предмет тот же, устройство то же, порядок
ходов тот же, сила та же, изложено нашим голосом. Ослаблять сходство ради
непохожести незачем — пост сработал именно тем, как он устроен, и ровно за
этим мы его и берём.

Отсюда устройство разбора: он вытаскивает не настроение, а конструктор —
предмет, число кадров, скелет по ходам, перечень пунктов. По нему карусель
пересобирается на нашем материале.

Механики копятся: одна ничего не даёт, а два десятка складываются в
представление о том, что вообще работает у людей, которых читают.
"""

from pydantic import BaseModel, Field

import db

ГДЕ = "свайп"          # где лежит накопленное
СКОЛЬКО_В_ПРОМПТ = 6   # больше модель перестаёт различать


class Механика(BaseModel):
    """Разбор чужого поста: его конструктор, разобранный до деталей.

    Полей о структуре тут больше, чем о впечатлении, и это нарочно. Пересобрать
    пост можно по скелету, порядку ходов и перечню пунктов; по одному «крючку»
    и «боли» выходит пересказ настроения, из которого ничего не собирается.
    """
    предмет: str = Field(default="", description=(
        "о чём пост по существу, одной фразой до 140 символов. Именно предмет, "
        "а не впечатление: «семь бесплатных замен платному софту для видео», "
        "а не «полезная подборка». Это станет темой нашей карусели"))
    слайдов: int = Field(default=0, description=(
        "сколько кадров в исходном, считая обложку. 0, если не видно"))
    скелет: str = Field(default="", description=(
        "устройство по кадрам, по порядку, через стрелки: «обложка с обещанием "
        "и числом → кадр на один инструмент: номер, название, цена → … → финал "
        "со сводкой». До 400 символов"))
    содержание: str = Field(default="", description=(
        "что именно перечислено по пунктам: названия, числа, шаги — по порядку, "
        "как в исходном. Это переносится в наш пост. До 600 символов"))
    крючок: str = Field(description=(
        "чем автор остановил листающего, названное приёмом, а не цитатой. "
        "Не «написал про субтитры», а «назвал скучную часть работы и обещал "
        "избавить от неё». До 120 символов"))
    боль: str = Field(description=(
        "в каком положении зритель, которому это зашло. Одной фразой"))
    каркас: str = Field(description=(
        "как устроен пост целиком: боль-решение, шаги по порядку, разбор "
        "ошибок, было и стало, разбор случая. Одно-два слова"))
    доказательство: str = Field(description=(
        "чем автор подкрепил обещание: числа, свой опыт, скриншот, сравнение. "
        "До 100 символов"))
    призыв: str = Field(description=(
        "о чём попросил в конце и что пообещал взамен. До 100 символов"))
    чему_учит: str = Field(default="", description=(
        "что из этого переносим, одной фразой до 140 символов. Приём, а не "
        "пересказ темы"))


ЗАДАНИЕ = """\
Перед вами чужой пост, который хорошо разошёлся. Разберите его до
конструктора: по нему мы соберём свой пост о том же — рерайтом.

Нужно устройство целиком: о чём пост по существу, сколько в нём кадров, какие
ходы и в каком порядке, что перечислено по пунктам. Чем точнее разбор, тем
ближе к оригиналу выйдет наш пост, а это и есть цель.

Записывайте разбором, а не выпиской: нужен конструктор, по которому собирают.
«Начинает с того, что называет самую нудную часть работы» — это разбор.

Если поста не видно или он пустой, всё равно отвечайте по форме, честно
написав, что разбирать нечего.
"""


def разобрать(текст: str) -> Механика:
    """Чужой пост — в конструктор. Модель, потому что это чтение, а не счёт."""
    import агент
    import config
    return агент.по_форме(f"{ЗАДАНИЕ}\n\nПОСТ:\n---\n{(текст or '')[:6000]}\n---",
                          Механика, модель=config.МОДЕЛЬ, метка="разбор чужого")


def запомнить(м: Механика, откуда: str = "") -> int:
    """Кладёт механику в свайп-файл. Возвращает, сколько их стало."""
    было = db.настройка(ГДЕ, []) or []
    было.insert(0, {**м.model_dump(), "откуда": откуда[:200]})
    db.запомнить(ГДЕ, было[:40])        # сорока хватает, дальше это архив
    return len(было[:40])


def список(сколько: int = 40) -> list[dict]:
    return (db.настройка(ГДЕ, []) or [])[:сколько]


def забыть(н: int) -> None:
    всё = db.настройка(ГДЕ, []) or []
    if 0 <= н < len(всё):
        всё.pop(н)
        db.запомнить(ГДЕ, всё)


def строкой() -> str:
    """Накопленные приёмы — куском для задания модели.

    Это фон, а не задание: карусель здесь пишется на свою тему, а отсюда
    берётся приём. Поэтому даём то, чему они учат, без разбора целиком.
    """
    свои = список(СКОЛЬКО_В_ПРОМПТ)
    if not свои:
        return ""
    строки = []
    for м in свои:
        чему = (м.get("чему_учит") or "").strip()
        крючок = (м.get("крючок") or "").strip()
        if чему:
            строки.append(f"• {чему}" + (f" (так делают: {крючок})" if крючок else ""))
    if not строки:
        return ""
    return ("\nПРИЁМЫ, ПОДСМОТРЕННЫЕ У ТЕХ, КОГО ЧИТАЮТ\n"
            "Это разборы чужих удачных постов, сведённые к приёму. Применяйте "
            "их устройство.\n" + "\n".join(строки) + "\n")


def указания(текст: str) -> tuple[str, str]:
    """Разбор чужого поста сразу в указания для генератора карусели."""
    return указания_по_механике(разобрать(текст))


def указания_по_механике(м: Механика) -> tuple[str, str]:
    """Готовый разбор — в указания генератору.

    Отделено от `указания`, потому что разбор не всегда делает модель: у постов,
    где вся работа в картинке, а подпись пуста, читать по ссылке нечего, и
    устройство приходит из разбора, сделанного руками по кадрам.

    Возвращает пару: указания и предмет оригинала. Предмет отдаётся отдельно,
    потому что по правилу рерайта он становится нашей темой — раньше тему
    генератор выбирал сам, и от исходного поста оставалось одно настроение.
    """
    сколько = (f"Кадров в исходном: {м.слайдов}. Столько же должно быть и у нас, "
               "считая обложку.\n" if м.слайдов else "")
    скелет = f"Скелет по кадрам, повторить по порядку: {м.скелет}\n" if м.скелет else ""
    содержание = f"Что перечислено в исходном: {м.содержание}\n" if м.содержание else ""
    return (
        "РЕРАЙТ ЧУЖОГО ПОСТА\n"
        "Исходный пост разобран ниже. Соберите наш о том же предмете, с тем же "
        "устройством и той же силы. Держитесь как можно ближе к исходному: он "
        "сработал именно так, как устроен.\n\n"
        f"Предмет: {м.предмет}\n"
        f"Крючок, который там сработал: {м.крючок}\n"
        f"Боль зрителя: {м.боль}\n"
        f"Каркас: {м.каркас}\n"
        f"{скелет}"
        f"{содержание}"
        f"{сколько}"
        f"Чем подкреплено: {м.доказательство}\n"
        f"Призыв в конце: {м.призыв}\n\n"
        "Ходы повторите все и в том же порядке, ни один не пропуская и не "
        "сливая с соседним. Слабее исходного наш пост быть не должен.\n"
        "Текст пишите нашим голосом: рерайт это тот же пост, изложенный нами. "
        "Про источник не упоминайте — ссылки на него у зрителя всё равно нет.",
        м.предмет or "",
    )
