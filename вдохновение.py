# -*- coding: utf-8 -*-
"""Свайп-файл: учимся у чужих удачных постов, не переписывая их.

Разница между «вдохновиться» и «списать» проходит по одной черте: берём
механику, а не текст. Механика это чем автор зацепил, какую боль назвал, как
построил доказательство и о чём попросил в конце. Она пересобирается на нашем
материале и остаётся нашей. Формулировка, оборот, найденный автором пример —
чужие, и трогать их нельзя: это уже не учёба, а кража, и видно её сразу.

Поэтому здесь нарочно нет функции «перепиши этот пост». Есть разбор в
механику, а карусель по ней пишется с нуля из наших фактов.

Механики копятся: одна ничего не даёт, а два десятка складываются в
представление о том, что вообще работает у людей, которых читают.
"""

from pydantic import BaseModel, Field

import db

ГДЕ = "свайп"          # где лежит накопленное
СКОЛЬКО_В_ПРОМПТ = 6   # больше модель перестаёт различать


class Механика(BaseModel):
    """Разбор чужого поста. Ни одного его предложения тут не остаётся."""
    крючок: str = Field(description=(
        "чем автор остановил листающего, названное приёмом, а не цитатой. "
        "Не «написал про субтитры», а «назвал скучную часть работы и обещал "
        "избавить от неё». До 120 символов"))
    боль: str = Field(description=(
        "в каком положении зритель, которому это зашло. Одной фразой"))
    каркас: str = Field(description=(
        "как устроен пост целиком: боль-решение, шаги по порядку, разбор "
        "ошибок, было и стало, разбор случая. Одно-два слова"))
    доказательство: str = Field(description=(
        "чем автор подкрепил обещание: числа, свой опыт, скриншот, сравнение. "
        "До 100 символов"))
    призыв: str = Field(description=(
        "о чём попросил в конце и что пообещал взамен. До 100 символов"))
    чему_учит: str = Field(description=(
        "что из этого стоит применить нам, одной фразой до 140 символов. "
        "Именно приём, а не тема: темы у нас свои"))


ЗАДАНИЕ = """\
Перед вами чужой пост, который хорошо разошёлся. Разберите, ПОЧЕМУ он
сработал, и опишите это как приём.

Главное правило: ни одной его формулировки в ответ не переносите. Нас
интересует устройство, а не слова. «Начал с того, что назвал самую нудную
часть работы» это разбор. Цитата из поста это не разбор.

Если поста не видно или он пустой, всё равно отвечайте по форме, честно
написав, что разбирать нечего.
"""


def разобрать(текст: str) -> Механика:
    """Чужой пост — в механику. Модель, потому что это чтение, а не счёт."""
    import агент
    import config
    return агент.по_форме(f"{ЗАДАНИЕ}\n\nПОСТ:\n---\n{(текст or '')[:6000]}\n---",
                          Механика, модель=config.МОДЕЛЬ, метка="разбор чужого")


def запомнить(м: Механика, откуда: str = "") -> int:
    """Кладёт механику в свайп-файл. Возвращает, сколько их стало."""
    было = db.настройка(ГДЕ, []) or []
    было.insert(0, {**м.model_dump(), "откуда": откуда[:200]})
    db.запомнить(ГДЕ, было[:40])        # сорока хватает, дальше это архив
    return len(было[:40])


def список(сколько: int = 40) -> list[dict]:
    return (db.настройка(ГДЕ, []) or [])[:сколько]


def забыть(н: int) -> None:
    всё = db.настройка(ГДЕ, []) or []
    if 0 <= н < len(всё):
        всё.pop(н)
        db.запомнить(ГДЕ, всё)


def строкой() -> str:
    """Накопленные приёмы — куском для задания модели.

    Отдаём то, чему они учат, а не разбор целиком: модели нужен приём, который
    она применит, и лишние подробности чужого поста только уводят её обратно к
    чужой теме.
    """
    свои = список(СКОЛЬКО_В_ПРОМПТ)
    if not свои:
        return ""
    строки = []
    for м in свои:
        чему = (м.get("чему_учит") or "").strip()
        крючок = (м.get("крючок") or "").strip()
        if чему:
            строки.append(f"• {чему}" + (f" (так делают: {крючок})" if крючок else ""))
    if not строки:
        return ""
    return ("\nПРИЁМЫ, ПОДСМОТРЕННЫЕ У ТЕХ, КОГО ЧИТАЮТ\n"
            "Это разборы чужих удачных постов, сведённые к приёму. Тема и "
            "материал у нас свои, чужие формулировки повторять нельзя — "
            "берите только устройство.\n" + "\n".join(строки) + "\n")


def указания(текст: str) -> str:
    """Разбор чужого поста сразу в указания для генератора карусели."""
    м = разобрать(текст)
    return ("ПО МОТИВАМ ЧУЖОГО ПРИЁМА\n"
            f"Крючок, который там сработал: {м.крючок}\n"
            f"Боль зрителя: {м.боль}\n"
            f"Каркас: {м.каркас}\n"
            f"Чем подкреплено: {м.доказательство}\n"
            f"Что применить нам: {м.чему_учит}\n\n"
            "Возьмите отсюда только устройство. Тему, примеры и числа берите "
            "наши: чужой текст не переписываем ни строчкой.")
