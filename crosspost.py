# -*- coding: utf-8 -*-
"""Тот же пост на других площадках.

Перепечатывать телеграмный текст в X и Threads нельзя: там другая длина, нет
разметки и нет наших иконок. Поэтому текст не режется, а переписывается под
площадку, и от исходника остаётся мысль, а не буквы.

Сам разговор с моделью живёт здесь, а отправка в x.py и threads.py: так проще
проверять каждую часть по отдельности.
"""

import json

import db

# Раньше здесь жила и рассылка. Теперь публикацией занимается publish: пост
# знает, куда он едет, и путь один для всех площадок. От этого модуля осталось
# то, ради чего он и заводился: переложить текст под чужие правила.
ГДЕ = "outside"                # какие площадки включены (старый переключатель)
СЕТИ = ("x", "threads", "tiktok")
ИМЕНА = {"x": "X", "threads": "Threads", "tiktok": "TikTok"}


def _модель():
    """Схема ответа. Заводится по требованию: pydantic есть только на маке, а
    включать и выключать площадки приложение умеет и из облака."""
    from pydantic import BaseModel, Field

    class Вовне(BaseModel):
        x: str = Field(description=(
            "версия для X, СТРОГО до 260 символов вместе с пробелами. "
            "Без разметки, без ссылок, максимум один эмодзи"))
        threads: str = Field(description=(
            "версия для Threads, до 460 символов. Разрешены абзацы, "
            "без разметки и без ссылок"))
        tiktok_title: str = Field(description=(
            "заголовок фотопоста в TikTok, до 80 символов, без хештегов"))
        tiktok: str = Field(description=(
            "описание для TikTok, до 900 символов. Живая речь, в конце "
            "3-5 хештегов по теме, каждый со знаком решётки"))

    return Вовне


ЗАДАЧА = """\
Переложи готовый пост телеграм-канала на две другие площадки.

ЧТО ВАЖНО ПОНЯТЬ
Это не сокращение и не пересказ. В телеграме у поста есть картинка, разметка и
место развернуться. В X места нет совсем, и там выживает одна мысль, зато
высказанная резко. В Threads чуть просторнее, и там уместен спокойный тон, как
будто пишешь в блокнот на людях.

ПРАВИЛА ДЛЯ ОБЕИХ ВЕРСИЙ
• Голос тот же, что в исходнике. Тот же человек, та же интонация.
• Никакой разметки: звёздочки и подчёркивания там покажутся мусором.
• Никаких ссылок и приглашений подписаться.
• Никаких тире, ни длинных, ни коротких, ни дефисов между словами.
• Ни одного числа, которого нет в исходнике. Выдумывать цифры нельзя.
• Не начинать словами «в этом посте», «сегодня расскажу», «делюсь».

X
Одна мысль и точка. Первая строка должна работать как удар: если её прочитали,
дальше уже дочитают. Лучше короче предела, чем впритык.

THREADS
Два-три коротких абзаца. Можно оставить открытый край: вопрос или признание,
что сам ещё пробуешь. Список делать не нужно, это лента, а не справка.

TIKTOK
Там пост это картинки, которые листают, а текст читают уже после. Значит
описание не пересказывает слайды, а даёт повод досмотреть до конца и написать
в комментарии. Тон проще и живее, чем везде: там сидят не за разбором, а между
делом. В самом конце 3-5 хештегов по теме, обычными словами, без выдуманных.
Хештеги это единственное место, где решётка уместна.
"""


def включено() -> dict:
    свод = db.настройка(ГДЕ, {}) or {}
    return {с: bool(свод.get(с)) for с in СЕТИ}


def переключить(сеть: str) -> bool:
    if сеть not in СЕТИ:
        raise ValueError("неизвестная площадка")
    свод = включено()
    свод[сеть] = not свод[сеть]
    db.запомнить(ГДЕ, свод)
    return свод[сеть]


def доступно() -> dict:
    """Где вообще заданы ключи. Кнопку без ключей показывать незачем."""
    import threads as тредс
    import tiktok as тт
    import x as икс
    return {"x": икс.настроен(), "threads": тредс.настроен(),
            "tiktok": тт.настроен()}


def переложить(текст: str):
    import config
    import агент
    в = агент.по_форме(f"Пост из телеграма:\n---\n{текст}\n---", _модель(),
                       система=ЗАДАЧА, модель=config.МОДЕЛЬ,
                       метка="перекладка")

    # Тот же второй проход по голосу, что и у постов канала: правило одно для
    # всего, что мы публикуем, где бы оно ни выходило.
    import humanizer
    import markup
    # Ни X, ни Threads, ни TikTok разметку не понимают: они покажут звёздочки
    # как звёздочки. Модель об этом знает, но иногда ставит их по привычке
    # канала, и полагаться на её память тут нельзя.
    в.x = _без_разметки(markup.без_тире(humanizer.очеловечить(в.x)))[:260]
    в.threads = _без_разметки(markup.без_тире(humanizer.очеловечить(в.threads)))[:460]
    # Хештеги гуманизатор бы разогнал по тексту, поэтому их снимаем на время
    # прохода и возвращаем на место сами.
    тело, метки = _отделить_хештеги(_без_разметки(в.tiktok))
    в.tiktok = (markup.без_тире(humanizer.очеловечить(тело)).strip()
                + ("\n\n" + " ".join(метки) if метки else ""))[:900]
    в.tiktok_title = markup.без_тире(в.tiktok_title)[:80].strip()
    return в


def _без_разметки(текст: str) -> str:
    import re
    т = re.sub(r"\*\*(.+?)\*\*", r"\1", текст or "")
    т = re.sub(r"(?<![\w*])[*_](.+?)[*_](?![\w*])", r"\1", т)
    т = re.sub(r"`(.+?)`", r"\1", т)
    return re.sub(r"^\s*>\s?", "", т, flags=re.M).strip()


def _отделить_хештеги(текст: str) -> tuple[str, list[str]]:
    слова = (текст or "").split()
    метки = [с for с in слова if с.startswith("#")]
    тело = " ".join(с for с in слова if not с.startswith("#"))
    return тело.strip(), метки


def тексты(ид: int, заново: bool = False) -> dict:
    """Версии поста для площадок. Считаются один раз и остаются в карточке."""
    ряд = db.взять(ид)
    if not ряд:
        raise ValueError("поста уже нет")
    поля = db.карточка(ряд)
    готовое = поля.get("outside_text") or {}
    if готовое and not заново:
        return готовое
    в = переложить(ряд["body"])
    поля["outside_text"] = готовое = {"x": в.x, "threads": в.threads,
                                      "tiktok": в.tiktok,
                                      "tiktok_title": в.tiktok_title}
    db.правка(ид, card=json.dumps(поля, ensure_ascii=False))
    return готовое
