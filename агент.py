# -*- coding: utf-8 -*-
"""Модель по подписке. Платный API запрещён.

Раньше бот ходил в Claude по ключу ANTHROPIC_API_KEY и платил деньгами за
каждый пост. Теперь всё идёт через Claude Code, который уже оплачен подпиской.
Разговаривать с ним можно только запуском отдельного процесса, и это меняет
три вещи по сравнению с API.

СТРОГИЙ ВЫВОД ОСТАЛСЯ. У API была форма pydantic, у CLI есть --json-schema, и
это то же самое: модель обязана вернуть объект указанной формы, а CLI проверяет
его до того, как отдать нам. Поэтому писателя, карусель и разбор фактов не
пришлось переделывать на «разбери простыню регуляркой»: формы те же, сменился
только способ спросить.

СИСТЕМНОЕ СООБЩЕНИЕ СВОЁ ЦЕЛИКОМ. По умолчанию Claude Code кладёт в каждый
запрос собственное вступление и описания всех своих инструментов — под пятьдесят
тысяч токенов, которых бот не использует ни разу. Денег это не стоит, но лимит
подписки тратит. Поэтому --system-prompt заменяет вступление нашим, а
инструменты выключены: боту нужен текст, а не агент с доступом к диску. Выходит
вчетверо дешевле по лимиту.

КЛЮЧ НАДО СНИМАТЬ. Если ANTHROPIC_API_KEY остался в окружении, CLI молча
возьмёт его и снова пойдёт по платному API. Мы снимаем его на каждый вызов, и
это не перестраховка: заметить такое можно только по счёту в конце месяца.
"""

import json
import os
import shutil
import subprocess
import sys
import time
from pathlib import Path

ПОПЫТОК = 3
ОЖИДАНИЕ = 900        # секунд на один вызов: длинные тексты идут медленно
ПАУЗА = 5             # между попытками

# Ни один инструмент боту не нужен: он просит текст, а не работу с диском.
# Выключенные, они не попадают в системное сообщение — отсюда и экономия.
# Имена сверяются с тем, что знает установленный CLI: неизвестное имя он не
# пропускает мимо, а падает на старте с «matches no known tool», и тогда молчит
# весь бот. Слэш-команды тут не нужны, их снимает отдельный флаг.
БЕЗ_ИНСТРУМЕНТОВ = ("Bash,Read,Write,Edit,Glob,Grep,WebFetch,WebSearch,Task,"
                    "Agent,TodoWrite,NotebookEdit,BashOutput,KillShell,"
                    "Skill,Artifact")

# Ключи платного доступа. Снимаются перед каждым запуском CLI.
КЛЮЧИ_API = ("ANTHROPIC_API_KEY", "ANTHROPIC_AUTH_TOKEN")


class ОшибкаАгента(RuntimeError):
    """Агент не ответил. Это не отказ модели, а сбой запуска или входа."""


# Беды, которые повтором не лечатся. Неизвестный флаг, негодная схема и
# отказ во входе устроены одинаково: они решаются нами, а не ожиданием, и
# вторая попытка вернёт тот же ответ слово в слово. Три попытки по кругу тут
# только откладывают минуту, когда человек узнает, что сломано.
БЕЗНАДЁЖНО = (
    "matches no known tool",       # имя инструмента, которого больше нет
    "unknown option",              # флаг, которого больше нет
    "property keys should match",  # кириллица в ключах схемы
    "input_schema",                # схема не по правилам API
    "invalid api key",
    "authentication_error",
)


def _безнадёжно(беда: str) -> bool:
    низ = (беда or "").lower()
    return any(п in низ for п in БЕЗНАДЁЖНО)


def бинарь() -> str | None:
    """Где лежит claude.

    Одним shutil.which обойтись нельзя: бота запускают и из терминала, и из
    launchd, а у launchd PATH куцый (/usr/bin:/bin), и claude там не находится
    вовсе. Поэтому смотрим ещё и в обычные места установки.
    """
    имя = os.getenv("CLAUDE_BIN", "").strip() or "claude"
    if os.sep in имя:
        п = Path(os.path.expanduser(имя))
        return str(п) if п.exists() else None
    найден = shutil.which(имя)
    if найден:
        return найден
    дом = Path.home()
    места = [дом / ".claude" / "local" / "claude",
             дом / ".local" / "bin" / "claude",
             дом / ".npm-global" / "bin" / "claude",
             дом / ".bun" / "bin" / "claude",
             Path("/opt/homebrew/bin/claude"),
             Path("/usr/local/bin/claude")]
    if sys.platform == "win32":
        данные = Path(os.environ.get("APPDATA", ""))
        места = [данные / "npm" / "claude.cmd", данные / "npm" / "claude.exe",
                 дом / ".local" / "bin" / "claude.exe",
                 дом / ".claude" / "local" / "claude.exe"] + места
    for п in места:
        if п.exists():
            return str(п)
    return None


def доступен() -> bool:
    """Есть ли чем сочинять. Без этого половина бота не работает."""
    return бинарь() is not None


def _окружение() -> dict:
    """Окружение для CLI: с полным PATH и без ключей от платного API."""
    среда = dict(os.environ)
    for ключ in КЛЮЧИ_API:
        среда.pop(ключ, None)
    путь = бинарь()
    добавка = [os.path.expanduser("~/.claude/local"), "/opt/homebrew/bin",
               "/usr/local/bin", os.path.expanduser("~/.local/bin")]
    if путь:
        добавка.insert(0, str(Path(путь).parent))
    среда["PATH"] = os.pathsep.join(добавка + [среда.get("PATH", "")])
    среда["PYTHONIOENCODING"] = "utf-8"
    return среда


def _вызвать(задача: str, система: str, модель: str, метка: str,
             схема: dict | None, усердие: str = "",
             картинки: "list | None" = None) -> dict:
    """Один разговор с CLI. Возвращает разобранный ответ целиком."""
    путь = бинарь()
    if not путь:
        raise ОшибкаАгента(
            "не нашёл claude. Поставьте Claude Code и войдите в подписку "
            "(наберите `claude`, затем /login), либо пропишите полный путь "
            "в CLAUDE_BIN")

    команда = [путь, "-p", "--output-format", "json",
               # Свои серверы и команды в этих вызовах не нужны, а описания их
               # инструментов уходили бы в каждый запрос.
               "--strict-mcp-config", "--disable-slash-commands"]
    if картинки:
        # Картинку в текст stdin не положишь: её надо открыть с диска, а значит
        # агенту нужен Read. Только он и только на этот вызов — остальные
        # по-прежнему идут вовсе без инструментов.
        команда += ["--allowedTools", "Read"]
        пути = "\n".join(f"- {п}" for п in картинки)
        задача = (f"{задача}\n\nОТКРОЙ инструментом Read каждый файл по порядку:\n"
                  f"{пути}")
    else:
        команда += ["--disallowedTools", БЕЗ_ИНСТРУМЕНТОВ]
    if модель:
        команда += ["--model", модель]
    if усердие:
        команда += ["--effort", усердие]
    if система:
        команда += ["--system-prompt", система]
    if схема is not None:
        команда += ["--json-schema", json.dumps(схема, ensure_ascii=False)]
    # Windows: обёртку npm (.cmd) subprocess напрямую не запускает.
    if sys.platform == "win32" and путь.lower().endswith((".cmd", ".bat")):
        команда = ["cmd", "/c"] + команда

    среда = _окружение()
    без_окна = getattr(subprocess, "CREATE_NO_WINDOW", 0) if sys.platform == "win32" else 0
    беда = ""
    for попытка in range(1, ПОПЫТОК + 1):
        try:
            готово = subprocess.run(команда, input=задача, capture_output=True,
                                    text=True, encoding="utf-8", env=среда,
                                    timeout=ОЖИДАНИЕ, creationflags=без_окна)
            if готово.returncode == 0 and (готово.stdout or "").strip():
                ответ = json.loads(готово.stdout)
                if not ответ.get("is_error"):
                    return ответ
                беда = str(ответ.get("result", ""))[:200]
            else:
                беда = (f"код {готово.returncode}; "
                        f"{(готово.stderr or готово.stdout or '').strip()[:200]}")
        except subprocess.TimeoutExpired:
            беда = f"молчит дольше {ОЖИДАНИЕ} с"
        except Exception as e:                               # noqa: BLE001
            беда = str(e)[:200]
        if _безнадёжно(беда):
            print(f"   ⛔ {метка or 'агент'}: {беда}")
            break
        print(f"   ⚠️ {метка or 'агент'}: попытка {попытка}/{ПОПЫТОК} мимо ({беда})")
        if попытка < ПОПЫТОК:
            time.sleep(ПАУЗА * попытка)

    подсказка = ""
    if _безнадёжно(беда):
        подсказка = (" Это не сбой связи: повтор ничего не изменит, чинить "
                     "надо у нас. Наберите `python3 проверка.py`.")
    elif any(с in беда.lower() for с in ("auth", "login", "credit", "unauthorized",
                                         "subscription", "api key", "usage limit")):
        подсказка = (" Похоже на вход или лимит: откройте терминал, наберите "
                     "`claude`, войдите в подписку и посмотрите /status.")
    сколько = "с первой попытки" if _безнадёжно(беда) else f"за {ПОПЫТОК} попытки"
    raise ОшибкаАгента(f"{метка or 'агент'} не ответил {сколько}. "
                       f"Последнее: {беда}.{подсказка}")


# ── имена полей латиницей ───────────────────────────────────────────────────
# Формы у нас описаны по-русски: «заголовок» читается в коде лучше, чем title,
# и модель по русскому имени понимает поле точнее. Но API принимает в схеме
# только имена из латиницы, цифр и точки с дефисом, и на кириллице отвечает
# 400 ещё до модели. Поэтому перед отправкой имена переводим, а в ответе
# возвращаем обратно: наружу это не видно нигде, формы остаются русскими.

_БУКВЫ = {
    "а": "a", "б": "b", "в": "v", "г": "g", "д": "d", "е": "e", "ё": "e",
    "ж": "zh", "з": "z", "и": "i", "й": "y", "к": "k", "л": "l", "м": "m",
    "н": "n", "о": "o", "п": "p", "р": "r", "с": "s", "т": "t", "у": "u",
    "ф": "f", "х": "h", "ц": "c", "ч": "ch", "ш": "sh", "щ": "sch",
    "ъ": "", "ы": "y", "ь": "", "э": "e", "ю": "yu", "я": "ya",
}


def _латиницей(имя: str) -> str:
    """Русское имя поля латиницей. Перевод один и тот же при каждом вызове."""
    буквы = []
    for б in имя:
        if б.lower() in _БУКВЫ:
            перевод = _БУКВЫ[б.lower()]
            буквы.append(перевод.upper() if б.isupper() else перевод)
        elif б.isascii() and (б.isalnum() or б in "_.-"):
            буквы.append(б)
        else:
            буквы.append("_")
    return ("".join(буквы) or "pole")[:64]


def _переименовать(узел, карта: dict):
    """Схема с латинскими именами. Карта заполняется по дороге: латинское → своё."""
    if isinstance(узел, list):
        return [_переименовать(э, карта) for э in узел]
    if not isinstance(узел, dict):
        return узел
    новый = {}
    for ключ, зн in узел.items():
        if ключ in ("properties", "$defs", "definitions") and isinstance(зн, dict):
            собрано = {}
            for имя, тело in зн.items():
                латиницей = _латиницей(имя)
                if латиницей != имя:
                    карта[латиницей] = имя
                собрано[латиницей] = _переименовать(тело, карта)
            новый[ключ] = собрано
        elif ключ == "required" and isinstance(зн, list):
            новый[ключ] = [_латиницей(и) if isinstance(и, str) else и for и in зн]
        elif ключ == "$ref" and isinstance(зн, str) and "/" in зн:
            голова, _, имя = зн.rpartition("/")
            новый[ключ] = f"{голова}/{_латиницей(имя)}"
        else:
            новый[ключ] = _переименовать(зн, карта)
    return новый


def _обратно(узел, карта: dict):
    """Ответ с русскими именами. Обход тот же, только в другую сторону."""
    if isinstance(узел, list):
        return [_обратно(э, карта) for э in узел]
    if not isinstance(узел, dict):
        return узел
    return {карта.get(к, к): _обратно(з, карта) for к, з in узел.items()}


def текстом(задача: str, система: str = "", модель: str = "",
            метка: str = "", усердие: str = "",
            картинки: "list | None" = None) -> str:
    """Ответ простым текстом. С картинками агент откроет их сам и посмотрит."""
    ответ = _вызвать(задача, система, модель, метка, None, усердие, картинки)
    return (ответ.get("result") or "").strip()


def по_форме(задача: str, форма, система: str = "", модель: str = "",
             метка: str = "", усердие: str = ""):
    """Ответ, разобранный в модель pydantic.

    Схему CLI проверяет сам и без годного объекта не возвращается, так что тут
    остаётся собрать из него нашу форму. Вложенные модели он понимает: pydantic
    отдаёт их ссылками через $defs, и это штатный случай.
    """
    карта: dict = {}
    схема = _переименовать(форма.model_json_schema(), карта)
    ответ = _вызвать(задача, система, модель, метка, схема, усердие)
    готовое = ответ.get("structured_output")
    if готовое is None:
        raise ОшибкаАгента(f"{метка or 'агент'} ответил мимо схемы: "
                           f"{str(ответ.get('result'))[:200]}")
    return форма.model_validate(_обратно(готовое, карта))
