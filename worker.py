# -*- coding: utf-8 -*-
"""Рабочий: берёт задания из очереди и делает тяжёлое.

Живёт на маке, потому что здесь есть всё, чего нет на Vercel: браузер для
карточек, модели, быстрый процессор. Крутится рядом с ботом в отдельной нити и
ничего не знает про то, кто задание положил, приложение или чат.

Опрос раз в две секунды. Это не нагрузка: один короткий запрос к базе, зато
человек в приложении видит отклик почти сразу.
"""

import os
import threading
import time
import traceback

import core
import db
import jobs

ПАУЗА = 2
ЖИВЁМ = True


def сделать(работа: dict) -> int | None:
    """Выполняет одно задание. Возвращает номер поста, если он появился."""
    ключ, вид, данные = работа["id"], работа["kind"], работа["payload"]
    ход = lambda что: jobs.шаг(ключ, что)                    # noqa: E731

    if вид == "новый":
        return core.новый(данные.get("rubric") or None, ход, данные.get("topic") or None)
    if вид == "анонс":
        return core.анонс()
    if вид == "заказ":
        сделаны = core.заказ(данные.get("сколько"), данные.get("куда") or "tiktok",
                             данные.get("часы"), данные.get("тема"), ход)
        return сделаны[0] if сделаны else None
    if вид == "карусель":
        return core.карусель(данные.get("topic") or None, ход)
    if вид == "переписать":
        return core.переписать(int(данные["id"]), данные.get("instruction", ""), ход)
    if вид == "перерисовать":
        # Номер слайда — значит, перерисовываем только его: пересобирать
        # восемь картинок из-за одной лишней лапы незачем.
        if данные.get("слайд"):
            return core.перерисовать_слайд(int(данные["id"]), int(данные["слайд"]),
                                           bool(данные.get("брак")),
                                           bool(данные.get("новая")))
        return core.перерисовать(int(данные["id"]))
    if вид == "обновить":
        core.обновить(int(данные["id"]), данные.get("body"), данные.get("card"))
        return int(данные["id"])
    if вид == "снять":
        core.снять_с_плана(int(данные["id"]))
        return int(данные["id"])
    if вид == "запланировать":
        import times
        from datetime import datetime
        когда = datetime.fromisoformat(данные["when"])
        if когда.tzinfo is None:
            когда = когда.replace(tzinfo=times.ЗОНА)
        core.запланировать(int(данные["id"]), когда)
        return int(данные["id"])
    if вид == "забрать":
        import config
        import выгрузка
        return выгрузка.забрать(int(данные["id"]), данные.get("куда") or "tiktok",
                                config.АДМИН)
    if вид == "опубликовать":
        import publish
        publish.опубликовать(int(данные["id"]), данные.get("by") or None)
        return int(данные["id"])
    if вид == "вовне":
        import publish
        ход("пишу")
        publish.опубликовать(int(данные["id"]), None, данные.get("where") or None)
        return int(данные["id"])
    if вид == "тикток_вход":
        import tiktok
        ход("пишу")
        tiktok.войти(данные["code"])
        tiktok.кто_мы(заново=True)      # чтобы имя профиля увидело и приложение
        return None
    if вид == "уборка":
        import уборка
        ход("рисую")
        уборка.прибраться()
        return None
    if вид == "показатели":
        import facts
        facts.обновить_из(данные.get("text", ""))
        return None
    if вид == "повторы":
        import repeats
        repeats.разложить()
        return None
    if вид == "неделя":
        return _неделя(данные, ход)
    raise ValueError(f"неизвестное задание: {вид}")


def _неделя(данные: dict, ход) -> int | None:
    """Набивает расписание вперёд: по посту на день в заданное время."""
    from datetime import timedelta
    import times
    дней = max(1, min(14, int(данные.get("days", 7))))
    часы = [ч for ч in (данные.get("times") or ["10:00"]) if ч] or ["10:00"]
    последний = None
    for н in range(дней):
        ход(f"пост {н + 1} из {дней}")
        ид = core.новый(None)
        час, минута = (часы[н % len(часы)].split(":") + ["0"])[:2]
        когда = (times.сейчас() + timedelta(days=н + 1)).replace(
            hour=int(час), minute=int(минута), second=0, microsecond=0)
        core.запланировать(ид, когда)
        последний = ид
    return последний


def собрать_охват() -> int:
    """Спрашивает у телеграма, сколько людей увидело недавние посты.

    Раз в полчаса и только по свежим: у поста месячной давности числа уже не
    меняются, а лишние запросы к аккаунту ни к чему.
    """
    import channels
    import db
    import publish
    if not publish.через_аккаунт():
        return 0
    import userbot
    # Охват собираем только по основному каналу: тестовый смотрит один человек,
    # и его двойка просмотров в средних числах только врёт.
    главный = channels.основной()
    свежие = db.свежие_публикации(канал=главный)
    по_каналам: dict[str, dict[int, int]] = {}
    for п in свежие:
        по_каналам.setdefault(главный, {})[int(п["tg_message_id"])] = int(п["id"])
    обновлено = 0
    for канал, соответствие in по_каналам.items():
        try:
            данные = userbot.охват(канал, list(соответствие))
        except Exception:                                    # noqa: BLE001
            continue
        for номер, д in данные.items():
            db.записать_охват(соответствие[номер], д["просмотры"],
                              д["реакции"] + д["пересылки"])
            обновлено += 1
    return обновлено


# Виды работ, о которых стоит написать. Остальные владелец видит сам: он
# стоит и смотрит на шаги, пока они идут.
ДОКЛАДЫВАЕМ = {"заказ": "🎠 Заказ собран", "карусель": "🎠 Карусель готова", "пост": "📝 Пост готов",
               "новый": "📝 Пост готов",
               "переписать": "✏️ Переписал", "неделя": "📅 План на неделю готов"}


# Долгая работа: о начале таких стоит сказать. Человек нажал кнопку и ушёл
# из приложения, и без единого слова он не знает, работает ли вообще что-то.
ДОЛГИЕ = {"заказ": "🎠 Взял заказ в работу", "карусель": "🎠 Собираю карусель",
          "новый": "📝 Пишу пост", "неделя": "📅 Набиваю план на неделю",
          "переписать": "✏️ Переписываю"}


def _взялся(вид: str) -> None:
    """Одна строка о том, что работа началась. Остальное скажет «готово»."""
    подпись = ДОЛГИЕ.get(вид)
    if not подпись:
        return
    try:
        import config
        import telegram as tg
        if config.АДМИН:
            tg.написать(config.АДМИН, f"{подпись}… напишу, когда будет готово.",
                        разметка="")
    except Exception:                                        # noqa: BLE001
        pass


def _доложить(вид: str, ид: int | None) -> None:
    """Владелец узнаёт, что работа кончилась, даже если свернул приложение.

    Карусель собирается минутами. За это время человек уходит из чата и
    возвращается неизвестно когда: без сообщения готовый пост просто лежит
    в очереди, и о нём вспоминают через день.
    """
    подпись = ДОКЛАДЫВАЕМ.get(вид)
    if not подпись:
        return
    try:
        import config
        import db
        import telegram as tg
        if not config.АДМИН:
            return
        пост = db.взять(ид) if ид else None
        имя = пост["title"] if пост else ""
        слайдов = len(db.картинки(пост)) if пост else 0
        хвост = f" · {слайдов} слайдов" if слайдов else ""
        tg.написать(config.АДМИН,
                    f"{подпись}: {имя}{хвост}\n\nЖдёт в очереди.",
                    разметка="")
    except Exception:                                        # noqa: BLE001
        pass          # не доложили — работа от этого не пропала


def круг() -> bool:
    """Одно задание за раз. Вернёт False, если работы не было."""
    работа = jobs.взять_работу()
    if not работа:
        return False
    print(f"рабочий: взял «{работа['kind']}»")
    _взялся(работа["kind"])
    try:
        # О черновике доложим сами и подробнее, поэтому база на это время
        # молчит: два сообщения об одном посте читаются как сбой.
        with db.тихо():
            пост = сделать(работа)
        jobs.готово(работа["id"], пост)
        print(f"рабочий: готово, пост {пост}")
        _доложить(работа["kind"], пост)
    except Exception as e:                                   # noqa: BLE001
        traceback.print_exc()
        jobs.сломалось(работа["id"], str(e))
    return True


def запустить() -> threading.Thread:
    """Поднимает рабочего рядом с ботом."""
    jobs.подготовить()
    брошено = jobs.вернуть_брошенные()
    if брошено:
        print(f"рабочий: вернул в очередь {брошено} брошенных заданий")

    # Сколько генераций разом. Одна была узким местом: карусель рисуется
    # минутами, и пока она идёт, вторая просьба стоит в очереди молча.
    # Больше двух-трёх на маке смысла нет — упирается в отрисовку слайдов
    # безголовым хромом, а он ест память.
    нитей = max(1, min(4, int(os.getenv("WORKERS", "2") or 2)))

    def фон():
        """Пульс бьётся отдельно от работы.

        Раньше пульс стоял в том же круге, что и задания. Карусель рисуется
        минутами, круг всё это время не возвращался, удар пропускался — и
        приложение показывало «мак выключен» ровно тогда, когда мак был
        занят вашей же генерацией. Пульс значит «мак работает», а не
        «рабочий свободен». Здесь же и вся повременная работа: рабочих нитей
        теперь несколько, и делать уборку в каждой было бы вчетверо больше
        уборки.
        """
        приборка, охват, повторы, сверка, пульс = 0, 0, 0, 0, 0
        while ЖИВЁМ:
            try:
                if time.time() - пульс > 20:
                    jobs.отметиться()
                    jobs.вернуть_зависшие()
                    пульс = time.time()
                if time.time() - приборка > 3600:
                    jobs.прибрать()
                    приборка = time.time()
                if time.time() - сверка > 300:
                    import publish
                    сколько = publish.сверить_с_телеграмом()
                    if сколько:
                        print(f"рабочий: поправил {сколько} расхождений с телеграмом")
                    сверка = time.time()
                if time.time() - повторы > 3600:
                    import repeats
                    for что in repeats.разложить():
                        print("рабочий: поставил повтор,", что)
                    повторы = time.time()
                if time.time() - охват > 1800:
                    сколько = собрать_охват()
                    if сколько:
                        print(f"рабочий: обновил охват у {сколько} постов")
                    охват = time.time()
            except Exception:                                # noqa: BLE001
                traceback.print_exc()
            time.sleep(5)

    def цикл():
        while ЖИВЁМ:
            try:
                if not круг():
                    time.sleep(ПАУЗА)
            except Exception:                                # noqa: BLE001
                traceback.print_exc()
                time.sleep(5)

    threading.Thread(target=фон, daemon=True).start()
    нити = [threading.Thread(target=цикл, daemon=True) for _ in range(нитей)]
    for н in нити:
        н.start()
    print(f"рабочий: {нитей} нит{'ь' if нитей == 1 else 'и'} на генерацию")
    return нити[0]
