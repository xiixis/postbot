# -*- coding: utf-8 -*-
"""Показ экранов и состояние разговора.

Меню бота — одно сообщение, которое переписывается на месте. Раньше каждое
нажатие слало новое: через десять нажатий в чате висело десять меню, и все
живые. Можно было проскроллить вверх и переключить канал кнопкой, снятой со
вчерашнего экрана, — бот честно исполнял, а человек не понимал, откуда взялось.

Здесь же живёт ожидание текста. Раньше его держали четыре разных словаря
(часы, правка, окно, факт), и ни у одного не было отмены: начал вводить часы,
передумал, написал что-то другое — и это уходило в часы. Теперь словарь один,
и любое нажатие его чистит.
"""

import экраны
import telegram as tg

# Чат → (номер сообщения с меню, код экрана). Код нужен не меньше номера:
# переключатель вроде «Звук» должен перерисовать тот экран, с которого его
# нажали, а не гадать.
ЭКРАН: dict[int, tuple[int, str]] = {}

# Чат → (чего ждём от человека словами, попутные данные).
ЖДЁМ: dict[int, tuple[str, dict]] = {}

# Чат → номер последней карточки поста. Кнопки с предыдущей снимаются, иначе
# чат снова превращается в ленту, только уже из карточек.
КАРТОЧКА: dict[int, int] = {}


class Ответ:
    """Гасилка «часиков» на кнопке.

    Телеграм крутит их, пока бот не ответил, и человек думает, что сломалось.
    Ответить надо ровно один раз: второй вызов телеграм отвергает. Раньше
    ответ слался до разбора нажатия, поэтому текст в него попасть не мог —
    всплывашка «этого черновика уже нет» была невозможна в принципе.
    """

    def __init__(self, ид: str):
        self.ид, self.сказано = ид, False

    def сказать(self, текст: str = "") -> None:
        if self.сказано:
            return
        self.сказано = True
        tg.ответить_на_кнопку(self.ид, текст)


def где(чат: int) -> str | None:
    """На каком экране человек сейчас. None, если экрана ещё нет."""
    есть = ЭКРАН.get(чат)
    return есть[1] if есть else None


def показать(чат: int, код: str, сообщение: int | None = None,
             ответ: Ответ | None = None, владелец: bool = False,
             публикует: bool = True) -> None:
    """Нарисовать экран: поправить нынешнее сообщение или послать новое."""
    запись, арг = экраны.найти(код)
    if not запись:
        if ответ:
            ответ.сказать("Кнопка устарела")
        if код != "home":
            показать(чат, "home", сообщение, None, владелец, публикует)
        return

    # Права проверяем до сборки: экран владельца может лезть туда, куда
    # чужому нельзя, и упасть раньше, чем мы скажем «нельзя».
    if запись.только_владельцу and not владелец:
        if ответ:
            ответ.сказать("🔒 Это настраивает только владелец")
        показать(чат, экраны.родитель(код) or "home", сообщение, None,
                 владелец, публикует)
        return

    # Любое нажатие снимает ожидание текста. Правило живёт ровно здесь, в
    # одном месте: ушёл в другой раздел — бот больше не ждёт от тебя часов.
    ЖДЁМ.pop(чат, None)

    п = экраны.Пар(чат, арг, владелец, публикует, сообщение or 0)
    try:
        э = запись.собрать(п)
    except экраны.НетЭкрана as e:
        if ответ:
            ответ.сказать(str(e)[:190])
        показать(чат, экраны.родитель(код) or "home", сообщение, None,
                 владелец, публикует)
        return

    # Крошки заменяют заголовок, а не дописываются к нему: иначе «Доступ»
    # печатался бы дважды подряд — в пути и строкой ниже.
    шапка = экраны.крошки(код, э.заголовок) or э.заголовок
    текст = f"{шапка}\n\n{э.текст}" if э.текст else шапка
    клава = экраны.клавиатура(код, э)
    _нарисовать(чат, код, текст, клава, сообщение)


def _нарисовать(чат: int, код: str, текст: str, клава: str,
                сообщение: int | None) -> None:
    """Правка на месте, если нажали с самого экрана; иначе новое сообщение."""
    было = ЭКРАН.get(чат)
    если_тот_же = было and сообщение and было[0] == сообщение
    if если_тот_же and tg.правка_текста(чат, сообщение, текст, клава):
        ЭКРАН[чат] = (сообщение, код)
        return
    # Сюда попадаем, когда нажали с карточки поста, со старого меню, после
    # перезапуска бота или когда правка не удалась. Кнопки со старого экрана
    # снимаем: два живых меню в чате — ровно то, от чего уходим.
    if было:
        tg.убрать_кнопки(чат, было[0])
    м = tg.написать(чат, текст, клава)
    ЭКРАН[чат] = (int(м.get("message_id") or 0), код)


def перерисовать(чат: int, код: str | None = None, владелец: bool = False,
                 публикует: bool = True) -> None:
    """Обновить висящее меню на месте, не трогая сообщение, с которого нажали.

    Нужно действиям с карточки поста. Карточка — отдельное сообщение с
    картинкой, править её текстом телеграм не даёт; а показать меню обычным
    путём значило бы послать его новым сообщением вниз, то есть вернуть ту
    самую ленту. Поэтому правим ровно то сообщение, где меню и живёт.

    Меню ещё не показывали — молчим: слать его вдогонку снятому посту незачем.
    """
    есть = ЭКРАН.get(чат)
    if not есть:
        return
    показать(чат, код or есть[1], есть[0], None, владелец, публикует)


def спросить(чат: int, что: str, текст: str, откуда: str,
             данные: dict | None = None) -> None:
    """Спросить у человека что-то словами, с возможностью передумать.

    Кнопка отмены несёт код экрана-источника и разбирается обычным маршрутом,
    а «показать» первым делом чистит ожидание. Поэтому отмена не требует ни
    своего кода, ни своей ветки и одинаково работает для всех вопросов.
    """
    ЖДЁМ[чат] = (что, данные or {})
    клава = tg.кнопки([[("✖️ Отменить", откуда)]])
    м = tg.написать(чат, текст, клава, разметка="")
    ЭКРАН[чат] = (int(м.get("message_id") or 0), откуда)


def чего_ждём(чат: int) -> tuple[str, dict] | None:
    return ЖДЁМ.get(чат)


def забыть(чат: int) -> None:
    ЖДЁМ.pop(чат, None)


def карточка(чат: int, послать) -> None:
    """Послать карточку поста, сняв кнопки с предыдущей.

    «послать» — функция без аргументов, возвращающая ответ телеграма: сама
    отправка живёт в bot, потому что умеет и фото, и альбом, и придирки.
    """
    прежняя = КАРТОЧКА.pop(чат, 0)
    if прежняя:
        tg.убрать_кнопки(чат, прежняя)
    м = послать()
    if isinstance(м, dict) and м.get("message_id"):
        КАРТОЧКА[чат] = int(м["message_id"])
