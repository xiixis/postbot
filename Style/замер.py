# -*- coding: utf-8 -*-
"""Замер снятых кадров карусели против наших порогов: python3 замер.py <папка со снимками>

Порог, который не замерен, — это мнение. Здесь считаются те шесть чисел, по которым
кадр в ленте либо читается, либо нет (пороги — из скила `визуал-слайдов`).

Две вещи сделаны нарочно.

**Контраст берётся по худшим 5% пикселей текста, а не в среднем.** Кадр, где одна
строка легла на светлое пятно фотосцены, по среднему выглядит отличным, а в ленте
эта строка пропадает.

**Чернила меряются двумя мерками.** На плоской заливке непустой пиксель — это буква,
и работает прежний порог 8–15%. На кадре с фотоподложкой он бессмысленен: у
разобранного референса непустых 34%, а буквами занято 4,7%. Поэтому для такого кадра
мерка — доля пикселей текста, 4–7%.
"""
import sys
from pathlib import Path

import numpy as np
from PIL import Image, ImageFilter

ПОРОГИ = {"контраст": 8.0, "акцент": (0.04, 0.06), "крупная строка": (0.12, 0.15),
          "перепад": 3.0, "слабых": 0.15, "текст": (0.04, 0.07), "чернила": (0.08, 0.15)}
ОКНО = 96          # окно локального фона в пикселях кадра 1080×1440: шире строки, уже блока


def _яркость(рисунок: np.ndarray) -> np.ndarray:
    """Относительная яркость по WCAG: та самая, из которой считается контраст."""
    к = np.where(рисунок <= 0.04045, рисунок / 12.92, ((рисунок + 0.055) / 1.055) ** 2.4)
    return к[..., 0] * 0.2126 + к[..., 1] * 0.7152 + к[..., 2] * 0.0722


def _низкие(я: np.ndarray, окно: int = ОКНО) -> np.ndarray:
    """Локальный грунт кадра: медиана по клеткам, растянутая обратно.

    Было усреднение (Image.BOX). Оно врёт на кадре из двух полос — светлая плита
    сверху, тёмное поле снизу: клетка на границе даёт средний серый, которого на
    кадре нет вовсе, и к нему приравнивается контраст обеих полос. На обложке
    «справочника» это давало 5,5:1 при «слабых 100%», хотя графит по белому там
    12,3:1, а белое по тёмному около 13:1 (Д-20, найден 19.09.2026).

    Медиана в той же клетке возвращает грунт той стороны, которой в клетке
    больше, а не полусумму двух. Буквы она тоже переживает: текста в клетке
    меньше половины, иначе это не текст, а заливка.
    """
    в, ш = я.shape
    кв, кш = max(1, в // окно), max(1, ш // окно)
    # Клетки нарезаются ровно, хвост кадра добирается к последней клетке.
    гв, гш = np.linspace(0, в, кв + 1).astype(int), np.linspace(0, ш, кш + 1).astype(int)
    сетка = np.empty((кв, кш), dtype=np.float32)
    for i in range(кв):
        for j in range(кш):
            сетка[i, j] = np.median(я[гв[i]:гв[i + 1], гш[j]:гш[j + 1]])
    мал = Image.fromarray((сетка * 255).astype(np.uint8))
    return np.asarray(мал.resize((ш, в), Image.BILINEAR), dtype=np.float32) / 255


def _огибающие(я: np.ndarray) -> tuple[np.ndarray, np.ndarray]:
    """Светлая и тёмная огибающие кадра — то, что лежит ВОКРУГ буквы.

    Простое размытие сюда не годится: в окно попадает сама строка, и подложка под
    чёрным текстом выходит серой. На проверке это занижало контраст с 16:1 до 6:1 —
    кадр объявлялся браком на ровном месте. Огибающая берётся максимумом и минимумом
    по окрестности: для тёмной буквы подложка — самое светлое вокруг, для выворотки —
    самое тёмное."""
    в, ш = я.shape
    мал = Image.fromarray((я * 255).astype(np.uint8)).resize((ш // 8, в // 8), Image.BOX)
    светлая = мал.filter(ImageFilter.MaxFilter(13))       # 13 на уменьшенном ≈ 104 px кадра
    тёмная = мал.filter(ImageFilter.MinFilter(13))
    растянуть = lambda и: np.asarray(и.resize((ш, в), Image.BILINEAR), dtype=np.float32) / 255
    return растянуть(светлая), растянуть(тёмная)


def _контраст(a: np.ndarray, b: np.ndarray) -> np.ndarray:
    светлее, темнее = np.maximum(a, b), np.minimum(a, b)
    return (светлее + 0.05) / (темнее + 0.05)


def кадр(путь) -> dict:
    """Числа одного кадра. Текстом считается то, что заметно отличается от своей подложки."""
    с = Image.open(путь).convert("RGB")
    рисунок = np.asarray(с, dtype=np.float32) / 255
    я = _яркость(рисунок)
    фон = _низкие(я)
    светлая, тёмная = _огибающие(я)
    # Полярность берётся от ЛОКАЛЬНОГО грунта, а не от медианы всего кадра.
    # Медиана годится, пока кадр одной полярности. На кадре из двух полос —
    # светлая плита сверху, тёмное поле снизу — одна глобальная медиана верна
    # только для одной половины, и во второй буквы сравниваются не с той
    # огибающей: измеритель печатал 5,5:1 при «слабых 100%» на обложке, где
    # графит по белому даёт 12,3:1, а выворотка по тёмному около 13:1
    # (Д-20, найден 19.09.2026; первая догадка про усреднение фона не
    # подтвердилась — грунт считался верно, врала именно полярность).
    грунт = float(np.median(я))
    подложка = np.where(я < фон, светлая, тёмная)
    контраст = _контраст(я, подложка)
    # Второе условие отсекает сам фон: его контраст к противоположной огибающей высок,
    # но от грунта он не отличается. Крупные области сцены отсекает первое: их огибающая
    # лежит внутри них самих, и контраст выходит около единицы.
    максимум = рисунок.max(axis=2)
    минимум = рисунок.min(axis=2)
    насыщенность = np.where(максимум > 0, (максимум - минимум) / np.maximum(максимум, 1e-6), 0)

    # Отличие тоже от локального грунта: на двухполосном кадре выворотка нижней
    # полосы от глобальной медианы почти не отличается и в текст не попадала.
    заметное = (контраст > 3.0) & (np.abs(я - фон) > 0.05)
    текст = заметное & ~_крупное(заметное)

    # Картинка внутри кадра — не строка. Снимок интерфейса несёт свой мелкий текст с
    # низким контрастом, и без этого отсева он тянет замер вниз: у разобранного референса
    # выходило 3,3:1 вместо настоящих 9,7:1, а «крупная строка» — 78% высоты кадра.
    полосы = _полосы(текст)
    строки = [(верх, низ) for верх, низ in полосы if (низ - верх) / текст.shape[0] <= 0.20]
    только_строки = np.zeros_like(текст)
    for верх, низ in строки:
        только_строки[верх:низ] = текст[верх:низ]

    доля_текста = float(только_строки.mean())
    # Контраст считается по ядру глифа, а не по всей букве: у края штриха цвет смешан с
    # подложкой сглаживанием и сжатием JPEG, и по краям любой чёрный текст даёт 3:1.
    # В ленте читается ядро — по нему и меряем.
    # В замер идут только пиксели своего цвета. Отделять картинку по насыщенности нельзя:
    # индиго и лайм насыщеннее любого логотипа, и такой фильтр выбрасывал сам текст.
    # Разница не в цветности, а в повторяемости: у строки цвет один, у логотипа россыпь.
    ядро = _ядро(только_строки & _частый_цвет(рисунок, только_строки))
    # Мерка не «худший пиксель», а доля непрошедших. Отдельный процентиль ловил контур
    # кота и край логотипа — картинку, а не букву — и объявлял брак на годном кадре.
    # Бледная строка целиком даёт заметную долю, точечная примесь — нет.
    свой = контраст[ядро] if ядро.any() else np.array([1.0])
    худший = float(np.median(свой))
    слабых = float((свой < ПОРОГИ["контраст"]).mean())

    акцент = (насыщенность > 0.35) & (максимум > 0.2) & (максимум < 0.95)

    # Чернила на плоском фоне: всё, что отличается от грунта кадра.
    чернила = float((np.abs(я - грунт) > 0.06).mean())

    return {"контраст_середина": худший,
            "слабых_доля": слабых,
            "акцент_доля": float(акцент.mean()),
            "текст_доля": доля_текста,
            "чернила_доля": чернила,
            "кегли": [(низ - верх) / текст.shape[0] for верх, низ in строки],
            "перепад": _перепад([(низ - верх) / текст.shape[0] for верх, низ in строки]),
            "светлота": float(я.mean()),
            "высота": int(текст.shape[0]),
            "маска_строк": только_строки,
            "фоторамка": чернила > 0.20}      # фотоподложка: мерка чернил другая


def _частый_цвет(рисунок: np.ndarray, маска: np.ndarray, доля: float = 0.7) -> np.ndarray:
    """Пиксели, чей цвет в маске повторяется: это буквы. Цвета грубо округляются до 8
    ступеней на канал, берутся самые частые, пока не наберётся 70% массы. Логотип даёт
    россыпь редких оттенков и в набор не попадает."""
    if not маска.any():
        return маска
    ступени = np.clip((рисунок * 255 // 32).astype(np.int32), 0, 7)
    коды = ступени[..., 0] * 64 + ступени[..., 1] * 8 + ступени[..., 2]
    счёт = np.bincount(коды[маска], minlength=512)
    порядок = np.argsort(счёт)[::-1]
    накопленное = np.cumsum(счёт[порядок]) / счёт.sum()
    сколько = int(np.searchsorted(накопленное, доля)) + 1
    свои = np.zeros(512, dtype=bool)
    свои[порядок[:сколько]] = True
    return свои[коды]


def _крупное(маска: np.ndarray, ядро: int = 9, доля: int = 4) -> np.ndarray:
    """Заливки: белая карточка, круглый значок, плашка. Всё, что переживает эрозию и
    восстанавливается обратно, — не буква: штрих даже крупного заголовка тоньше.

    Морфология считается на кадре, уменьшенном вчетверо: ядро 9 там отвечает 36 px кадра,
    а работает в шестнадцать раз быстрее — на полном кадре карусель мерилась минуту."""
    в, ш = маска.shape
    м = Image.fromarray((маска * 255).astype(np.uint8)).resize((ш // доля, в // доля), Image.BOX)
    открытая = м.filter(ImageFilter.MinFilter(ядро)).filter(ImageFilter.MaxFilter(ядро))
    return np.asarray(открытая.resize((ш, в), Image.NEAREST)) > 127


def _ядро(маска: np.ndarray) -> np.ndarray:
    """Сердцевина штрихов: пиксели, у которых соседи тоже текст. Съедает кайму в 1 px."""
    м = Image.fromarray((маска * 255).astype(np.uint8)).filter(ImageFilter.MinFilter(3))
    сжатая = np.asarray(м) > 127
    return сжатая if сжатая.any() else маска


def _полосы(текст: np.ndarray) -> list[tuple[int, int]]:
    """Связные полосы кадра по вертикали, где строки заняты текстом: (верх, низ) в пикселях."""
    в = текст.shape[0]
    занято = текст.mean(axis=1) > 0.012        # ниже — пыль сжатия и засечки, а не строка
    найдено, начало = [], None
    for y, есть in enumerate(занято):
        if есть and начало is None:
            начало = y
        elif not есть and начало is not None:
            найдено.append((начало, y))
            начало = None
    if начало is not None:
        найдено.append((начало, в))
    return [(верх, низ) for верх, низ in найдено if (низ - верх) / в > 0.004]


def _перепад(кегли: list[float]) -> float:
    return max(кегли) / min(кегли) if len(кегли) > 1 else 1.0


def карусель(папка) -> str:
    """Отчёт по всем кадрам и слово «годен» или «брак: …» с перечнем бед."""
    кадры = sorted(Path(папка).glob("*.png")) or sorted(Path(папка).glob("*.jpg"))
    if not кадры:
        return "брак: в папке нет кадров"

    строки, беды = [], []
    светлоты = []
    for н, путь in enumerate(кадры, 1):
        д = кадр(путь)
        светлоты.append(д["светлота"])
        мерка = "текст" if д["фоторамка"] else "чернила"
        значение = д["текст_доля"] if д["фоторамка"] else д["чернила_доля"]
        строки.append(f"{н:02d}: контраст {д['контраст_середина']:.1f}:1 "
                      f"(слабых {д['слабых_доля'] * 100:.0f}%) · "
                      f"акцент {д['акцент_доля'] * 100:.1f}% · "
                      f"{мерка} {значение * 100:.1f}% · "
                      f"крупная {max(д['кегли'] or [0]) * 100:.1f}% · "
                      f"перепад {д['перепад']:.1f}:1 · L {д['светлота']:.2f}")

        if д["слабых_доля"] > ПОРОГИ["слабых"]:
            беды.append(f"кадр {н}: {д['слабых_доля'] * 100:.0f}% текста ниже 8:1 "
                        f"(середина {д['контраст_середина']:.1f}:1)")
        низ, верх = ПОРОГИ["акцент"]
        if not низ <= д["акцент_доля"] <= верх:
            беды.append(f"кадр {н}: акцент {д['акцент_доля'] * 100:.1f}% вне 4–6%")
        низ, верх = ПОРОГИ[мерка]
        if not низ <= значение <= верх:
            беды.append(f"кадр {н}: {мерка} {значение * 100:.1f}% вне "
                        f"{низ * 100:.0f}–{верх * 100:.0f}%")
        if д["кегли"] and max(д["кегли"]) < ПОРОГИ["крупная строка"][0]:
            беды.append(f"кадр {н}: крупная строка {max(д['кегли']) * 100:.1f}% ниже 12%")
        if д["перепад"] < ПОРОГИ["перепад"]:
            беды.append(f"кадр {н}: перепад кеглей {д['перепад']:.1f}:1 ниже 3:1")

        # Служебная зона — прямоугольник вокруг знака: он стоит слева, на 1191..1235 меры
        # холста. Охраняется именно он: кот у правого края знаку не мешает, а обводка или
        # снимок, заехавшие на него слева, — мешают. Правило нарушалось трижды подряд,
        # поэтому теперь его проверяет замер, а не глаз.
        в, ш = д["маска_строк"].shape
        # Проверяется полоса ЗАПАСА над знаком (1105..1185), а не сам знак: он тут и стоит.
        зона = д["маска_строк"][int(в * 1105 / 1440):int(в * 1185 / 1440),
                                int(ш * 60 / 1080):int(ш * 400 / 1080)]
        if зона.size and зона.mean() > 0.004:
            беды.append(f"кадр {н}: контент заходит на знак")

    if max(светлоты) - min(светлоты) < 0.25:
        беды.append("ритм ленты: все кадры одной светлоты — в сетке профиля сольются")

    итог = "годен" if not беды else "брак:\n  " + "\n  ".join(беды)
    return "\n".join(строки) + "\n" + итог


def main():
    if len(sys.argv) < 2:
        raise SystemExit(__doc__)
    print(карусель(sys.argv[1]))


if __name__ == "__main__":
    main()
