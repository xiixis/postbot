# -*- coding: utf-8 -*-
"""Картинки для обложек: `python3 коллаж.py` → снимки/сетка.png, полоса.png, стопка.png

Обложка не должна повторять снимок, который зритель увидит на следующем кадре:
это правило владельца от 21.09.2026. Поэтому у обложек своя картинка, собранная
из тех же снимков, но в композицию, которой нет ни в одном кадре карусели.

Три композиции — три разных подхода, а не три оттенка одного:
  сетка  — девять плиток, по числу событий;
  полоса — три крупных снимка встык, как кадры плёнки;
  стопка — карточки внахлёст, будто колода новостей.
"""
from pathlib import Path

from PIL import Image, ImageDraw

ТУТ = Path(__file__).parent
СНИМКИ = ТУТ / "снимки"
ФОН = (231, 231, 231)
Ш, В = 1740, 1100          # исходник обложки: пропорция примерно 1,6 как у снимков


def _взять(имя: str) -> Image.Image:
    return Image.open(СНИМКИ / f"{имя}.png").convert("RGB")


def _скруглить(и: Image.Image, радиус: int) -> Image.Image:
    маска = Image.new("L", и.size, 0)
    ImageDraw.Draw(маска).rounded_rectangle((0, 0, и.width - 1, и.height - 1), радиус, fill=255)
    холст = Image.new("RGB", и.size, ФОН)
    холст.paste(и, (0, 0), маска)
    return холст


def _плитка(имя: str, ш: int, в: int, сверху: float = 0.0) -> Image.Image:
    """Кусок снимка нужной пропорции: режем по ширине от верха, чтобы попал контент."""
    и = _взять(имя)
    нужно = ш / в
    высота = min(и.height, round(и.width / нужно))
    верх = min(и.height - высота, round(и.height * сверху))
    и = и.crop((0, верх, и.width, верх + высота))
    return и.resize((ш, в), Image.LANCZOS)


def сетка() -> Image.Image:
    """Девять плиток по числу событий: видно, что новостей много, и ни одна не узнаётся как кадр."""
    имена = ["codex", "roboty", "netflix", "lingbot", "lucas", "teachers", "fable", "kimi", "brics"]
    зазор, край = 16, 20
    ш = (Ш - край * 2 - зазор * 2) // 3
    в = (В - край * 2 - зазор * 2) // 3
    холст = Image.new("RGB", (Ш, В), ФОН)
    for н, имя in enumerate(имена):
        плитка = _скруглить(_плитка(имя, ш, в, сверху=0.08), 14)
        холст.paste(плитка, (край + (н % 3) * (ш + зазор), край + (н // 3) * (в + зазор)))
    return холст


def полоса() -> Image.Image:
    """Три крупных снимка встык: читается как лента новостей, а не как отдельный кадр."""
    имена = ["roboty", "codex", "brics"]
    зазор, край = 16, 20
    ш = (Ш - край * 2 - зазор * 2) // 3
    в = В - край * 2
    холст = Image.new("RGB", (Ш, В), ФОН)
    for н, имя in enumerate(имена):
        холст.paste(_скруглить(_плитка(имя, ш, в, сверху=0.1), 16), (край + н * (ш + зазор), край))
    return холст


def стопка() -> Image.Image:
    """Карточки внахлёст: колода новостей, из которой торчат края нижних."""
    имена = ["kimi", "netflix", "codex"]
    холст = Image.new("RGB", (Ш, В), ФОН)
    ш, в = round(Ш * 0.72), round(В * 0.72)
    for н, имя in enumerate(имена):
        карточка = _скруглить(_плитка(имя, ш, в, сверху=0.08), 18)
        тень = Image.new("RGB", (ш + 10, в + 10), (208, 208, 204))
        x = round(Ш * 0.05) + н * round(Ш * 0.09)
        y = round(В * 0.05) + н * round(В * 0.07)
        холст.paste(тень, (x - 5, y - 5))
        холст.paste(карточка, (x, y))
    return холст


def main():
    for имя, собрать in (("сетка", сетка), ("полоса", полоса), ("стопка", стопка)):
        путь = СНИМКИ / f"{имя}.png"
        собрать().save(путь)
        print(путь.name, f"{путь.stat().st_size // 1024} КБ")


if __name__ == "__main__":
    # Windows без PYTHONUTF8: консоль cp1251, print кириллицы и значков падает.
    import sys
    sys.path.insert(0, str(Path(__file__).resolve().parents[2]))
    import консоль
    консоль.в_utf8()
    main()
