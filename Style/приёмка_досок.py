# ── Пороги доски 1080×1440 ───────────────────────────────────────────────────
# «40 px на кадре 1620» (слово владельца 15.09) — это 26,7 px доски. Порог 26: на принятых
# кадрах «пар» рубрика над категорией стоит ровно на 26, разницы в пиксель доски на
# телефоне нет. От края — 100 px кадра = 67 px доски.
ЗАПАС, КРАЙ = 26, 67
# Колонка кнопок TikTok (лайки, репосты, аватар): правее ≈900 px и ниже середины кадра
# (слово владельца 24.09). Снизу полоса кончается у знака: сноска у самого низа справа
# допустима, кнопки туда не доходят. Коту 20 px допуска — финал «пар» принят с краем 907.
КНОПКИ_X, ДОПУСК_КОТА = 900, 20
ЗОНА_ВЕРХ, ЗОНА_НИЗ = 720, дх.ЗНАК_ВЕРХ - 1

ДОСКА_JS = стиль.ЗАПАС_JS + """
document.fonts.ready.then(() => {
  const корень = document.querySelector('x-dc > div') || document.body.firstElementChild;
  const К = корень.getBoundingClientRect(), зона = [];
  for (const el of корень.children) {
    const б = el.getBoundingClientRect();
    // Фон, сетка и сцена во весь кадр лежат под всем: это подложка, а не блок.
    if (б.width * б.height >= 0.9 * К.width * К.height || getComputedStyle(el).pointerEvents === 'none') continue;
    el.setAttribute('data-блок', '');
    const л = б.left - К.left, п = б.right - К.left, в = б.top - К.top, н = б.bottom - К.top;
    const кот = el.hasAttribute('data-кот') || el.classList.contains('кот');
    if (н > %(ВЕРХ)d && в < %(НИЗ)d && (кот ? п > %(X)d + %(ДОПУСК)d : л >= %(X)d))
      зона.push((кот ? 'кот' : el.textContent.trim().slice(0, 14) || el.tagName.toLowerCase())
                + ' ' + Math.round(л) + '–' + Math.round(п));
  }
  document.body.setAttribute('data-замер', JSON.stringify({
    шрифты: ![...document.fonts].some(f => f.status === 'error'), зона,
    ...запас_кадра('', %(ЗАПАС)d, %(КРАЙ)d)}));
});
""" % {"ВЕРХ": ЗОНА_ВЕРХ, "НИЗ": ЗОНА_НИЗ, "X": КНОПКИ_X, "ДОПУСК": ДОПУСК_КОТА,
       "ЗАПАС": ЗАПАС, "КРАЙ": КРАЙ}


def _имя(кто: str) -> str:
    """«:Hedra хватает,» → «Hedra хватает,»; класс без текста остаётся классом."""
    класс, _, текст = кто.partition(":")
    return " ".join((текст or класс or "блок").split())


def по_разметке(папка: Path, файл: str) -> list[str]:
    """Проверка 2 в Chrome: впритык, у края, под кнопками TikTok. Пусто — чисто."""
    sys.path.insert(0, str(стиль.ПОСТБОТ))
    import браузер
    замер = браузер.замерить(снять_доски.страница(папка, файл, ДОСКА_JS), 1080, 1440)
    if not замер:
        return [приёмка.СТРАНИЦА + "браузер не ответил, разметка не проверена"]
    беды = []
    for пара in замер.get("тесно", []):
        левый, _, правый = пара.rpartition(" ")
        а, _, б = левый.partition(" ↔ ")
        беды.append(f"впритык: {_имя(а)} ↔ {_имя(б)} {правый} px")
    for край in замер.get("край", []):
        кто, _, где = край.rpartition(" ")
        беды.append(f"у края: {_имя(кто)} {где}")
    for кто in замер.get("зона", []):
        беды.append(f"под кнопками TikTok: {кто}")
    if not замер.get("шрифты", True):
        беды.append(приёмка.СТРАНИЦА + "шрифт не загрузился")
    return беды
