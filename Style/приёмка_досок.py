"""Приёмка досок холста: «годен» или список бед с номерами досок — текстом, до глаз.

    python3 приёмка_досок.py <холст> [--без-снимка]

Замер 24.09.2026: половина кругов правок владельца ловила машинный брак — заголовок в три
строки налез на список, подпись на заголовок, кот сел под кнопки TikTok. Всё это видно
по разметке, без вкуса. Проверки от дешёвой к дорогой:

1. **По тексту** (`по_тексту`), без браузера: сколько строк займёт крупный текст и на что
   он налезет. Это оценка по ширине знака, быстрая и грубая; `--без-снимка` — только она.
2. **По разметке в Chrome** (`по_разметке`): общий замер запаса `стиль.ЗАПАС_JS` на верхних
   блоках доски плюс зона кнопок TikTok.
3. **По снимку** (`по_снимку`): `замер.py`. Нормы вкуса (акцент, чернила, контраст) —
   замечания: принятые владельцем кадры их не держат. Брак — только заход на знак.

Итог — отчёт в форме `приёмка.py` (`годен` / `брак: №N: …`) и лист всех досок одной
картинкой: смотреть его в конце, а не каждую доску.
"""
