# ── Проверка 1: по тексту, без браузера ──────────────────────────────────────
# Ширины знаков наших шрифтов сняты в Chrome (`ширины_знаков.py` → `ширины_знаков.json`): по
# средней ширине буквы оценка врала в обе стороны. Средняя — запасная, для чужой гарнитуры и
# знака, которого нет в таблице. Оценка ловит «заголовок лёг лишней строкой», а точное
# «впритык» меряет Chrome.
ШИРИНА_ЗНАКА = {"Onest": 0.56, "Golos": 0.5, "Oswald": 0.42, "JetBrains": 0.6}
_ШИРИНЫ = (json.loads((ТУТ / "ширины_знаков.json").read_text(encoding="utf-8"))
           if (ТУТ / "ширины_знаков.json").exists() else {})


def ширина_строки(текст: str, семья: str, вес: int, кегль: float, разрядка: float = 0.0) -> float:
    """Ширина строки в px по таблице знаков; `разрядка` — letter-spacing в долях кегля."""
    таблица = _ШИРИНЫ.get(f"{семья} {вес}", {})
    средняя = ШИРИНА_ЗНАКА.get(семья, 0.55)
    return sum(таблица.get(з, средняя) + разрядка for з in текст) * кегль
КРУПНЫЙ = 56          # кегль, с которого текст — заголовок: мельче оценка не нужна
_ВНУТРИ_СТРОКИ = {"span", "b", "i", "em", "strong", "br"}
_ПУСТЫЕ = {"img", "br", "meta", "link", "input", "hr", "source"}


def _px(значение: str) -> float | None:
    м = re.fullmatch(r"\s*(-?[\d.]+)(px)?\s*", значение or "")
    return float(м.group(1)) if м else None


def _свойства(стиль_: str) -> dict:
    """Инлайновый style блока → числа: left, top, width, right, font-size, line-height, семья."""
    с = {}
    for пара in стиль_.split(";"):
        ключ, _, значение = пара.partition(":")
        с[ключ.strip().lower()] = значение.strip()
    итог = {к: _px(с.get(к, "")) for к in ("left", "top", "width", "right", "font-size")}
    итог = {к: (int(в) if в is not None and в == int(в) else в) for к, в in итог.items()}
    кегль = итог["font-size"]
    высота = с.get("line-height", "")
    if высота.endswith("px") and кегль:
        итог["line-height"] = _px(высота) / кегль
    else:
        итог["line-height"] = _px(высота) or 1.2
    итог["семья"] = с.get("font-family", "").split(",")[0].strip(" '\"")
    итог["разрядка"] = float(м.group(1)) if (м := re.fullmatch(r"(-?[\d.]+)em", с.get("letter-spacing", ""))) else 0.0
    итог["вес"] = int(в) if (в := с.get("font-weight", "")).isdigit() else 700 if в == "bold" else 400
    итог["капс"] = с.get("text-transform") == "uppercase"
    return итог


class _Блоки(HTMLParser):
    """Верхние дети корня доски (`div` шириной 1080): стиль, строки текста, есть ли вложенные блоки."""

    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.глубина, self.корень, self.тек, self.блоки = 0, None, None, []

    def handle_starttag(self, тег, атрибуты):
        а = dict(атрибуты)
        верхний = self.корень is not None and self.глубина == self.корень
        if тег in _ПУСТЫЕ:
            if self.тек is not None and тег == "br":
                self.тек["строки"].append("")
            elif верхний:
                self.блоки.append({"тег": тег, "стиль": а.get("style") or "", "строки": [""], "вложено": True})
            return
        self.глубина += 1
        if self.корень is None and тег == "div" and "width: 1080px" in (а.get("style") or ""):
            self.корень = self.глубина
        elif верхний:
            self.тек = {"тег": тег, "стиль": а.get("style") or "", "строки": [""], "вложено": False}
            self.блоки.append(self.тек)
        elif self.тек is not None and тег not in _ВНУТРИ_СТРОКИ:
            self.тек["вложено"] = True

    def handle_endtag(self, тег):
        if тег in _ПУСТЫЕ:
            return
        if self.корень is not None and self.глубина == self.корень + 1:
            self.тек = None
        elif self.корень is not None and self.глубина == self.корень:
            self.корень = None
        self.глубина -= 1

    def handle_data(self, данные):
        if self.тек is not None:
            self.тек["строки"][-1] += данные


def строк(текст: str, ширина: float, мерка) -> int:
    """Жадный перенос по словам, как у браузера; `мерка(строка) -> px`. Длинное слово — строка."""
    число, строка = 0, ""
    for слово in текст.split():
        проба = f"{строка} {слово}" if строка else слово
        if число and мерка(проба) <= ширина:
            строка = проба
        else:
            число, строка = число + 1, слово
    return max(число, 1)


def _строки_слово(н: int) -> str:
    return "строка" if н % 10 == 1 and н % 100 != 11 else (
        "строки" if н % 10 in (2, 3, 4) and н % 100 not in (12, 13, 14) else "строк")


def по_тексту(html: str) -> list[str]:
    """Проверка 1: крупный текст, который по оценке строк налезет на блок под ним."""
    разбор = _Блоки()
    разбор.feed(html)
    блоки = []
    for б in разбор.блоки:
        с = _свойства(б["стиль"])
        if с["left"] is None and с["right"] is not None and с["width"] is not None:
            с["left"] = 1080 - с["right"] - с["width"]
        текст = " ".join(" ".join(б["строки"]).split())
        блоки.append({**б, **с, "текст": текст})
    беды = []
    for б in блоки:
        if (б["вложено"] or not б["текст"] or (б["font-size"] or 0) < КРУПНЫЙ
                or None in (б["left"], б["top"], б["width"])):
            continue
        def мерка(т, б=б):
            return ширина_строки(т.upper() if б["капс"] else т, б["семья"], б["вес"], б["font-size"], б["разрядка"])
        n = sum(строк(с, б["width"], мерка) for с in б["строки"] if с.strip())
        низ = round(б["top"] + n * б["font-size"] * б["line-height"])
        # Запас судится по буквам, как у Chrome, а не по коробке строки: низ букв без
        # выносных примерно на пятую часть кегля выше низа строки. По коробке «5 ИИ
        # рисуют ролик за тебя» (4 строки, 118 px) стоит в 17 px от подписи, по буквам — в 41.
        буквы = низ - 0.2 * б["font-size"]
        for с in блоки:
            if с is б or с["top"] is None or с["left"] is None or с["top"] <= б["top"]:
                continue
            правый = с["left"] + (с["width"] or 1)
            if с["left"] < б["left"] + б["width"] and правый > б["left"] and буквы > с["top"] - ЗАПАС:
                сосед = с["текст"][:16] or с["тег"]
                беды.append(f"«{б['текст'][:24]}» ≈{n} {_строки_слово(n)} до {низ} px — "
                            f"налезет на «{сосед}» (верх {с['top']})")
                break
    return беды


def по_снимку(путь: Path) -> tuple[list[str], list[str]]:
    """Проверка 3: `замер.py` по снимку → (брак, замечания).

    Брак — только заход на знак: это наложение, его видно без вкуса. Контраст, акцент,
    чернила и перепад кеглей — нормы: принятые владельцем кадры 24.09 держали их не все
    (акцент 7–17% на тёмных кадрах «ролика из текста»), и приёмка, считающая это браком,
    не пропустила бы ни одного холста.
    """
    замер = _модуль("замер_стилей", ТУТ / "замер.py")
    беды = замер.беды_кадра(замер.кадр(путь))
    return [б for б in беды if б == замер.ЗНАК], [б for б in беды if б != замер.ЗНАК]


def _модуль(имя: str, путь: Path):
    """Модуль по пути, мимо sys.path: у постбота и у стилей есть тёзки — `замер.py` в
    корне и в `Style/`, общий `лист.py` и свой у стиля «пары»."""
    if имя not in sys.modules:
        спек = importlib.util.spec_from_file_location(имя, путь)
        sys.modules[имя] = importlib.util.module_from_spec(спек)
        спек.loader.exec_module(sys.modules[имя])
    return sys.modules[имя]


def _лист(снимки: list[Path], куда: Path, брак: list[int]) -> Path:
    return _модуль("лист_постбота", стиль.ПОСТБОТ / "лист.py").собрать(снимки, куда, брак=брак)


def проверить(холст: Path, снимки: bool = True) -> dict:
    """Отчёт по всем доскам холста в форме `приёмка.py`, со снимками — ещё и путь к листу.

    `снимки=False` — только проверка по тексту, без Chrome: за доли секунды.
    """
    папка = снять_доски.проект(холст)
    кадры = []
    for д in снять_доски.доски(папка):
        брак = по_тексту((папка / д["file"]).read_text(encoding="utf-8"))
        if снимки:
            брак += по_разметке(папка, д["file"])
        кадры.append({"номер": д["номер"], "вид": д.get("title") or д["file"], "доска": д["file"],
                      "брак": брак, "замечания": [], "ужато": 1.0})
    отчёт = {"годен": not any(к["брак"] for к in кадры), "кадры": кадры}
    if снимки:
        пути = снять_доски.снять(папка)
        for к, путь in zip(кадры, пути):
            брак, замечания = по_снимку(путь)
            к["брак"] += брак
            к["замечания"] += замечания
        отчёт["годен"] = not any(к["брак"] for к in кадры)
        отчёт["лист"] = str(_лист(пути, папка.parent / "лист.jpg", приёмка.бракованные(отчёт)))
    return отчёт


def доложить(холст: Path, снимки: bool = True) -> dict:
    """Печатает отчёт: доска за доской, лист и итоговую строку. Возвращает отчёт."""
    отчёт = проверить(холст, снимки)
    for к in отчёт["кадры"]:
        print(f"№{к['номер']} {к['доска'].removesuffix('.dc.html')} — "
              + ("годен" if not к["брак"] else "брак: " + "; ".join(к["брак"])))
        if к["замечания"]:
            print("     замечания: " + "; ".join(к["замечания"]))
    if "лист" in отчёт:
        print("лист:", отчёт["лист"])
    print("годен" if приёмка.годен(отчёт) else "брак: " + приёмка.строкой(отчёт))
    return отчёт


def main():
    if len(sys.argv) < 2:
        raise SystemExit(__doc__)
    отчёт = доложить(Path(sys.argv[1]), снимки="--без-снимка" not in sys.argv[2:])
    sys.exit(0 if приёмка.годен(отчёт) else 1)


def _имя(кто: str) -> str:
    """«:Hedra хватает,» → «Hedra хватает,»; класс без текста остаётся классом."""
    класс, _, текст = кто.partition(":")
    return " ".join((текст or класс or "блок").split())


def по_разметке(папка: Path, файл: str) -> list[str]:
    """Проверка 2 в Chrome: впритык, у края, под кнопками TikTok. Пусто — чисто."""
    sys.path.insert(0, str(стиль.ПОСТБОТ))
    import браузер
    замер = браузер.замерить(снять_доски.страница(папка, файл, ДОСКА_JS), 1080, 1440)
    if not замер:
        return [приёмка.СТРАНИЦА + "браузер не ответил, разметка не проверена"]
    беды = []
    for пара in замер.get("тесно", []):
        левый, _, правый = пара.rpartition(" ")
        а, _, б = левый.partition(" ↔ ")
        беды.append(f"впритык: {_имя(а)} ↔ {_имя(б)} {правый} px")
    for край in замер.get("край", []):
        кто, _, где = край.rpartition(" ")
        беды.append(f"у края: {_имя(кто)} {где}")
    for кто in замер.get("зона", []):
        беды.append(f"под кнопками TikTok: {кто}")
    if not замер.get("шрифты", True):
        беды.append(приёмка.СТРАНИЦА + "шрифт не загрузился")
    return беды


if __name__ == "__main__":
    main()
