# -*- coding: utf-8 -*-
"""Д-19 и Д-20: два дефекта измерителя, найденные 19.09.2026 на живых кадрах.

По Контуру Р — сперва падающий тест, потом правка. Кадры взяты настоящие, из
`Style/справочник/референс/`: они лежат в репозитории и не меняются, то есть
работают замороженной страницей.

Синтетические кадры для этих двух дефектов не годятся, и это проверено: кадр,
нарисованный «как надо» (ровный шаг строк, честные отступы), полосы чернил
разделяет правильно, и дефект не воспроизводится. Ломается измеритель именно
на чужой вёрстке, где строки стоят теснее, чем разделяет алгоритм.
"""
import sys
import unittest
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

import замер  # noqa: E402

РЕФЕРЕНС = Path(__file__).resolve().parent.parent / "справочник" / "референс"


class Д19ПерепадНаПлотномСписке(unittest.TestCase):
    """Кегль считается по высоте полосы чернил, а не по буквам.

    На кадре 02 у @whygolding блок «иконка + имя команды + описание» непрерывен
    по вертикали, и его полоса равна полосе заголовка. Измеритель печатает
    перепад 1,71:1, тогда как по кеглям он 120/54 ≈ 2,2:1.

    Опасна не ложная тревога, а обратное: на такой вёрстке измеритель не
    различает 2,2:1 и 3,5:1 и пропустит настоящий брак иерархии.
    """

    def test_заголовок_отличим_от_строк_списка(self):
        д = замер.кадр(РЕФЕРЕНС / "02.jpg")
        self.assertGreater(
            д["перепад"], 2.0,
            f"перепад {д['перепад']:.2f}:1 при настоящих ≈2,2:1 по кеглям; "
            f"кегли {[round(к * 100, 1) for к in д['кегли']]}")


class Д20КонтрастНаДвухполосном(unittest.TestCase):
    """Локальный фон усредняется по обеим полосам двухполосного кадра.

    Кадр 01 — светлая плита сверху, тёмное поле снизу. Графит по белому даёт
    12,3:1, белое по тёмному около 13:1, слабого текста нет вовсе. Измеритель
    печатает 5,5:1 при «слабых 100%»: окно локального фона шире полосы, и
    средний грунт оказывается между двумя настоящими.

    Грозит тем, что обложки этого типа будут отвергаться приёмкой без причины,
    а настоящий брак на границе полос потеряется в общем шуме.
    """

    def test_обе_полосы_читаются(self):
        д = замер.кадр(РЕФЕРЕНС / "01.jpg")
        # Медиана — главное: раньше она была 5,5:1, потому что чёрный заголовок
        # по белому измеритель считал слабым наравне с вывороткой.
        self.assertGreater(
            д["контраст_середина"], 8.0,
            f"контраст {д['контраст_середина']:.1f}:1, а чёрное по белому здесь 12,3:1")
        # Слабые на этом кадре остаются, и это правда: подзаголовок у автора набран
        # серым (#646464 ≈ 5,9:1 — записано в паспорте стиля как его брак). Ловим
        # не ноль, а уход от «слабо всё подряд»: было 100%.
        self.assertLess(
            д["слабых_доля"], 0.60,
            f"слабых {д['слабых_доля'] * 100:.0f}%: в них снова попал контрастный текст")


if __name__ == "__main__":
    unittest.main()
