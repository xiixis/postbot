# -*- coding: utf-8 -*-
"""Стиль «сводка»: кадр держится на снимке, и это проверяется, а не подразумевается.

Проверок ровно три, и каждая ловит настоящую ошибку, а не пересказывает код:
кадр собран из всех своих блоков; кадр без снимка не рисуется вовсе; снимок
вшит данными, потому что по `file://` Chrome молча ничего не покажет.
"""
import sys
import unittest
from pathlib import Path

ТУТ = Path(__file__).resolve().parent
sys.path.insert(0, str(ТУТ.parent))
sys.path.insert(0, str(ТУТ.parent / "сводка"))

СНИМОК = ТУТ.parent / "сводка" / "референс" / "01.jpg"


def рисовалка():
    import рисовать as р
    р.П = {"обложка": {}, "кадры": [], "финал": {}}
    return р


class Кадр(unittest.TestCase):
    def test_несёт_все_части(self):
        р = рисовалка()
        html = р.кадр({"рубрика": "Событие", "заголовок": "OpenAI выпустили железо",
                       "текст": "Пульт за $230, чтобы управлять агентами, которые пишут код",
                       "снимок": str(СНИМОК)}, 0.5)
        for класс in ("карточка", "рубрика", "заголовок", "пояснение", "снимок"):
            self.assertIn(f"class={класс}", html, f"нет блока {класс}")
        self.assertIn("OpenAI выпустили железо", html)
        self.assertIn("data:image/jpeg;base64,", html)

    def test_без_снимка_падает(self):
        р = рисовалка()
        with self.assertRaises(ValueError) as поймано:
            р.кадр({"рубрика": "Событие", "заголовок": "Без картинки", "текст": "..."}, 0.5)
        self.assertIn("снимок", str(поймано.exception))


class ОбложкаИФинал(unittest.TestCase):
    def test_рисуются(self):
        р = рисовалка()
        р.П = {"обложка": {"рубрика": "ИИ 2026", "заголовок": "Девять событий, что ты пропустил",
                           "снимок": str(СНИМОК)},
               "кадры": [],
               "финал": {"заголовок": "Хватит этих девяти", "текст": "Сохрани, чтобы вернуться"}}
        о = р.обложка(1 / 11)
        ф = р.финал(1.0)
        self.assertIn("Девять событий", о)
        self.assertIn("data:image/jpeg;base64,", о)
        self.assertIn("Хватит этих девяти", ф)


if __name__ == "__main__":
    unittest.main()
