# -*- coding: utf-8 -*-
"""Выпуск карусели с холста согласования — без проверок и просмотров (слово владельца 15.09.2026).

    python3 выпуск.py <стиль>/посты/<пост>.json

Снимаются доски из `<стиль>/холсты/<пост>/project/` — Main и кадры, без запасных обложек.
Правки владельца с холста забираются заранее поверх рабочих досок: `Artifact read` с `paths`
`project/*.dc.html` и `out_dir` = `<стиль>/холсты/<пост>` (`.claude/ПУБЛИКАЦИЯ.md`, шаг 6).
Прежний путь «сохранённый index.html → распаковать помощником холста» мёртв с 21.09.2026:
seed-canvas не распаковывается, и выпуск с этим аргументом падал. Итог — JPG 1080×1440 и
подпись на столе, в папке из поля «папка». Печатает одну строку.
"""
import json, re, shutil, sys, tempfile
from pathlib import Path
from PIL import Image

ТУТ = Path(__file__).parent
sys.path.insert(0, str(ТУТ))
import стиль  # noqa: E402


def снять(папка: Path, куда: Path) -> None:
    """Снимки досок 1620×2160 рисовальщиком постбота, по раскладке холста строка за строкой.

    Раньше снимал `снять-холст.mjs` через playwright-core из ~/4xSoft/html-instagram-carousel;
    17.09.2026 той папки не стало, и выпуск падал. Доска открывается как есть, без support.js
    холста, а картинки вшиваются данными (`снять_доски.страница`). Запасные обложки
    `Oblozhka*` в выпуск не идут.
    """
    sys.path.insert(0, str(стиль.ПОСТБОТ))
    import браузер
    import снять_доски
    куда.mkdir(parents=True, exist_ok=True)
    доски = [д for д in снять_доски.доски(папка) if not д["file"].startswith("Oblozhka")]
    for н, д in enumerate(доски, 1):
        if not браузер.снять(снять_доски.страница(папка, д["file"]), 1080, 1440, куда / f"{н:02d}.png"):
            raise SystemExit(f"снимок не вышел: {д['file']}")


# Хештеги в подписи обязательны всегда (слово владельца 17.09.2026: «Хештеги!!! Они всегда
# должны быть»). Это канон на весь проект; те же числа в `postbot/придирки.ХЕШТЕГОВ`.
ХЕШТЕГОВ = (6, 8)          # ровно пять ставит половина ниши, и это худший вариант:
                           # замер даёт 23 тыс. показов против 159 тыс. у шести и больше
ПОДПИСЬ_ЗНАКОВ = 80        # без хештегов; до нажатия «ещё» видна примерно сотня символов
НАЗВАНИЕ_ЗНАКОВ = 90       # отдельное поле площадки: его читает поиск, а не зритель


def хештеги(подпись: str, тест: str = "") -> None:
    метки = re.findall(r"#\w+", подпись)
    мало, много = ХЕШТЕГОВ
    if мало <= len(метки) <= много:
        return
    # Норма выведена из замера, но владелец вправе её проверить: пост с полем
    # «тест» проходит, и причина отступления печатается в вывод, чтобы замер
    # потом было с чем сопоставить.
    if тест:
        print(f"⚠️  хештегов {len(метки)} вместо {мало}–{много} · тест: {тест}")
        return
    raise SystemExit(f"в подписи хештегов {len(метки)}, нужно от {мало} до {много} — допиши в поле «подпись»")


def тексты(пост: dict) -> None:
    """Длина подписи и названия — по правилам из `carousel.py`.

    Проверка заведена 19.09.2026: подписи на 828 и 861 знак дошли до стола
    молча, потому что выпуск считал только хештеги. Замер на 458 каруселях:
    подпись до 80 знаков идёт с медианой 333 тыс. показов, длиннее 800 — 29 тыс.
    """
    тело = re.sub(r"#\w+", "", пост["подпись"]).strip()
    if len(тело) > ПОДПИСЬ_ЗНАКОВ:
        raise SystemExit(
            f"подпись {len(тело)} знаков без хештегов, норма до {ПОДПИСЬ_ЗНАКОВ}: "
            "это одна фраза, а не абзац. Содержание живёт на слайдах, подпись только "
            "подводит к ним (правило и замеры — в carousel.py)")
    название = пост.get("название", "")
    if len(название) > НАЗВАНИЕ_ЗНАКОВ:
        raise SystemExit(f"название {len(название)} знаков, норма до {НАЗВАНИЕ_ЗНАКОВ}")


def main():
    файл = Path(sys.argv[1]).resolve()
    пост = json.loads(файл.read_text())
    хештеги(пост["подпись"], пост.get("тест", ""))   # без хештегов пост на стол не уходит
    тексты(пост)                           # и с подписью-простынёй тоже не уходит
    рабочие = файл.parent.parent / "холсты" / файл.stem
    if len(sys.argv) > 2:
        raise SystemExit("второй аргумент больше не нужен: правки владельца забрать поверх рабочих досок — "
                         "Artifact read, paths project/*.dc.html, out_dir " + str(рабочие)
                         + " (ПУБЛИКАЦИЯ.md, шаг 6), и выпускать без него")
    with tempfile.TemporaryDirectory() as врем:
        снимки = Path(врем) / "снимки"
        снять(рабочие, снимки)
        стол = стиль.СТОЛ / пост["папка"]
        if стол.exists():
            shutil.rmtree(стол)
        стол.mkdir(parents=True)
        for png in sorted(снимки.glob("*.png")):
            with Image.open(png) as и:
                и.convert("RGB").resize((1080, 1440), Image.LANCZOS).save(стол / f"{png.stem}.jpg", quality=92)
        (стол / "подпись.txt").write_text(пост["подпись"])
        # Название — отдельное поле площадки (до 90 знаков, словами для поиска),
        # и раньше его на столе не было: копировать при выкладке было неоткуда.
        if пост.get("название"):
            (стол / "название.txt").write_text(пост["название"])
        # Теги — не хештеги: поисковые фразы отдельным полем, как в YouTube.
        # Площадка по ним понимает, кому показывать пост; в подписи они не стоят.
        if пост.get("теги"):
            (стол / "теги.txt").write_text(", ".join(пост["теги"]))
    print(f"на столе: {стол} — {len(list(стол.glob('*.jpg')))} кадров")


if __name__ == "__main__":
    main()
