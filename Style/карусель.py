# -*- coding: utf-8 -*-
"""Одна команда сборки карусели: python3 карусель.py <стиль>/посты/<пост>.json [--без-снимка]

После «рисовать» (сценарий утверждён) — вместо ручного прохода по шагам:
1. рисовальщик — `<стиль>/<вид>.py` по полю «вид» поста;
2. снабжение: значки (`"файл"` → `<стиль>/значки/`), позы кота (`"поза"`), сцены с карточками
   (`"сцена"` → `.claude/маскот/сцены/` или путь `картинки/…` у прежних постов). Чего нет —
   список для снабженца и выход с кодом 2: собирать без файлов бессмысленно;
3. запасные обложки: ровно две, из каталога, с полями; та же пара, что у другого поста стиля, —
   предупреждение (правило 9 — про ленту профиля, а запасные в неё попадают, только если их
   выбрали главной);
4. сборка рисовальщиком — он сам печатает приёмку досок и путь к листу;
5. параметры выкладки холста для одного вызова Artifact (выкладывает Claude, не скрипт).

Автопочинки нет: брак возвращается списком, код выхода 1.
"""
import json
import subprocess
import sys
from pathlib import Path

ТУТ = Path(__file__).resolve().parent
sys.path.insert(0, str(ТУТ))
import стиль  # noqa: E402
import обложки  # noqa: E402


def рисовальщик(пост: dict, папка: Path) -> Path:
    путь = папка / f"{пост.get('вид', '')}.py"
    if пост.get("вид") and путь.exists():
        return путь
    кандидаты = sorted(п.stem for п in папка.glob("*.py"))
    raise SystemExit(f"нет рисовальщика для «вид»: {пост.get('вид')!r} — в стиле есть: {', '.join(кандидаты)}")


def снабжение(пост: dict, папка: Path) -> list[str]:
    """Файлы, на которые ссылается пост, но которых нет на диске."""
    беды = []

    def обход(узел):
        if isinstance(узел, dict):
            for ключ, значение in узел.items():
                if isinstance(значение, str):
                    проверить_файл(ключ, значение)
                else:
                    обход(значение)
        elif isinstance(узел, list):
            for элемент in узел:
                обход(элемент)

    def проверить_файл(ключ: str, значение: str):
        if ключ == "файл":
            путь, что = папка / "значки" / значение, "значок"
        elif ключ == "поза":
            путь, что = стиль.ПОЗЫ / f"{значение}.png", "поза кота"
        elif ключ == "сцена" and "/" in значение:
            путь, что = папка / значение, "сцена"
        elif ключ == "сцена":
            нет = [ф for ф in (f"{значение}.jpg", f"{значение}.json") if not (обложки.СЦЕНЫ / ф).exists()]
            if нет:
                беды.append(f"нет {' и '.join(нет)} в {обложки.СЦЕНЫ} (сцена «{значение}» с карточкой)")
            return
        else:
            return
        if not путь.exists():
            беды.append(f"нет {путь} ({что} «{значение}»)")

    обход(пост)
    return list(dict.fromkeys(беды))


def обложки_поста(пост: dict, файл: Path) -> tuple[list[str], list[str]]:
    """(беды, предупреждения) по запасным обложкам."""
    запасные = пост.get("запасные", {})
    беды = [] if len(запасные) == 2 else [f"запасных обложек {len(запасные)}, нужно ровно две — из каталога: "
                                          + ", ".join(обложки.МАКЕТЫ)]
    for имя, о in запасные.items():
        беды += обложки.проверить(имя, о, None)
    предупреждения = []
    for сосед in sorted(Path(файл).parent.glob("*.json")):
        if сосед.resolve() == Path(файл).resolve():
            continue
        try:
            пара = set(json.loads(сосед.read_text(encoding="utf-8")).get("запасные", {}))
        except (json.JSONDecodeError, AttributeError):
            continue
        if запасные and пара == set(запасные):
            предупреждения.append(f"та же пара запасных, что у поста «{сосед.stem}»: " + ", ".join(запасные))
    return беды, предупреждения


def main():
    if len(sys.argv) < 2:
        raise SystemExit(__doc__)
    файл = Path(sys.argv[1]).resolve()
    пост = json.loads(файл.read_text(encoding="utf-8"))
    папка = файл.parent.parent
    путь = рисовальщик(пост, папка)

    нет = снабжение(пост, папка)
    if нет:
        print("для снабженца (snabzhenets):\n  " + "\n  ".join(нет))
        sys.exit(2)
    беды, предупреждения = обложки_поста(пост, файл)
    for п in предупреждения:
        print("⚠️ ", п)
    if беды:
        print("обложки:\n  " + "\n  ".join(беды))
        sys.exit(1)

    флаги = ["--без-снимка"] if "--без-снимка" in sys.argv[2:] else []
    р = subprocess.run([sys.executable, str(путь), str(файл), *флаги], capture_output=True, text=True)
    вывод = [с for с in р.stdout.splitlines() if с.strip()]
    print("\n".join(вывод))
    if р.returncode:
        print(р.stderr.strip()[-1500:])
        sys.exit(1)
    итог = вывод[-1] if вывод else ""

    холст = папка / "холсты" / файл.stem
    print("\nвыкладка холста — один вызов Artifact:")
    print(f"  url: {пост['холст']}" if пост.get("холст") else
          "  новый холст: Artifact quickstart intent «design» → publish с type_url; ссылку — в поле «холст» поста")
    print(f"  root: {холст}\n  file_path: project/canvas.json")
    sys.exit(0 if итог == "годен" else 1)


if __name__ == "__main__":
    main()
