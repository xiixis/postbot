# -*- coding: utf-8 -*-
"""Хозяин бота: второй экземпляр не стартует, пока жив первый.

Бот работает только на маке (решение владельца 25.09.2026), но код тот же на ПК, и база
общая. Два запущенных бота делили бы расписание и опрос Telegram (ответ 409), поэтому
живой бот раз в минуту ставит в базе отметку «кто и когда», а новый при старте её
проверяет. Отметка старше СВЕЖЕСТИ значит, что прежний бот умер, не попрощавшись.
"""

import os
import socket
import time

import db

КЛЮЧ = "хозяин_бота"
СВЕЖЕСТЬ = 180          # секунд: отметка обновляется раз в минуту, три пропуска — бот мёртв


def я() -> str:
    return f"{socket.gethostname()}:{os.getpid()}"


def отметиться(когда: float | None = None) -> None:
    db.запомнить(КЛЮЧ, {"кто": я(), "машина": socket.gethostname(),
                        "жив": time.time() if когда is None else когда})


def занят_другим() -> dict | None:
    """Отметка другого живого бота или None, если запускаться можно."""
    db.забыть_кэш()                  # настройки кэшируются, а тут нужна свежая отметка
    запись = db.настройка(КЛЮЧ)
    if not isinstance(запись, dict) or запись.get("кто") == я():
        return None
    if time.time() - float(запись.get("жив", 0)) > СВЕЖЕСТЬ:
        return None
    return запись


def уйти() -> None:
    """Снимает свою отметку при штатной остановке: следующий старт не ждёт СВЕЖЕСТЬ."""
    db.забыть_кэш()
    запись = db.настройка(КЛЮЧ)
    if isinstance(запись, dict) and запись.get("кто") == я():
        db.запомнить(КЛЮЧ, None)
