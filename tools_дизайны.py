# -*- coding: utf-8 -*-
"""Папка на каждый дизайн карусели: паспорт из кода и лист образцовых кадров.

    python3 tools_дизайны.py                 # паспорта и листы всех дизайнов
    python3 tools_дизайны.py --без-картинок  # только паспорта, Chrome не нужен
    python3 tools_дизайны.py терминал каталог

По образцу `html-instagram-carousel/styles/<стиль>/` у знакомого: у каждого стиля своя
папка со всем, что о нём известно. Отличие нарочное: CSS сюда не копируется. Дизайн
живёт в `card.ДИЗАЙНЫ`, правила — в `форматы.py`, дефекты — в `docs/дефекты-кадров.md`;
описание рядом с кодом устарело бы с первой правки. Поэтому паспорт собирается из кода
этим скриптом, а правят код и пересобирают.
"""
import sys
from datetime import date
from pathlib import Path

import card
import форматы

ПАПКА = Path(__file__).resolve().parent / "docs" / "дизайны"
ФОРМАТ = "3к4"
ВСЕГО = 8
# Образцовые тексты: короткие и длинные строки, подсветка, список — то, на чём дизайны ломаются.
ОБЛОЖКА = ("Шпаргалка", "Таблица сама посчитает, если попросить ИИ")
КАДРЫ = [
    ("список", 2, {"заголовок": "Кому что поручить",
                   "пункты": ["ChatGPT: формулы в таблице", "Claude: длинный отчёт по шагам",
                              "Gemini: письмо из Google Таблиц"]}),
    ("правка", 3, {"неверно": "Посчитай мне продажи", "верно": "Сложи столбец C *по месяцам*"}),
]
ВЫВОД = "ИИ пишет формулу, а проверяешь её ты"
ТОН = {"тёмный": "тёмных", "светлый": "светлых"}
ПРИЗЫВ = "Сохрани, пригодится. Подпишись: один приём за пост"


def запреты(имя: str) -> list[str]:
    строки = []
    for п in форматы.НЕЛЬЗЯ:
        if п["дизайн"] != имя:
            continue
        где = []
        if п.get("виды"):
            где.append("вёрстки " + ", ".join(f"«{в}»" for в in sorted(п["виды"])))
        if п.get("тон"):
            где.append(f"на {ТОН[п['тон']]} кадрах")
        if п.get("формат"):
            где.append(f"в формате {п['формат']}")
        строки.append(f"- {п['дефект']}: нельзя " + (" ".join(где) or "нигде"))
    if имя in форматы.БЕЗ_ПОДСВЕТКИ:
        тон, дефект = форматы.БЕЗ_ПОДСВЕТКИ[имя]
        строки.append(f"- {дефект}: без подсветки слов на {ТОН[тон]} кадрах (снимает предполёт)")
    return строки


def паспорт(имя: str, лист: bool) -> str:
    д = card.ДИЗАЙНЫ[имя]
    в_ротации = имя in форматы.ДИЗАЙНЫ_ОК
    фон = форматы.СВОЙ_ФОН.get(имя)
    гарнитуры = sorted({f"{семья} {вес}" for _, семья, вес in д.get("фейсы", [])}) or ["Onest и Plex (базовые)"]
    масштаб = ", ".join(f"{к} ×{в}" for к, в in д.get("масштаб", {}).items()) or "базовые кегли"
    годится = [ф for ф in ("3к4", "квадрат") if форматы.дизайн_годится(имя, ф)]
    части = [
        f"# Дизайн «{имя}»",
        "",
        f"> Собрано `tools_дизайны.py` из кода {date.today():%d.%m.%Y}. Не править руками:",
        f"> дизайн — `card.ДИЗАЙНЫ[\"{имя}\"]`, правила — `форматы.py`, потом пересобрать.",
        "",
        f"**Что это:** {д.get('о', '—')}.",
        "",
        "| | |",
        "|---|---|",
        f"| В ротации | {'да — в `форматы.ДИЗАЙНЫ_ОК`' if в_ротации else 'нет — выключен, паспорт карусели его не выберет'} |",
        f"| Форматы | {', '.join(годится) or 'ни один'} |",
        f"| Фон | {'только «' + фон + '» (`форматы.СВОЙ_ФОН`)' if фон else 'любой из ' + ', '.join(форматы.ОФОРМЛЕНИЯ_ОК)} |",
        f"| Гарнитуры | {', '.join(гарнитуры)} |",
        f"| Кегли | {масштаб} |",
        f"| Своя обложка | {'да' if д.get('обложка') else 'нет, общая'} |",
        f"| Пилюли-метки | {'да' if д.get('пилюля') else 'нет'} |",
        "",
        "## Запреты",
        "",
        *(запреты(имя) or ["Нет. Связки, которые ломаются, записывать в `форматы.НЕЛЬЗЯ` с номером из реестра дефектов."]),
        "",
        "## Образец",
        "",
    ]
    if лист:
        части += [f"Обложка, «список» (тёмный кадр), «правка» (светлый), финал; формат {ФОРМАТ}, "
                  f"фон «{фон or 'сетка'}».", "", "![образец](лист.jpg)"]
    else:
        части += ["Лист не собран: `python3 tools_дизайны.py " + имя + "`."]
    return "\n".join(части) + "\n"


def страницы(имя: str) -> list[tuple]:
    """Вёрстка четырёх кадров без снимка: _снять подменён записью."""
    фон = форматы.СВОЙ_ФОН.get(имя, "сетка")
    снято = []
    было = card._снять
    card._снять = lambda стр, ш=1280, в=720: снято.append((стр, ш, в))
    try:
        card.слайд_обложка(*ОБЛОЖКА, None, 1, ВСЕГО, ФОРМАТ, дизайн=имя, оформление=фон)
        кадры = [снято[-1]]
        for вид, номер, поля in КАДРЫ:
            кадры.append(card.страница_вида(вид, поля, номер, ВСЕГО, ФОРМАТ,
                                            оформление=фон, дизайн=имя))
        card.слайд_финал(ВЫВОД, ВСЕГО, ВСЕГО, ФОРМАТ, ПРИЗЫВ, дизайн=имя, оформление=фон)
        кадры.append(снято[-1])
    finally:
        card._снять = было
    return кадры


def лист(имя: str, куда: Path) -> None:
    import tempfile
    import браузер
    from PIL import Image
    ш, в, о = 360, 480, 12
    итог = Image.new("RGB", (4 * ш + 5 * о, в + 2 * о), (60, 60, 60))
    with tempfile.TemporaryDirectory() as врем:
        for н, (стр, ширина, высота) in enumerate(страницы(имя)):
            png = Path(врем) / f"{н}.png"
            if not браузер.снять(стр, ширина, высота, png):
                raise RuntimeError(f"{имя}: кадр {н + 1} не снялся")
            with Image.open(png) as к:
                итог.paste(к.convert("RGB").resize((ш, в), Image.LANCZOS), (о + н * (ш + о), о))
    итог.save(куда, quality=88)


def main():
    без_картинок = "--без-картинок" in sys.argv
    имена = [а for а in sys.argv[1:] if not а.startswith("--")] or list(card.ДИЗАЙНЫ)
    ПАПКА.mkdir(parents=True, exist_ok=True)
    for имя in имена:
        папка = ПАПКА / имя
        папка.mkdir(exist_ok=True)
        if not без_картинок:
            лист(имя, папка / "лист.jpg")
        (папка / "ПАСПОРТ.md").write_text(паспорт(имя, (папка / "лист.jpg").exists()))
        print(имя, "готов", flush=True)
    строки = ["# Дизайны карусели", "",
              "Папка на каждый дизайн: `ПАСПОРТ.md` и `лист.jpg`. Собирает `tools_дизайны.py` из кода.",
              "", "| Дизайн | В ротации | Что это |", "|---|---|---|"]
    for имя, д in card.ДИЗАЙНЫ.items():
        строки.append(f"| [{имя}]({имя}/ПАСПОРТ.md) | {'да' if имя in форматы.ДИЗАЙНЫ_ОК else 'нет'} | {д.get('о', '')} |")
    (ПАПКА / "README.md").write_text("\n".join(строки) + "\n")


if __name__ == "__main__":
    main()
