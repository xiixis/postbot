"""Предполёт: что сломается на кадре, видно ещё по тексту карусели.

Приёмка судит готовые картинки, и её брак стоит перерисовки: Chrome, минута
работы, картинки в контексте сессии. А часть брака видна раньше — по тому,
какую вёрстку выбрала модель и что в неё положила. «Было» в каталоге на
тёмном кадре выходит белым по крему всегда, и знать это можно до снимка.

Беда — то, что на кадре точно выйдет поломкой; её чинят до отрисовки.
Замечание — то, на что стоит взглянуть: длинный заголовок, полупустой кадр,
призыв не по смыслу. Модуль без модели и без браузера: счёт по тексту и
матрица из `форматы`. Отчёт того же вида, что у приёмки, чтобы их показывали
одинаково.
"""

import re

import форматы

ПУНКТ_ДО = 28
ЗВЁЗДОЧКИ = re.compile(r"\*([^*]+)\*")
ЙЁ = re.compile(r"[ЙйЁё]")
ЧИСЛО = re.compile(r"(?<!\d)(\d{1,2})(?!\d)")
# Вёрстки, где пункт — строка текста, а не «что|сколько|доля».
ПРОСТЫЕ_СТРОКИ = {"список", "поток", "было", "правка", "против", "стрелка"}
# Вёрстки, у которых вся начинка в «текст»: короткий оставит кадр пустым.
НАЧИНКА_В_ТЕКСТЕ = {"мысль", "выделение", "вопрос"}
ВИДЫ_СПИСКА = {"список", "шпаргалка", "поток"}
ВИДЫ_ШАГОВ = {"шаг", "поток"}
НА = {"тёмный": "тёмном", "светлый": "светлом"}
ЙЁ_ЗАМЕЧАНИЕ = ("«Й» или «Ё» не в первом слове заголовка: в манифесте значок "
                "садится на строку выше (Д-06)")


def _кадр(номер: int, вид: str) -> dict:
    return {"номер": номер, "вид": вид, "беды": [], "замечания": []}


def _без_звёздочек(текст) -> str:
    return ЗВЁЗДОЧКИ.sub(r"\1", str(текст or "")).strip()


def _йё_не_в_начале(заголовок) -> bool:
    return any(ЙЁ.search(слово) for слово in str(заголовок or "").split()[1:])


def _слайд(с: dict, номер: int, дизайн: str, формат: str, годится: bool) -> dict:
    import carousel
    вид = с.get("вид") or форматы.НАДЁЖНЫЙ_ВИД
    кадр = _кадр(номер, вид)
    тон = форматы.тон(номер)
    дефект = годится and форматы.запрет(дизайн, вид, номер, формат)
    if дефект:
        кадр["беды"].append(
            f"«{вид}» ломается на {НА[тон]} кадре дизайна «{дизайн}» ({дефект})")
    без = форматы.БЕЗ_ПОДСВЕТКИ.get(дизайн)
    if без and без[0] == тон and ЗВЁЗДОЧКИ.search(str(с.get("текст") or "")):
        кадр["беды"].append(
            f"подсветка пропадёт на {НА[тон]} кадре дизайна «{дизайн}» ({без[1]})")
    заголовок = str(с.get("заголовок") or "")
    if len(заголовок) > carousel.ЗАГОЛОВОК_ДО:
        кадр["замечания"].append(
            f"заголовок {len(заголовок)} знаков при пределе "
            f"{carousel.ЗАГОЛОВОК_ДО}: кегль ужмётся")
    if вид in ПРОСТЫЕ_СТРОКИ:
        длинные = [х for х in (с.get("строки") or []) if len(str(х)) > ПУНКТ_ДО]
        if длинные:
            кадр["замечания"].append(
                f"пункт длиннее {ПУНКТ_ДО} знаков ляжет в две строки: «{длинные[0]}»")
    if (вид in НАЧИНКА_В_ТЕКСТЕ and not (с.get("строки") or [])
            and len(_без_звёздочек(с.get("текст"))) < carousel.МЫСЛЬ[0]):
        кадр["замечания"].append(
            f"текст короче {carousel.МЫСЛЬ[0]} знаков, кадр выйдет полупустым (Д-12)")
    if дизайн == "манифест" and _йё_не_в_начале(заголовок):
        кадр["замечания"].append(ЙЁ_ЗАМЕЧАНИЕ)
    return кадр


def проверить(к: dict, формат: str) -> dict:
    """Отчёт вида приёмки: {годен, кадры: [{номер, вид, беды, замечания}]}."""
    import carousel
    паспорт = к.get("паспорт") or {}
    дизайн = паспорт.get("дизайн") or "фирменный"
    слайды = к.get("slides") or []
    один = carousel.одним_кадром(паспорт)
    годится = форматы.дизайн_годится(дизайн, формат)
    кадры = []

    if not один:
        обложка = _кадр(1, "обложка")
        if дизайн == "манифест" and _йё_не_в_начале(к.get("cover_title")):
            обложка["замечания"].append(ЙЁ_ЗАМЕЧАНИЕ)
        обещано = ЧИСЛО.search(str(к.get("cover_title") or ""))
        if обещано and 2 <= int(обещано.group(1)) <= 20 \
                and int(обещано.group(1)) > len(слайды):
            обложка["замечания"].append(
                f"обложка обещает {обещано.group(1)}, а слайдов середины {len(слайды)}")
        кадры.append(обложка)

    for номер, с in enumerate(слайды, start=1 if один else 2):
        кадры.append(_слайд(с, номер, дизайн, формат, годится))

    if not один and (к.get("closing") or "").strip():
        финал = _кадр(len(слайды) + 2, "финал")
        призыв = carousel.призыв(к, "слайд").lower()
        виды = {с.get("вид") for с in слайды}
        if "список" in призыв and not виды & ВИДЫ_СПИСКА:
            финал["замечания"].append(
                "призыв просит сохранить список, а списка в карусели нет (Д-08)")
        if ("по шагам" in призыв and к.get("каркас") != "шаги"
                and not виды & ВИДЫ_ШАГОВ):
            финал["замечания"].append(
                "призыв обещает разбор по шагам, а шагов в карусели нет (Д-08)")
        кадры.append(финал)

    if not годится and кадры:
        # Дизайн целиком не годится формату: слайды тут ни при чём, чинит это
        # паспорт, а не вёрстка, поэтому беда одна и на первом кадре.
        кадры[0]["беды"].insert(0, f"дизайн «{дизайн}» не читается в формате "
                                   f"«{формат}» (Д-05)")
    return {"годен": not any(кадр["беды"] for кадр in кадры), "кадры": кадры}


